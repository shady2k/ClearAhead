// worldRevision — ревизия, которой помечается статический ярус мира.
//
// Названа константой, а не двумя литералами, потому что число одно и то же у
// прогрева (Bootstrap) и у порождения по требованию (NewLazy). Разойдись они —
// и один и тот же чанк лежал бы в базе с разной ревизией в зависимости от того,
// посчитали его при старте или по запросу, хотя байты у него одни. Ревизия
// пока не меняется ничем: мутаций мира не существует, и вводить её счётчик до
// появления того, что её двигает, значило бы завести форму без потребителя.
const worldRevision = 1

// matchID — имя единственной партии.
//
// Постоянное, а не случайное при каждом старте: клиент, переподключившийся к
// тому же серверу, обязан видеть ту же партию. Случайное имя означало бы, что
// перезапуск сервера — это новая партия, а сегодня перезапуск не теряет ничего:
// расстановка та же, движения нет. Когда появится журнал команд, имя партии
// станет его ключом, и вот тогда оно перестанет быть константой.
const matchID = "M1"

func main() {
	dbPath := flag.String("db", "world.db", "файл базы мира")
	addr := flag.String("addr", ":8080", "адрес прослушивания")
	// Путь ОТНОСИТЕЛЬНЫЙ и относительный именно к рабочему каталогу, а не к
	// бинарю: модуль лежит в server/, и `make serve` заходит туда же, поэтому
	// умолчание работает при запуске из server/. Makefile всё равно передаёт
	// абсолютный путь — умолчание удобно человеку, а не цели сборки.
	mapPath := flag.String("map", mapfmt.ShippedMapPath, "файл карты мира")
	// ИСХОДНИКИ ПАРТИИ — ОТДЕЛЬНАЯ база рядом с проекциями (sqym.18). Сторож
	// assertProjectionsOnly требует, чтобы база проекций несла ТОЛЬКО проекции;
	// исходники (закоммиченная карта, правки высот, вырубка, журнал коммитов)
	// живут здесь и -reseed их не касается вовсе: проекцию сносить можно всегда,
	// исходник — нет (решение W6-B). Путь отдельный, потому что сносить эти два
	// файла нельзя одним движением.
	sourcesPath := flag.String("sources", "sources.db", "файл базы исходников партии")
	// Пересоздание мира — решение ТОГО, КТО ЗАПУСКАЕТ, и потому ключ, а не
	// поведение бутстрапа: worldgen.Bootstrap идемпотентен нарочно.
	//
	// УМОЛЧАНИЕ ВЫКЛЮЧЕНО. Разрушительное действие не бывает умолчанием: голый
	// `make serve` или запуск бинаря руками мир не сносит. Включает его цикл
	// разработки — `make dev`, где правку карты, рецепта рельефа или правила
	// уровня чанка надо видеть на экране сразу, а не разбираться, почему в базе
	// лежат вчерашние чанки.
	//
	// ОТВЕРГНУТА переменная окружения (владелец разрешал и её): ключ однороден с
	// -db и -addr, виден в `ps` рядом с путём базы, которую сносит, и не требует
	// собственного разбора «ture» как опечатки. Переменная читается молча — а
	// молча сносить базу нельзя.
	reseed := flag.Bool("reseed", false, "снести базу мира перед стартом и засеять заново")
	// ПРОГРЕВ — КЭШ, А НЕ ЧАСТЬ МИРА (решение владельца 2026-08-13, спека §4).
	//
	// Бутстрап больше не греет чанки: он заводит запись региона, а всё
	// остальное порождение по требованию считает само. Прогрев включается
	// ЗДЕСЬ, явно, тем, кто запускает, и только для СВЕЖЕГО засева — греть
	// существующую базу заново означало бы пересчитывать весь мир при каждом
	// старте (полный пересчёт региона — около семи минут машинного времени,
	// спека §8.1).
	//
	// Умолчание включено, чтобы цикл разработки (make dev с -reseed) получал
	// тёплый мир, как и до отвязки; оператор большой карты снимает флаг и
	// полагается на порождение по требованию с его бюджетом и очередью.
	preheat := flag.Bool("preheat", true, "греть свежезасеянный мир чанками (кэш, а не правильность)")
	// САМОЗАВЕРШЕНИЕ. Ноль значит «работать, пока не остановят», и это умолчание:
	// игровой сервер, гаснущий сам, — не сервер.
	//
	// Ключ заведён по замеренной причине, а не про запас. За одну сессию проверок
	// на машине владельца осталось ШЕСТЬ переживших своего запускающего серверов
	// (порты 8080, 8093, 8094, 8098, 8099, 8123): проверяющий поднимает сервер
	// фоном, снимает кадр, заканчивает — а процесс держит порт дальше. Дальше
	// хуже, чем занятый порт: такой сервер держит СТАРУЮ базу и отвечает на
	// запросы вчерашними числами, отчего следующая проверка меряет не то, что
	// думает, и расхождение выглядит поломкой правки.
	//
	// ОТВЕРГНУТО: `timeout N` в вызове — на macOS её нет в базовой поставке, и
	// цель сборки, работающая на Linux и молча падающая здесь, хуже флага.
	// Убийство по PID тоже отвергнуто: PID надо откуда-то взять и не потерять,
	// а срок жизни знает ровно тот, кто запускает.
	quitAfter := flag.Duration("quit-after", 0, "погаснуть через столько времени после старта (0 — не гаснуть)")
	// НАБОР КОНТЕНТА — каталог, а не файл: в нём перечень и байты ассетов рядом.
	// Путь относительный к рабочему каталогу, как и у карты, и по той же
	// причине: `make serve` заходит в server/.
	//
	// Ключ, а не константа сборки: go:embed на двадцать мегабайт локомотива
	// раздул бы бинарь сервера ради данных, которые данные и есть.
	contentDir := flag.String("content", "assets", "каталог набора контента: паспорта и ассеты")
	// РАССТАНОВКА — состояние ПАРТИИ, а не карты (решение владельца 2026-08-13).
	//
	// Пусто значит «партия без подвижного состава», и это законный мир, а не
	// недонастроенный: станция без единой машины — обычное дело. Отсутствие
	// ключа и отсутствие названного файла — разные вещи: первое молчаливо и
	// законно, второе отказ старта.
	placement := flag.String("placement", "", "файл начальной расстановки партии (пусто — без подвижного состава)")
	flag.Parse()

	// Карта читается ФАЙЛОМ. Тихой подстановки затравки из кода при отсутствии
	// файла нет и быть не должно: сервер, поднявшийся не с той картой, которую
	// ему назвали, — это ровно то правдоподобное умолчание, которое правило
	// проекта запрещает. Нет файла — отказ на старте, с путём и ключом в тексте.
	worldMap, err := mapfmt.DecodeFile(*mapPath)
	if err != nil {
		log.Fatalf("карта не прочитана (ключ -map): %v", err)
	}

	if *reseed {
		if err := dropWorld(*dbPath); err != nil {
			log.Fatalf("пересоздание мира: %v", err)
		}
	}

	// ИСХОДНИКИ ПАРТИИ: закоммиченное поднимается из sourcestore, а не
	// сочиняется заново. Сервис правок — шов, за который будущий транспорт
	// (шаг 12 эпика) дернёт модель; сегодня он держит закоммиченный мир и
	// исходники, и компиляторы мира читают их через него.
	sources, err := sourcestore.Open(*sourcesPath)
	if err != nil {
		log.Fatalf("база исходников %s: %v", *sourcesPath, err)
	}
	defer sources.Close()
	editSvc, err := edit.NewServiceStored(sources, worldMap, uuidv7.New)
	if err != nil {
		log.Fatalf("сервис правок: %v", err)
	}
	committed := editSvc.Committed()
	veg, err := sources.GetVegetation()
	if err != nil {
		log.Fatalf("растительность из базы исходников: %v", err)
	}
	src := worldgen.Sources{Grading: editSvc.Grading(), Vegetation: veg}
	if n := editSvc.JournalSeq(); n > 0 {
		log.Printf("исходники партии: журнал коммитов %d, правок высот %d, рубок %d",
			n, len(src.Grading.Cells), len(src.Vegetation.Cuts))
	}

	// Одна и та же карта для сети в памяти и для мира в базе: иначе сеть
	// описывала бы одну станцию, а рельеф — другую. Карта здесь —
	// ЗАКОММИЧЕННАЯ (файл плюс принятые правки пути): сеть, которую видит
	// клиент, обязана описывать мир, который лежит в базе.
	store := mapstore.Open()
	st, err := store.Set(&committed)
	if err != nil {
		log.Fatalf("карта %s не проходит вход: %v", *mapPath, err)
	}
	log.Printf("карта %s ревизия %d: %d элементов, сеть %s",
		st.Manifest.MapID, st.Manifest.Revision, len(st.Network.Elements), st.Manifest.NetworkHash[:12])

	world, err := worldstore.Open(*dbPath)
	if err != nil {
		log.Fatalf("база мира %s: %v", *dbPath, err)
	}
	defer world.Close()

	// Бутстрап идемпотентен: заводит регион, чанков не трогает (прогрев — кэш,
	// включается ниже явно, а не подразумевается бутстрапом).
	rep, seeded, err := worldgen.Bootstrap(world, &committed, worldRevision, provenanceOf(*mapPath))
	if err != nil {
		log.Fatalf("бутстрап мира: %v", err)
	}
	if seeded {
		log.Printf("мир засеян: регион %s (домен x [%v, %v] z [%v, %v])",
			rep.Region, worldMap.Terrain.Domain.MinX, worldMap.Terrain.Domain.MaxX,
			worldMap.Terrain.Domain.MinZ, worldMap.Terrain.Domain.MaxZ)
	} else {
		log.Printf("мир уже есть: регион %s, база не тронута", rep.Region)
	}

	// Прогрев: явный шаг того, кто запускает, и только для свежего засева
	// (см. ключ -preheat выше). Порождение по требованию уже построено ниже и
	// посчитает всё недостающее само — прогрев лишь делает первые запросы
	// клиента попаданиями в базу.
	//
	// Строки ложатся ПОД ВЕРСИЮ МИРА, которую назвала голова проекций:
	// бутстрап завёл её версией 1, и прогрев обязан совпасть с ней, иначе
	// разошлись бы неверсионный адрес (текущий мир) и версионные (публикации).
	if *preheat && seeded {
		head, ok, err := world.GetProjectionHead(rep.Region)
		if err != nil {
			log.Fatalf("голова проекций: %v", err)
		}
		if !ok {
			log.Fatalf("голова проекций региона %s не заведена", rep.Region)
		}
		warm, err := worldgen.GenerateSources(world, &committed, src, rep.Region, worldRevision, head.WorldVersion)
		if err != nil {
			log.Fatalf("прогрев мира: %v", err)
		}
		log.Printf("мир прогрет: чанков %d, %.1f МБ", warm.TotalChunks, float64(warm.TotalBytes)/1e6)
	}

	// Порождение по требованию строится ОДИН РАЗ на старте, а не на запрос.
	//
	// Цена постройки поля — выборка оси и два индекса — замерена
	// (BenchmarkFieldConstruction, M2 Pro): 82 мкс на затравке, 583 мкс на оси
	// 20 км, 5.7 мс на 200 км, 62 мс на 2000 км. Один чанк при этом стоит 2.7 мс
	// и от длины оси НЕ ЗАВИСИТ. То есть на запрос поле строить нельзя уже на
	// карте средней длины: постройка обогнала бы саму работу и, в отличие от
	// неё, росла бы вместе с сетью. На старте же это единовременные доли
	// секунды даже на сети в две тысячи километров.
	//
	// Держать поле общим безопасно: terrain.Field после New не меняется, и это
	// не рассуждение, а замер — BenchmarkChunkGenerationParallel гоняет
	// ChunkHeights на всех ядрах сразу.
	//
	// Отказ здесь — отказ СТАРТА, а не тихая работа без порождения: сервер,
	// который не может посчитать недостающее, отвечал бы пустотой там, где
	// земля есть, и клиенту это было бы неотличимо от края мира.
	lazy, err := worldgen.NewLazySources(world, &committed, src, rep.Region, worldRevision)
	if err != nil {
		log.Fatalf("порождение чанков по требованию: %v", err)
	}

	// КОМПОЗИЦИЯ ЖИВЁТ ЗДЕСЬ, а не внутри обработчиков.
	//
	// Каждая ручка знает ровно своё хранилище: сети — mapstore, чанков —
	// worldstore. Появление третьего хранилища добавит строку сюда и не тронет
	// ни одного существующего обработчика. Обратный порядок — передать второе
	// хранилище в обработчик карт и разветвлять путь внутри его ServeHTTP —
	// сделал бы его корнем композиции для всего мира.
	//
	// У корня /regions/ ровно поэтому такая форма: сеть региона лежит в
	// mapstore, рельеф — в worldstore, а собрать один корень из двух хранилищ
	// вправе только тот, кто открыл оба, — то есть main. Роутер получает готовые
	// подручки и не знает ни одного хранилища; манифест региона — единственный,
	// кому нужны оба, и оба приходят ему аргументами, а не через соседа.
	// Набор контента — ТРЕТЬЕ хранилище рядом с картой и миром, и появление его
	// добавило строку сюда, не тронув ни одного существующего обработчика:
	// ровно то, ради чего композиция и живёт в main.
	// КОМПИЛЯТОР АДРЕСНОЙ ПЕРЕСБОРКИ — часть боевой композиции (sqym.18):
	// замыкание по правке, пересборка ровно затронутых чанков, публикация под
	// новой версией мира. Несёт с собой правки высот и вырубку (src) и позицию
	// журнала коммитов (editSvc.JournalSeq): пересобранный мир обязан быть
	// построен ДО той же позиции журнала, которую назовёт голова проекций.
	// Сегодня его держит только композиция — ручки команд строителя это шаг 12
	// эпика, и до них Rebuild зовётся лишь из тестов.
	compiler := worldgen.NewCompilerSources(world, rep.Region, worldRevision, editSvc.JournalSeq(), src)
	_ = compiler

	set, err := content.Load(*contentDir)
	if err != nil {
		log.Fatalf("набор контента (ключ -content): %v", err)
	}
	log.Printf("набор контента %s: паспортов %d, ассетов %d, перечень %s",
		*contentDir, len(set.Stock), len(set.Assets), set.Hash[:12])

	// Партия поднимается ПОСЛЕ карты и набора, потому что проверяет расстановку
	// об обоих: тип берётся из набора, элемент и его длина — из скомпилированной
	// сети. Отказ здесь — отказ старта: расстановка, которую нельзя проверить,
	// не должна доехать до клиента полусобранной.
	game, err := match.Start(matchID, *placement, st.Network, set)
	if err != nil {
		log.Fatalf("расстановка (ключ -placement): %v", err)
	}
	if n := len(game.Units); n > 0 {
		log.Printf("партия %s: подвижных единиц %d", game.ID, n)
	}

	// ХОД ВРЕМЕНИ. С этой строки партия перестаёт быть неподвижной картинкой:
	// движок берёт её во владение, и читать её по указателю `game` дальше
	// нельзя — отсюда он никуда больше не передаётся.
	//
	// Петля пускается ДО HTTP-сервера, а не после: иначе первый запрос,
	// пришедший в ту же миллисекунду, увидел бы мир, в котором время ещё стоит,
	// и разница была бы не в числах, а в объяснении — «у вас сервер иногда
	// отдаёт нулевое время» ловится потом днями.
	//
	// Контекст здесь Background и отмены не имеет НАРОЧНО: у сервера нет мягкого
	// завершения вовсе (разбор — у ключа -quit-after ниже), и заводить его ради
	// одной петли значило бы городить остановку для процесса, который гасится
	// os.Exit. Отмена нужна тем, кто крутит движок в тестах, и там она есть.
	sim := engine.New(game)
	go sim.Run(context.Background())
	log.Printf("время партии %s идёт: тик %s", game.ID, engine.TickDuration)

	mux := http.NewServeMux()
	// Каталог регионов — БЕЗ косой черты, и это не опечатка рядом со строкой
	// ниже: у ServeMux "/regions" адресует один ресурс, "/regions/" — поддерево.
	// Список того, во что можно войти, и есть отдельный ресурс, а не корень
	// чужих подресурсов.
	mux.Handle("/regions", httpapi.NewRegionCatalogHandler(world, store))
	mux.Handle("/regions/", httpapi.NewRegionsHandler(
		httpapi.NewRegionManifestHandler(world, store),
		httpapi.NewNetworkHandler(store),
		// Ручка чанков получает ДВА источника, и порядок между ними — её дело:
		// база отвечает первой, рецепт считает недостающее. Сюда это приходит
		// двумя аргументами ровно потому, что решение «база стала кэшем»
		// принимает тот, кто собирает сервер, а не тот, кто отдаёт байты.
		httpapi.NewChunksHandler(world, lazy),
		httpapi.NewObjectsHandler(store),
		httpapi.NewLiveHandler(sim),
		// КАНАЛ КОМАНД: один сокет, JSON-RPC 2.0 в обе стороны (ClearAhead-wa51).
		// Источник идентификаторов — системный: предсказуемая
		// последовательность нужна тестам, а боевой сессии нужна
		// неугадываемость, потому что session_id возвращается клиентом при
		// переподключении и служит ключом к его ключам идемпотентности.
		channel.NewHandler(sim, uuidv7.New, set),
	))
	// ВЕРСИОННЫЕ АДРЕСА МИРА (sqym.5): /matches/{m}/worlds/{v}/… отдают
	// замороженные публикации с immutable. Матч один (matchID), регион — тот,
	// что засеял бутстрап; каталог партий появится вместе со второй партией.
	mux.Handle("/matches/", httpapi.NewWorldsHandler(matchID, rep.Region, world))
	// Набор контента и байты ассетов — БЕЗ региона в адресе, и это решение, а не
	// экономия: «ВЛ80 — общий контент, к карте отношения не имеет» (владелец,
	// 2026-08-13). Блоб под регионом означал бы, что второй регион качает те же
	// байты заново, потому что у них разный адрес при одинаковом содержимом.
	mux.Handle("/content", httpapi.NewContentHandler(set))
	mux.Handle("/assets/", httpapi.NewBlobHandler(set))
	mux.Handle("/", httpapi.NewHandler(store))

	// http.ListenAndServe не ставит ни одного таймаута: соединение, которое
	// медленно шлёт заголовки, держит горутину бесконечно. На LAN-игре это не
	// катастрофа, но таймауты стоят четыре строки и ставятся сразу.
	srv := &http.Server{
		Addr:              *addr,
		Handler:           mux,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      60 * time.Second,
		IdleTimeout:       120 * time.Second,
		MaxHeaderBytes:    1 << 16,
	}
	// Срок жизни ставится ДО ListenAndServe и на выходе не снимается: он
	// отсчитывается от старта, а не от последнего запроса. Отсчёт от запроса дал
	// бы «пока пользуются — живи», и сервер, к которому проверка ходит в цикле,
	// не погас бы никогда — то есть ровно тот случай, ради которого ключ заведён.
	//
	// Завершение ЖЁСТКОЕ (os.Exit), а не мягкое: у мира нет состояния, которое
	// стоило бы дописать на выходе, — карта на диске, чанки в базе, обе записаны
	// до первого запроса. Мягкое завершение стоило бы контекста и канала ради
	// того, чтобы дождаться незавершённой выдачи чанка, которую всё равно никто
	// не читает: тот, кто запустил сервер со сроком, к этой минуте уже ушёл.
	if *quitAfter > 0 {
		log.Printf("погасну через %s (ключ -quit-after)", *quitAfter)
		time.AfterFunc(*quitAfter, func() {
			log.Printf("срок вышел (%s) — гасну", *quitAfter)
			os.Exit(0)
		})
	}

	log.Printf("слушаю %s", *addr)
	log.Fatal(srv.ListenAndServe())
}

// provenanceOf — происхождение региона: откуда пришла карта.
//
// Строка едет в базу и оттуда в каталог регионов, поэтому это JSON, а не текст:
// читателю нужен источник отдельно от вида, а не одна фраза, которую придётся
// разбирать глазами. Путь пишется как есть — он и есть ответ на вопрос «что у
// меня в мире»; kind говорит, что карта авторская, а не порождена импортом.
func provenanceOf(path string) string {
	b, err := json.Marshal(map[string]string{"source": path, "kind": "authored"})
	if err != nil {
		// Строка и строка: сериализация двух строк не может отказать иначе, чем
		// от порчи памяти, и молчаливая пустота здесь была бы хуже паники.
		panic("clearahead: провенанс не сериализуется: " + err.Error())
	}
	return string(b)
}

// dropWorld сносит базу мира ЦЕЛИКОМ и говорит, что снёс.
//
// # Что сносится и что нет — решение W6-B (бида ClearAhead-26g)
//
// Сносится ПРОЕКЦИЯ: чанки, регионы, головы проекций, тела сетей. Исходники
// сносу не подлежат — карта живёт файлом, а закоммиченное партии (правки
// высот, вырубка, журнал коммитов, закоммиченная карта) — в ОТДЕЛЬНОЙ базе
// sourcestore (ключ -sources), которой -reseed не касается вовсе: проекцию
// сносить можно всегда, исходник — нет. Выбран первый рог развилки из брифа
// W6-B: правки хранятся ОТДЕЛЬНО от развёрнутых чанков и переживают пересев
// (чанк остаётся производным, исходник живёт своей жизнью). В базу чанков
// исходники не ложатся НИКОГДА, и пересев не может их стереть — это держит
// сторож assertProjectionsOnly; сам сторож и хранилище, которое он
// подразумевает, разведены по двум файлам (sqym.18).
//
// # Почему удаление файла, а не удаление региона средствами worldstore
//
// Точнее было бы снести один регион с его чанками: файл может нести и то, чего
// затравка не порождала. Но такой операции у worldstore НЕТ, и заводить её
// пришлось бы ради единственного вызывающего — ключа рабочего цикла. Это ровно
// «форма без потребителя» (`map-format-design` §8), да ещё и самая опасная из
// возможных: удаление.
//
// Цена выбора названа прямо: сносится ВСЁ, включая регионы, которых эта карта не
// заводила. Сегодня их не бывает — регионы заводит только бутстрап, и только по
// одной карте, — а перестанет быть правдой вместе со вторым источником регионов.
//
// # Почему снос громкий
//
// Тихий снос неотличим от «базы не было»: и там и там сервер стартует и засевает
// мир. Разница видна, только если назвать её числами — сколько чанков и сколько
// байт исчезло.
func dropWorld(path string) error {
	info, err := os.Stat(path)
	if os.IsNotExist(err) {
		log.Printf("пересоздание мира: базы %s не было, сносить нечего", path)
		return nil
	}
	if err != nil {
		return err
	}

	// Сторож исходников: база, несущая таблицы вне набора проекций, — база с
	// работой игрока внутри, и -reseed обязан отказать, а не стереть.
	if err := assertProjectionsOnly(path); err != nil {
		return err
	}

	// Считаем ДО сноса и через тот же worldstore, которым база написана: свой
	// SQL здесь означал бы второе место, знающее форму таблицы чанков.
	// Отдельного «сколько всего» у него нет, поэтому счёт по уровням — заодно
	// видно, что снесено, а не только сколько.
	chunks := 0
	if st, err := worldstore.Open(path); err == nil {
		regions, err := st.ListRegions()
		if err == nil {
			for _, r := range regions {
				// По потолку ФОРМЫ, а не по правилу региона: база сносится в том
				// числе тогда, когда правило в ней неизвестно или разошлось с
				// картой, — а считать надо всё, что в ней лежит.
				for level := 0; level <= chunk.MaxLevelLimit; level++ {
					n, err := st.CountChunks(r.ID, level)
					if err != nil {
						break
					}
					chunks += n
				}
			}
		}
		st.Close()
	}

	// Спутники SQLite сносятся вместе с базой: журнал, оставшийся от снесённого
	// файла, следующее открытие либо отвергнет, либо накатит на пустую базу.
	for _, suffix := range []string{"", "-wal", "-shm", "-journal"} {
		if err := os.Remove(path + suffix); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	log.Printf("пересоздание мира: база %s снесена — было %d чанков, %.1f МБ на диске",
		path, chunks, float64(info.Size())/1e6)
	return nil
}

// projectionTables — таблицы, которые мир держит в базе: регионы, чанки,
// головы проекций, тела сетей. ВСЁ это проекции, и сносить их можно всегда.
// Таблицы-исходники (журнал партии, правки высот) в набор НЕ входят: их снос
// уничтожил бы работу игрока и выглядел бы как «правка не сработала» — отказ
// без следа, худший вид дефекта. Список обязан расти вместе со схемой
// worldstore: таблица вне набора не «ломает» -reseed, а честно его
// останавливает, и остановка читается как сигнал — сознательно расширить
// набор или не сносить.
var projectionTables = map[string]bool{
	"regions":          true,
	"chunks":           true,
	"projection_heads": true,
	"network_versions": true,
}

// assertProjectionsOnly проверяет, что база несёт ТОЛЬКО проекции.
//
// Сторож решения W6-B: пересев сносит проекции и не трогает исходники.
// Сегодня база проекции и есть — правки живут с закоммиченным миром, — но
// сторож стоит не для сегодняшнего дня, а для того дня, когда в базе появится
// таблица-исходник: молчаливый снос такой базы стёр бы работу игрока, и
// выглядело бы это как «правка не сработала». Отказ, а не подстановка:
// названная таблица — факт, и решает по нему человек, а не код.
func assertProjectionsOnly(path string) error {
	db, err := sql.Open("sqlite", "file:"+path+"?mode=ro")
	if err != nil {
		return fmt.Errorf("пересоздание мира: открыть базу %s для проверки: %w", path, err)
	}
	defer db.Close()
	rows, err := db.Query(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'`)
	if err != nil {
		return fmt.Errorf("пересоздание мира: чтение таблиц базы %s: %w", path, err)
	}
	defer rows.Close()
	var foreign []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return fmt.Errorf("пересоздание мира: чтение таблиц базы %s: %w", path, err)
		}
		if !projectionTables[name] {
			foreign = append(foreign, name)
		}
	}
	if err := rows.Err(); err != nil {
		return fmt.Errorf("пересоздание мира: чтение таблиц базы %s: %w", path, err)
	}
	if len(foreign) > 0 {
		return fmt.Errorf("пересоздание мира: база %s несёт таблицы-исходники: %s — снос уничтожил бы работу игрока; пересев сносит только проекции (решение W6-B)",
			path, strings.Join(foreign, ", "))
	}
	return nil
}
