// Lazy — порождение чанка ПО ТРЕБОВАНИЮ. База при этом перестаёт быть
// единственным источником рельефа и становится кэшем.
//
// # Зачем
//
// Прогрев (Generate) выбирает подробность БЛИЗОСТЬЮ К ОСИ: уровень 0 кладётся
// только внутри R_0 — на затравке это 512 м от рельсов. Клиент же выбирает
// подробность КАМЕРОЙ: спустился к земле в трёх километрах от дороги — и ему
// нужен уровень 0 там, где прогрев не породил ничего грубее четвёртого. Сервер
// на такой запрос отвечал 204, и починить это клиент не мог ничем: крупный план
// оставался мыльным навсегда.
//
// Отсюда разделение ролей: прогрев решает, что положить ЗАРАНЕЕ, а Lazy —
// что вправе посчитать, когда спросят. Первое осталось нетронутым, второе
// добавлено рядом.
//
// # Почему это дёшево
//
// Замер (BenchmarkChunkGeneration*, M2 Pro): один чанк — 2.7 мс у станции,
// 1.8 мс вдали от оси, 0.33 мс на чанк в несколько потоков. Стоимость НЕ
// ЗАВИСИТ от длины пути (0.99 мс при оси 2 км и 1.03 мс при 2000 км): удаление
// до оси берётся по индексу, а не перебором. Один запрос по петле стоит ~90 мкс
// у ручки и порядка десятков миллисекунд у настоящего клиента, так что
// порождение — единицы процентов круга обращения.
//
// # Что от этого НЕ меняется
//
// Охват. Ключ terrain.extent объявляет, докуда мир существует вообще, и за
// пределом по-прежнему пустота, а не бесконечная земля (inExtent). Уровень выше
// объявленного — отказ. Правило подробности региона — тоже: поле строится тем
// же prepare, что и у прогрева, а он отказывается работать, если правило в базе
// разошлось с картой.
type Lazy struct {
	store *worldstore.Store
	// sel держит и поле, и правило, и габарит оси. Поле после terrain.New не
	// меняется, поэтому читать его из многих горутин можно без блокировки —
	// это не рассуждение, а замер: BenchmarkChunkGenerationParallel гоняет
	// ChunkHeights на всех ядрах сразу и под -race.
	sel      selector
	region   string
	revision int64
	baseZmm  int64
	flights  flightGroup
}

// NewLazy строит порождение по требованию для одного региона.
//
// Карта приходит документом, а не готовым полем, и это то же решение, что у
// Bootstrap: знание «карта -> рельеф» живёт в конвейере входа, а не у того, кто
// его вызывает. Иначе композиция в main.go обзавелась бы собственными
// track.Propagate и terrain.New — второй копией пути входа в месте, где его
// никто не проверяет.
//
// Отказ здесь — отказ СТАРТА: регион не заведён, карта не проходит валидацию,
// правило подробности разошлось с записанным в базе. Молча поднять сервер,
// который считает чанки не тем правилом, каким засеян мир, нельзя: снаружи это
// выглядит исправным миром с невидимым швом.
func NewLazy(s *worldstore.Store, m *mapfmt.Map, region string, revision int64) (*Lazy, error) {
	sel, err := prepare(s, m, region)
	if err != nil {
		return nil, err
	}
	return &Lazy{
		store:    s,
		sel:      sel,
		region:   region,
		revision: revision,
		// Опорная высота берётся из рецепта и одна на весь регион — ровно как у
		// прогрева. Считать её у каждого чанка заново значило бы получить два
		// округления одного числа и, рано или поздно, две разные базы отсчёта.
		baseZmm: int64(math.Round(sel.field.BaseZ() * 1000)),
	}, nil
}

// MakeChunk считает недостающий чанк, кладёт его в базу и возвращает.
//
// # Три исхода, и они не сливаются
//
//	(чанк, true, nil)  — посчитан и записан;
//	(_, false, nil)    — ЗАКОННАЯ ПУСТОТА: адрес верен, но земли там нет ни для
//	                     кого (за охватом мира);
//	(_, false, ошибка) — СБОЙ: посчитать или записать не смогли.
//
// Разница между второй и третьей строкой — то, ради чего у метода два признака
// вместо одного. Пустой чанк вместо отказа нарисовал бы игроку ровную землю на
// месте сломанного рецепта, и сломанное выглядело бы исправным.
func (l *Lazy) MakeChunk(a chunk.Address) (worldstore.Chunk, bool, error) {
	// Чужой регион — отказ, а не пустота. Рецепт у сервера ровно один, и
	// «посчитать не могу» здесь не свойство места, а нехватка исходных данных:
	// выдав 204, сервер сказал бы «земли там нет», хотя на самом деле он про ту
	// землю ничего не знает.
	if a.Region != l.region {
		return worldstore.Chunk{}, false, fmt.Errorf(
			"worldgen: чанк региона %s считать нечем: рецепт загружен только для %s", a.Region, l.region)
	}
	// Уровень вне правила региона — отказ по той же причине: такого уровня
	// подробности у этого мира не существует, и вызвавший обязан был отвергнуть
	// адрес раньше (это делает ручка чанков). Тихое «пусто» скрыло бы ошибку
	// вызывающего.
	if a.Level < 0 || a.Level > l.sel.rule.MaxLevel {
		return worldstore.Chunk{}, false, fmt.Errorf(
			"worldgen: уровня %d у региона %s не существует: последний уровень %d",
			a.Level, l.region, l.sel.rule.MaxLevel)
	}
	// Граница мира. Проверяется ДО одиночного полёта: ответ не зависит ни от
	// базы, ни от чужой работы, и держать под него запись в карте полётов
	// значило бы синхронизировать вычисление, которое ничего не делит.
	if !l.sel.inExtent(a) {
		return worldstore.Chunk{}, false, nil
	}
	return l.flights.do(a, func() (worldstore.Chunk, bool, error) { return l.compute(a) })
}

// compute считает чанк, пишет его в базу и отдаёт ПРОЧИТАННЫМ ИЗ БАЗЫ.
//
// # Почему ответ перечитывается, а не собирается из посчитанного
//
// Хеш чанка считает worldstore.PutChunk и наружу не отдаёт — нарочно: он служит
// ETag'ом, и вычисленный вызывающим хеш однажды разошёлся бы с телом. Значит,
// собрать полный ответ на месте всё равно нельзя, и выбор стоит между «вернуть
// половину и дописать хеш вторым способом» и «перечитать». Перечитывание стоит
// 25 мкс (BenchmarkGetChunk/попадание) против 2.7 мс счёта и 80 мкс записи — то
// есть процент к промаху — и даёт то, чего не даёт первый
// вариант: чанк, отданный при промахе, и чанк, отданный при попадании, приходят
// ИЗ ОДНОГО МЕСТА и одной дорогой. Различия между первым и повторным ответом
// взяться неоткуда — их не нужно проверять, их нечем создать.
//
// Заодно это проверка записи: чанк, который база не отдала сразу после
// вставки, — сбой, а не пустота.
func (l *Lazy) compute(a chunk.Address) (worldstore.Chunk, bool, error) {
	// Порядок и состав слоёв те же, что у прогрева (Generate), и по той же
	// причине: покров берётся из того же рецепта в тех же координатах, а лес
	// считается ИЗ ПОКРОВА, отчего инвариант «бит только в лесном классе»
	// держится построением.
	heights, err := l.sel.field.ChunkHeights(a)
	if err != nil {
		return worldstore.Chunk{}, false, err
	}
	cover, err := l.sel.field.ChunkCover(a)
	if err != nil {
		return worldstore.Chunk{}, false, err
	}
	forest := l.sel.field.ChunkForest(a, cover)

	if err := l.store.PutChunk(worldstore.Chunk{
		Address:  a,
		Revision: l.revision,
		BaseZmm:  l.baseZmm,
		Heights:  heights,
		Cover:    cover,
		Forest:   forest,
	}); err != nil {
		return worldstore.Chunk{}, false, err
	}

	c, ok, err := l.store.GetChunk(a)
	if err != nil {
		return worldstore.Chunk{}, false, err
	}
	if !ok {
		return worldstore.Chunk{}, false, fmt.Errorf(
			"worldgen: чанк %s/%d/%d/%d записан и тут же не найден в базе",
			a.Region, a.Level, a.CX, a.CZ)
	}
	return c, true, nil
}

// flightGroup — ОДИНОЧНЫЙ ПОЛЁТ ПО АДРЕСУ: пока чанк считается, второй запрос
// на тот же адрес не считает его заново, а ждёт и получает тот же ответ.
//
// # Почему это, а не транзакция и не мьютекс на всё
//
// Клиент шлёт запросы пачками, и два запроса на один адрес приходят разом
// штатно, а не в редкой гонке. Считать одно и то же дважды — 2.7 мс работы в
// мусор на каждом дубле.
//
// Транзакция базы решала бы ДРУГУЮ задачу — целостность записи, — и не мешала
// бы обеим горутинам посчитать чанк: счёт идёт вне базы. Вторая запись при этом
// не ошибка (PutChunk идемпотентен: ON CONFLICT DO UPDATE, а рельеф выводится
// из рецепта детерминированно, поэтому байты совпадают), но она бессмысленна.
//
// Один мьютекс на всё порождение сериализовал бы НЕЗАВИСИМЫЕ адреса и убил бы
// то, ради чего порождение вообще годится по срокам: 0.33 мс на чанк в
// несколько потоков против 2.7 мс в один (BenchmarkChunkGenerationParallel).
//
// golang.org/x/sync/singleflight делает то же самое, но по строковому ключу и
// ценой первой в проекте зависимости ради тридцати строк; адрес чанка —
// сравнимое значение и годится ключом карты как есть.
//
// # Чего здесь сознательно НЕТ
//
// Перепроверки базы перед счётом. Ручка чанков читает базу непосредственно
// перед вызовом, и второе чтение отвечало бы на тот же вопрос второй раз ради
// узкого окна — между промахом ручки и захватом полёта, — в котором
// пересчитанный чанк всё равно выйдет байт в байт прежним.
type flightGroup struct {
	mu sync.Mutex
	in map[chunk.Address]*flight
}

// flight — один идущий счёт. Результат читают только после закрытия done,
// поэтому лишних блокировок вокруг полей не нужно: закрытие канала
// упорядочивает запись ведущего и чтение ждущих.
type flight struct {
	done chan struct{}
	c    worldstore.Chunk
	ok   bool
	err  error
}

func (g *flightGroup) do(a chunk.Address, fn func() (worldstore.Chunk, bool, error)) (worldstore.Chunk, bool, error) {
	g.mu.Lock()
	if g.in == nil {
		g.in = make(map[chunk.Address]*flight)
	}
	if f, ok := g.in[a]; ok {
		g.mu.Unlock()
		<-f.done
		return f.c, f.ok, f.err
	}
	f := &flight{done: make(chan struct{})}
	g.in[a] = f
	g.mu.Unlock()

	// Паника ведущего не должна оставить ждущих висеть на канале навсегда:
	// повисшая горутина держит соединение и не даёт о себе знать ничем.
	// Поэтому полёт закрывается ВСЕГДА, ждущие получают отказ (а не пустоту,
	// которая выглядела бы законной), а сама паника летит дальше — прятать её
	// здесь значило бы превратить ошибку в коде в загадочный 500 без следа.
	defer func() {
		if r := recover(); r != nil {
			f.ok = false
			f.err = fmt.Errorf("worldgen: порождение чанка %s/%d/%d/%d сорвалось: %v",
				a.Region, a.Level, a.CX, a.CZ, r)
			g.land(a, f)
			panic(r)
		}
		g.land(a, f)
	}()

	f.c, f.ok, f.err = fn()
	return f.c, f.ok, f.err
}

// land снимает полёт с учёта и будит ждущих. Порядок важен: адрес освобождается
// ДО пробуждения, иначе разбуженный успел бы прицепиться к уже завершённому
// полёту и ждать его повторно.
func (g *flightGroup) land(a chunk.Address, f *flight) {
	g.mu.Lock()
	delete(g.in, a)
	g.mu.Unlock()
	close(f.done)
}
