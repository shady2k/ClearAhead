// Package worldgen — конвейер входа: карта попадает в базу мира.
//
// # Инвариант входа
//
// В базу попадает только то, что прошло ПОЛНЫЙ путь входа: разбор, валидацию,
// компиляцию. Правило mapstore «файл, который нельзя загрузить, не пишется»
// переносится сюда дословно (`world-storage` §6). Поэтому Generate сам зовёт
// валидацию и распространение поз, а не доверяет вызывающему.
//
// # Порядок
//
//	карта -> валидация -> распространение поз -> рельеф
//	                                               |
//	                        выбор чанков по удалённости от пути
//	                                               |
//	                                развёртка в отсчёты -> база
//
// # JSON не выбрасывается
//
// Он меняет роль: остаётся обменным и авторским форматом — импорт, экспорт,
// дифф, фикстуры, ручное авторство небольшой станции. Рантайм читает базу.
package worldgen

import (
	"encoding/json"
	"fmt"
	"math"

	"github.com/shady2k/ClearAhead/server/internal/chunk"
	"github.com/shady2k/ClearAhead/server/internal/mapfmt"
	"github.com/shady2k/ClearAhead/server/internal/terrain"
	"github.com/shady2k/ClearAhead/server/internal/track"
	"github.com/shady2k/ClearAhead/server/internal/worldstore"
)

// Report — что получилось. Возвращается вызывающему, а не пишется в лог:
// решать, показывать это человеку или нет, не дело конвейера.
type Report struct {
	Region      string
	ByLevel     map[int]int
	TotalChunks int
	TotalBytes  int
}

// Generate разворачивает карту в чанки и пишет их в базу.
//
// Регион должен быть заведён заранее: у него своя геопривязка и своё
// происхождение, и придумывать их за автора конвейер не вправе.
func Generate(s *worldstore.Store, m *mapfmt.Map, region string, revision int64) (Report, error) {
	rep := Report{Region: region, ByLevel: map[int]int{}}

	if _, ok, err := s.GetRegion(region); err != nil {
		return rep, err
	} else if !ok {
		return rep, fmt.Errorf("worldgen: региона %s нет в базе; заведите его до порождения чанков", region)
	}

	// Полный путь входа. Валидация зовётся здесь, а не предполагается
	// сделанной: инвариант базы держится этим вызовом.
	if err := mapfmt.Validate(m); err != nil {
		return rep, fmt.Errorf("worldgen: карта не прошла валидацию: %w", err)
	}
	_, els, err := track.Propagate(m)
	if err != nil {
		return rep, fmt.Errorf("worldgen: распространение поз: %w", err)
	}
	if m.Terrain == nil {
		return rep, fmt.Errorf("worldgen: у карты нет рельефа; порождать нечего")
	}
	field, err := terrain.New(m, els)
	if err != nil {
		return rep, fmt.Errorf("worldgen: рельеф: %w", err)
	}

	minX, minY, maxX, maxY, ok := field.Bounds()
	if !ok {
		return rep, fmt.Errorf("worldgen: у карты нет ни одной точки оси")
	}

	baseZmm := int64(math.Round(field.BaseZ() * 1000))
	sel := selector{field: field, minX: minX, minY: minY, maxX: maxX, maxY: maxY}

	_, _, err = walk(sel, region, sel.covers, func(a chunk.Address) error {
		heights, err := field.ChunkHeights(a)
		if err != nil {
			return err
		}
		// Покров разворачивается тем же проходом, что и высоты, а не отдельным:
		// оба берутся из одного рецепта в одних координатах, и второй обход
		// стоил бы ровно столько же, сколько первый, ради разделения, которого
		// никто не просил. nil означает карту без рецепта покрова — законное
		// состояние, отличимое от пустого покрова.
		cover, err := field.ChunkCover(a)
		if err != nil {
			return err
		}
		if err := s.PutChunk(worldstore.Chunk{
			Address:  a,
			Revision: revision,
			BaseZmm:  baseZmm,
			Heights:  heights,
			Cover:    cover,
		}); err != nil {
			return err
		}
		rep.ByLevel[a.Level]++
		rep.TotalChunks++
		rep.TotalBytes += chunk.HeightsBytes + len(cover)
		return nil
	})
	if err != nil {
		return rep, err
	}
	return rep, nil
}

// selector — правило покрытия, применённое к одному полю. Габарит оси хранится
// рядом с полем: он нужен и обходу, и отсеву дальних клеток.
type selector struct {
	field                  *terrain.Field
	minX, minY, maxX, maxY float64
}

// probesPerSide — на сколько частей делится сторона клетки, когда решить о ней
// одним запросом не удалось. Число названо в covers вместе с ценой ошибки.
const probesPerSide = 16

// covers решает, порождается ли клетка по адресу a.
//
// # Пирамида, а не полосы
//
// Уровень L независимо покрывает ВСЁ в пределах своего радиуса R_L, а не кольцо
// между R_{L-1} и R_L. Круги уровней вложены, клиент рисует самый подробный из
// доступных.
//
// Прежнее правило — «хранить клетку уровня L тогда и только тогда, когда
// LevelFor(расстояние от ЦЕНТРА клетки) == L» — утверждало, что полосы
// удалённости не пересекаются и не оставляют пропусков. Это неверно: полосы
// заданы расстоянием, а клетки нарезаны сетками РАЗНОГО шага, и границы
// объединений клеток не совпадают. Замер клиентом на затравке: 6.57 % площади
// не покрыто ни одним уровнем, 2.50 % покрыто двумя; дыры видны на снимке
// экрана чёрными квадратами (ClearAhead-cue). Свой замер прежнего правила
// (TestCoverageHasNoHoles) на другой сетке проб даёт 18.07 % непокрытой площади
// вблизи пути и 18.75 % по всему охвату: окно проб другое, дефект тот же.
//
// # Отвергнуто: оставить полосы, но мерить по ближайшей точке клетки
//
// Дыры этим не устраняются, и вот арифметика, чтобы к варианту не возвращаться.
// Путь прямой вдоль y = 0:
//
//	клетка уровня 0 [768, 1024]: ближайшая точка 768 м, LevelFor(768) = 1,
//	значит на уровне 0 не хранится;
//	клетка уровня 1 [512, 1024]: ближайшая точка 512 м, LevelFor(512) = 0,
//	значит на уровне 1 не хранится;
//	точка y = 900 не покрыта ни одной из двух.
//
// # Отвергнуто: квадродерево «родитель есть, если не все дети есть»
//
// Покрытие есть ИЗМЕНЯЕМОЕ СОСТОЯНИЕ СЕРВЕРА, а не формула: режим строителя
// меняет его на ходу, и клетка, бывшая уровня 3, становится уровня 0. Если
// правильность картинки зависит от того, повторил ли клиент правило сервера
// в точности — включая шаг выборки оси, порядок округления и включённость
// границ, — контракт слишком хрупок. При пирамиде ошибка клиента даёт менее
// подробную землю, а не чёрную дыру.
//
// # По ТЕЛУ клетки, а не по её центру
//
// Дыр не даёт ни то ни другое: точку с расстоянием d покрывает уровень L+1,
// даже если центр её клетки уровня L вышел за R_L. Разница в ГАРАНТИИ на краю.
// По центру уровень не покрывает свой круг целиком: у границы остаётся рваная
// кайма шириной до полудиагонали клетки — 181 м на уровне 0 и 2896 м на
// последнем. На мелких уровнях это «у края будет земля грубее», а на ПОСЛЕДНЕМ
// уровне грубее уже нечего: там кайма — это площадь, не покрытая никем.
// По телу правило выразимо одной фразой: внутри R_L земля есть на уровне L.
//
// Цена измерена, а не оценена (TestRuleCost). Прямой коридор 200 км:
// 4640 чанков прежним правилом, 6120 пирамидой по центру (× 1.32), 7663
// пирамидой по телу (× 1.65) — то есть тело стоит ещё +25 % к пирамиде по
// центру. На затравке отношение выше (55 -> 73 -> 124, × 2.25): у короткой
// станции почти вся стоимость — круги дальних уровней, и они не растут вместе с
// путём. Пересчёт на сеть 2000 км по длинному коридору: 392 МБ прежним правилом
// (прежняя оценка в chunk давала 388 МБ — сходится), 517 МБ по центру, 648 МБ
// по телу.
func (s selector) covers(a chunk.Address) bool {
	side := chunk.SideM(a.Level)
	r := chunk.RadiusM(a.Level)
	x0, z0 := a.OriginM()

	// Габаритный отсев. Ось лежит внутри своего габарита, поэтому клетка,
	// удалённая от габарита дальше r, круга не достаёт заведомо. Стоит это
	// четыре вычитания и снимает запрос к индексу с каждой дальней клетки —
	// а дальних тем больше, чем больше сеть.
	if rectGap(x0, z0, x0+side, z0+side, s.minX, s.minY, s.maxX, s.maxY) > r {
		return false
	}

	// Расстояние до оси 1-липшицево: сдвиг точки на t меняет его не более чем
	// на t. Отсюда два решения по одному запросу в центре клетки.
	half := side * math.Sqrt2 / 2
	d, ok := s.field.DistanceToAxis(x0+side/2, z0+side/2)
	// Оракул отвечает лишь до радиуса последнего уровня; дальше он говорит
	// «не знаю», и это само по себе нижняя оценка.
	lower := d
	if !ok {
		lower = chunk.RadiusM(chunk.MaxLevel)
	}
	switch {
	case ok && d <= r:
		return true // центр внутри круга — тело тем более пересекает
	case lower-half > r:
		return false // ближе полудиагонали к центру подойти нельзя
	}

	// Осталась клетка, через которую проходит сама граница круга. Её решают
	// пробы по решётке шага side/probesPerSide, включая границу клетки.
	//
	// Липшицевой оценки здесь недостаточно: на последнем уровне предел оракула
	// СОВПАДАЕТ с проверяемым радиусом, поэтому доказать отдалённость нечем и
	// оценка объявила бы неопределённой всю дальнюю площадь. Поэтому решают
	// пробы, а ошибка ограничена кривизной: граница круга радиуса R отходит от
	// хорды длины g не дальше g²/(8R), а g = R/32 (сторона клетки — половина
	// радиуса), значит потеря не шире R/8192 — 6 см на уровне 0 и 1 м на
	// последнем. На уровнях мельче последнего эта полоса лежит глубоко внутри
	// круга следующего уровня и покрыта им; на последнем это метровая кайма на
	// восьми километрах, где отсутствие чанка и так законно.
	step := side / probesPerSide
	for i := 0; i <= probesPerSide; i++ {
		for j := 0; j <= probesPerSide; j++ {
			d, ok := s.field.DistanceToAxis(x0+float64(i)*step, z0+float64(j)*step)
			if ok && d <= r {
				return true
			}
		}
	}
	return false
}

// rectGap — расстояние между двумя прямоугольниками, 0 если пересекаются.
func rectGap(ax0, az0, ax1, az1, bx0, bz0, bx1, bz1 float64) float64 {
	dx := math.Max(0, math.Max(bx0-ax1, ax0-bx1))
	dz := math.Max(0, math.Max(bz0-az1, az0-bz1))
	return math.Hypot(dx, dz)
}

// walk перебирает клетки-кандидаты всех уровней и зовёт fn на тех, которые rule
// велит хранить. Возвращает, сколько адресов рассмотрено и сколько отобрано.
//
// Обход отделён от правила нарочно: цену правила меряют, подставляя сюда другое
// (coverage_test.go), и мерить приходится тем же обходом, каким порождают, —
// иначе замер говорил бы о копии, а не о конвейере.
//
// Кандидаты берутся по габариту оси, расширенному на радиус УРОВНЯ, а не на
// предельный радиус: дальше своего круга уровень не хранится, и расширять обход
// нулевого уровня на восемь километров значило бы обойти в тысячу раз больше
// пустых адресов, чем нужно.
func walk(s selector, region string, rule func(chunk.Address) bool, fn func(chunk.Address) error) (candidates, kept int, err error) {
	for level := 0; level <= chunk.MaxLevel; level++ {
		side := chunk.SideM(level)
		r := chunk.RadiusM(level)
		c0x := int(math.Floor((s.minX - r) / side))
		c1x := int(math.Floor((s.maxX + r) / side))
		c0y := int(math.Floor((s.minY - r) / side))
		c1y := int(math.Floor((s.maxY + r) / side))

		for cx := c0x; cx <= c1x; cx++ {
			for cz := c0y; cz <= c1y; cz++ {
				a := chunk.Address{Region: region, Level: level, CX: cx, CZ: cz}
				candidates++
				if !rule(a) {
					continue
				}
				kept++
				if fn != nil {
					if err := fn(a); err != nil {
						return candidates, kept, err
					}
				}
			}
		}
	}
	return candidates, kept, nil
}

// Bootstrap заполняет пустую базу затравочной картой.
//
// # Зачем это здесь
//
// Карта больше не лежит файлом: JSON удалён из проекта целиком. Значит должен
// существовать путь, которым мир появляется на чистой машине, и это код, а не
// файл. Затравка строится фабрикой seedmap — той же, что порождает фикстуры
// тестов, поэтому она не может разойтись со схемой формата: карта, переставшая
// быть валидной, перестаёт компилироваться.
//
// # Идемпотентность
//
// Если регион уже заведён, не делается НИЧЕГО. Бутстрап обязан быть безопасным
// при каждом старте: перезапись существующего мира затравкой уничтожила бы
// правки, сделанные редактором.
func Bootstrap(s *worldstore.Store, m *mapfmt.Map, revision int64) (Report, bool, error) {
	region := m.MapID
	if _, ok, err := s.GetRegion(region); err != nil {
		return Report{}, false, err
	} else if ok {
		return Report{Region: region}, false, nil
	}

	frame := "{}"
	if m.Georeference != nil {
		if b, err := json.Marshal(m.Georeference); err == nil {
			frame = string(b)
		}
	}
	err := s.PutRegion(worldstore.Region{
		ID:    region,
		Frame: frame,
		// Затравка порождена нами и распространяема без оговорок: у неё нет
		// внешнего источника, а значит нет и чужой лицензии.
		Provenance:      `{"source":"seedmap","kind":"generated"}`,
		Redistributable: true,
		Epoch:           1,
	})
	if err != nil {
		return Report{}, false, err
	}

	rep, err := Generate(s, m, region, revision)
	return rep, true, err
}
