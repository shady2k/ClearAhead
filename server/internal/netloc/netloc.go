// Package netloc — адрес на сети: где именно находится объект.
//
// Один тип на все слои. До этого пакета протяжённость была выражена ПЯТЬЮ
// раздельными типами в трёх координатных пространствах, и направление несли
// два из пяти:
//
//	mapfmt.SpanInterval    файл, u        направления нет
//	mapfmt.RunSpan         файл, u        направление есть
//	track.TrackSpanS       компиляция, s  направления нет
//	track.RenderSpan       провод, u      направления нет
//	track.RenderRunSpan    провод, u      направление есть
//
// Потребность в направлении проект обнаружил при работе над решёткой и закрыл
// в одном слое; остальные четыре остались без него. Разбор —
// .internal/specs/2026-08-11-map-content-design.md §3, бида ClearAhead-xm7.
//
// # Почему координата — параметр типа
//
// Авторская u (метры, float, вдоль горизонтальной проекции) и скомпилированная
// s (целые микрометры, пространственная длина оси) — РАЗНЫЕ величины
// (map-format-design §3). Их смешение не даёт отказа загрузки: оно даёт
// правдоподобную, но физически неверную симуляцию — это ровно та ошибка, ради
// исправления которой переписывалась первая редакция формата.
//
// Здесь она закрыта системой типов: Interval[float64] и
// Interval[units.Distance] несовместимы, и присвоить одно другому нельзя.
// Общей остаётся форма, а не координата.
//
// # Чего здесь пока нет и почему
//
// Точечный адрес (LinearElementRef спеки §8) и упорядоченный проход через
// порты (PathLocation) в пакет НЕ заведены: у них сегодня нет ни одного
// потребителя, а map-format-design §8 прямо запрещает объявлять форму без
// потребителя — «объявленная форма без потребителя окажется неверной». Оба
// входят сюда в тот день, когда появится первый вызывающий: точка — с
// сигналами и предельными столбиками, проход — с маршрутами.
package netloc

import (
	"fmt"

	"github.com/shady2k/ClearAhead/server/internal/units"
)

// Именованные координатные пространства. Их ровно два, и называет их этот
// пакет, чтобы каждый слой не изобретал своё имя для того же самого.
//
// U — авторская координата вдоль горизонтальной проекции: метры, float, так
// записан файл карты и так уходит на провод (клиент не имеет цепочки
// вертикального профиля и восстановить размещение по s не способен).
//
// S — скомпилированная пространственная длина оси: целые микрометры, в ней
// живут занятость, длина состава и тормозной путь.
type (
	IntervalU = Interval[float64]
	LinearU   = Linear[float64]
	IntervalS = Interval[units.Distance]
	LinearS   = Linear[units.Distance]
)

// Coord — координата вдоль элемента: метры u (float64) или микрометры s
// (units.Distance, то есть int64). Ограничение намеренно узкое: третьего
// координатного пространства в проекте нет, и появление нового должно быть
// заметным изменением здесь, а не тихим следствием.
type Coord interface {
	~float64 | ~int64
}

// Direction — направление прохождения относительно РОСТА u элемента.
//
// В файле карты необязательно, и это не небрежность: у платформы направления
// нет, а у run'а путевой решётки и у ограничения скорости есть. Пустое
// значение означает «объект направления не имеет», а не «forward».
//
// Умолчание, где оно осмысленно, разрешает КОМПИЛЯТОР до провода — тот же
// приём, что у Construction.DefaultType, и по той же причине: клиент скрытого
// умолчания не применяет никогда.
type Direction string

const (
	// DirNone — у объекта направления нет. Платформа, здание.
	DirNone Direction = ""
	// DirForward — по росту u элемента.
	DirForward Direction = "forward"
	// DirReverse — против роста u элемента.
	DirReverse Direction = "reverse"
)

// Valid сообщает, что значение допустимо в файле карты.
func (d Direction) Valid() bool {
	return d == DirNone || d == DirForward || d == DirReverse
}

// Directed сообщает, что направление задано явно.
func (d Direction) Directed() bool {
	return d == DirForward || d == DirReverse
}

// Interval — направленный интервал на одном линейном элементе.
//
// From < To ВСЕГДА, независимо от направления. Кодировать направление
// перестановкой концов нельзя по двум причинам: обратный интервал стал бы
// неотличим от ошибки автора, а проверка «в пределах элемента» потеряла бы
// однозначную форму. Протяжённость — геометрия, направление — отдельный факт.
type Interval[C Coord] struct {
	Element   string    `json:"element"`
	From      C         `json:"from"`
	To        C         `json:"to"`
	Direction Direction `json:"direction,omitempty"`
}

// Structural проверяет инварианты, НЕ зависящие от координаты: непустой
// элемент, допустимое направление, порядок концов.
//
// Границ элемента здесь нет намеренно. Ни один слой проекта не держит длину
// элемента в той же координате, что интервал: в файле интервал записан в
// метрах-float, а длина сравнивается в целых микрометрах, потому что округление
// к ближайшему микрометру — правило формата (map-format-design §3), и сравнение
// float'ов отвергало бы интервал, кончающийся ровно на конце элемента. Проверка
// границ поэтому принадлежит слою, который владеет переводом, а общей остаётся
// форма.
func (iv Interval[C]) Structural() error {
	if iv.Element == "" {
		return fmt.Errorf("netloc: пустой идентификатор элемента")
	}
	if !iv.Direction.Valid() {
		return fmt.Errorf("netloc: элемент %s: направление %q, ожидается forward, reverse или пустое",
			iv.Element, iv.Direction)
	}
	if iv.From > iv.To {
		return fmt.Errorf("netloc: элемент %s: интервал [%v, %v] вывернут; направление задаётся полем direction, а не перестановкой концов",
			iv.Element, iv.From, iv.To)
	}
	return nil
}

// Linear — протяжённость на сети: упорядоченный список интервалов.
//
// Список, а не пара смещений на одном ребре: платформа, ограничение скорости и
// участок обнаружения пересекают границы элементов и проходы устройств
// (map-format-design §8).
//
// Интервалы могут быть НЕСВЯЗНЫМИ. Станция или эксплуатационный объект не
// обязаны быть одним непрерывным диапазоном, и требовать связности здесь
// значило бы повторить ошибку первой редакции формата, которая безусловно
// требовала связности карты и конфликтовала с тупиком отстоя.
//
// Порядок интервалов — авторский порядок прохождения, и он значим: для run'а
// решётки по нему идёт фаза укладки.
type Linear[C Coord] []Interval[C]

// Structural проверяет непустоту протяжённости и каждый её интервал.
func (l Linear[C]) Structural() error {
	if len(l) == 0 {
		return fmt.Errorf("netloc: пустая протяжённость")
	}
	for i, iv := range l {
		if err := iv.Structural(); err != nil {
			return fmt.Errorf("netloc: интервал %d: %w", i, err)
		}
	}
	return nil
}

// Directed сообщает, что направление задано у ВСЕХ интервалов.
//
// Проверка нужна там, где направление обязательно по смыслу слоя: run путевой
// решётки укладывается по ходу, и спан без направления в нём — не «объект без
// направления», а недоописанный спан.
func (l Linear[C]) Directed() bool {
	for _, iv := range l {
		if !iv.Direction.Directed() {
			return false
		}
	}
	return len(l) > 0
}
