// Package chunk — геометрия сетки чанков мира.
//
// Числа контракта живут здесь, а не в документе: спека
// .internal/specs/2026-08-11-world-chunk-contract.md описывает их смысл, а
// сходимость проверяется тестом. Прежний приёмочный критерий биды —
// «числа совпадают с chunk_debug.gd» — снят: отладочный слой удалён вместе с
// клиентом, и сверять было не с чем.
//
// НЕ ВСЕ числа контракта здесь: охват мира (докуда порождаются чанки) уехал в
// карту 2026-08-12 и приезжает значением Rule. Разбор, где проходит граница
// между «форма чанка» и «размер мира», — у типа Rule.
//
// # Почему шаг 4 м, а не 5
//
// Согласовано в разговоре было «256 м, шаг 5 м, сетка 53×53». Арифметика не
// сходится: 256/5 = 51.2, а 53 отсчёта дают 260 м. Сторона 256 выбрана ради
// двух свойств — степень двойки (квадродерево делит пополам) и 256 = 8×32
// (чанки травы ложатся без остатка), — и 53×53 достижимо только при стороне
// 260, которая ломает оба.
//
// Шаг 8 м отвергнут по существу: основная площадка пути с откосами имеет
// ширину порядка 11 м, при шаге 8 м на неё приходится один отсчёт и насыпь
// перестаёт читаться как форма. При 4 м их три.
package chunk

import (
	"encoding/binary"
	"fmt"
)

// Геометрия уровня 0. Уровень L вдвое шире и вдвое грубее при том же числе
// отсчётов.
const (
	// SideM0 — сторона чанка уровня 0 в метрах.
	SideM0 = 256
	// StepM0 — шаг сетки уровня 0 в метрах.
	StepM0 = 4
	// Samples — отсчётов по стороне, на любом уровне.
	//
	// Их на единицу больше, чем интервалов: последний ряд и столбец
	// принадлежат одновременно соседнему чанку. Без общего ряда на стыке
	// остаётся щель — соседи не делят вершину, и между треугольниками видно
	// небо.
	Samples = SideM0/StepM0 + 1
	// GrassChunkM — сторона чанка травы. Сторона чанка мира обязана делиться
	// на неё нацело.
	GrassChunkM = 32
)

// Address — ключ чанка (world-storage §4).
type Address struct {
	Region string
	Level  int
	CX, CZ int
}

// SideM — сторона чанка уровня в метрах.
func SideM(level int) float64 {
	side := SideM0
	return float64(side << level)
}

// StepM — шаг сетки уровня в метрах.
func StepM(level int) float64 {
	step := StepM0
	return float64(step << level)
}

// OriginM — координаты угла чанка в системе координат региона.
func (a Address) OriginM() (x, z float64) {
	side := SideM(a.Level)
	return float64(a.CX) * side, float64(a.CZ) * side
}

// SampleM — абсолютные координаты отсчёта (i, j) чанка.
//
// Координаты считаются от угла региона, а не от угла чанка, и это существенно:
// общий узел двух соседних чанков обязан получить бит в бит одно и то же
// значение, а это обеспечивается только тем, что аргумент рельефа у него один.
func (a Address) SampleM(i, j int) (x, z float64) {
	ox, oz := a.OriginM()
	step := StepM(a.Level)
	return ox + float64(i)*step, oz + float64(j)*step
}

// Кодирование отсчётов высоты.
//
// Порядок байт — little-endian, явно и для всех многобайтовых полей: все
// целевые платформы little-endian, а называется это затем, чтобы автору
// адаптера не приходилось угадывать.
//
// Высота — int16 целых сантиметров ОТНОСИТЕЛЬНО base_z чанка. База своя у
// каждого чанка, а не у региона: int16 покрывает ±327,67 м вокруг базы, чего
// хватает на сторону 256 м в любых горах и заведомо не хватает на регион
// 400 × 400 км.

// HeightsBytes — размер блоба высот одного чанка.
const HeightsBytes = Samples * Samples * 2

// EncodeHeights укладывает отсчёты в блоб.
//
// Порядок обхода: строками по возрастанию j, внутри строки по возрастанию i.
// Он часть контракта: клиент читает блоб одним проходом и не имеет иного
// способа узнать раскладку.
func EncodeHeights(h []int16) ([]byte, error) {
	if len(h) != Samples*Samples {
		return nil, fmt.Errorf("chunk: отсчётов %d, ожидалось %d", len(h), Samples*Samples)
	}
	out := make([]byte, HeightsBytes)
	for k, v := range h {
		binary.LittleEndian.PutUint16(out[k*2:], uint16(v))
	}
	return out, nil
}

// DecodeHeights разбирает блоб обратно.
func DecodeHeights(b []byte) ([]int16, error) {
	if len(b) != HeightsBytes {
		return nil, fmt.Errorf("chunk: блоб %d байт, ожидалось %d", len(b), HeightsBytes)
	}
	out := make([]int16, Samples*Samples)
	for k := range out {
		out[k] = int16(binary.LittleEndian.Uint16(b[k*2:]))
	}
	return out, nil
}

// Index — порядковый номер отсчёта (i, j) в блобе.
func Index(i, j int) int { return j*Samples + i }

// Выбор уровня подробности по удалённости от пути.
//
// `world-storage` §5 объявляет «коридор — уровень 0, дальше грубее, за
// пределами интереса — ничего», но числами это задано не было; открытый вопрос
// §10.4 контракта чанков. Здесь он закрыт.
//
// Правило: радиус удваивается вместе с уровнем. Дальше подробность падает ровно
// так же, как растёт сторона чанка, поэтому число чанков в кольце остаётся того
// же порядка.
//
// # Круги вложены, а не смежны
//
// Уровень L покрывает ВСЁ в пределах своего радиуса, а не кольцо между
// радиусами L-1 и L. Уровни перекрываются, и это сознательно: смежные полосы
// оставляли дыры, потому что заданы они расстоянием, а нарезаны сетками разного
// шага (ClearAhead-cue; правило покрытия и цена — worldgen.selector.covers).
//
// Цена перекрытия измерена на прямом коридоре 200 км (worldgen,
// TestRuleCost): хранимых чанков становится 1.65 от прежнего числа. Проверка
// прежнего правила на сети Краснодарского края (2000 км) давала 388 МБ при
// покрытии до 8 км от пути, и замер коридора эту оценку подтверждает (392 МБ);
// пирамида по телу клетки даёт на той же сети 648 МБ. Оценка `world-storage` §1
// для полосы ±1 км была ~430 МБ — пирамида остаётся того же порядка при
// вчетверо большем охвате, вдвое более мелком шаге вблизи пути и без единой
// дыры.

// MaxLevelLimit — потолок номера уровня, задаваемый ФОРМОЙ, а не картой.
//
// Он нужен двум местам, которые правила конкретного региона не знают: разбору
// адреса чанка (уровень из URL недоверен и обязан быть отвергнут до похода в
// базу) и обходу уровней при сносе базы. Обе задачи спрашивают «бывает ли такой
// уровень вообще», а не «есть ли он у этого региона».
//
// Шестнадцать, потому что сторона чанка есть SideM0 << level: на уровне 16 это
// 16 777 216 м — больше диаметра Земли, — а сдвиг остаётся заведомо в пределах
// int на любой платформе. Потолок отвергает мусор, а не выбирает охват: охват
// выбирает карта, и её выбор проверяет mapfmt (MaxDetailLevels, MaxReachM).
const MaxLevelLimit = 16

// Rule — правило подробности: докуда достаёт уровень 0 и сколько уровней всего.
//
// # Почему это значение, а не константы пакета
//
// До 2026-08-12 здесь стояли `Level0RadiusM = 512` и `MaxLevel = 4`, то есть
// охват мира 512·2⁴ = 8192 м решал КОМПИЛЯТОР. Владелец спросил «зачем нам
// такая большая карта, давай маленькую и большую» — и выяснилось, что двумя
// файлами карты это не решается: любая вторая карта получила бы тот же охват в
// восемь километров, каким бы ни был её путь. Это тот же класс дефекта, что
// решён днём раньше для русла реки: русло было кодом и стало данными, а
// НАСКОЛЬКО ВЕЛИК МИР ВОКРУГ КАРТЫ по-прежнему решала сборка.
//
// Числа приезжают из карты (mapfmt.Terrain.Extent) и оттуда же попадают в
// запись региона (worldstore.Region.Rule) и в манифест региона. Клиент их
// читает манифестом и своей копии не держит — ради этого поле chunks в
// манифесте и существует.
//
// # Что осталось константой и почему именно оно
//
// SideM0, StepM0 и выведенное из них Samples картой НЕ ЕЗДЯТ. Разделение
// проходит по вопросу, на который число отвечает:
//
//   - Level0RadiusM и MaxLevel отвечают «КАК ДАЛЕКО тянется мир». Они не меняют
//     ни одного байта на проводе: чанк остаётся HeightsBytes байт, покров —
//     CoverBytes, лес — ForestBytes. Меняется только то, сколько клеток
//     порождается, — а это ровно тот вопрос, который задал владелец;
//   - SideM0 и StepM0 отвечают «КАКОВА ФОРМА чанка». Они задают длину блоба и
//     адресное пространство дерева (0..4095, контракт §8), то есть протокол:
//     два региона с разным шагом означали бы две длины блоба в одном столбце
//     базы и два декодера у клиента. Сверх того шаг 4 м выбран по ФИЗИЧЕСКОМУ
//     доводу, а не по вкусу карты (шапка пакета): основная площадка с откосами
//     шириной порядка 11 м при шаге 8 м получает один отсчёт и перестаёт
//     читаться как форма. Разрешить карте шаг 8 м значило бы разрешить ей
//     сделать модель непригодной — и «маленькая карта» стала бы не меньшим
//     миром, а худшей землёй.
//
// Замер, подтверждающий, что охвата достаточно: на затравке ST_A из 124 чанков
// 68 (55 %) порождают уровни 2–4, то есть та часть правила, которая уехала в
// карту, и распоряжается она большей половиной цены. Полный ряд замеров обеих
// версий карты — в отчёте биды.
type Rule struct {
	// Level0RadiusM — радиус уровня 0 от оси пути. У затравки 512 м: две
	// стороны чанка нулевого уровня, с запасом перекрывающие зону земляных
	// работ (у ST_A она 36.5 м — площадка 5 м плюс откос 1:1,5 на перепад 21 м).
	// Запас не даровой и не произвольный: mapfmt отказывает карте, у которой
	// радиус уровня 0 меньше вылета её же откосов.
	Level0RadiusM float64
	// MaxLevel — последний хранимый уровень. Дальше не хранится ничего:
	// отсутствие чанка законно, клиент рисует базовую поверхность.
	MaxLevel int
}

// Known сообщает, что правило действительно задано, а не пришло нулями.
//
// Нужно ровно одному месту — чтению региона из базы, засеянной сборкой, которая
// правила ещё не записывала. Молчаливо подставить прежние 512/4 нельзя: чанки в
// такой базе порождены НЕИЗВЕСТНЫМ правилом, и выдавать их за своё — это выдача
// чужих чанков под видом исправного мира.
//
// Проверкой карты это не является: диапазоны и согласованность чисел проверяет
// mapfmt, и второе место с теми же порогами разошлось бы с первым.
func (r Rule) Known() bool {
	return r.Level0RadiusM > 0 && r.MaxLevel >= 0 && r.MaxLevel <= MaxLevelLimit
}

// RadiusM — радиус покрытия уровня: уровень L хранится всюду в пределах
// Level0RadiusM·2^L от оси.
//
// Радиусы вложены: круг уровня L целиком лежит внутри круга L+1. Поэтому
// «радиус уровня» — это не внешняя граница кольца, а полный охват уровня.
func (r Rule) RadiusM(level int) float64 {
	return r.Level0RadiusM * float64(int64(1)<<level)
}

// ReachM — охват мира: радиус последнего уровня. За ним чанков нет ни у кого.
func (r Rule) ReachM() float64 { return r.RadiusM(r.MaxLevel) }

// LevelFor называет САМЫЙ ПОДРОБНЫЙ уровень, круг которого накрывает расстояние.
//
// Уровни перекрываются, поэтому точку в 600 м от оси накрывают круги уровней
// 1..MaxLevel; LevelFor называет из них первый. Для клиента это точка входа в
// пирамиду: с названного уровня он начинает и, если чанка там нет, спускается к
// более грубому. Промах на уровень стоит подробности, а не земли — ради этого
// свойства уровни и перекрываются.
//
// ok == false означает «дальше интереса»: чанк не порождается и не хранится.
// Разреженность — свойство хранилища, а не сбой.
func (r Rule) LevelFor(distM float64) (level int, ok bool) {
	if distM < 0 {
		return 0, false
	}
	rad := r.Level0RadiusM
	for l := 0; l <= r.MaxLevel; l++ {
		if distM <= rad {
			return l, true
		}
		rad *= 2
	}
	return 0, false
}

// Покров: класс поверхности и сомкнутость низового покрова.
//
// # Почему сетка 64 × 64, а не 65 × 65, как у высот
//
// Покров — величина ПЛОЩАДНАЯ, высота — точечная. 65 отсчётов высоты дают 64
// квадрата между ними, и класс поверхности принадлежит квадрату, а не узлу.
// Отсюда три следствия, и каждое куплено этим выбором:
//
//   - НЕТ дублирования крайнего ряда с соседом. У высот оно необходимо (без
//     общей вершины треугольники не сходятся и между чанками видно небо), у
//     классов бессмысленно: у ячейки нет соседа, с которым надо совпасть;
//   - НЕТ неоднозначной интерполяции категорий. «Полулуг-полупесок» между двумя
//     вершинами не значит ничего, а между двумя ячейками вопрос не возникает;
//   - индекс ячейки СОВПАДАЕТ с адресом дерева 0..4095 (контракт чанков §8).
//     Это не совпадение, а причина: лес адресуется ячейкой уровня 0, и вторая
//     сетка под него означала бы два адреса одного места.
//
// Решение записано в биде ClearAhead-s6v, п. 2.
const (
	// CoverCells — ячеек по стороне чанка на любом уровне.
	CoverCells = Samples - 1
	// CoverBytes — размер блоба покрова: один байт на ячейку.
	CoverBytes = CoverCells * CoverCells
)

// Классы поверхности. Старший полубайт байта покрова.
//
// Значений четыре из шестнадцати возможных, и это запас вчетверо. Спайк
// различал ШЕСТЬ состояний, но два из них — оттенок одного луга (решение
// художника), а «обнажённый грунт на крутизне» ВЫВОДИТСЯ ИЗ УКЛОНА, то есть из
// уже присланных высот, и данными быть не обязан.
//
// Лес разделён на хвойный и лиственный НЕ ради цвета: порода дерева
// наследуется от класса покрова и стоит ноль байт (s6v п. 5). Цена названа
// там же: единичная берёза в хвойном массиве этой моделью невыразима.
const (
	SurfaceMeadow        = 0 // луг
	SurfaceForestConifer = 1 // лес хвойный
	SurfaceForestBroad   = 2 // лес лиственный
	SurfaceSand          = 3 // песок, пойма
	SurfaceBareSoil      = 4 // голая почва
	SurfaceClassCount    = 5
)

// PackCover укладывает класс и сомкнутость в байт.
//
// Класс в старший полубайт, сомкнутость в младший: так байт читается глазом в
// шестнадцатеричном дампе — «10» это хвойный лес нулевой сомкнутости, а не
// число 16. Сомкнутость — 16 градаций, и их хватает: у прототипа порогов было
// два (0.26 и 0.42), то есть модель различала три состояния.
func PackCover(class, closure int) byte {
	return byte(class&0x0f)<<4 | byte(closure&0x0f)
}

// UnpackCover разбирает байт покрова.
func UnpackCover(b byte) (class, closure int) {
	return int(b >> 4), int(b & 0x0f)
}

// CoverIndex — порядковый номер ячейки (i, j) в блобе покрова.
//
// Порядок обхода тот же, что у высот: строками по возрастанию j, внутри строки
// по возрастанию i. Он часть контракта — клиент читает блоб одним проходом и
// иного способа узнать раскладку не имеет.
func CoverIndex(i, j int) int { return j*CoverCells + i }

// CoverCellCenterM — центр ячейки покрова в координатах региона.
//
// Именно ЦЕНТР, а не угол: класс принадлежит площади, и брать его в углу
// значило бы сдвинуть весь покров на полшага относительно того, что он
// описывает.
func (a Address) CoverCellCenterM(i, j int) (x, z float64) {
	ox, oz := a.OriginM()
	step := StepM(a.Level)
	return ox + (float64(i)+0.5)*step, oz + (float64(j)+0.5)*step
}

// Лес: битовая карта занятости ячеек уровня 0.
//
// # Почему бит, а не список и не атрибуты
//
// Разбор .internal/briefs/2026-08-12-forest-layout.md замерил три формы. Бит
// побеждает не по цене, а потому, что ВСЁ ОСТАЛЬНОЕ УЖЕ ЕСТЬ:
//
//   - порода берётся из класса покрова той же ячейки (SurfaceForestConifer или
//     SurfaceForestBroad) и стоит ноль байт;
//   - отметка берётся из уже присланных высот;
//   - смещение внутри ячейки, высота ствола и поворот — детерминированная
//     функция АДРЕСА (ForestJitter), одинаковая у сервера и клиента.
//
// Отсюда 512 байт: 4096 ячеек по биту. Замер сжатия из того же разбора: gzip -9
// даёт в среднем 268 из 512 — энтропия бита при занятости 24 % равна 0.76,
// то есть 512 это ОКОНЧАТЕЛЬНАЯ цена, а не «до сжатия».
//
// # Почему только уровень 0
//
// Тождество нужно дереву затем, что его РУБЯТ, а рубят там, куда дотянулись, —
// в коридоре. Полоса рубки совпадает с полосой уровня 0. За её границей деревья
// рассыпает клиент сам по покрову, как траву: у них нет тождества, потому что их
// некому срубить.
const (
	// ForestBytes — размер блоба леса: по биту на ячейку покрова.
	ForestBytes = CoverCells * CoverCells / 8
	// ForestLevel — единственный уровень, на котором лес существует.
	ForestLevel = 0
)

// ForestOccupied сообщает, стоит ли дерево в ячейке.
//
// Порядок бит внутри байта — от младшего к старшему, порядок байт — тот же
// строчный обход, что у покрова и высот. Он часть контракта: клиент читает блоб
// одним проходом и иного способа узнать раскладку не имеет.
func ForestOccupied(blob []byte, i, j int) bool {
	k := CoverIndex(i, j)
	if k < 0 || k/8 >= len(blob) {
		return false
	}
	return blob[k/8]&(1<<uint(k%8)) != 0
}

// SetForestOccupied ставит бит занятости.
func SetForestOccupied(blob []byte, i, j int) {
	k := CoverIndex(i, j)
	if k < 0 || k/8 >= len(blob) {
		return
	}
	blob[k/8] |= 1 << uint(k%8)
}

// ForestJitter — детерминированная функция адреса дерева.
//
// Возвращает три числа в [0, 1): смещение по x и z внутри ячейки и долю для
// высоты ствола. ЭТО ЧАСТЬ КОНТРАКТА, а не деталь сервера: высота дерева —
// факт о мире (его можно спилить и померить), и два рендерера, посчитавшие её
// по-разному, покажут разные деревья на одном месте.
//
// Функция целочисленная и без трансцендентных операций — по той же причине, по
// которой такой сделан шум рельефа: результат обязан совпадать на любой машине
// бит в бит, а деление на 2^32 точно в float64.
func ForestJitter(cx, cz, i, j int) (dx, dz, h float64) {
	k := uint64(uint32(cx))<<32 | uint64(uint32(cz))
	c := uint64(uint32(j*CoverCells+i)) + 0x9E3779B97F4A7C15
	m := forestMix(k ^ forestMix(c))
	dx = float64(uint32(m)) / 4294967296.0
	m = forestMix(m)
	dz = float64(uint32(m)) / 4294967296.0
	m = forestMix(m)
	h = float64(uint32(m)) / 4294967296.0
	return dx, dz, h
}

func forestMix(z uint64) uint64 {
	z ^= z >> 30
	z *= 0xBF58476D1CE4E5B9
	z ^= z >> 27
	z *= 0x94D049BB133111EB
	z ^= z >> 31
	return z
}
