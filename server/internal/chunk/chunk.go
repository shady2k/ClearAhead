// Package chunk — геометрия сетки чанков мира.
//
// Числа контракта живут здесь, а не в документе: спека
// .internal/specs/2026-08-11-world-chunk-contract.md описывает их смысл, а
// сходимость проверяется тестом. Прежний приёмочный критерий биды —
// «числа совпадают с chunk_debug.gd» — снят: отладочный слой удалён вместе с
// клиентом, и сверять было не с чем.
//
// # Почему шаг 4 м, а не 5
//
// Согласовано в разговоре было «256 м, шаг 5 м, сетка 53×53». Арифметика не
// сходится: 256/5 = 51.2, а 53 отсчёта дают 260 м. Сторона 256 выбрана ради
// двух свойств — степень двойки (квадродерево делит пополам) и 256 = 8×32
// (чанки травы ложатся без остатка), — и 53×53 достижимо только при стороне
// 260, которая ломает оба.
//
// Шаг 8 м отвергнут по существу: основная площадка пути с откосами имеет
// ширину порядка 11 м, при шаге 8 м на неё приходится один отсчёт и насыпь
// перестаёт читаться как форма. При 4 м их три.
package chunk

import (
	"encoding/binary"
	"fmt"
)

// Геометрия уровня 0. Уровень L вдвое шире и вдвое грубее при том же числе
// отсчётов.
const (
	// SideM0 — сторона чанка уровня 0 в метрах.
	SideM0 = 256
	// StepM0 — шаг сетки уровня 0 в метрах.
	StepM0 = 4
	// Samples — отсчётов по стороне, на любом уровне.
	//
	// Их на единицу больше, чем интервалов: последний ряд и столбец
	// принадлежат одновременно соседнему чанку. Без общего ряда на стыке
	// остаётся щель — соседи не делят вершину, и между треугольниками видно
	// небо.
	Samples = SideM0/StepM0 + 1
	// GrassChunkM — сторона чанка травы. Сторона чанка мира обязана делиться
	// на неё нацело.
	GrassChunkM = 32
)

// Address — ключ чанка (world-storage §4).
type Address struct {
	Region string
	Level  int
	CX, CZ int
}

// SideM — сторона чанка уровня в метрах.
func SideM(level int) float64 {
	side := SideM0
	return float64(side << level)
}

// StepM — шаг сетки уровня в метрах.
func StepM(level int) float64 {
	step := StepM0
	return float64(step << level)
}

// OriginM — координаты угла чанка в системе координат региона.
func (a Address) OriginM() (x, z float64) {
	side := SideM(a.Level)
	return float64(a.CX) * side, float64(a.CZ) * side
}

// SampleM — абсолютные координаты отсчёта (i, j) чанка.
//
// Координаты считаются от угла региона, а не от угла чанка, и это существенно:
// общий узел двух соседних чанков обязан получить бит в бит одно и то же
// значение, а это обеспечивается только тем, что аргумент рельефа у него один.
func (a Address) SampleM(i, j int) (x, z float64) {
	ox, oz := a.OriginM()
	step := StepM(a.Level)
	return ox + float64(i)*step, oz + float64(j)*step
}

// Кодирование отсчётов высоты.
//
// Порядок байт — little-endian, явно и для всех многобайтовых полей: все
// целевые платформы little-endian, а называется это затем, чтобы автору
// адаптера не приходилось угадывать.
//
// Высота — int16 целых сантиметров ОТНОСИТЕЛЬНО base_z чанка. База своя у
// каждого чанка, а не у региона: int16 покрывает ±327,67 м вокруг базы, чего
// хватает на сторону 256 м в любых горах и заведомо не хватает на регион
// 400 × 400 км.

// HeightsBytes — размер блоба высот одного чанка.
const HeightsBytes = Samples * Samples * 2

// EncodeHeights укладывает отсчёты в блоб.
//
// Порядок обхода: строками по возрастанию j, внутри строки по возрастанию i.
// Он часть контракта: клиент читает блоб одним проходом и не имеет иного
// способа узнать раскладку.
func EncodeHeights(h []int16) ([]byte, error) {
	if len(h) != Samples*Samples {
		return nil, fmt.Errorf("chunk: отсчётов %d, ожидалось %d", len(h), Samples*Samples)
	}
	out := make([]byte, HeightsBytes)
	for k, v := range h {
		binary.LittleEndian.PutUint16(out[k*2:], uint16(v))
	}
	return out, nil
}

// DecodeHeights разбирает блоб обратно.
func DecodeHeights(b []byte) ([]int16, error) {
	if len(b) != HeightsBytes {
		return nil, fmt.Errorf("chunk: блоб %d байт, ожидалось %d", len(b), HeightsBytes)
	}
	out := make([]int16, Samples*Samples)
	for k := range out {
		out[k] = int16(binary.LittleEndian.Uint16(b[k*2:]))
	}
	return out, nil
}

// Index — порядковый номер отсчёта (i, j) в блобе.
func Index(i, j int) int { return j*Samples + i }

// Выбор уровня подробности по удалённости от пути.
//
// `world-storage` §5 объявляет «коридор — уровень 0, дальше грубее, за
// пределами интереса — ничего», но числами это задано не было; открытый вопрос
// §10.4 контракта чанков. Здесь он закрыт.
//
// Правило: радиус удваивается вместе с уровнем. Уровень 0 покрывает 512 м от
// оси — это две стороны чанка нулевого уровня и с запасом перекрывает зону
// земляных работ, которая на реальных откосах не выходит за несколько десятков
// метров. Дальше подробность падает ровно так же, как растёт сторона чанка,
// поэтому число чанков в кольце остаётся того же порядка.
//
// Проверка правила на сети Краснодарского края (2000 км): уровень 0 — 264 МБ,
// уровень 1 — 66, дальше 33, 16, 8; итого 388 МБ при покрытии до 8 км от пути.
// Оценка `world-storage` §1 для полосы ±1 км давала ~430 МБ — правило даёт
// тот же порядок при вчетверо большем охвате и вдвое более мелком шаге вблизи
// пути.
const (
	// Level0RadiusM — радиус уровня 0 от оси пути.
	Level0RadiusM = 512.0
	// MaxLevel — последний хранимый уровень. Дальше не хранится ничего:
	// отсутствие чанка законно, клиент рисует базовую поверхность.
	MaxLevel = 4
)

// LevelFor выбирает уровень по расстоянию до ближайшей оси.
//
// ok == false означает «дальше интереса»: чанк не порождается и не хранится.
// Разреженность — свойство хранилища, а не сбой.
func LevelFor(distM float64) (level int, ok bool) {
	if distM < 0 {
		return 0, false
	}
	r := Level0RadiusM
	for l := 0; l <= MaxLevel; l++ {
		if distM <= r {
			return l, true
		}
		r *= 2
	}
	return 0, false
}
