package chunk

// ground.go — ПРАВИЛО ЗЕМЛИ: пороги, по которым покров и уклон превращаются в
// вид земли.
//
// # Что здесь закончилось
//
// Решение ClearAhead-s6v (п. 6) объявило прямо: «обнажённый грунт на крутизне»
// выводится из уклона, то есть из уже присланных высот, данными быть не обязан,
// НО ПОРОГ И АЛГОРИТМ ОБЯЗАНЫ ВОЙТИ В КОНТРАКТ — иначе два рендерера разойдутся.
//
// Не вошли. Порог полтора месяца жил константами в клиенте
// (terrain_mesh.gd: SCARP_SLOPE_LO/HI), и в записи бида это названо единственным
// невыполненным местом п. 6 и единственным местом, где клиент держит число о
// мире.
//
// Мало того, рядом с константами стоял комментарий, утверждавший ОБРАТНОЕ
// принятому решению: «оба порога и оба цвета — решение художника, второй клиент
// вправе взять другие, и мир от этого не изменится». Два места в проекте
// говорили про одно число противоположное, и разошлись они молча — тот же класс,
// что у наката (track/ride.go) и у строжки остряка.
//
// Разрешает спор владелец, 2026-08-18: «клиент — тупой рендер, всё должен
// отдавать сервер».
//
// # Почему это ПРАВИЛО, а не данные
//
// Обнажённый грунт не хранится байтом покрова, и это остаётся верным: он не
// свойство места, а следствие крутизны, и хранить его значило бы держать вторую
// запись того, что уже сказано высотами. Данными едет ПОРОГ — три числа, по
// которым правило считается одинаково у всякого, кто рисует.
//
// Разница существенная. Порог в контракте не заставляет сервер хранить лишний
// байт на ячейку (4096 байт на чанк), но лишает клиента права выбрать свой.
//
// # Почему цвет остался у показа, а порог — нет
//
// Цвет обнажённого грунта — решение художника, и второй клиент вправе взять
// другой: мир от этого не изменится, изменится картинка. Порог решает, ГДЕ
// ИМЕННО кончается луг и начинается осыпь, то есть утверждает факт о месте.
// Два клиента с разными порогами покажут игрокам РАЗНЫЙ мир, а не разный вкус.
//
// Та же граница, что у наката и фаски: где идёт колесо — сервер, каким цветом
// это рисовать — показ.

// GroundRule — числа правила земли. Все безразмерные, кроме уклона.
type GroundRule struct {
	// ScarpSlopeLo, ScarpSlopeHi — уклон (тангенс, то есть подъём на единицу
	// длины), при котором обнажённый грунт начинает проступать и при котором
	// проступает целиком. Между ними — линейно.
	//
	// АЛГОРИТМ ОБЪЯВЛЕН ЗДЕСЬ, а не только пороги, потому что решение s6v
	// требует именно этого: t = clamp((slope − lo) / (hi − lo), 0, 1), и доля t
	// подмешивается к цвету покрова. Всё, что сверх — насколько густо мешать,
	// каким цветом — остаётся показу.
	ScarpSlopeLo float64 `json:"scarp_slope_lo"`
	ScarpSlopeHi float64 `json:"scarp_slope_hi"`

	// GrassMinClosure — сомкнутость (0..15 из байта покрова), начиная с которой
	// низовой ярус вообще есть. Ниже неё земля голая, и трава не ставится.
	GrassMinClosure int `json:"grass_min_closure"`

	// NoUnderstory — классы покрова, где низового яруса нет ни при какой
	// сомкнутости.
	//
	// Списком, а не правилом «класс больше такого-то»: это перечень фактов о
	// биомах, и порядок классов в перечислении к делу не относится. Песок и
	// голая почва — не «мало травы», а «травы нет»; на пойменном песке трава
	// растёт пятнами, и когда пятна понадобятся, они приедут сомкнутостью, а не
	// исключением из этого списка.
	NoUnderstory []int `json:"no_understory"`
}

// Ground — правило земли этого сервера.
//
// # Откуда числа
//
// ЗАМЕР И СЛИЧЕНИЕ С ЭТАЛОНОМ, и оба шага записаны, потому что первый заход был
// неверен и выглядел обоснованным.
//
// ПЕРВЫЙ ЗАХОД (2026-08-12): 0.20…0.50, по замеру уклонов чанка 0/0/0 — медиана
// 0.087, 90-й процентиль 0.144 — при откосах земляных работ 1:1.5, то есть
// 0.667. Довод «полка ниже 0.20 остаётся ровной» опирался на замер и потому
// казался безопасным: покрашено и правда мало, 0.6 % вершин.
//
// ВТОРОЙ ЗАХОД (сличение с запущенным эталоном, тот же день): красились не
// откосы, а ПОДЪЁМЫ ПРИРОДНОЙ ЗЕМЛИ, и на кадре это добавляло бурого там, где у
// эталона ровный луг. Пороги подняты втрое, до 0.62…1.03. Откосы земляных работ
// (0.667) в новый порог по-прежнему попадают — ради них он и заведён.
//
// СОМКНУТОСТЬ 4 из 15 — порог прототипа 0.26, переведённый в шкалу байта
// покрова: 0.26 × 15 ≈ 3.9. Прототип различал три состояния двумя порогами
// (0.26 и 0.42); второй здесь не нужен — он делил густую траву от редкой, а это
// решение показа о том, сколько пучков ставить.
var Ground = GroundRule{
	ScarpSlopeLo:    0.62,
	ScarpSlopeHi:    1.03,
	GrassMinClosure: 4,
	NoUnderstory:    []int{SurfaceSand, SurfaceBareSoil},
}
