package content

import (
	"fmt"
	"math"

	"github.com/shady2k/ClearAhead/server/internal/mapfmt"
)

// StockType — паспорт подвижной единицы: что за машина.
//
// # Почему полей так мало
//
// Потому что у остальных сегодня нет потребителя. Масса тары, тяговая и
// тормозная характеристики, конструкционная скорость, сцепной вес, песочница —
// всё это перечислено в sim-core-design §7.1 и всё это войдёт сюда, когда
// появится физика, которая их читает. Объявить их сейчас нулями значит записать
// в контракт ложь: ноль будет неотличим от «не заполнено», и через месяц никто
// не вспомнит, тара это или пропуск.
//
// Владелец потребовал заложить архитектуру под температуру, тормоза и
// пантограф, и она заложена не пустыми полями, а разделением: паспорт (здесь) /
// органы управления / состояние физики / производное — четыре разных места, и
// добавление в любое не трогает три остальных.
//
// # Откуда числа
//
// ЗАМЕР МЕША, умноженный на масштаб подгонки под колею (см. Asset.Scale), а не
// справочник. Источник назван честно, потому что он временный: настоящая машина
// короче и уже нарисованной, и в тот день, когда у проекта появится источник
// норм на ВЛ80, паспорт разойдётся с мешем — и это будет правильно. Паспорт —
// модель мира, меш — вид; сегодня они совпадают только потому, что другого
// источника чисел нет.
type StockType struct {
	ID string `json:"id"`
	// LengthM — длина между плоскостями автосцепок, метры.
	//
	// Определение важнее числа: длина по кузову, по буферам и по автосцепкам —
	// три разных величины, и «длина» без уточнения означала бы, что два автора
	// заполнят поле по-разному. Точка отсчёта единицы — СЕРЕДИНА этого отрезка
	// (netloc.Point), поэтому от неё до каждого конца ровно LengthM/2.
	LengthM float64 `json:"length"`
	// WidthM — наибольшая ширина, метры. Поперёк оси пути.
	WidthM float64 `json:"width"`
	// HeightM — наибольшая высота НАД ПОВЕРХНОСТЬЮ КАТАНИЯ, метры. Отсчёт тот
	// же, что у всей вертикали проекта (контракт отрисовки редакции 6 §2):
	// второго датума машина не заводит.
	HeightM float64 `json:"height"`
	// BogieBaseM — расстояние между КРАЙНИМИ шкворнями, метры.
	//
	// Заведено с потребителем, а не про запас, и потребитель нашёлся дорого.
	// Первая редакция ставила меш ЖЁСТКО ПО КАСАТЕЛЬНОЙ в точке отсчёта, и это
	// было объявленным упрощением — на прямой оно незаметно. Владелец поймал
	// его в тот же день: боевая машина стоит серединой ровно на стыке дуги
	// R=500 и прямой, и хвост уходил от оси на L²/2R = 17.09²/1000 = 0.29 м,
	// то есть колёса стояли рядом с рельсами, а не на них.
	//
	// По двум точкам тело ложится ХОРДОЙ, как и настоящая машина: шкворни
	// садятся на ось, а отход середины кузова остаётся и равен провесу хорды
	// (для базы 24.7 м на R=500 это 0.15 м).
	//
	// ПОЛНОСТЬЮ это не лечится, пока машина — ОДНО тело: у ВЛ80 две секции, и
	// на кривой они поворачиваются друг относительно друга. Настоящий ответ —
	// две единицы в сцепе, и он приходит с В4 (ClearAhead-xj9), а не здесь.
	BogieBaseM float64 `json:"bogie_base"`
	// Appearance — имя записи каталога ассетов. НЕ идентификатор типа и не
	// имя файла: у одной машины бывает несколько ливрей, и перекраска не должна
	// менять физику. Сегодня у каждого типа один вид, и ссылка выглядит лишней;
	// завести её потом значило бы разделять паспорт и вид задним числом, когда
	// на прежнюю форму уже кто-то сослался.
	Appearance string `json:"appearance"`
}

// loadStock проверяет и укладывает паспорта.
func (s *Set) loadStock(types []StockType) error {
	seen := map[string]bool{}
	for i, t := range types {
		if err := mapfmt.ValidID("тип подвижного состава", t.ID); err != nil {
			return fmt.Errorf("content: паспорт %d: %w", i, err)
		}
		if seen[t.ID] {
			return fmt.Errorf("content: тип %s объявлен дважды: одно имя — одна машина", t.ID)
		}
		seen[t.ID] = true
		for _, d := range []struct {
			name string
			v    float64
		}{{"length", t.LengthM}, {"width", t.WidthM}, {"height", t.HeightM},
			{"bogie_base", t.BogieBaseM}} {
			if !(d.v > 0) || math.IsInf(d.v, 0) {
				return fmt.Errorf("content: тип %s: %s = %v, ожидалось положительное конечное число",
					t.ID, d.name, d.v)
			}
		}
		// База шкворней внутри машины: она мерится между опорами, а не между
		// автосцепками, и база длиннее машины означала бы опечатку в разряде.
		if t.BogieBaseM >= t.LengthM {
			return fmt.Errorf("content: тип %s: база шкворней %.2f м не меньше длины %.2f м",
				t.ID, t.BogieBaseM, t.LengthM)
		}
		// Ссылка разрешается ЗДЕСЬ, а не при отдаче: паспорт, ссылающийся в
		// пустоту, — испорченный набор, и он обязан не собраться.
		if t.Appearance == "" {
			return fmt.Errorf("content: тип %s: не указан appearance; вид объявляется ссылкой, "+
				"а не выводится из имени типа", t.ID)
		}
		if _, ok := s.asset(t.Appearance); !ok {
			return fmt.Errorf("content: тип %s: вид %q в наборе не объявлен", t.ID, t.Appearance)
		}
	}
	s.Stock = append([]StockType(nil), types...)
	sortedByID(s.Stock, func(t StockType) string { return t.ID })
	return nil
}
