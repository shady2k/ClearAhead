// StockType — паспорт подвижной единицы: что за машина.
//
// # Что здесь есть с 2026-08-13
//
// Прежняя редакция этой шапки объясняла, почему полей так мало: «у остальных
// сегодня нет потребителя… войдут сюда, когда появится физика, которая их
// читает». Условие наступило — появился internal/physics, — и поля вошли: масса,
// сцепной вес, конструкционная скорость, коэффициенты сопротивления, точка
// длительного режима.
//
// # Откуда числа, и почему источников ДВА
//
// ГАБАРИТ — ЗАМЕР МЕША, умноженный на масштаб подгонки под колею (Asset.Scale).
// ФИЗИКА — ОПУБЛИКОВАННЫЙ ПАСПОРТ МАШИНЫ.
//
// Разойтись им не только позволено, но и предсказано: прежняя редакция писала
// «в тот день, когда у проекта появится источник норм на ВЛ80, паспорт
// разойдётся с мешем — и это будет правильно». День настал, и расхождение уже
// есть числом: длина по осям автосцепок у ВЛ80 равна 32.84 м по паспорту против
// 34.18 м по замеру нарисованной модели — нарисованная машина длиннее
// настоящей на 1.34 м. Габарит остаётся замером НАРОЧНО: по нему рисуется
// коробка и проверяется помещаемость на путь, и разъехаться с тем, что видно на
// экране, ему нельзя.
//
// # Чего здесь по-прежнему нет и почему
//
// ТОРМОЗА. Он нужен, и его отсутствие названо, а не забыто: честная тормозная
// сила считается через расчётные тормозные нажатия и коэффициент трения колодок
// от скорости, а этих таблиц ПТР найденные источники не дают текстом. Правило
// проекта — такие таблицы по памяти не пишутся (sim-core-design §13.3), — и
// правдоподобное число здесь было бы хуже пустоты: по нему считался бы
// тормозной путь, то есть решение игрока.
//
// ПЕСОЧНИЦА. У неё известен эффект, но не число прироста сцепления; поле без
// числа было бы формой без потребителя.
//
// Оба приезжают вместе с интегратором — там, где им впервые есть что тормозить.
type StockType struct {
	ID string `json:"id"`
	// LengthM — длина между плоскостями автосцепок, метры.
	//
	// Определение важнее числа: длина по кузову, по буферам и по автосцепкам —
	// три разных величины, и «длина» без уточнения означала бы, что два автора
	// заполнят поле по-разному. Точка отсчёта единицы — СЕРЕДИНА этого отрезка
	// (netloc.Point), поэтому от неё до каждого конца ровно LengthM/2.
	LengthM float64 `json:"length"`
	// WidthM — наибольшая ширина, метры. Поперёк оси пути.
	WidthM float64 `json:"width"`
	// HeightM — наибольшая высота НАД ПОВЕРХНОСТЬЮ КАТАНИЯ, метры. Отсчёт тот
	// же, что у всей вертикали проекта (контракт отрисовки редакции 6 §2):
	// второго датума машина не заводит.
	HeightM float64 `json:"height"`
	// BogieBaseM — расстояние между КРАЙНИМИ шкворнями, метры.
	//
	// Заведено с потребителем, а не про запас, и потребитель нашёлся дорого.
	// Первая редакция ставила меш ЖЁСТКО ПО КАСАТЕЛЬНОЙ в точке отсчёта, и это
	// было объявленным упрощением — на прямой оно незаметно. Владелец поймал
	// его в тот же день: боевая машина стоит серединой ровно на стыке дуги
	// R=500 и прямой, и хвост уходил от оси на L²/2R = 17.09²/1000 = 0.29 м,
	// то есть колёса стояли рядом с рельсами, а не на них.
	//
	// По двум точкам тело ложится ХОРДОЙ, как и настоящая машина: шкворни
	// садятся на ось, а отход середины кузова остаётся и равен провесу хорды
	// (для базы 24.7 м на R=500 это 0.15 м).
	//
	// ПОЛНОСТЬЮ это не лечится, пока машина — ОДНО тело: у ВЛ80 две секции, и
	// на кривой они поворачиваются друг относительно друга. Настоящий ответ —
	// две единицы в сцепе, и он приходит с В4 (ClearAhead-xj9), а не здесь.
	BogieBaseM float64 `json:"bogie_base"`
	// MassT — служебная масса в тоннах: с топливом, песком, водой и экипажем.
	//
	// Именно СЛУЖЕБНАЯ, а не тара, и разница названа, потому что кандидатов
	// снова несколько: тара (пустая машина), служебная (готовая к работе),
	// полная (с грузом). Для локомотива работает служебная — он и ездит
	// заправленным.
	//
	// У МАШИНЫ С ГРУЗОМ ЭТОГО ПОЛЯ НЕТ: обещанное «другое поле» приехало
	// блоком freight (тара плюс грузоподъёмность), и ровно одно из двух
	// обязано быть заполнено. Разбор — у FreightSpec.
	//
	// Тонна — единица паспорта и человека; в килограммы её переводит домен
	// (units.TonnesToMass), и перевод живёт в одном месте.
	MassT float64 `json:"mass,omitempty"`

	// Freight — машина ВОЗИТ ГРУЗ: тара, грузоподъёмность, число осей.
	// Отсутствие значит «вес машины постоянен», и тогда его называет mass.
	Freight *FreightSpec `json:"freight,omitempty"`

	// MaxSpeedKmh — конструкционная скорость, км/ч.
	//
	// Предел ПРОЧНОСТИ И ЭКИПАЖНОЙ ЧАСТИ, а не тяги: выше него машину не
	// разгоняют, даже если сила есть и уклон помогает. Сегодня его никто не
	// сторожит — сторожить будет интегратор.
	MaxSpeedKmh float64 `json:"max_speed"`

	// Res — коэффициенты основного удельного сопротивления по ПТР:
	// w = a + b·V + c·V², км/ч на входе, Н/кН на выходе.
	//
	// В паспорте, а не в коде физики, потому что это свойство КЛАССА машины:
	// у электровоза, гружёного и порожнего вагона они разные, и набор машин
	// обязан расширяться данными, а не правкой пакета physics.
	//
	// У МАШИНЫ С ГРУЗОМ это ПОРОЖНЯЯ кривая: гружёная приезжает отдельным
	// блоком, потому что у неё другая ФОРМА (LoadedResistanceSpec).
	Res ResistanceSpec `json:"resistance"`

	// ResLoaded — сопротивление ГРУЖЁНОЙ машины. Обязателен при freight и
	// запрещён без него: у машины постоянного веса гружёного состояния нет
	// вовсе, и блок был бы формой без потребителя.
	ResLoaded *LoadedResistanceSpec `json:"resistance_loaded,omitempty"`

	// Brake — тормозные свойства. Обязательны у всего, что катится: машина без
	// тормоза — это машина, которую нельзя остановить, и молчаливого умолчания
	// здесь быть не может.
	Brake BrakeSpec `json:"brake"`

	// Traction — тяговые свойства. ОТСУТСТВИЕ ЗНАЧИТ «НЕ ЛОКОМОТИВ».
	//
	// Отдельным необязательным блоком, а не полями вперемешку с общими, ровно
	// затем: у вагона тяги нет вовсе, и нули в его паспорте были бы неотличимы
	// от незаполненного локомотива. Сегодня в наборе только локомотивы, и блок
	// выглядит всегда заполненным; заводить его потом значило бы менять форму,
	// на которую уже сослались.
	Traction *TractionSpec `json:"traction,omitempty"`

	// Controls — ОРГАНЫ УПРАВЛЕНИЯ: сколько их и какие у них пределы.
	//
	// В паспорте, а не в коде и не у клиента, по той же причине, что и
	// сопротивление: это свойство КЛАССА машины. У вагона органов нет вовсе,
	// поэтому блок необязателен — отсутствие значит «управлять нечем», а не
	// «ноль ступеней».
	Controls *ControlsSpec `json:"controls,omitempty"`

	// Organs — КАКИЕ ОРГАНЫ У ЭТОЙ МАШИНЫ ЕСТЬ, перечнем имён.
	//
	// # Поле ВЫВОДИТСЯ, автор его не пишет
	//
	// Наличие органа уже сказано пределами: тридцать три ступени тяги, блок
	// пневматики, предельное давление вспомогательного крана. Перечень — та же
	// правда, СОБРАННАЯ В ОДНОМ МЕСТЕ, и собирает её сервер. Автор, написавший
	// поле руками, получает отказ: два источника одного факта разошлись бы на
	// первой же машине.
	//
	// # Зачем он на проводе
	//
	// Слово владельца 2026-08-15: «мы передаём серверу локомотив, его паспорт,
	// возможности; клиент лишь использует их — на стороне клиента не должно быть
	// никакой информации». До этого поля клиент знал ПРАВИЛО ВЫВОДА: что кран
	// машиниста есть тогда, когда у машины есть магистраль, а ступенчатый тормоз
	// — когда объявлены ступени. Правило жило в двух местах сразу, и разойтись им
	// было нечем помешать: клиент так и держал клавиши ступенчатого тормоза у
	// машины, у которой его нет.
	//
	// Теперь клиент спрашивает перечень. Что означает каждое имя, он по-прежнему
	// знает — иначе ему нечем было бы рисовать рукоятку, — но ЕСТЬ ЛИ орган,
	// КАК ОН НАЗЫВАЕТСЯ и КАКОЙ КЛАВИШЕЙ ЕГО ВЕДУТ, решает сервер.
	Organs []Organ `json:"organs,omitempty"`

	// Appearance — имя записи каталога ассетов. НЕ идентификатор типа и не
	// имя файла: у одной машины бывает несколько ливрей, и перекраска не должна
	// менять физику. Сегодня у каждого типа один вид, и ссылка выглядит лишней;
	// завести её потом значило бы разделять паспорт и вид задним числом, когда
	// на прежнюю форму уже кто-то сослался.
	Appearance string `json:"appearance"`

	// loco — паспорт, переведённый в домен. Заполняет loadStock, и только он.
	//
	// Перевод делается ОДИН РАЗ при загрузке набора, а не на каждом обращении
	// физики, и это не экономия тактов: после Load невалидного паспорта не
	// существует — тот же приём, что в пакете protocol, где у пришедшего снаружи
	// запроса нет невалидного представления.
	loco   physics.Locomotive
	isLoco bool
	// freight — паспорт груза в доменных единицах. Заполняет loadStock, и
	// только он; nil у машины постоянного веса.
	freight *freightDomain
	// air — уставки пневматики, переведённые в домен. hasAir разводит «машина
	// тормозит давлением» и «машина тормозит одним числом»: у второй пульт не
	// рисует ни манометров, ни крана, и это разные машины, а не одна с нулями.
	air    brake.Spec
	hasAir bool
}

// ControlsSpec — органы управления машины: их пределы и дискретность.
//
// # Что здесь ОБЪЯВЛЕННОЕ УПРОЩЕНИЕ, а что число машины
//
// Разница названа вслух, потому что смешать их — значит однажды принять нашу
// выдумку за паспорт локомотива. Тот же приём, что у отрисовки: «рельс — это
// прямоугольник head_width × height, профиля рельса в контракте нет».
//
// ЧИСЛО МАШИНЫ — ступени тяги. У ВЛ80С главный контроллер ЭКГ-8Ж имеет 33
// позиции; это и есть ступени напряжения на тяговых двигателях, то есть то
// самое, чем машинист набирает тягу.
//
// НАША МОДЕЛЬ, А НЕ МАШИНА — то, ЧЕМ эти ступени набираются. На настоящем ВЛ80С
// машинист двигает главную рукоятку контроллера КМ-84, у которой восемь
// положений (0, АВ, РВ, ФВ, ФП, РП плюс самовозвратные АП и БВ), и КОМАНДУЕТ
// ими главному контроллеру: «набирай», «сбрасывай», «стой». Позиция ЭКГ —
// результат, а не то, что выставляют. У нас машинист ставит ступень напрямую.
// Это упрощение ровно того сорта, что и огибающая тяговой характеристики в
// physics.TractiveEffort: набор позиций сохранён, способ их достижения — нет.
//
// НАША МОДЕЛЬ ЦЕЛИКОМ — ступени торможения. Настоящая глубина служебного
// торможения задаётся разрядкой тормозной магистрали и НЕПРЕРЫВНА, а
// physics.BrakeForce сегодня знает одно число — полное служебное нажатие по
// ПТР. Ступень у нас — доля от него. Число ступеней НЕ взято ни из какой
// машины: реверсивная и тормозная рукоятки КМ-84 управляют ослаблением
// возбуждения и реостатным торможением, то есть другими системами, и списать
// их число сюда значило бы поставить правдоподобное вместо верного.
//
// ЧЕГО ЗДЕСЬ НЕТ. Песочницы: «известен эффект, но не число прироста сцепления»
// (шапка StockType), и орган без числа был бы кнопкой, которая ничего не
// делает. Ослабления возбуждения (ОП1–ОП3 реверсивной рукоятки) и реостатного
// торможения: у physics нет ни того, ни другого. Независимого тормоза
// локомотива: у нас одно нажатие на всё, и делить его нечем.
type ControlsSpec struct {
	// TractionNotches — сколько ступеней тяги, не считая нулевой.
	//
	// Положение контроллера — целая ступень от 0 до этого числа; сила тяги
	// доля от physics.TractiveEffort на этой скорости. Дробных положений нет:
	// у настоящей машины их тоже нет, ЭКГ стоит на позиции, а не между.
	TractionNotches int `json:"traction_notches"`
	// BrakeNotches — сколько ступеней служебного торможения, не считая нулевой.
	BrakeNotches int `json:"brake_notches"`
	// NotchRate — сколько позиций в секунду проходит главный контроллер.
	//
	// # Почему рукоятка — ЗАДАНИЕ, а не позиция
	//
	// Потому что так устроена машина, и до 2026-08-15 это было записано как
	// упрощение: «на настоящем ВЛ80С машинист двигает главную рукоятку КМ-84 и
	// КОМАНДУЕТ главному контроллеру набирай, сбрасывай, стой. Позиция ЭКГ —
	// РЕЗУЛЬТАТ, а не то, что выставляют. У нас машинист ставит ступень напрямую»
	// (спека кабины §2). Упрощение снято по замечанию владельца: «двигатель не
	// может выдать сразу 100 % мощности».
	//
	// Следствие видно сразу: поставить рукоятку на последнюю позицию можно, но
	// машина придёт туда через десятки секунд, набирая позиции по одной, — и
	// забуксует не в тот миг, когда рукоятку двинули, а когда контроллер дойдёт
	// до позиции, которую сцепление не держит.
	//
	// ЧИСЛО ПРЕДВАРИТЕЛЬНОЕ: у ЭКГ-8Ж переход с позиции на позицию занимает около
	// секунды, отсюда порядок 1 позиция в секунду. Источник не назначен, и число
	// названо тем, что оно есть.
	//
	// Ноль значит «контроллер встаёт мгновенно» — прежнее поведение. Это законная
	// машина: у тепловоза с гидропередачей набор устроен иначе, и электровозное
	// число ему не подходит.
	NotchRate float64 `json:"notch_rate,omitempty"`

	// Keys — РАСКЛАДКА КАБИНЫ: имя каждого органа и клавиши, которыми его ведут.
	//
	// Ключ словаря — имя органа или действия (Organ*, Action*). Запись обязана
	// быть у КАЖДОГО органа, который у машины есть, и не может быть у того,
	// которого нет: и то и другое — отказ (checkControls). Первое означало бы
	// рукоятку, которую нечем двинуть, второе — клавишу, которая ничего не
	// делает.
	//
	// В ПАСПОРТЕ, А НЕ У КЛИЕНТА. Слово владельца 2026-08-15: «горячие клавиши,
	// кстати, тоже должны приходить с сервера». В паспорте МАШИНЫ, а не одной
	// таблицей на сервер, потому что кабина у каждой машины своя: у ВЛ80 кран
	// № 395 с шестью положениями, у следующей машины его может не быть вовсе.
	Keys map[string]OrganKeys `json:"keys,omitempty"`
}

// OrganKeys — как орган зовут и чем его ведут.
//
// # Форма имени клавиши
//
// Одна буква или цифра латиницей, с необязательной приставкой «shift+»: «W»,
// «2», «shift+R». Перечень намеренно узок — это ПРЕДЛОЖЕНИЕ раскладки, а не
// перехват ввода: клиент вправе повесить своё, а клиент без клавиатуры вовсе
// читает только Name.
type OrganKeys struct {
	// Name — как назвать орган человеку: «контроллер тяги», «кран машиниста».
	Name string `json:"name"`
	// Up, Down — клавиши «прибавить» и «убавить». У действия заполняется только
	// Up.
	Up   []string `json:"up,omitempty"`
	Down []string `json:"down,omitempty"`
}

// ResistanceSpec — три коэффициента ПТР как их пишет автор набора.
type ResistanceSpec struct {
	A float64 `json:"a"`
	B float64 `json:"b"`
	C float64 `json:"c"`
}

// FreightSpec — МАШИНА ВОЗИТ ГРУЗ: тара и грузоподъёмность, тонны.
//
// # Почему отдельным блоком, а не полем mass
//
// Комментарий у StockType.MassT обещал это ещё до первого вагона: «у вагона
// понадобится тара плюс груз, и это будет ДРУГОЕ поле, а не переопределение
// этого». Причина не в аккуратности имён. Служебная масса — ОДНО число машины,
// которая всегда весит одинаково; тара и грузоподъёмность — ДВА конца отрезка,
// внутри которого машина живёт, и всё, что зависит от массы (сопротивление,
// тормозное нажатие, сила трогания), у гружёной и порожней разное. Слить их в
// одно поле значило бы объявить вагон машиной постоянного веса.
//
// Ровно одно из двух: либо mass, либо freight. Оба сразу — два источника одной
// массы, ни одного — машина без веса; и то и другое отказ.
type FreightSpec struct {
	// TareT — масса ПОРОЖНЕЙ машины, тонны. Для машины с грузом это то же, чем
	// служебная масса для локомотива: вес, с которого всё начинается.
	TareT float64 `json:"tare"`
	// PayloadT — грузоподъёмность, тонны: сколько груза машина принимает сверх
	// тары. Брутто = тара + груз, и груз не бывает больше этого числа.
	PayloadT float64 `json:"payload"`
	// Axles — число осей, по которому считается нагрузка на ось q0 = брутто /
	// оси.
	//
	// ОТДЕЛЬНО ОТ ТОРМОЗНЫХ ОСЕЙ (BrakeSpec.BrakedAxles), хотя у четырёхосного
	// полувагона оба числа равны четырём: тормозная ось — та, у которой есть
	// колодки, а q0 считается по ВСЕМ осям, на которые машина опирается. У
	// вагона с одной тормозной тележкой равенство сломается, и тогда паспорт,
	// в котором эти два числа были одним, соврал бы либо в сопротивлении, либо
	// в тормозе.
	Axles int `json:"axles"`
}

// LoadedResistanceSpec — основное удельное сопротивление ГРУЖЁНОГО вагона по
// ПТР: форма, которая делится на нагрузку от оси.
//
//	w = Base + (K0 + K1·V + K2·V²) / q0
//
// # Почему это не ResistanceSpec с другими числами
//
// Потому что у ПТР для гружёного вагона ДРУГАЯ ФОРМА, а не другие коэффициенты:
// три члена делятся на q0, то есть зависят от того, сколько в вагоне груза.
// Записать их тройкой a, b, c можно только ПРИ ИЗВЕСТНОМ q0 — и тогда тройка
// становится выводом, а не паспортом. Вывод и делает домен (StockType.AtLoad),
// один раз и в одном месте.
//
// # Порог порожней формулы приезжает ЧИСЛОМ ИСТОЧНИКА
//
// У порожнего четырёхосного вагона ПТР даёт независимую от q0 зависимость и
// объявляет её применимой при q0 < 6 тс/ось. Порог стоит в паспорте, а не в
// коде физики, по той же причине, что и всё остальное здесь: это число ПТР, а
// не решение программы, и набор машин расширяется данными.
//
// ЗАМЕР НА ГРАНИЦЕ (полувагон 12-132, тара 24 т на 4 оси даёт РОВНО 6.0
// тс/ось): две формулы в этой точке не сходятся. При V = 0 порожняя даёт
// 1.00 кгс/тс, гружёная 1.20; при V = 40 — 2.94 против 2.53. Разрыв до 20 %
// НАШЕЙ моделью не внесён: он есть в самих Правилах, где это две разные
// эмпирические кривые, а не одна кусочная.
//
// СЛЕДСТВИЕ, КОТОРОЕ ОБЯЗАНО БЫТЬ НАЗВАНО: порожний вагон нашего набора СТОИТ
// НА ГРАНИЦЕ И БЕРЁТ ГРУЖЁНУЮ ФОРМУЛУ, потому что порожняя объявлена
// источником для q0 < 6, а у него ровно 6.0. Это не описка и не выбор
// программы: условие взято у Правил как напечатано, а вагон оказался ровно на
// его краю. Сторожит это TestShippedWagonCarriesLoad — иначе первый же
// читатель «починит» границу на <=, решив, что порожний обязан считаться
// порожней формулой.
type LoadedResistanceSpec struct {
	Base float64 `json:"base"`
	K0   float64 `json:"k0"`
	K1   float64 `json:"k1"`
	K2   float64 `json:"k2"`
	// EmptyBelowQ0 — нагрузка от оси, ниже которой действует ПОРОЖНЯЯ формула
	// (ResistanceSpec), тс/ось.
	EmptyBelowQ0 float64 `json:"empty_below_q0"`
}

// BrakeSpec — тормозные свойства как их пишет автор набора.
//
// # Откуда числа
//
// РАСЧЁТНЫЕ НАЖАТИЯ ПТР, таблица нажатий на ось локомотивов, гружёный режим:
// ВЛ80 всех индексов — 14.0 тс на ось, ЧМЭ3 — 11.0 тс. Колодки у обоих
// чугунные. Порожний режим (6.0 и 5.0 тс) в паспорт не заведён: переключать
// его сегодня нечем, и поле было бы формой без потребителя.
type BrakeSpec struct {
	// Shoes — материал колодок: cast_iron или composite. Неизвестное значение —
	// отказ: формулы трения у них разные, и умолчание выбрало бы за автора.
	Shoes string `json:"shoes"`
	// BrakedAxles — число тормозных осей. У ВЛ80 их восемь, у ЧМЭ3 шесть —
	// столько же, сколько всех, но равенство это свойство ЭТИХ машин, а не
	// правило: у вагона с одной тормозной тележкой оно нарушится.
	BrakedAxles int `json:"braked_axles"`
	// AxleForceKN — расчётное нажатие на ОДНУ ось, килоньютоны.
	//
	// Килоньютоны по той же причине, что у силы тяги: таблица напечатана в
	// тоннах-силы (14.0 тс), а тонна-сила зависит от принятого g. Перевод
	// сделан здесь один раз при g = 9.80665: 14.0 тс = 137.3 кН.
	//
	// У МАШИНЫ С ГРУЗОМ этого поля нет: её нажатие не одно число, а функция
	// загрузки (разбор — у AxleForceEmptyKN).
	AxleForceKN float64 `json:"axle_force,omitempty"`
	// AxleForceEmptyKN, AxleForceLoadedKN — расчётное нажатие на ось у ПОРОЖНЕЙ
	// и у полностью ГРУЖЁНОЙ машины, килоньютоны. Между ними нажатие идёт
	// НЕПРЕРЫВНО по массе, и это не сглаживание модели, а устройство прибора.
	//
	// # Почему не три ступени, хотя таблица ПТР даёт три режима
	//
	// Первая редакция этого поля была таблицей «порожний / средний / гружёный»
	// (3.5 / 5.0 / 7.0 тс на ось для чугунных колодок), и упиралась в вопрос,
	// на который у меня не было ответа из источника: КТО и ПО КАКОМУ ПРАВИЛУ
	// выбирает режим. Выдумать порог загрузки означало бы поставить своё
	// решение туда, где стоит устройство вагона, — и ошибиться в тормозном
	// пути, то есть в решении игрока.
	//
	// Ответ владельца 2026-08-18: на грузовом вагоне стоит АВТОРЕЖИМ. Прибор
	// упирается стержнем в балку тележки, меряет прогиб рессор — то есть
	// фактическую загрузку — и сам ограничивает давление в тормозном цилиндре:
	// у порожнего до 1.4–1.8 кгс/см², у гружёного до 3.9–4.2. Переключатель
	// воздухораспределителя при этом ЗАКРЕПЛЁН и человеком не трогается.
	// Отсюда и форма: не три ступени с правилом выбора, а два конца отрезка,
	// внутри которого нажатие меняется с массой.
	//
	// Средний режим (5.0 тс) в паспорт не заведён НАРОЧНО: это третье положение
	// РУЧНОГО переключателя, а у машины с авторежимом его не выбирают. Поле
	// приедет вместе с вагоном без авторежима, если такой в наборе появится.
	//
	// Линейность между концами — ОБЪЯВЛЕННОЕ УПРОЩЕНИЕ, а не число прибора:
	// источник называет зависимость плавной и «в интервале между тарой и
	// брутто», но кривой авторежима нам никто не давал. Названа здесь, чтобы её
	// нельзя было однажды принять за паспорт вагона.
	AxleForceEmptyKN  float64 `json:"axle_force_empty,omitempty"`
	AxleForceLoadedKN float64 `json:"axle_force_loaded,omitempty"`
	// Air — ПНЕВМАТИКА: магистраль, краны, цилиндр. Отсутствие значит, что
	// машина тормозит ОДНИМ ЧИСЛОМ — полным нажатием по нажатию рукоятки, — а не
	// давлением.
	//
	// # Почему необязателен, хотя тормоз обязателен
	//
	// Потому что тормозная система у машин РАЗНАЯ (слово владельца 2026-08-15), и
	// пневматика — не единственная: у моторвагонной секции электропневматический
	// тормоз со своими положениями, у дрезины может не быть магистрали вовсе.
	// Обязательным здесь остаётся то, что верно для всего катящегося: колодки,
	// оси и расчётное нажатие. КАК это нажатие набирается — свойство системы.
	//
	// Число ступеней (ControlsSpec.BrakeNotches) при заполненном блоке не
	// применяется: глубину торможения задаёт разрядка магистрали, и она
	// непрерывна.
	Air *AirBrakeSpec `json:"air,omitempty"`
}

// AirBrakeSpec — уставки автоматического тормоза как их пишет автор набора,
// кгс/см² и кгс/см² в секунду.
//
// # Откуда числа
//
// Типовые уставки грузового поезда: зарядное давление магистрали 5.3–5.5,
// первая ступень служебного торможения — разрядка 0.5–0.6, полное служебное —
// около 1.5–1.7, темп служебной разрядки 0.2–0.25 в секунду, экстренной — не
// менее 0.8. Главные резервуары ВЛ80 — 7.5…9.0 с автоматическим пуском
// компрессора. Кран вспомогательного тормоза № 254 держит в цилиндре до 4.0.
//
// НАЗВАНЫ ПРЕДВАРИТЕЛЬНЫМИ, как профиль норм и эпюра переводных брусьев:
// источник не назначен, числа взяты типовыми и дают правдоподобное поведение.
// Проверить их по документу — работа автора набора, и место для этого здесь: они
// в паспорте, а не в коде.
type AirBrakeSpec struct {
	ChargeKgf          float64 `json:"charge"`
	FullServiceDropKgf float64 `json:"full_service_drop"`
	CylinderFullKgf    float64 `json:"cylinder_full"`
	ServiceRateKgfS    float64 `json:"service_rate"`
	EmergencyRateKgfS  float64 `json:"emergency_rate"`
	ChargeRateKgfS     float64 `json:"charge_rate"`
	LeakRateKgfS       float64 `json:"leak_rate"`
	MainMinKgf         float64 `json:"main_min"`
	MainMaxKgf         float64 `json:"main_max"`
	CompressorRateKgfS float64 `json:"compressor_rate"`
	CylinderRateKgfS   float64 `json:"cylinder_rate"`
	// IndependentMaxKgf — предельное давление крана вспомогательного тормоза
	// локомотива. НОЛЬ ЗНАЧИТ, ЧТО КРАНА НЕТ (разбор — у brake.Spec).
	IndependentMaxKgf float64 `json:"independent_max,omitempty"`
}

// Air — уставки, переведённые в домен. Пусто у машины без пневматики.
func (b BrakeSpec) Domain() (brake.Spec, bool) {
	if b.Air == nil {
		return brake.Spec{}, false
	}
	a := b.Air
	return brake.Spec{
		Charge:          brake.FromKgf(a.ChargeKgf),
		FullServiceDrop: brake.FromKgf(a.FullServiceDropKgf),
		CylinderFull:    brake.FromKgf(a.CylinderFullKgf),
		ServiceRate:     brake.FromKgf(a.ServiceRateKgfS),
		EmergencyRate:   brake.FromKgf(a.EmergencyRateKgfS),
		ChargeRate:      brake.FromKgf(a.ChargeRateKgfS),
		LeakRate:        brake.FromKgf(a.LeakRateKgfS),
		MainMin:         brake.FromKgf(a.MainMinKgf),
		MainMax:         brake.FromKgf(a.MainMaxKgf),
		CompressorRate:  brake.FromKgf(a.CompressorRateKgfS),
		CylinderRate:    brake.FromKgf(a.CylinderRateKgfS),
		IndependentMax:  brake.FromKgf(a.IndependentMaxKgf),
	}, true
}

// TractionSpec — тяговые свойства локомотива.
type TractionSpec struct {
	// AdhesiveMassT — сцепной вес: масса, приходящаяся на ДВИЖУЩИЕ оси, тонны.
	//
	// У ВЛ80 и ЧМЭ3 все оси движущие, и число равно служебной массе — то есть
	// поле выглядит списанным. Оно всё равно объявлено отдельно, потому что
	// равенство это СВОЙСТВО ЭТИХ МАШИН, а не правило: у паровоза и у тепловоза
	// с бегунковыми осями сцепной вес меньше служебного, и подстановка одного
	// вместо другого завысила бы силу трогания молча.
	AdhesiveMassT float64 `json:"adhesive_mass"`

	// ContinuousForceKN — сила тяги ДЛИТЕЛЬНОГО режима, килоньютоны.
	// ContinuousSpeedKmh — скорость того же режима, км/ч.
	//
	// # Почему пара чисел, а не мощность
	//
	// Потому что паспортная мощность — это мощность ДВИГАТЕЛЯ, а физике нужна
	// мощность НА ОБОДЕ КОЛЕСА, и между ними передача со своими потерями.
	// Замер на двух машинах показывает, что разница не мелочь и не одинакова:
	//
	//	ВЛ80С  6160 кВт двигателя против 40.9 тс · 53.6 км/ч = 5971 кВт на ободе
	//	       — отношение 0.97;
	//	ЧМЭ3    993 кВт дизеля против 23 тс · 11.4 км/ч = 714 кВт на ободе
	//	       — отношение 0.72, потому что у тепловоза между дизелем и колесом
	//	       ещё генератор, тяговые двигатели и вспомогательные машины.
	//
	// Записав мощность двигателя, пришлось бы завести рядом КПД передачи — то
	// есть выдуманное число вместо двух опубликованных. Пара «сила и скорость
	// режима» напечатана в паспорте прямо, и мощность на ободе выводится из неё
	// умножением.
	//
	// # Почему килоньютоны, а не тонны-силы
	//
	// Паспорта печатают тонны-силы (у ВЛ80С это 40.9 тс), и хранить их было бы
	// ближе к источнику. Но тонна-сила зависит от принятого g, то есть число в
	// данных не определяло бы само себя. Перевод сделан здесь один раз при
	// g = 9.80665: 40.9 тс = 401.1 кН.
	ContinuousForceKN  float64 `json:"continuous_force"`
	ContinuousSpeedKmh float64 `json:"continuous_speed"`
	// MaxForceKN — наибольшая сила тяги, которую дают ДВИГАТЕЛИ, килоньютоны.
	//
	// # Зачем она отдельно от длительного режима
	//
	// Потому что буксование — это разница между тем, что дают двигатели, и тем,
	// что удержит рельс, и пока сила тяги была минимумом из мощности и сцепления,
	// этой разницы не существовало вовсе: доля бралась от уже ограниченного
	// числа, и последняя позиция контроллера была безопасна по построению.
	// Владелец это заметил: «можно установить контроллер сразу на 33 и он
	// поедет, а должен буксовать».
	//
	// ЧИСЛО ПРЕДВАРИТЕЛЬНОЕ. Оно назначает, на какой позиции машина срывается с
	// места, и проверяется следствием: при 900 кН и сцепном весе 192 т с места
	// без буксования берутся позиции до 23 из 33 (замер:
	// physics.TestGentleNotchDoesNotSlip). Источник не назначен, порядок взят
	// правдоподобным, и до проверки по документу число обязано выглядеть тем,
	// что оно есть.
	//
	// Ноль значит «предел двигателей не объявлен»: машина не буксует, сила тяги
	// остаётся прежней огибающей. Законная машина, а не недописанный паспорт.
	MaxForceKN float64 `json:"max_force,omitempty"`
}

// Locomotive — паспорт в доменных единицах и признак того, что это локомотив.
//
// Возвращает готовое значение, а не считает: перевод и проверки случились при
// загрузке набора (loadStock), и отказать здесь уже нечему.
//
// У МАШИНЫ С ГРУЗОМ это состояние ПОРОЖНЕЙ машины: масса — тара, нажатие —
// нижний конец авторежима. Не «единственное» и не «умолчание»: гружёное
// состояние существует только вместе с числом груза, а число груза — факт
// экземпляра, и спрашивают его у AtLoad.
func (t StockType) Locomotive() (physics.Locomotive, bool) { return t.loco, t.isLoco }

// freightDomain — числа груза, переведённые в домен при загрузке набора.
type freightDomain struct {
	tareT    float64 // тонны: q0 считается в тс/ось, и перевод в кг здесь только помешал бы
	payloadT float64
	axles    float64
	// emptyKN, loadedKN — концы отрезка авторежима, килоньютоны на ось.
	emptyKN, loadedKN float64
	// res — числа ПТР гружёной формулы; тройка выводится по q0 в AtLoad.
	res LoadedResistanceSpec
}

// Freighted — возит ли машина груз и какова её грузоподъёмность, тонны.
// Второе значение ложно у машины постоянного веса: спрашивающий обязан
// различать эти случаи, а не получать ноль под видом грузоподъёмности.
func (t StockType) Freighted() (payloadT float64, ok bool) {
	if t.freight == nil {
		return 0, false
	}
	return t.freight.payloadT, true
}

// AtLoad — паспорт машины С ЭТИМ ГРУЗОМ, тонны.
//
// # Что здесь считается и почему именно здесь
//
// Три величины машины зависят от загрузки, и все три обязаны меняться ВМЕСТЕ:
// масса (тара плюс груз), основное удельное сопротивление (у ПТР для вагона
// оно делится на нагрузку от оси) и расчётное тормозное нажатие (авторежим
// ведёт его по массе). Посчитай их порознь — и появится состояние, в котором
// вагон уже тяжёлый, а тормозит ещё как порожний.
//
// Место — здесь, а не у зовущего, по правилу набора: паспорт переводится в
// домен один раз и в одном месте, и невалидного паспорта после Load не
// существует. Отказать AtLoad может ровно одним способом — грузом, которого
// машина не принимает, и это ошибка ВЫЗЫВАЮЩЕГО, а не набора.
func (t StockType) AtLoad(loadT float64) (physics.Locomotive, error) {
	f := t.freight
	if f == nil {
		return physics.Locomotive{}, fmt.Errorf(
			"content: тип %s: груз %.1f т машине постоянного веса; грузоподъёмности у неё нет", t.ID, loadT)
	}
	if loadT < 0 || math.IsNaN(loadT) || loadT > f.payloadT {
		return physics.Locomotive{}, fmt.Errorf(
			"content: тип %s: груз %.1f т вне [0, %.1f] — грузоподъёмность машины столько не принимает",
			t.ID, loadT, f.payloadT)
	}
	l := t.loco
	mass, err := units.TonnesToMass(f.tareT + loadT)
	if err != nil {
		return physics.Locomotive{}, fmt.Errorf("content: тип %s: масса брутто: %w", t.ID, err)
	}
	l.Mass = mass

	// НАГРУЗКА ОТ ОСИ — в тс на ось, как её печатает ПТР: масса в тоннах равна
	// весу в тоннах-силы численно, и лишний перевод в ньютоны и обратно только
	// добавил бы округление в знаменатель.
	q0 := (f.tareT + loadT) / f.axles
	if q0 >= f.res.EmptyBelowQ0 {
		// Гружёная форма: три члена делятся на q0. Тройка выводится ЗДЕСЬ и
		// нигде больше — иначе паспорт и физика считали бы её порознь.
		res, err := physics.ResistanceFrom(
			f.res.Base+f.res.K0/q0, f.res.K1/q0, f.res.K2/q0)
		if err != nil {
			return physics.Locomotive{}, fmt.Errorf("content: тип %s: сопротивление при q0=%.2f тс/ось: %w",
				t.ID, q0, err)
		}
		l.Res = res
	}
	// Иначе остаётся порожняя кривая, уже стоящая в t.loco.Res: ниже порога
	// источника действует она, и подменять её выведенной значило бы применить
	// формулу за границей, для которой её напечатали.

	// АВТОРЕЖИМ: нажатие идёт от порожнего конца к гружёному вместе с грузом.
	// Доля берётся от ГРУЗА, а не от массы брутто: прибор меряет прогиб
	// рессор, то есть то, что добавили сверх тары.
	kn := f.emptyKN
	if f.payloadT > 0 {
		kn += (f.loadedKN - f.emptyKN) * loadT / f.payloadT
	}
	force, err := units.KilonewtonsToForce(kn)
	if err != nil {
		return physics.Locomotive{}, fmt.Errorf("content: тип %s: нажатие на ось при грузе %.1f т: %w",
			t.ID, loadT, err)
	}
	l.AxleBrakeForce = force
	return l, nil
}

// AirBrake — уставки пневматики машины. Второе значение ложно у машины, которая
// тормозит одним числом, а не давлением: спрашивающий обязан различать эти
// случаи, а не получать нули под видом уставок.
func (t StockType) AirBrake() (brake.Spec, bool) { return t.air, t.hasAir }

// loadStock проверяет и укладывает паспорта.
func (s *Set) loadStock(types []StockType) error {
	seen := map[string]bool{}
	for i, t := range types {
		if err := mapfmt.ValidID("тип подвижного состава", t.ID); err != nil {
			return fmt.Errorf("content: паспорт %d: %w", i, err)
		}
		if seen[t.ID] {
			return fmt.Errorf("content: тип %s объявлен дважды: одно имя — одна машина", t.ID)
		}
		seen[t.ID] = true
		type positive struct {
			name string
			v    float64
		}
		sizes := []positive{{"length", t.LengthM}, {"width", t.WidthM}, {"height", t.HeightM},
			{"bogie_base", t.BogieBaseM}, {"max_speed", t.MaxSpeedKmh}}
		// ВЕС НАЗЫВАЕТСЯ РОВНО ОДНИМ СПОСОБОМ. Машина с грузом живёт между тарой
		// и брутто, машина постоянного веса — одним числом; заполненные оба
		// поля дали бы два источника одной массы, а пустые оба — машину, у
		// которой веса нет вовсе.
		switch {
		case t.Freight != nil && t.MassT != 0:
			return fmt.Errorf("content: тип %s: объявлены и mass, и freight — "+
				"вес машины называется одним способом: постоянным числом либо тарой с грузоподъёмностью", t.ID)
		case t.Freight == nil:
			sizes = append(sizes, positive{"mass", t.MassT})
		default:
			sizes = append(sizes,
				positive{"freight.tare", t.Freight.TareT},
				positive{"freight.payload", t.Freight.PayloadT})
			if t.Freight.Axles <= 0 {
				return fmt.Errorf("content: тип %s: freight.axles = %d — машина без осей "+
					"нагрузки на ось не имеет, а по ней считается сопротивление", t.ID, t.Freight.Axles)
			}
		}
		for _, d := range sizes {
			if !(d.v > 0) || math.IsInf(d.v, 0) {
				return fmt.Errorf("content: тип %s: %s = %v, ожидалось положительное конечное число",
					t.ID, d.name, d.v)
			}
		}
		// ФИЗИКА КОМПИЛИРУЕТСЯ В МЕСТЕ ХРАНЕНИЯ, а не в копии цикла: результат
		// перевода обязан уехать в набор, а `t` — копия по значению, и запись в
		// неё потерялась бы молча.
		if err := types[i].compilePhysics(); err != nil {
			return err
		}
		// База шкворней внутри машины: она мерится между опорами, а не между
		// автосцепками, и база длиннее машины означала бы опечатку в разряде.
		if t.BogieBaseM >= t.LengthM {
			return fmt.Errorf("content: тип %s: база шкворней %.2f м не меньше длины %.2f м",
				t.ID, t.BogieBaseM, t.LengthM)
		}
		// Ссылка разрешается ЗДЕСЬ, а не при отдаче: паспорт, ссылающийся в
		// пустоту, — испорченный набор, и он обязан не собраться.
		if t.Appearance == "" {
			return fmt.Errorf("content: тип %s: не указан appearance; вид объявляется ссылкой, "+
				"а не выводится из имени типа", t.ID)
		}
		a, ok := s.asset(t.Appearance)
		if !ok {
			return fmt.Errorf("content: тип %s: вид %q в наборе не объявлен", t.ID, t.Appearance)
		}
		if err := t.checkCabs(a); err != nil {
			return err
		}
		if err := t.checkControls(); err != nil {
			return err
		}
		// ПЕРЕЧЕНЬ ОРГАНОВ — В МЕСТО ХРАНЕНИЯ, а не в копию цикла, по тому же
		// доводу, что и физика восемью строками выше. Здесь стояло `t.Organs = …`,
		// и запись пропадала МОЛЧА: на проводе organs оказывался пустым, клиент
		// не находил ни одного органа, и ни одна клавиша кабины не работала.
		// Поймал это зонд кабины, а не проверки: у проверок свои фикстуры, и они
		// собирают перечень сами.
		types[i].Organs = types[i].organs()
	}
	s.Stock = append([]StockType(nil), types...)
	sortedByID(s.Stock, func(t StockType) string { return t.ID })
	return nil
}

// compilePhysics переводит паспорт в домен и отказывает, если он не сходится.
//
// # Почему проверки именно эти
//
// Каждая ловит опечатку, которая иначе прошла бы насквозь и вышла на экране
// правдоподобным враньём, а не отказом:
//
//	сцепной вес больше служебного — машина, у которой на движущих осях больше
//	  массы, чем в ней самой; сила трогания завышена ровно на эту разницу;
//	скорость режима выше конструкционной — режим, в котором машина не бывает,
//	  и мощность на ободе, выведенная из него, завышена;
//	неположительная сила или скорость режима — деление на ноль при выводе
//	  мощности либо машина, тянущая назад.
//
// Тонны-силы, перепутанные с килоньютонами, здесь НЕ ловятся, и это названо
// честно: 40.9 и 401.1 обе правдоподобны, отличаются вдесятеро и обе проходят
// любую проверку диапазона. От этого сторожит только имя поля с единицей в
// комментарии и тест, сверяющий с паспортом.
func (t *StockType) compilePhysics() error {
	res, err := physics.ResistanceFrom(t.Res.A, t.Res.B, t.Res.C)
	if err != nil {
		return fmt.Errorf("content: тип %s: %w", t.ID, err)
	}
	// Масса домена — у машины с грузом это ТАРА: паспорт описывает её порожней,
	// а гружёное состояние существует только вместе с числом груза (AtLoad).
	massT := t.MassT
	if t.Freight != nil {
		massT = t.Freight.TareT
	}
	mass, err := units.TonnesToMass(massT)
	if err != nil {
		return fmt.Errorf("content: тип %s: масса: %w", t.ID, err)
	}
	maxSpeed, err := units.KmhToSpeed(t.MaxSpeedKmh)
	if err != nil {
		return fmt.Errorf("content: тип %s: конструкционная скорость: %w", t.ID, err)
	}
	shoes := physics.ShoeKind(t.Brake.Shoes)
	if !shoes.Known() {
		return fmt.Errorf("content: тип %s: brake.shoes = %q, знаю %q и %q; "+
			"у чугунной и композиционной колодки разные формулы трения, и умолчание выбрало бы за автора",
			t.ID, t.Brake.Shoes, physics.ShoesCastIron, physics.ShoesComposite)
	}
	if t.Brake.BrakedAxles <= 0 {
		return fmt.Errorf("content: тип %s: brake.braked_axles = %d — машина без тормозных осей "+
			"остановиться не может", t.ID, t.Brake.BrakedAxles)
	}
	// НАЖАТИЕ НАЗЫВАЕТСЯ ПО ФОРМЕ МАШИНЫ: постоянного веса — одним числом,
	// с грузом — двумя концами авторежима. Перепутанные формы — отказ, а не
	// подстановка: паспорт вагона с одним нажатием означал бы вагон, который
	// тормозит гружёным как порожний.
	if err := t.checkBrakeForm(); err != nil {
		return err
	}
	emptyKN := t.Brake.AxleForceKN
	if t.Freight != nil {
		emptyKN = t.Brake.AxleForceEmptyKN
	}
	axleBrake, err := units.KilonewtonsToForce(emptyKN)
	if err != nil {
		return fmt.Errorf("content: тип %s: расчётное нажатие на ось: %w", t.ID, err)
	}
	// ПНЕВМАТИКА — ДО замыкания ниже, и порядок этот вынужденный: локальное имя
	// brake затенило бы пакет brake, а проверять уставки надо им.
	if air, ok := t.Brake.Domain(); ok {
		if err := air.Validate(); err != nil {
			return fmt.Errorf("content: тип %s: %w", t.ID, err)
		}
		t.air = air
		t.hasAir = true
	}
	brake := func(l physics.Locomotive) physics.Locomotive {
		l.Shoes = shoes
		l.AxleBrakeForce = axleBrake
		l.BrakedAxles = int64(t.Brake.BrakedAxles)
		return l
	}
	// ГРУЗ — В ДОМЕН, до ветвления на локомотив: возить груз и тянуть поезд не
	// исключают друг друга (мотор-вагонная секция возит и то и другое), и
	// привязывать перевод груза к отсутствию тяги значило бы объявить это
	// правилом.
	if t.Freight != nil {
		if err := t.compileFreight(); err != nil {
			return err
		}
	} else if t.ResLoaded != nil {
		return fmt.Errorf("content: тип %s: объявлено сопротивление гружёной машины (resistance_loaded) "+
			"у машины постоянного веса — гружёного состояния у неё нет", t.ID)
	}
	if t.Traction == nil {
		// Не локомотив — законный случай, а не недописанный паспорт. Сопротивление
		// и тормоз у него всё равно есть: катится и тормозит всё.
		t.loco = brake(physics.Locomotive{Mass: mass, MaxSpeed: maxSpeed, Res: res})
		t.isLoco = false
		return nil
	}
	tr := *t.Traction
	for _, d := range []struct {
		name string
		v    float64
	}{{"adhesive_mass", tr.AdhesiveMassT}, {"continuous_force", tr.ContinuousForceKN},
		{"continuous_speed", tr.ContinuousSpeedKmh}} {
		if !(d.v > 0) || math.IsInf(d.v, 0) {
			return fmt.Errorf("content: тип %s: traction.%s = %v, ожидалось положительное конечное число",
				t.ID, d.name, d.v)
		}
	}
	if tr.AdhesiveMassT > t.MassT {
		return fmt.Errorf("content: тип %s: сцепной вес %.1f т больше служебной массы %.1f т — "+
			"на движущих осях не бывает больше массы, чем во всей машине", t.ID, tr.AdhesiveMassT, t.MassT)
	}
	if tr.ContinuousSpeedKmh > t.MaxSpeedKmh {
		return fmt.Errorf("content: тип %s: скорость длительного режима %.1f км/ч выше конструкционной %.1f км/ч",
			t.ID, tr.ContinuousSpeedKmh, t.MaxSpeedKmh)
	}
	adhesive, err := units.TonnesToMass(tr.AdhesiveMassT)
	if err != nil {
		return fmt.Errorf("content: тип %s: сцепной вес: %w", t.ID, err)
	}
	force, err := units.KilonewtonsToForce(tr.ContinuousForceKN)
	if err != nil {
		return fmt.Errorf("content: тип %s: сила длительного режима: %w", t.ID, err)
	}
	speed, err := units.KmhToSpeed(tr.ContinuousSpeedKmh)
	if err != nil {
		return fmt.Errorf("content: тип %s: скорость длительного режима: %w", t.ID, err)
	}
	// Мощность на ободе — произведение силы на скорость режима. Ньютон на
	// микрометр в секунду даёт микроватты, отсюда деление на миллион.
	// Предел двигателей необязателен: ноль значит «не объявлен», и машина не
	// буксует (разбор — у physics.TractionLimit).
	var maxForce units.Force
	if tr.MaxForceKN > 0 {
		maxForce, err = units.KilonewtonsToForce(tr.MaxForceKN)
		if err != nil {
			return fmt.Errorf("content: тип %s: предел двигателей: %w", t.ID, err)
		}
		if maxForce < force {
			return fmt.Errorf("content: тип %s: traction.max_force = %g кН меньше силы длительного "+
				"режима %g кН — двигатели не могут быть слабее собственного длительного режима",
				t.ID, tr.MaxForceKN, tr.ContinuousForceKN)
		}
	}
	t.loco = brake(physics.Locomotive{
		Mass:         mass,
		AdhesiveMass: adhesive,
		RimPower:     int64(force) * int64(speed) / 1_000_000,
		MaxSpeed:     maxSpeed,
		MaxForce:     maxForce,
		Res:          res,
	})
	t.isLoco = true
	return nil
}

// checkBrakeForm — нажатие названо той формой, которая отвечает устройству
// машины: одним числом либо двумя концами авторежима, и никогда обеими сразу.
//
// Отдельной функцией, а не строчками в compilePhysics, потому что это ЧЕТЫРЕ
// разных отказа с четырьмя разными причинами, и каждая обязана называться
// своим текстом: автор, написавший вагону одно нажатие, и автор, написавший
// локомотиву два, ошиблись по-разному.
func (t *StockType) checkBrakeForm() error {
	hasSingle := t.Brake.AxleForceKN != 0
	hasRange := t.Brake.AxleForceEmptyKN != 0 || t.Brake.AxleForceLoadedKN != 0
	if t.Freight == nil {
		if hasRange {
			return fmt.Errorf("content: тип %s: у машины постоянного веса объявлены концы авторежима "+
				"(axle_force_empty/axle_force_loaded) — регулировать нажатие по загрузке у неё нечем", t.ID)
		}
		if !(t.Brake.AxleForceKN > 0) || math.IsInf(t.Brake.AxleForceKN, 0) {
			return fmt.Errorf("content: тип %s: brake.axle_force = %v, ожидалось положительное конечное число",
				t.ID, t.Brake.AxleForceKN)
		}
		return nil
	}
	if hasSingle {
		return fmt.Errorf("content: тип %s: у машины с грузом объявлено одно нажатие (axle_force) — "+
			"нажатие такой машины идёт с загрузкой, и одним числом её тормоз описать нельзя", t.ID)
	}
	for _, d := range []struct {
		name string
		v    float64
	}{{"axle_force_empty", t.Brake.AxleForceEmptyKN}, {"axle_force_loaded", t.Brake.AxleForceLoadedKN}} {
		if !(d.v > 0) || math.IsInf(d.v, 0) {
			return fmt.Errorf("content: тип %s: brake.%s = %v, ожидалось положительное конечное число",
				t.ID, d.name, d.v)
		}
	}
	// Гружёный конец НИЖЕ порожнего — это переставленные местами числа, и
	// поймать их больше нечем: оба правдоподобны по величине, а последствие —
	// вагон, который с грузом тормозит слабее, чем пустой.
	if t.Brake.AxleForceLoadedKN < t.Brake.AxleForceEmptyKN {
		return fmt.Errorf("content: тип %s: нажатие гружёной машины %.1f кН меньше порожней %.1f кН — "+
			"похоже, концы авторежима переставлены местами",
			t.ID, t.Brake.AxleForceLoadedKN, t.Brake.AxleForceEmptyKN)
	}
	return nil
}

// compileFreight переводит блок груза в домен и отказывает, если он не сходится.
//
// Проверки те же по духу, что у тяги: каждая ловит опечатку, которая иначе
// вышла бы на экран правдоподобным враньём. Порог порожней формулы обязан быть
// положительным — ноль означал бы, что порожней кривой нет вовсе, хотя она
// объявлена полем resistance; коэффициенты гружёной формы неотрицательны, а её
// свободный член положителен по тому же доводу, что и у physics.ResistanceFrom:
// машина без основного сопротивления катилась бы по горизонтали вечно.
func (t *StockType) compileFreight() error {
	if t.ResLoaded == nil {
		return fmt.Errorf("content: тип %s: у машины с грузом не объявлено сопротивление гружёной "+
			"(resistance_loaded) — гружёная кривая ПТР не выводится из порожней", t.ID)
	}
	r := *t.ResLoaded
	if !(r.Base > 0) || math.IsInf(r.Base, 0) {
		return fmt.Errorf("content: тип %s: resistance_loaded.base = %v, ожидалось положительное конечное число",
			t.ID, r.Base)
	}
	for _, d := range []struct {
		name string
		v    float64
	}{{"k0", r.K0}, {"k1", r.K1}, {"k2", r.K2}} {
		if d.v < 0 || math.IsInf(d.v, 0) || math.IsNaN(d.v) {
			return fmt.Errorf("content: тип %s: resistance_loaded.%s = %v, ожидалось неотрицательное конечное число",
				t.ID, d.name, d.v)
		}
	}
	if !(r.EmptyBelowQ0 > 0) || math.IsInf(r.EmptyBelowQ0, 0) {
		return fmt.Errorf("content: тип %s: resistance_loaded.empty_below_q0 = %v — "+
			"порог порожней формулы объявлен ПТР и обязан быть положительным", t.ID, r.EmptyBelowQ0)
	}
	t.freight = &freightDomain{
		tareT:    t.Freight.TareT,
		payloadT: t.Freight.PayloadT,
		axles:    float64(t.Freight.Axles),
		emptyKN:  t.Brake.AxleForceEmptyKN,
		loadedKN: t.Brake.AxleForceLoadedKN,
		res:      r,
	}
	return nil
}

// checkCabs — посты вида обязаны попадать в габарит паспорта.
//
// # Почему проверку делает паспорт, а не запись вида
//
// Потому что габарита у вида нет и быть не должно: он его не знает. Сверить
// нарисованное с объявленным можно только там, где обе стороны на руках, а это
// ровно здесь — в месте, где разрешается ссылка appearance.
//
// # Что ловится
//
// Опечатка в разряде и путаница осей. Пост, оказавшийся вне габарита, — это
// либо метры, набранные не в тех единицах, либо z, записанное в поле y, и на
// экране это выйдет машинистом, стоящим в воздухе рядом с машиной или под
// колёсами. Отказ здесь дешевле: набор не соберётся, и сервер не поднимется.
//
// # Чего проверка НЕ доказывает
//
// Что пост стоит именно в кабине. Габарит — это коробка вокруг всей машины, и
// точка посреди тягового трансформатора пройдёт её так же успешно. Доказывает
// это ЗАМЕР МЕША, которым числа и получены (Asset.Cabs), и кадр из кабины;
// здесь стоит грубое сито, и оно объявлено грубым, чтобы на него не полагались
// как на точное.
//
// Отсчёт вертикали — ОТ ПОВЕРХНОСТИ КАТАНИЯ, тот же, что у HeightM: второго
// датума машина не заводит. Ноль допустим (пол на уровне головки рельса — не
// наша машина, но и не опечатка), отрицательное — нет.
// checkControls проверяет блок органов управления.
//
// Проверок ровно две, и обе про одно: ступень обязана существовать. Ноль
// ступеней означает орган, который нельзя сдвинуть, — то есть паспорт, где
// автор заполнил блок и забыл число; отрицательное — опечатку в знаке.
// Верхней границы нет: 33 ступени ЭКГ-8Ж уже необычно много, и любой потолок
// сверх этого был бы взят с потолка.
//
// ЛОКОМОТИВ БЕЗ ОРГАНОВ — ОТКАЗ, и это не педантизм: машина с тягой, которой
// нечем управлять, поедет только по команде автопилота, которого нет. Вагон с
// органами — тоже отказ: управлять вагоном нечем, и блок в его паспорте
// означает, что автор перепутал строки.
// Имена органов управления (StockType.Organs).
//
// Перечень ЗАКРЫТ, и это его смысл: имя органа — часть договора, по нему клиент
// решает, какую рукоятку рисовать и какую клавишу к ней привязывать. Новый орган
// заводится вместе с тем, что он делает в физике, а не «про запас»: рукоятка,
// которой нечего двигать, — та же кнопка-обманка, что и ступени тормоза у машины
// с магистралью.
const (
	// OrganTraction — контроллер тяги. Есть у всякой машины с тягой.
	OrganTraction = "traction"
	// OrganReverser — реверсор. Там же, где контроллер: без него цепь тяги не
	// собирается.
	OrganReverser = "reverser"
	// OrganBrake — СТУПЕНЧАТЫЙ тормоз: у машины без магистрали глубину задаёт
	// ступень, а не давление.
	OrganBrake = "brake"
	// OrganHandle — кран машиниста. Есть ровно там, где есть магистраль.
	OrganHandle = "handle"
	// OrganIndependent — кран вспомогательного тормоза локомотива.
	OrganIndependent = "independent"
)

// ActionRelease — ДЕЙСТВИЕ МАШИНЫ ЦЕЛИКОМ, а не орган: экстренная остановка
// ведёт сразу несколько рукояток (тяга в ноль, кран в экстренное, вспомогательный
// на полное, реверсор в ноль).
//
// Стоит в том же перечне, что органы, потому что вопрос у клиента один и тот же:
// какой клавишей это делают и как назвать это человеку. Отличается полем Kind.
const ActionRelease = "release"

// Виды записей перечня: орган (рукоятка, у которой есть положение) и действие
// (одно нажатие, которое ведёт несколько рукояток разом).
const (
	KindOrgan  = "organ"
	KindAction = "action"
)

// Organ — ЗАПИСЬ ПЕРЕЧНЯ УПРАВЛЕНИЯ: что у машины есть, как оно называется и
// какой клавишей его ведут.
//
// # Почему КЛАВИШИ ТОЖЕ ЗДЕСЬ
//
// Слово владельца 2026-08-15: «горячие клавиши, кстати, тоже должны приходить с
// сервера». До этого раскладка кабины была таблицей в world.gd, а СПИСОК КЛАВИШ
// на экране (F1) — второй таблицей в cab_panel.gd, и обе были клиентскими. Две
// таблицы одного и того же уже расходились: пары 3/4 не было в списке, хотя
// клавиши работали.
//
// Возражение, которое здесь стоит назвать, потому что оно верное: клавиатура —
// свойство УСТРОЙСТВА ВВОДА, а не мира, и у клиента с геймпадом никакой «W» нет.
// Ответ: сервер объявляет ПРЕДЛОЖЕННУЮ раскладку вместе с органом, а чем её
// нажать — по-прежнему дело клиента. Клиент с геймпадом читает Name и Kind и
// вешает свою кнопку; клиент с клавиатурой берёт готовое и не выдумывает. Что
// сегодня НЕ приходит с сервера — клавиши ВИДА и ОТЛАДКИ (V, H, F1, F): они не о
// машине вовсе.
type Organ struct {
	// ID — имя органа или действия (Organ*, Action*).
	ID string `json:"id"`
	// Kind — KindOrgan или KindAction.
	Kind string `json:"kind"`
	// Name — как назвать это человеку. Показывает список клавиш.
	Name string `json:"name"`
	// Up, Down — клавиши «прибавить» и «убавить». У действия (Kind == KindAction)
	// заполнена только Up: убавлять там нечего.
	//
	// СПИСКОМ, а не одной: у контроллера тяги их две пары (W/S и 2/1), и вторая —
	// не запасная, а вторая рука. Форма имени объявлена ниже (keyName).
	Up   []string `json:"up,omitempty"`
	Down []string `json:"down,omitempty"`
}

// organs — перечень органов и действий ЭТОЙ машины. Зовётся один раз при
// загрузке, после того как пределы проверены: перечень выводится из них, а
// выводить его из непроверенных чисел значило бы назвать орган у машины,
// паспорт которой не сошёлся.
//
// ИМЕНА И КЛАВИШИ БЕРУТСЯ ИЗ ПАСПОРТА (ControlsSpec.Keys): их пишет автор
// набора, потому что у каждой машины кабина своя. Орган без записи клавиш —
// отказ (checkControls), поэтому здесь ветки «а если не написали» нет.
func (t StockType) organs() []Organ {
	if t.Controls == nil {
		return nil
	}
	ids := []string{OrganTraction, OrganReverser}
	if t.Controls.BrakeNotches > 0 {
		ids = append(ids, OrganBrake)
	}
	if air, ok := t.Brake.Domain(); ok {
		ids = append(ids, OrganHandle)
		if air.HasIndependent() {
			ids = append(ids, OrganIndependent)
		}
	}
	ids = append(ids, ActionRelease)
	out := make([]Organ, 0, len(ids))
	for _, id := range ids {
		k := t.Controls.Keys[id]
		kind := KindOrgan
		if id == ActionRelease {
			kind = KindAction
		}
		out = append(out, Organ{ID: id, Kind: kind, Name: k.Name, Up: k.Up, Down: k.Down})
	}
	return out
}

// hasOrgan — есть ли у машины орган (или действие) с таким именем. Считается по
// тому же правилу, что перечень: второго правила вывода не заводится.
func (t StockType) hasOrgan(id string) bool {
	for _, o := range t.organs() {
		if o.ID == id {
			return true
		}
	}
	return false
}

func (t StockType) checkControls() error {
	// ПЕРЕЧЕНЬ ОРГАНОВ АВТОР НЕ ПИШЕТ. Он выводится из пределов (organs), и
	// написанный руками стал бы вторым источником того же факта — первым же
	// расхождением была бы рукоятка, которую пульт рисует, а сервер не принимает.
	if len(t.Organs) > 0 {
		return fmt.Errorf("content: тип %s: поле organs выводится из пределов, автор его не пишет", t.ID)
	}
	if t.Traction == nil {
		if t.Controls != nil {
			return fmt.Errorf("content: тип %s: органы управления объявлены у машины без тяги — "+
				"управлять нечем", t.ID)
		}
		return nil
	}
	if t.Controls == nil {
		return fmt.Errorf("content: тип %s: у локомотива не объявлены органы управления "+
			"(controls): машиной с тягой должно быть чем управлять", t.ID)
	}
	if t.Controls.TractionNotches < 1 {
		return fmt.Errorf("content: тип %s: controls.traction_notches = %d, "+
			"ожидалась хотя бы одна ступень тяги", t.ID, t.Controls.TractionNotches)
	}
	// СТУПЕНИ ТОРМОЖЕНИЯ И МАГИСТРАЛЬ ВЗАИМНО ИСКЛЮЧАЮТ ДРУГ ДРУГА.
	//
	// У машины с тормозной магистралью глубину торможения задаёт РАЗРЯДКА, и
	// физика читает давление цилиндра, а не ступень (sim.forces): ветка ступеней
	// у такой машины недостижима по построению. Объявленное число ступеней при
	// этом доезжало до пульта, и клавиши двигали рукоятку, которой ничего не
	// соответствует, — орган, который ходит и не действует.
	//
	// Отказ, а не молчаливое обнуление: паспорт, объявивший обе тормозные
	// системы разом, — это не машина с двумя тормозами, а недописанный паспорт, и
	// подставить за автора одну из двух значило бы выбрать за него тормоз.
	_, hasAir := t.Brake.Domain()
	if hasAir {
		if t.Controls.BrakeNotches != 0 {
			return fmt.Errorf("content: тип %s: объявлены и тормозная магистраль (brake.air), "+
				"и controls.brake_notches = %d — глубину торможения задаёт что-то одно: "+
				"у машины с магистралью её задаёт разрядка, а ступеней нет",
				t.ID, t.Controls.BrakeNotches)
		}
		return nil
	}
	if t.Controls.BrakeNotches < 1 {
		return fmt.Errorf("content: тип %s: controls.brake_notches = %d, "+
			"ожидалась хотя бы одна ступень торможения", t.ID, t.Controls.BrakeNotches)
	}
	return t.checkKeys()
}

// checkKeys — РАСКЛАДКА СХОДИТСЯ С ТЕМ, ЧТО У МАШИНЫ ЕСТЬ.
//
// Два отказа, и оба про одно и то же — про орган, который ходит и не действует
// (либо действует, но его нечем тронуть):
//
//	КЛАВИШ НЕТ У ОРГАНА, КОТОРЫЙ ЕСТЬ — рукоятка на пульте, к которой не
//	  привязано ничего. Ровно тем и был ступенчатый тормоз ВЛ80 до этого дня.
//	КЛАВИШИ ЕСТЬ У ОРГАНА, КОТОРОГО НЕТ — клавиша, которая молча пропадает, и
//	  человек ищет причину в себе.
func (t StockType) checkKeys() error {
	for _, o := range t.organs() {
		if o.Name == "" {
			return fmt.Errorf("content: тип %s: у органа %s не объявлены клавиши и имя "+
				"(controls.keys) — рукоятку нечем тронуть и нечем назвать", t.ID, o.ID)
		}
		if len(o.Up) == 0 {
			return fmt.Errorf("content: тип %s: у органа %s нет ни одной клавиши", t.ID, o.ID)
		}
		if o.Kind == KindOrgan && len(o.Down) == 0 {
			return fmt.Errorf("content: тип %s: у органа %s нет клавиши «убавить» — "+
				"рукоятка, которая идёт только в одну сторону, не рукоятка", t.ID, o.ID)
		}
		for _, k := range append(append([]string{}, o.Up...), o.Down...) {
			if err := checkKeyName(t.ID, o.ID, k); err != nil {
				return err
			}
		}
	}
	for id := range t.Controls.Keys {
		if !t.hasOrgan(id) {
			return fmt.Errorf("content: тип %s: клавиши объявлены для %s, которого у машины нет — "+
				"клавиша, которая ничего не делает", t.ID, id)
		}
	}
	return nil
}

// checkKeyName — форма имени клавиши. Разбор — у OrganKeys.
func checkKeyName(typeID, organ, key string) error {
	name := strings.TrimPrefix(key, "shift+")
	if len(name) != 1 {
		return fmt.Errorf("content: тип %s: орган %s: клавиша %q — ожидалась одна буква или цифра "+
			"с необязательной приставкой shift+", typeID, organ, key)
	}
	c := name[0]
	if !(c >= 'A' && c <= 'Z') && !(c >= '0' && c <= '9') {
		return fmt.Errorf("content: тип %s: орган %s: клавиша %q — ожидалась ЗАГЛАВНАЯ латинская "+
			"буква либо цифра", typeID, organ, key)
	}
	return nil
}

func (t StockType) checkCabs(a Asset) error {
	for i, raw := range a.Cabs {
		p := a.Placed(raw)
		for _, d := range []struct {
			name   string
			v      float64
			lo, hi float64
			why    string
		}{
			{"поперёк оси", p[0], -t.WidthM / 2, t.WidthM / 2, "ширина"},
			{"над поверхностью катания", p[1], 0, t.HeightM, "высота"},
			{"вдоль хода", p[2], -t.LengthM / 2, t.LengthM / 2, "длина"},
		} {
			if d.v < d.lo || d.v > d.hi {
				return fmt.Errorf("content: тип %s, вид %s: пост %d %s на %.3f м, "+
					"а габарит паспорта (%s) допускает %.3f…%.3f м; "+
					"пост объявляется в осях ассета ДО масштаба и сдвига",
					t.ID, a.Name, i, d.name, d.v, d.why, d.lo, d.hi)
			}
		}
	}
	return nil
}
