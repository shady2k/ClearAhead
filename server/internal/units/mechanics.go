package units

import (
	"fmt"
	"math"
)

// GravityMicro — ускорение свободного падения в микрометрах на секунду в
// квадрате.
//
// 9.80665 м/с² — стандартное значение (CGPM, 1901), а не местное: широты в мире
// проекта нет, и выбирать значение по месту не из чего. Названо константой,
// потому что вес обязан считаться одной формулой: вторая копия числа разошлась
// бы с первой на правке разрядности и разошлась бы молча.
const GravityMicro = 9806650

// Mass — масса в килограммах.
//
// int64 килограммов покрывает ±9.2e18 кг; состав в десять тысяч тонн — это 1e7,
// то есть запас одиннадцать порядков. Грамм не нужен: паспортные массы известны
// с точностью до тонны, и разрядность ниже килограмма изображала бы точность,
// которой у источника нет.
type Mass int64

const (
	Kilogram Mass = 1
	Tonne         = 1000 * Kilogram
)

// TonnesToMass переводит тонны паспорта в килограммы домена.
//
// Тонна — единица ИНТЕРФЕЙСА: в ней записаны все паспорта и в ней их читает
// человек. Килограмм — представление. То же правило и та же граница, что у
// метра и микрометра (vertical-slice-design §7).
func TonnesToMass(t float64) (Mass, error) {
	if math.IsNaN(t) || math.IsInf(t, 0) {
		return 0, fmt.Errorf("units: недопустимое значение тонн: %v", t)
	}
	const maxTonnes = float64(math.MaxInt64) / float64(Tonne)
	if t > maxTonnes || t < -maxTonnes {
		return 0, fmt.Errorf("units: %v т не помещается в Mass", t)
	}
	return Mass(math.Round(t * float64(Tonne))), nil
}

// Tonnes возвращает массу в тоннах для показа. В домен результат не годится:
// округление уже произошло.
func (m Mass) Tonnes() float64 { return float64(m) / float64(Tonne) }

// Weight — вес: сила, с которой масса давит на путь.
//
// Считается ЗДЕСЬ, а не в физике, потому что это свойство массы, а не модели
// движения: сцепление, сопротивление и тормоз умножают на один и тот же вес, и
// три места умножения дали бы три разных ответа при первой же правке g.
//
// Округление к ближайшему ньютону: 192 т дают 1 883 087 Н, и единица в младшем
// разряде здесь ниже точности любого паспортного числа.
func (m Mass) Weight() Force {
	return Force((int64(m)*GravityMicro + 500_000) / 1_000_000)
}

// Speed — скорость в микрометрах в секунду.
//
// Шкала та же, что у расстояния, и это не совпадение: скорость складывается с
// расстоянием через время, и разные шкалы у них означали бы деление с потерей
// остатка на каждом шаге. 110 км/ч — это 3.06e7 мкм/с, запас до int64 —
// одиннадцать порядков.
type Speed int64

const MicrometerPerSecond Speed = 1

// KmhToSpeed переводит километры в час паспорта в микрометры в секунду домена.
func KmhToSpeed(kmh float64) (Speed, error) {
	if math.IsNaN(kmh) || math.IsInf(kmh, 0) {
		return 0, fmt.Errorf("units: недопустимое значение км/ч: %v", kmh)
	}
	// 1 км/ч = 1e9 мкм / 3600 с.
	v := kmh * 1e9 / 3600
	if math.Abs(v) > float64(math.MaxInt64) {
		return 0, fmt.Errorf("units: %v км/ч не помещается в Speed", kmh)
	}
	return Speed(math.Round(v)), nil
}

// Kmh возвращает скорость в километрах в час для показа.
func (v Speed) Kmh() float64 { return float64(v) * 3600 / 1e9 }

// MilliKmh — скорость в тысячных долях километра в час.
//
// # Зачем эта шкала существует
//
// Формулы ПТР записаны от скорости В КИЛОМЕТРАХ В ЧАС, и переводить в них
// микрометры в секунду пришлось бы в каждом слагаемом отдельно, множа шансы
// перепутать разряд. Милликилометр в час — компромисс, у которого есть замер:
// шаг 0.001 км/ч это 0.28 мм/с, то есть заметно мельче любой скорости, которую
// физика различает, и при этом V² на конструкционной скорости 110 км/ч даёт
// 1.2e10 — до потолка int64 остаётся восемь порядков.
//
// Деление ЦЕЛОЕ и остаток теряется НАРОЧНО: это перевод в более грубую шкалу
// для формулы сопротивления, а не шаг накопления. Накопитель остатка здесь
// хранил бы дробь скорости между вызовами чистой функции, то есть завёл бы у
// неё состояние.
func (v Speed) MilliKmh() int64 { return int64(v) * 36 / 10_000 }

// Force — сила в ньютонах.
//
// Целые ньютоны, а не милли: паспортная сила тяги известна с точностью до
// десятых тонны-силы (сотни ньютонов), и младшие разряды изображали бы точность
// источника, которой в нём нет. Запас до int64 — четырнадцать порядков от
// миллиона ньютонов боевой машины.
type Force int64

const (
	Newton     Force = 1
	Kilonewton       = 1000 * Newton
)

// Kilonewtons возвращает силу в килоньютонах для показа.
func (f Force) Kilonewtons() float64 { return float64(f) / float64(Kilonewton) }

// TonnesForce возвращает силу в тоннах-силы — единице, в которой её печатают
// все русские паспорта. Только для показа и сверки с источником.
func (f Force) TonnesForce() float64 { return float64(f) * 1e6 / (1000 * GravityMicro) }

// KilonewtonsToForce переводит килоньютоны паспорта в ньютоны домена.
func KilonewtonsToForce(kn float64) (Force, error) {
	if math.IsNaN(kn) || math.IsInf(kn, 0) {
		return 0, fmt.Errorf("units: недопустимое значение кН: %v", kn)
	}
	const maxKN = float64(math.MaxInt64) / float64(Kilonewton)
	if kn > maxKN || kn < -maxKN {
		return 0, fmt.Errorf("units: %v кН не помещается в Force", kn)
	}
	return Force(math.Round(kn * float64(Kilonewton))), nil
}
