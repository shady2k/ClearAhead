package units

import (
	"fmt"
	"strconv"
)

// SimTime — МОДЕЛЬНОЕ время партии в микросекундах от её начала.
//
// # Почему свой тип, а не time.Duration
//
// Потому что настенное время и модельное — разные величины, и складывать их
// нельзя. time.Duration складывается с чем угодно того же типа, и выражение
// вида `simTime + time.Since(started)` компилируется молча — а это ровно та
// ошибка, ради невозможности которой заведён отдельный тип. Тот же приём, что у
// netloc: авторская u и скомпилированная s разведены системой типов, потому что
// их смешение не даёт отказа загрузки — оно даёт правдоподобный, но неверный
// результат.
//
// Разделение записано в вертикальном срезе §8 списком из четырёх сущностей:
// SimTime (каноническое время мира), EngineTick (номер тика), JournalSeq
// (порядок команд) и Pacer (как быстро процесс продвигает SimTime относительно
// настенных часов). Здесь — первая из них.
//
// # Почему микросекунды
//
// Число из эскиза ядра §8 («время | мкс модельного времени»). Довод — тот же,
// что у микрометров: события ВНУТРИ тика (пересечение сигнала, границы участка,
// момент остановки) имеют точный момент, и миллисекунда для него слишком груба —
// поезд на 160 км/ч проходит за неё 44 мм.
//
// Наносекунды отвергнуты нарочно, и не из экономии разрядов: наносекунда — это
// единица time.Duration, и тип, совпадающий с ней по масштабу, однажды будет в
// неё присвоен «потому что и так сходится».
type SimTime int64

const (
	Microsecond SimTime = 1
	Millisecond         = 1000 * Microsecond
	Second              = 1000 * Millisecond
	// Hour заведён с потребителем, а не для полноты ряда: им выражена смена в
	// восемь часов модельного времени — величина, которой проект меряет
	// детерминированный прогон (эскиз ядра §21).
	Hour = 3600 * Second
)

// Seconds возвращает время в секундах для показа и логов.
//
// Обратно в домен результат не годится: округление уже произошло. То же
// правило и по той же причине, что у Distance.Meters.
func (t SimTime) Seconds() float64 {
	return float64(t) / float64(Second)
}

// String печатает модельное время секундами с миллисекундной точностью.
//
// Не часы-минуты-секунды: у партии сегодня нет ни времени суток, ни даты — есть
// время ОТ НАЧАЛА, и «08:00:00» на экране обещало бы календарь, которого нет.
func (t SimTime) String() string {
	return strconv.FormatFloat(t.Seconds(), 'f', 3, 64) + "s"
}

// MarshalJSON пишет модельное время строкой микросекунд.
//
// # Правило провода
//
// Записано в revision-7-plan §4 и звучит так: «int64 микросекунд строкой, а не
// JSON-числом», потому что JSON.parse_string в Godot разбирает числа как float.
//
// ЗАМЕР, а не пересказ: float64 держит целые точно до 2^53, то есть до
// 9.0e15 мкс — это 285 лет модельного времени. Для НАШИХ величин потери
// точности, которой пугает записанный довод, не наступает вовсе, и честнее
// сказать это, чем повторять предупреждение, которого числа не подтверждают.
//
// Правило всё равно соблюдается, и опирается оно на второй довод, а не на
// первый: единообразие провода. Рядом уже едет units.Distance строкой, и
// «микрометры строкой, а микросекунды числом» — это соглашение, которое клиенту
// придётся помнить по одному полю за раз.
func (t SimTime) MarshalJSON() ([]byte, error) {
	return []byte(`"` + strconv.FormatInt(int64(t), 10) + `"`), nil
}

// UnmarshalJSON читает модельное время из строки микросекунд.
//
// Заведён вместе с записью, а не «когда понадобится», по единственной причине:
// без него json.Unmarshal в структуру с этим полем отказывает с сообщением про
// строку и int64, и разбирать его пришлось бы тому, кто пишет тест провода.
// Первый настоящий читатель — команда с меткой времени — приходит с В2.
func (t *SimTime) UnmarshalJSON(b []byte) error {
	if len(b) < 2 || b[0] != '"' || b[len(b)-1] != '"' {
		return fmt.Errorf("units: SimTime ожидается строкой микросекунд, получено %s", b)
	}
	v, err := strconv.ParseInt(string(b[1:len(b)-1]), 10, 64)
	if err != nil {
		return fmt.Errorf("units: разбор SimTime: %w", err)
	}
	*t = SimTime(v)
	return nil
}
