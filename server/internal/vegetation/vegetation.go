// Package vegetation — исходники и компилятор проекции леса.
//
// # Вопрос владельца и ответ формата
//
// «Вот у меня 1000 деревьев, одно срубили. Клиенту же нужно знать, что дерево,
// растущее там-то, теперь рисовать не надо.» Клиенту, чтобы НЕ нарисовать
// дерево, идентификатор не нужен — нужно знать, что ячейка пуста, а это уже
// несёт чанк: ForestBytes = CoverCells²/8, бит на ячейку покрова. Срубили одно
// дерево — бит стал нулём, и рубка стоит НОЛЬ лишних байт на проводе: блоб
// проекции фиксированного размера, рубка только снимает бит внутри него.
//
// # Чего не хватало и что добавилось
//
// ChunkForest (terrain) выводит лес из рецепта, и пересчёт воскрешает
// срубленное: вырубка нигде не сохранялась. Здесь она переезжает в исходники
// партии (журналируются), а проекция пересобирается компилятором по формуле
//
//	проекция = лес рецепта − срубленные + посаженные
//
// Обратной дельты нет и порядок не важен — проекция есть чистая функция
// множества исходников (контракт sources-compilers-projections §1, §3), те же
// свойства, что у насыпи.
//
// # Форма — гибрид, и каждая часть оплачена
//
//   - массовая вырубка под площадку — ОБЛАСТЬ (Clearing): одна запись на
//     площадку вместо тысячи записей на деревья;
//   - одиночная рубка — НАДГРОБИЕ адреса (Cut): чанк уровня 0 + индекс ячейки;
//   - посадка — явный экземпляр (Planted);
//   - высокая плотность рубок одного чанка — БИТОВАЯ МАСКА (CutMask), тот же
//     формат, что ForestBytes. Маска в 512 байт окупается после 64 рубок на
//     чанк: рубка в исходниках упаковывается в 8 байт (16+16+6+6 бит), и
//     512 / 8 = 64.
//
// # Тождество дерева — адрес, а не UUID
//
// Решение владельца «UUIDv7 везде» принято для сущностей, на которые
// ССЫЛАЮТСЯ. Деревья под него не попадают, и довод содержательный, а не
// экономящий байты: UUID не несёт МЕСТА. Клиент обязан поставить дерево до
// того, как на него кто-то сошлётся, а место он берёт из адреса —
// ForestJitter(cx, cz, i, j) даёт смещение, высоту ствола и поворот
// детерминированно от адреса, одинаково на сервере и клиенте. При UUID-тождестве
// пришлось бы возить таблицу «UUID → где стоит» на каждое рисуемое дерево.
// Правило: UUIDv7 — тождество того, на что ссылаются; дерево остаётся
// рельефом, пока на него никто не сослался. Понадобится ссылка (владелец
// делянки, подряд на вырубку) — дерево в тот момент становится сущностью.
// Сегодня такого потребителя нет, и поле под него не заводится (chunk-contract
// §8 назвал адрес дерева исключением, а не образцом).
//
// # Что отменено и почему — не переоткрывать
//
// Редакция 1 спеки хранила вырубку изменением сомкнутости на области. Отменено
// двумя доводами: арифметическим (§0.2 п. 3 — «состояние размером с мир»
// неверно по счёту: 570 661 экземпляр по биту это 71 КБ, а формат чанка УЖЕ
// несёт бит на ячейку) и решающим: правка сомкнутости ПЕРЕСЕВАЕТ ЛЕС ЗАНОВО,
// и уцелевшие деревья прыгают на новые места. Игрок срубил одно дерево —
// сдвинулась вся роща.
//
// Второй довод сильнее первого и применим к любой схеме, которая меняет ВХОД
// генератора вместо того, чтобы вычитать из его ВЫХОДА. Этот компилятор
// вычитает из выхода: рецепт (ChunkForest) не знает о рубках вовсе.
//
// # Семантика, которая держит пересборку
//
//   - исходники — МНОЖЕСТВО: рубка дважды — одна рубка, область дважды — одна
//     область, маска дважды — одна маска. Иначе повторная доставка журнала
//     меняла бы результат;
//   - рубка ячейки, где рецепт не дал дерева, — no-op: иначе областная вырубка
//     (покрывает и пустые ячейки) разошлась бы с поштучной на той же площади,
//     а повторная рубка уже срубленного — отказала бы на идемпотентной команде;
//   - рубка и посадка одного адреса — ОТКАЗ, а не разрешение порядком: формула
//     аддитивна, и исходник, чей результат зависит от того, кто применился
//     раньше, противоречил бы «порядок не важен». Срубил посаженное — исходник
//     посадки удаляется из партии, а не компенсируется рубкой;
//   - посадка проверяется на входе: ячейка обязана быть лесного класса покрова,
//     без дерева и вне вырубки — иначе отказ. Инвариант «бит только в лесном
//     классе» (шапка ChunkForest) держится по построению: у рецепта он держится
//     генератором, у посадки — этой проверкой;
//   - рубка и посадка за пределами уровня 0 бессмысленны: лес существует только
//     там, где его рубят (chunk.ForestLevel), и адресное пространство дерева —
//     0..4095 ячеек уровня 0.
//
// # Чего здесь нет намеренно
//
// Зарастание. Множество срубленных растёт монотонно всю партию, и ограничивать
// его зарастанием — игровой вопрос владельца. Ни отрастания, ни поля «посажено
// в такой-то тик» этот пакет не содержит.
package vegetation

import (
	"fmt"
	"math"

	"github.com/shady2k/ClearAhead/server/internal/chunk"
)

// Cut — надгробие одиночной рубки: адрес (чанк уровня 0, индекс ячейки).
//
// Уровень 0 в адресе не хранится — он единственный, на котором лес существует
// (chunk.ForestLevel), и часть контракта адресного пространства дерева.
type Cut struct {
	CX, CZ int
	I, J   int
}

// Planted — посаженный экземпляр: явная запись «здесь стоит дерево» независимо
// от рецепта. Адрес тот же, что у Cut, и по той же причине.
type Planted struct {
	CX, CZ int
	I, J   int
}

// Clearing — областная вырубка под площадку: прямоугольник в координатах
// региона, одна запись на площадку. Ячейка считается вырубленной, если её
// ЦЕНТР лежит в прямоугольнике: ячейка — квант тождества дерева, и областная
// форма обязана совпасть с поштучной, которая адресуется ячейкой.
type Clearing struct {
	MinX, MinZ, MaxX, MaxZ float64
}

// CutMask — плотная битовая маска вырубки ОДНОГО чанка уровня 0.
//
// Формат бит — тот же, что у ForestBytes (chunk.ForestOccupied): маска в 512
// байт окупается после 64 рубок на чанк и безразлична к форме остальных
// исходников.
type CutMask struct {
	CX, CZ int
	Bits   []byte
}

// NewCutMask заводит пустую маску вырубки чанка (cx, cz).
func NewCutMask(cx, cz int) *CutMask {
	return &CutMask{CX: cx, CZ: cz, Bits: make([]byte, chunk.ForestBytes)}
}

// Add отмечает ячейку (i, j) вырубленной.
//
// Адрес вне сетки — отказ, а не молчание chunk.SetForestOccupied: маску строит
// вызывающий по своим координатам, и опечатка адреса, спрятанная в no-op,
// потеряла бы рубку без следа — тот же класс, что рубка в чужом чанке.
func (m *CutMask) Add(i, j int) error {
	if i < 0 || i >= chunk.CoverCells || j < 0 || j >= chunk.CoverCells {
		return fmt.Errorf("vegetation: маска вырубки чанка (%d,%d): ячейка (%d,%d) вне сетки %d×%d",
			m.CX, m.CZ, i, j, chunk.CoverCells, chunk.CoverCells)
	}
	chunk.SetForestOccupied(m.Bits, i, j)
	return nil
}
func (m CutMask) Contains(i, j int) bool { return chunk.ForestOccupied(m.Bits, i, j) }

// Sources — множество исходников вырубки и посадки, релевантных ОДНОМУ чанку
// уровня 0.
//
// Отбор релевантности — забота вызывающего (worldgen): Cut, Planted и CutMask
// адресуют чанк явно, Clearing — геометрией, и компилятор отказывает, если
// чанко-адресный исходник пришёл не для этого чанка: молча пропустить чужой
// исходник значило бы молча потерять рубку.
type Sources struct {
	Cuts      []Cut
	Planted   []Planted
	Clearings []Clearing
	CutMasks  []CutMask
}

// Project — компилятор проекции леса чанка уровня 0:
//
//	проекция = лес рецепта − вырубка + посадка
//
// recipe — выход terrain.ChunkForest (лес, каким его дал рецепт, без единой
// рубки), cover — выход terrain.ChunkCover (нужен посадке: проверяется лесной
// класс ячейки). Оба приходят готовыми блобами: компилятор не читает рецепт
// рельефа и не умеет порождать лес — он только вычитает и складывает.
//
// Возврат nil, nil на уровне выше нулевого и на карте без покрова с ПУСТЫМИ
// исходниками: леса там нет вовсе (ChunkForest возвращает то же), и проекции
// быть не может. Непустые исходники на уровне выше нулевого и на карте без
// покрова — отказ, называющий уровень и число: терять журналируемую рубку
// молча запрещено.
//
// Ошибка — отказ, а не подстановка: исходник, нарушивший контракт (чужая
// ячейка, вырожденная область, посадка на лугу или в вырубке), называет себя
// числом, и партия не публикуется.
func Project(a chunk.Address, recipe, cover []byte, srcs Sources) ([]byte, error) {
	if a.Level != chunk.ForestLevel {
		// Лес существует только на уровне 0 (chunk.ForestLevel). Пустые исходники
		// на любом другом уровне — законная пустота: проекции нет, потому что леса
		// нет. Непустые — отказ: рубка, поданная не на тот уровень, исчезла бы без
		// следа, а это журналируемый исходник партии.
		if len(srcs.Cuts) == 0 && len(srcs.Planted) == 0 && len(srcs.Clearings) == 0 && len(srcs.CutMasks) == 0 {
			return nil, nil
		}
		n := len(srcs.Cuts) + len(srcs.Planted) + len(srcs.Clearings) + len(srcs.CutMasks)
		return nil, fmt.Errorf("vegetation: уровень %d, где леса нет (лес — только уровень %d): исходников %d шт.",
			a.Level, chunk.ForestLevel, n)
	}
	if cover == nil {
		// Карта без рецепта покрова не имеет леса (ChunkForest). Пустые исходники
		// дают пустую проекцию — законный мир без растительности. Непустые —
		// отказ: рубка или посадка на карте, где леса нет, есть ложь партии, и
		// молча вернуть nil значило бы потерять журналируемый исходник.
		if len(srcs.Cuts) == 0 && len(srcs.Planted) == 0 && len(srcs.Clearings) == 0 && len(srcs.CutMasks) == 0 {
			return nil, nil
		}
		return nil, fmt.Errorf("vegetation: рубка или посадка на карте без покрова — леса нет")
	}
	if len(cover) != chunk.CoverBytes {
		return nil, fmt.Errorf("vegetation: покров %d байт, ожидалось %d", len(cover), chunk.CoverBytes)
	}
	if len(recipe) != chunk.ForestBytes {
		return nil, fmt.Errorf("vegetation: лес рецепта %d байт, ожидалось %d", len(recipe), chunk.ForestBytes)
	}

	// Множество вырубки собирается из всех четырёх форм в один блоб ДО того,
	// как тронута проекция: проверка «посадка вне вырубки» и применение вырубки
	// обязаны видеть одно и то же множество, а не результат первой
	// применившейся формы.
	cut := make([]byte, chunk.ForestBytes)
	for _, c := range srcs.Cuts {
		if err := checkCell(c.CX, c.CZ, c.I, c.J, a, "рубка"); err != nil {
			return nil, err
		}
		chunk.SetForestOccupied(cut, c.I, c.J)
	}
	for _, m := range srcs.CutMasks {
		if m.CX != a.CX || m.CZ != a.CZ {
			return nil, fmt.Errorf("vegetation: маска вырубки чанка (%d,%d) применена к чанку (%d,%d)",
				m.CX, m.CZ, a.CX, a.CZ)
		}
		if len(m.Bits) != chunk.ForestBytes {
			return nil, fmt.Errorf("vegetation: маска вырубки %d байт, ожидалось %d", len(m.Bits), chunk.ForestBytes)
		}
		for k := range cut {
			cut[k] |= m.Bits[k]
		}
	}
	for _, cl := range srcs.Clearings {
		// NaN проходит любое сравнение (NaN > x ложно при всех x) и превратился бы
		// в молчаливую пустую вырубку — тот же класс, на котором проект уже горел.
		if math.IsNaN(cl.MinX) || math.IsNaN(cl.MinZ) || math.IsNaN(cl.MaxX) || math.IsNaN(cl.MaxZ) {
			return nil, fmt.Errorf("vegetation: область вырубки с NaN-границей: [%g, %g] × [%g, %g]",
				cl.MinX, cl.MaxX, cl.MinZ, cl.MaxZ)
		}
		// Min == Max даёт площадь ноль — пустую вырубку молча; это ошибка автора,
		// а не вырубка, и >= ловит её вместе с Min > Max.
		if cl.MinX >= cl.MaxX || cl.MinZ >= cl.MaxZ {
			return nil, fmt.Errorf("vegetation: область вырубки вырождена: [%g, %g] × [%g, %g]",
				cl.MinX, cl.MaxX, cl.MinZ, cl.MaxZ)
		}
		for j := 0; j < chunk.CoverCells; j++ {
			for i := 0; i < chunk.CoverCells; i++ {
				x, z := a.CoverCellCenterM(i, j)
				if x >= cl.MinX && x <= cl.MaxX && z >= cl.MinZ && z <= cl.MaxZ {
					chunk.SetForestOccupied(cut, i, j)
				}
			}
		}
	}

	out := make([]byte, chunk.ForestBytes)
	copy(out, recipe)
	for j := 0; j < chunk.CoverCells; j++ {
		for i := 0; i < chunk.CoverCells; i++ {
			if chunk.ForestOccupied(cut, i, j) {
				chunk.ClearForestOccupied(out, i, j)
			}
		}
	}

	// Посадка: проверка каждой записи, затем дедупликация в множество — повторная
	// доставка одной команды не должна отказать на «здесь уже растёт дерево».
	// Проверка занятости идёт ПО МНОЖЕСТВУ, по уже вычтенной вырубке (out).
	plants := make(map[[2]int]struct{}, len(srcs.Planted))
	for _, p := range srcs.Planted {
		if err := checkCell(p.CX, p.CZ, p.I, p.J, a, "посадка"); err != nil {
			return nil, err
		}
		class, _ := chunk.UnpackCover(cover[chunk.CoverIndex(p.I, p.J)])
		if class != chunk.SurfaceForestConifer && class != chunk.SurfaceForestBroad {
			return nil, fmt.Errorf("vegetation: посадка в чанке (%d,%d) ячейка (%d,%d): класс покрова %d — не лес",
				a.CX, a.CZ, p.I, p.J, class)
		}
		if chunk.ForestOccupied(cut, p.I, p.J) {
			return nil, fmt.Errorf("vegetation: посадка в чанке (%d,%d) ячейка (%d,%d): адрес в вырубке — рубка и посадка одного дерева",
				a.CX, a.CZ, p.I, p.J)
		}
		plants[[2]int{p.I, p.J}] = struct{}{}
	}
	for cell := range plants {
		i, j := cell[0], cell[1]
		if chunk.ForestOccupied(out, i, j) {
			return nil, fmt.Errorf("vegetation: посадка в чанке (%d,%d) ячейка (%d,%d): здесь уже растёт дерево",
				a.CX, a.CZ, i, j)
		}
		chunk.SetForestOccupied(out, i, j)
	}
	return out, nil
}

// checkCell проверяет, что чанко-адресный исходник адресует именно этот чанк и
// ячейку внутри сетки покрова.
func checkCell(cx, cz, i, j int, a chunk.Address, what string) error {
	if cx != a.CX || cz != a.CZ {
		return fmt.Errorf("vegetation: %s чанка (%d,%d) применена к чанку (%d,%d)", what, cx, cz, a.CX, a.CZ)
	}
	if i < 0 || i >= chunk.CoverCells || j < 0 || j >= chunk.CoverCells {
		return fmt.Errorf("vegetation: %s в чанке (%d,%d): ячейка (%d,%d) вне сетки %d×%d",
			what, cx, cz, i, j, chunk.CoverCells, chunk.CoverCells)
	}
	return nil
}
