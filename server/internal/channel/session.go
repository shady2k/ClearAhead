// Package channel — канал команд: один сокет, JSON-RPC 2.0 в обе стороны.
//
// # Что здесь есть и чего здесь нет
//
// Веха ClearAhead-wa51 расщепила В2 надвое: КАНАЛ, по которому любая команда
// доходит до движка, и ДИСПЕТЧЕРСКУЮ СЕМАНТИКУ — стрелки, маршруты, замыкание.
// Здесь первое и только оно. Проверка, что шов выбран по месту, записана в
// биде и звучит так: пакет обязан быть закончен, не назвав НИ ОДНОЙ доменной
// команды. Он её и не называет — единственный метод здесь hello, а первая
// доменная команда приезжает с органами управления кабины (ClearAhead-6ygr).
//
// Довод, по которому канал сделан раньше стрелок: позиция контроллера тяги
// едет на сервер тем же путём, что перевод стрелки (sim-core-design §11:
// органы управления -> состояние актуаторов -> физика). Канал нужен обеим
// ролям одинаково, а диспетчерская семантика — только ДСП.
//
// # Почему WebSocket, а не POST + SSE
//
// Решение d6d561a, отмена записана в vertical-slice-design §6: клиент на
// движке, WebSocketPeer в Godot первого класса, а SSE пришлось бы собирать
// руками из HTTPClient. Крупное неизменяемое (сеть, рельеф, ассеты) в сокет НЕ
// уезжает и остаётся на обычном GET с ETag и immutable — оно статично и
// кэшируется по хешу.
//
// # Почему сессия переживает соединение
//
// Разрыв на LAN длится секунды, а ключи идемпотентности живут в сессии. Клиент,
// потерявший сокет между отправкой команды и ответом, обязан повторить её тем
// же command_id и получить ТОТ ЖЕ ответ. Привяжи ключи к соединению — и повтор
// после разрыва станет вторым применением, то есть идемпотентность работала бы
// ровно там, где она не нужна, и отказывала бы там, ради чего заведена.
package channel

import (
	"sync"

	"github.com/shady2k/ClearAhead/server/internal/protocol"
)

// MaxCachedCommands — сколько ответов на команды сессия помнит.
//
// Область жизни ключа по вертикальному срезу §6 — «до конца сессии в памяти, в
// журнале постоянно». Журнала нет (см. engine), значит остаётся память, а у
// памяти обязан быть потолок: сессия живёт часами, и карта ключей без предела
// растёт ровно столько же.
//
// Тысяча — это не замер, а ОЦЕНКА, и названа оценкой: команд у машиниста
// несколько в минуту (vertical-slice-design §6: «позиция контроллера, ступень
// торможения, отпуск, реверс — несколько раз в минуту»), тысяча покрывает часы
// игры. Замер появится, когда появятся команды; до тех пор здесь стоит число,
// которое заведомо больше нужного.
//
// Переполнение выбрасывает САМЫЕ СТАРЫЕ ключи. Цена честная: повтор команды,
// поданной тысячу команд назад, применится second time. Это не проблема,
// потому что повтор возникает от разрыва связи, а не от раздумья: клиент,
// молчавший тысячу команд, давно получил ответ.
const MaxCachedCommands = 1000

// commandKey — ключ идемпотентности: тройка (session_id, actor_id, command_id).
//
// session_id и actor_id ЗДЕСЬ, а не в params: actor берётся из соединения
// (vertical-slice-design §6), иначе любой клиент командует от чужого имени и
// проверка прав зон фиктивна.
type commandKey struct {
	actor     string
	commandID string
}

// session — подключение клиента, пережившее разрыв.
type session struct {
	id string
	// actor — от чьего имени идут команды этого подключения.
	//
	// Сегодня actor выдаётся сервером один на сессию, потому что ролей и
	// хоста, который их назначает, ещё не существует. Форма связи
	// «соединение -> актёр» заведена сразу: когда появятся роли, меняться
	// будет НАЗНАЧЕНИЕ актёра, а не то, откуда его берут при исполнении
	// команды.
	actor string

	mu sync.Mutex
	// snapshotSeq — сквозной номер полных снапшотов, отданных ЭТОЙ сессии.
	//
	// Счётчик один: stream_seq откладывался как обоснованный потоком доменных
	// событий, и вместе с SSE исчез его второй довод — нумерация записей для
	// заголовка id:. Заведётся заново вместе с доменными событиями.
	snapshotSeq uint64
	// done — ответы на уже обслуженные команды, в порядке поступления.
	done  map[commandKey][]byte
	order []commandKey
}

func newSession(id, actor string) *session {
	return &session{id: id, actor: actor, done: map[commandKey][]byte{}}
}

// nextSnapshotSeq выдаёт номер следующего полного снапшота.
func (s *session) nextSnapshotSeq() uint64 {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.snapshotSeq++
	return s.snapshotSeq
}

// cachedReply возвращает ответ на уже обслуженную команду.
func (s *session) cachedReply(commandID string) ([]byte, bool) {
	if commandID == "" {
		return nil, false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	body, ok := s.done[commandKey{actor: s.actor, commandID: commandID}]
	return body, ok
}

// remember запоминает ответ на команду.
//
// Запоминается ОТВЕТ ЦЕЛИКОМ, включая отказ. Это не небрежность: повтор
// отказанной команды обязан получить тот же отказ, а не быть применённым
// заново. Отказ «стрелка занята» при повторе через секунду мог бы пройти —
// и тогда клиент, пославший команду один раз и повторивший её из-за разрыва,
// получил бы результат, которого не просил.
func (s *session) remember(commandID string, reply []byte) {
	if commandID == "" {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	key := commandKey{actor: s.actor, commandID: commandID}
	if _, dup := s.done[key]; dup {
		return
	}
	s.done[key] = reply
	s.order = append(s.order, key)
	for len(s.order) > MaxCachedCommands {
		delete(s.done, s.order[0])
		s.order = s.order[1:]
	}
}

// registry — все сессии сервера.
//
// Карта, а не список: сессию ищут по идентификатору при переподключении, и
// линейный поиск по списку соединений означал бы, что цена рукопожатия растёт
// с числом игроков.
type registry struct {
	mu   sync.Mutex
	byID map[string]*session
	// newID выдаёт идентификаторы. Поле, а не вызов пакета, потому что тест
	// обязан получать предсказуемые идентификаторы, не подменяя генератор
	// глобально.
	newID func() (string, error)
}

func newRegistry(newID func() (string, error)) *registry {
	return &registry{byID: map[string]*session{}, newID: newID}
}

// resume находит названную сессию или заводит новую.
//
// Названная, но неизвестная сессия — НЕ ошибка клиента и не повод молча выдать
// новую: сервер перезапустили, и клиент обязан узнать об этом, потому что его
// ключи идемпотентности перестали что-либо значить. Поэтому возвращается отказ
// с машинной причиной, а не тихая подмена.
func (r *registry) resume(id string) (*session, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if id != "" {
		s, ok := r.byID[id]
		if !ok {
			return nil, &protocol.Refusal{Reason: protocol.ReasonUnknownSession, ResourceID: id}
		}
		return s, nil
	}
	sid, err := r.newID()
	if err != nil {
		return nil, err
	}
	actor, err := r.newID()
	if err != nil {
		return nil, err
	}
	s := newSession(sid, actor)
	r.byID[sid] = s
	return s, nil
}
