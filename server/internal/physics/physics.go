// Package physics — силы, действующие на подвижную единицу.
//
// # Что это и чего здесь нет
//
// Здесь ЧИСТЫЕ ФУНКЦИИ и ни одного байта состояния: сопротивление, сцепление и
// сила тяги при заданной скорости и заданном месте. Ни времени, ни интегратора,
// ни положения — они приходят следующим шагом и приходят в движок, а не сюда.
//
// Разделение не косметическое. Силы проверяются АРИФМЕТИКОЙ — числом против
// числа, посчитанного руками из опубликованного паспорта; интегратор проверяется
// прогоном. Слитые в одно, они проверялись бы только вторым способом, и ошибка в
// коэффициенте выглядела бы как ошибка шага.
//
// # Откуда формулы
//
// ПРАВИЛА ТЯГОВЫХ РАСЧЁТОВ ДЛЯ ПОЕЗДНОЙ РАБОТЫ (ПТР, МПС СССР, 1980) — тот же
// документ, по которому эти величины считают на настоящей дороге. Выбор не
// произвольный: проект заявляет материалом российские железные дороги, а такая
// заявка создаёт более высокий стандарт проверки, чем вымышленная система
// (sim-core-design §13.3). Формулы взяты из источников, а не по памяти, и каждая
// названа у своей функции.
//
// # Почему целые числа
//
// Правило проекта записано дважды и куплено дорого: «плавающая точка в
// состоянии сима запрещена» (эскиз ядра §8) и «float64 не сверяется байт в байт
// — проект уже терял на этом эталон контракта (расхождение ~1e-13 при
// неизменном коде)». Силы входят в приращение скорости, то есть в состояние, и
// float здесь протащил бы расхождение туда же.
//
// Поэтому у каждой величины ОБЪЯВЛЕННАЯ ЦЕЛОЧИСЛЕННАЯ ШКАЛА, а деления округляют
// к ближайшему, а не отбрасывают: систематическое отбрасывание — это дрейф в
// одну сторону, и на тысяче шагов он виден.
//
// Накопителей остатков здесь НЕТ и быть не может: у чистой функции нет места,
// где их хранить. Они принадлежат интегратору (эскиз ядра §8) и приезжают с ним.
//
// # Единица удельного сопротивления — и почему она одна на три величины
//
// Н/кН: сколько ньютонов сопротивления приходится на килоньютон веса. Эта
// единица численно совпадает с кгс/тс, в которой печатают паспорта, и с
// промилле уклона — и последнее совпадение не случайность, а причина, по которой
// ПТР складывает сопротивление от уклона с основным напрямую.
package physics

import (
	"fmt"
	"math"

	"github.com/shady2k/ClearAhead/server/internal/units"
)

// SpecificResistance — удельное сопротивление в ТЫСЯЧНЫХ долях Н/кН.
//
// Тысячные, а не целые: коэффициент при V² равен 0.0003, и на целой шкале он
// исчез бы вовсе. Замер запаса: самое большое, что здесь бывает, — уклон 40 ‰
// плюс кривая R=200 плюс основное на 110 км/ч, то есть около 50 Н/кН = 50 000
// единиц; до потолка int64 остаётся четырнадцать порядков.
type SpecificResistance int64

// On переводит удельное сопротивление в силу для тела заданного веса.
//
// F[Н] = w[Н/кН] · G[кН], а в наших шкалах w хранится в тысячных Н/кН, а G — в
// ньютонах, отчего делитель равен миллиону.
func (w SpecificResistance) On(weight units.Force) units.Force {
	return units.Force(divRound(int64(w)*int64(weight), 1_000_000))
}

// Resistance — коэффициенты основного удельного сопротивления одной машины.
//
// ПТР задаёт его эмпирической зависимостью w = a + b·V + c·V², где V в км/ч, а
// результат в Н/кН. Коэффициенты — свойство КЛАССА подвижного состава (электровоз
// на звеньевом пути, гружёный четырёхосный вагон, порожний вагон), поэтому они
// живут в паспорте, а не в этом пакете: набор машин расширяется данными, а не
// правкой физики.
//
// Хранятся в целых с разными масштабами — по одному на слагаемое, и масштаб
// выведен из того, что слагаемое должно дать тысячные Н/кН:
//
//	w[тыс. Н/кН] = 1000a + b·V[тыс. км/ч] + c·V[тыс. км/ч]²/1000
//
// откуда A = 1000a, а B и C удобно хранить домноженными на миллион, чтобы
// 0.01 и 0.0003 стали целыми 10000 и 300.
type Resistance struct {
	a  int64 // a · 1000
	b6 int64 // b · 1e6
	c6 int64 // c · 1e6
}

// ResistanceFrom собирает коэффициенты из паспортных чисел.
//
// Единственная точка входа float → домен, и она же место отказа: коэффициент,
// не помещающийся в объявленную шкалу, — это опечатка в разряде, и подставлять
// вместо неё что-либо нельзя.
func ResistanceFrom(a, b, c float64) (Resistance, error) {
	for _, d := range []struct {
		name string
		v    float64
	}{{"a", a}, {"b", b}, {"c", c}} {
		if math.IsNaN(d.v) || math.IsInf(d.v, 0) || d.v < 0 {
			return Resistance{}, fmt.Errorf(
				"physics: коэффициент сопротивления %s = %v, ожидалось неотрицательное конечное число", d.name, d.v)
		}
	}
	// Ноль у a запрещён отдельно: машина без основного сопротивления катилась бы
	// по горизонтали вечно, и это не крайний случай модели, а незаполненный
	// паспорт. У b и c ноль законен — он означает, что зависимость от скорости
	// не измерена, а не что её нет.
	if a <= 0 {
		return Resistance{}, fmt.Errorf(
			"physics: коэффициент a = %v: основное сопротивление при нулевой скорости не бывает нулевым", a)
	}
	return Resistance{
		a:  int64(math.Round(a * 1000)),
		b6: int64(math.Round(b * 1e6)),
		c6: int64(math.Round(c * 1e6)),
	}, nil
}

// At — основное удельное сопротивление на заданной скорости.
//
// Знака у скорости не различает: сопротивление направлено ПРОТИВ движения, куда
// бы оно ни шло, и хранить это в знаке значило бы, что вычитающий его забудет
// про случай заднего хода.
func (r Resistance) At(v units.Speed) SpecificResistance {
	vm := v.MilliKmh()
	if vm < 0 {
		vm = -vm
	}
	// Слагаемые выведены у объявления Resistance. Порядок вычисления выбран так,
	// чтобы умножение шло до деления: обратный порядок обнулил бы вклад
	// квадратичного члена на малых скоростях.
	return SpecificResistance(r.a + divRound(r.b6*vm, 1_000_000) + divRound(r.c6*vm*vm, 1_000_000_000))
}

// GradeResistance — удельное сопротивление от уклона.
//
// ФУНКЦИЯ ВЫГЛЯДИТ ПУСТОЙ, И ЭТО ПРАВИЛЬНО: по ПТР удельное сопротивление от
// уклона ЧИСЛЕННО РАВНО уклону в промилле. Равенство держится ровно потому, что
// Н/кН и промилле — одна и та же безразмерная величина, и написано оно функцией,
// а не комментарием, чтобы система типов не давала сложить промилле с ньютонами
// напрямую.
//
// Аргумент — промилле, домноженные на тысячу, потому что шкала результата
// тысячные: уклон 2.5 ‰ приходит как 2500.
//
// Знак значим и сохраняется: на подъёме сопротивление положительно, на спуске
// отрицательно и разгоняет. Это единственная из трёх составляющих, у которой
// знак есть.
func GradeResistance(milliPermille int64) SpecificResistance {
	return SpecificResistance(milliPermille)
}

// CurveResistance — удельное сопротивление от кривой по ПТР: w = 700/R, где R в
// метрах, результат в Н/кН.
//
// Формула эмпирическая и в ПТР приводится для случая, когда поезд размещается в
// кривой целиком. Наш случай сегодня именно такой (одиночная машина короче любой
// кривой затравки), а разбор длинного состава на переломе принадлежит той же
// работе, что распределённый профиль, — и приедет вместе с ней.
//
// ПРЯМАЯ — ЭТО НУЛЬ, А НЕ ДЕЛЕНИЕ НА НОЛЬ. Радиус прямой равен нулю по
// соглашению формата карты (у примитива straight поля radius нет вовсе), и
// «бесконечный радиус» здесь выражается нулём на входе, а не бесконечностью.
func CurveResistance(radius units.Distance) SpecificResistance {
	if radius <= 0 {
		return 0
	}
	// 700 Н/кН·м в шкале тысячных — это 700 000, а радиус хранится в
	// микрометрах, отчего числитель домножается ещё на миллион.
	return SpecificResistance(divRound(700_000*1_000_000, int64(radius)))
}

// MilliAdhesion — расчётный коэффициент сцепления, тысячные доли.
type MilliAdhesion int64

// On — наибольшая сила тяги, которую удержит сцепление при этом сцепном весе.
//
// Метод, а не строка внутри TractiveEffort, ровно затем, чтобы его можно было
// проверить против ОПУБЛИКОВАННОГО числа: паспорт ЧМЭ3 называет силу тяги
// трогания вместе с коэффициентом, при котором она посчитана, и это редкий
// случай, когда источник даёт проверить не результат, а саму механику.
func (a MilliAdhesion) On(adhesiveWeight units.Force) units.Force {
	return units.Force(divRound(int64(a)*int64(adhesiveWeight), 1000))
}

// Adhesion — расчётный коэффициент сцепления колеса с рельсом по ПТР:
//
//	ψ = 0.28 + 3/(50 + 20V) − 0.0007V,  V в км/ч.
//
// Это РАСЧЁТНЫЙ коэффициент, а не физический предел: он занижен относительно
// того, что даёт чистый сухой рельс, и занижен нарочно — по нему считают, чтобы
// расчёт был верен и в плохих условиях. Разница видна на числах: формула даёт
// 0.34 при трогании, а паспорт ЧМЭ3 называет силу тяги трогания при
// коэффициенте 0.25, то есть заводская оговорка ещё осторожнее правил.
//
// ПЕСОК НЕ МОДЕЛИРУЕТСЯ, и это объявлено, а не забыто: у песочницы есть
// известный эффект, но числа его прироста в найденных источниках нет, а писать
// такую таблицу по памяти проект запрещает. Поле песочницы в паспорте поэтому
// тоже не заведено — форма без потребителя.
func Adhesion(v units.Speed) MilliAdhesion {
	vm := v.MilliKmh()
	if vm < 0 {
		vm = -vm
	}
	// Вывод шкал: ψ·1000 = 280 + 3000/(50+20V) − 0.7V; подстановка V = vm/1000
	// даёт 50+20V = (2500+vm)/50, откуда второе слагаемое равно 150000/(2500+vm),
	// а третье — 7·vm/10000.
	return MilliAdhesion(280 + divRound(150_000, 2500+vm) - divRound(7*vm, 10_000))
}

// ShoeKind — материал тормозной колодки.
//
// Перечень ЗАКРЫТ, и неизвестное значение — отказ на входе, а не умолчание:
// у чугунной и композиционной колодки РАЗНЫЕ формулы трения, и подстановка
// одной вместо другой врёт вдвое к сотне километров в час — то есть ровно в
// тормозном пути.
type ShoeKind string

const (
	ShoesCastIron  ShoeKind = "cast_iron"
	ShoesComposite ShoeKind = "composite"
)

// Known сообщает, что материал колодки объявлен в перечне.
func (k ShoeKind) Known() bool { return k == ShoesCastIron || k == ShoesComposite }

// MilliFriction — расчётный коэффициент трения колодки, тысячные доли.
type MilliFriction int64

// Friction — РАСЧЁТНЫЙ коэффициент трения тормозной колодки о бандаж.
//
//	чугунные       φкр = 0.27 · (V+100)/(5V+100)
//	композиционные φкр = 0.36 · (V+150)/(2V+150)
//
// # Почему дробный вид, а не линейный — разбор стоил отдельной сверки
//
// Источники разошлись. Один даёт линейное φкр = 0.270 − 0.00066V, другой —
// дробное. На нуле они совпадают, на 100 км/ч дают 0.204 против 0.09, то есть
// расходятся вдвое с лишним, и расходятся ровно в тормозном пути — величине,
// по которой игрок принимает решение. Усреднить их было бы худшим из решений.
//
// Разрешено доводом, а не выбором. Утверждённая МПС формула ДЕЙСТВИТЕЛЬНОГО
// коэффициента для чугунных колодок имеет вид
//
//	φк = 0.6 · (V+100)/(5V+100) · (16K+100)/(80K+100)
//
// где K — нажатие на колодку. Расчётный коэффициент есть тот же действительный
// при ФИКСИРОВАННОМ опорном нажатии, то есть отличается от него только
// множителем, зависящим от K, — а зависимость от СКОРОСТИ обязан наследовать
// целиком. Значит форма дробная, и линейное выражение — местное приближение.
//
// Сверка, подтверждающая источник: его собственный пример при V = 70 и K = 1 тс
// даёт 0.146, и формула воспроизводит это число.
//
// # Что означает «расчётный»
//
// Он идёт В ПАРЕ с расчётными нажатиями ПТР (Locomotive.AxleBrakeForce) и
// осмыслен только вместе с ними: нажатия и коэффициент подобраны так, чтобы их
// произведение давало настоящую тормозную силу. Подставить сюда действительное
// нажатие на колодку — распространённая ошибка, дающая двойной учёт.
func Friction(kind ShoeKind, v units.Speed) MilliFriction {
	vm := v.MilliKmh()
	if vm < 0 {
		vm = -vm
	}
	// Подстановка V = vm/1000 в дробь сокращает тысячи в числителе и
	// знаменателе, поэтому шкала скорости уходит целиком.
	if kind == ShoesComposite {
		return MilliFriction(divRound(360*(vm+150_000), 2*vm+150_000))
	}
	return MilliFriction(divRound(270*(vm+100_000), 5*vm+100_000))
}

// Locomotive — паспорт машины, переведённый в домен: то, что читает физика.
//
// Отдельный тип, а не content.StockType, и граница здесь по смыслу, а не по
// удобству: паспорт — это ИНТЕРФЕЙС АВТОРА (тонны, км/ч, километры в час,
// float), а здесь домен (килограммы, микрометры в секунду, целые). Перевод
// делается один раз при загрузке набора, а не на каждом шаге физики.
type Locomotive struct {
	// Mass — служебная масса: с топливом, песком и экипажем.
	Mass units.Mass
	// AdhesiveMass — сцепной вес: масса, приходящаяся на ДВИЖУЩИЕ оси. У
	// современного магистрального локомотива все оси движущие, и она равна
	// служебной; заводить её отдельно всё равно необходимо, потому что у машин с
	// бегунковыми осями это разные числа, и подстановка одного вместо другого
	// завышала бы силу трогания молча.
	AdhesiveMass units.Mass
	// RimPower — мощность НА ОБОДЕ КОЛЕСА, ватты. Не мощность двигателя:
	// разница уходит в передачу и вспомогательные машины (разбор — у
	// content.Traction).
	RimPower int64
	// MaxSpeed — конструкционная скорость.
	MaxSpeed units.Speed
	// Res — коэффициенты основного сопротивления.
	Res Resistance
	// Shoes — материал тормозных колодок.
	Shoes ShoeKind
	// AxleBrakeForce — РАСЧЁТНОЕ нажатие тормозных колодок на одну ось.
	//
	// Не физическое нажатие, а табличная величина ПТР, подобранная в паре с
	// расчётным коэффициентом трения (разбор — у Friction). Взята из таблицы
	// расчётных нажатий на ось локомотивов, гружёный режим.
	//
	// # Почему табличная величина, а не цепочка «давление — цилиндр — рычаги»
	//
	// Потому что цепочку нечем замкнуть. Диаметр тормозного цилиндра ЧМЭ3
	// известен (8″, 203 мм), число колодок известно (24 при двусторонней
	// передаче), материал известен (чугун), а ПЕРЕДАТОЧНОЕ ЧИСЛО рычажной
	// передачи и её КПД в найденных источниках не названы — и без них давление
	// в силу на ободе не превращается. Табличное нажатие обходит оба
	// недостающих числа: оно и есть результат этой цепочки, измеренный заводом.
	//
	// Цена решения названа честно: пневматика (зарядка магистрали, ступени
	// торможения, отпуск) сюда НЕ пристёгивается — таблица даёт полное
	// служебное нажатие и ничего не говорит о том, как оно нарастает. Это и
	// есть та работа, ради которой цепочку придётся достроить, когда появится
	// кран машиниста.
	AxleBrakeForce units.Force
	// BrakedAxles — число тормозных осей.
	BrakedAxles int64
	// MaxForce — наибольшая сила тяги, которую дают ДВИГАТЕЛИ, не спрашивая
	// рельс. Ноль значит «предел не объявлен»: машина не буксует, и сила тяги
	// остаётся минимумом из мощности и сцепления (разбор — у TractionLimit).
	MaxForce units.Force
}

// BrakeForce — полная тормозная сила при полном служебном торможении.
//
// Произведение расчётного нажатия на расчётный коэффициент трения, просуммированное
// по тормозным осям. Ступеней торможения здесь НЕТ и быть не может: таблица ПТР
// даёт одну величину — полное нажатие, — а доля от неё принадлежит крану
// машиниста, которого ещё нет. Когда он появится, эта функция станет ВЕРХНЕЙ
// ГРАНИЦЕЙ, а положение крана — долей от неё; ломать её для этого не придётся,
// ровно как и TractiveEffort.
//
// Предела по сцеплению здесь тоже нет, и это не забывчивость: превышение
// сцепления означает ЮЗ — заклиненные колёса, ползуны на бандажах и потерю
// торможения, — то есть событие модели, а не молчаливое обрезание силы.
// Обрезать его здесь значило бы сделать юз невозможным по построению.
func (l Locomotive) BrakeForce(v units.Speed) units.Force {
	total := int64(l.AxleBrakeForce) * l.BrakedAxles
	return units.Force(divRound(int64(Friction(l.Shoes, v))*total, 1000))
}

// TractiveEffort — наибольшая сила тяги, которую машина может приложить к
// рельсу на этой скорости.
//
// # Модель и её граница
//
// Минимум из двух пределов: сколько удержит сцепление и сколько отдаст
// мощность. Это ОБЪЯВЛЕННОЕ УПРОЩЕНИЕ настоящей тяговой характеристики, и вот
// чем оно не является: у боевой машины характеристика — семейство кривых по
// позициям контроллера и зонам регулирования, и снять с неё одну огибающую
// значит потерять всё, чем машинист управляет между нулём и полной тягой.
//
// Упрощение годится сегодня по одной причине: органов управления ещё нет. В тот
// день, когда появится контроллер тяги, огибающая станет ВЕРХНЕЙ ГРАНИЦЕЙ, а
// позиция — долей от неё; ломать эту функцию для этого не придётся.
//
// # Почему огибающая по ДЛИТЕЛЬНОМУ режиму, а не по часовому
//
// Потому что нагрева мы не моделируем. Часовой режим — это то, что машина
// держит час и не дольше; взять его огибающей значило бы разрешить держать его
// вечно. Ошибка при выборе длительного идёт В БЕЗОПАСНУЮ СТОРОНУ: машина
// получается слабее настоящей примерно на десятую часть (у ВЛ80С часовая сила
// 45.1 тс против длительной 40.9 тс), а не сильнее.
// TractionLimit — сколько силы дадут ДВИГАТЕЛИ на ПОЛНОЙ позиции и этой
// скорости, не спрашивая рельс.
//
// # Зачем отдельно от TractiveEffort
//
// Потому что буксование — это РАЗНИЦА между тем, что дают двигатели, и тем, что
// удержит сцепление, а функция, берущая минимум из двух пределов, эту разницу
// уничтожает. Пока сила тяги была минимумом, поставить контроллер сразу на
// последнюю позицию было безопасно по построению: доля бралась от уже
// ограниченного сцеплением числа. Владелец это и заметил: «можно установить
// контроллер сразу на 33 и он поедет, а должен буксовать».
//
// MaxForce == 0 значит, что предела двигателей у машины НЕ ОБЪЯВЛЕНО, и тогда
// возвращается прежнее поведение: минимум из мощности и сцепления, буксовать
// нечем. Это законная машина, а не недописанный паспорт: у маневрового тепловоза
// с гидропередачей ограничение другой природы, и подставлять ему электровозное
// значило бы выдумать.
func (l Locomotive) TractionLimit(v units.Speed) units.Force {
	speed := int64(v)
	if speed < 0 {
		speed = -speed
	}
	if l.MaxForce <= 0 {
		return l.TractiveEffort(v)
	}
	if speed == 0 {
		// На стоянке мощность не ограничивает (F = P/v обращается в
		// бесконечность), и предел один — ток двигателей.
		return l.MaxForce
	}
	byPower := units.Force(divRound(l.RimPower*1_000_000, speed))
	if byPower < l.MaxForce {
		return byPower
	}
	return l.MaxForce
}

// NotchEffort — сила, которую дают ДВИГАТЕЛИ на позиции permille и скорости v.
//
// v — скорость ВДОЛЬ ТОГО НАПРАВЛЕНИЯ, КУДА ТОЛКАЮТ ДВИГАТЕЛИ, со знаком.
// Отрицательная означает, что машину катит НАВСТРЕЧУ тяге (уклон, толчок), и
// это не крайний случай, а обычное состояние трогания под уклон: противо-ЭДС
// тогда вычитается со своим знаком, то есть помогает, и предел остаётся один —
// ток. Модуль здесь взять нельзя: он выдал бы падение силы там, где её рост.
//
// # ТРИ ПРЕДЕЛА, И У КАЖДОГО СВОЁ ИМЯ
//
//	ТОК          MaxForce: больше двигатели не отдадут ни на какой позиции.
//	МОЩНОСТЬ     RimPower/v: гипербола, за которую не выйти на ходу.
//	ПРОТИВО-ЭДС  позиция задаёт НАПРЯЖЕНИЕ, и по мере разгона встречная ЭДС
//	             съедает его: на скорости, где они сравнялись, ток обращается в
//	             ноль вместе с силой.
//
// # Что здесь стояло и почему это была ошибка
//
// Стояла ДОЛЯ ОТ ОГИБАЮЩЕЙ: сила = permille · min(ток, мощность). У огибающей
// нет скорости, на которой сила исчезает, — она гипербола, — поэтому позиция
// оказывалась долей МОЩНОСТИ, а не напряжения. Следствие замерено (зонд равновесной
// скорости, 2026-08-15): на ПЕРВОЙ позиции одиночный ВЛ80 выходил на 77 км/ч, на
// второй — на 107, а с третьей не уравновешивался до конструкционной вовсе.
// Владелец увидел ровно это: «даже в положении 1 он набирает скорость бесконечно,
// так не может быть».
//
// # Откуда взялась скорость, на которой сила обращается в ноль
//
// Из КОНСТРУКЦИОННОЙ СКОРОСТИ паспорта, и это ОБЪЯВЛЕННОЕ ТОЖДЕСТВО МОДЕЛИ, а не
// измеренное число: на последней позиции сила тяги обращается в ноль ровно на
// MaxSpeed. Выдумывать отдельную «скорость холостого хода» проект запрещает, а
// это тождество не выдумка, а выбор: оно говорит, что паспортная конструкционная
// скорость и есть та, до которой машина разгоняет сама себя.
//
// Цена названа: на горизонтали одиночная машина к MaxSpeed только приближается —
// замер даёт 108.5 км/ч из 110. Разгоняется выше только под уклон, и это верно.
//
// СВЕРКА, а не рассуждение: на последней позиции при 53.6 км/ч модель даёт
// 401.1 кН — ровно паспортную силу длительного режима, потому что там связывает
// мощность. Три предела сходятся с паспортом в той точке, в которой паспорт
// вообще что-то говорит.
//
// MaxForce == 0 (предел двигателей не объявлен) оставляет ПРЕЖНЕЕ поведение:
// характеристики позиций у такой машины нет, и доля берётся от огибающей.
// Строить противо-ЭДС не от чего — нечему сравняться с напряжением.
func (l Locomotive) NotchEffort(v units.Speed, permille int64) units.Force {
	if permille <= 0 {
		return 0
	}
	if l.MaxForce <= 0 || l.MaxSpeed <= 0 {
		return units.Force(divRound(int64(l.TractiveEffort(v))*permille, 1000))
	}
	// ПРОТИВО-ЭДС. F = MaxForce · (permille·MaxSpeed/1000 − v) / MaxSpeed, и
	// деление одно: разбив его на два, мы потеряли бы позицию 1 в округлении
	// (permille·MaxSpeed/1000 — это 30 тысячных конструкционной).
	out := units.Force(divRound(
		int64(l.MaxForce)*(permille*int64(l.MaxSpeed)-1000*int64(v)),
		1000*int64(l.MaxSpeed)))
	if out <= 0 {
		// Ноль, а не отрицательное: двигатель, у которого встречная ЭДС выше
		// напряжения, переходит в генераторный режим, а рекуперации у нас нет.
		// Тормозить тягой было бы тормозом, которого на машине не собрано.
		return 0
	}
	// ТОК.
	if out > l.MaxForce {
		out = l.MaxForce
	}
	// МОЩНОСТЬ. На стоянке и на встречном ходу не ограничивает вовсе: F = P/v
	// обращается в бесконечность, а при v < 0 меняет знак — то есть говорит не о
	// пределе, а ни о чём.
	if v > 0 {
		if byPower := units.Force(divRound(l.RimPower*1_000_000, int64(v))); byPower < out {
			out = byPower
		}
	}
	return out
}

// AdhesionLimit — сколько силы УДЕРЖИТ рельс при этом сцепном весе и скорости.
func (l Locomotive) AdhesionLimit(v units.Speed) units.Force {
	return Adhesion(v).On(l.AdhesiveMass.Weight())
}

// SlipEffortMilli — какая ДОЛЯ расчётного сцепления остаётся при буксовании,
// тысячными.
//
// Буксующее колесо переходит с трения покоя на трение скольжения, и сила падает.
// НАЗВАНО ПРЕДВАРИТЕЛЬНЫМ: источник не назначен, порядок падения известен —
// примерно вдвое, — и 600 тысячных взято как правдоподобное в этом порядке.
// Проверить его по документу — работа, а не догадка, и до неё число обязано
// выглядеть тем, что оно есть.
//
// ВАЖНО, ЧТО ОНО МЕНЬШЕ ЕДИНИЦЫ: если бы буксование давало ту же силу, машинисту
// было бы всё равно, буксует он или нет, а песок и осторожный набор позиции
// потеряли бы смысл.
const SlipEffortMilli = 600

// Traction — сила тяги при данной доле контроллера и признак БУКСОВАНИЯ.
//
// permille — позиция контроллера, приведённая к безразмерному виду тем, у кого
// есть число позиций. Это доля НАПРЯЖЕНИЯ, а не доля силы: во что она
// превращается на этой скорости, считает NotchEffort.
//
// v — скорость вдоль направления тяги, СО ЗНАКОМ (разбор — у NotchEffort).
//
// # Модель буксования и её граница
//
// Буксование наступает, когда двигатели просят больше, чем удержит сцепление.
// Тогда к рельсу приложено НЕ полное сцепление, а его доля (SlipEffortMilli):
// колесо сорвалось и трение упало.
//
// ЧЕГО ЗДЕСЬ НЕТ: вращения колёсной пары. Настоящее буксование — это раскрутка
// колеса с ростом скольжения, и у неё своя динамика: сила падает, колесо
// разгоняется, машинист сбрасывает позицию. У нас нет состояния вращения, и
// заводить его без потребителя рано. Что есть — СОБЫТИЕ и его цена в силе:
// поставил контроллер выше сцепления и поехал ХУЖЕ, а не лучше. Этого хватает,
// чтобы позиция перестала быть бесплатной.
//
// ПЕСОК тоже не моделируется — по той же причине, что и в Adhesion: эффект
// известен, числа нет.
func (l Locomotive) Traction(v units.Speed, permille int64) (units.Force, bool) {
	if permille <= 0 {
		return 0, false
	}
	want := l.NotchEffort(v, permille)
	hold := l.AdhesionLimit(v)
	if want <= hold {
		return want, false
	}
	return units.Force(divRound(int64(hold)*SlipEffortMilli, 1000)), true
}

func (l Locomotive) TractiveEffort(v units.Speed) units.Force {
	byAdhesion := Adhesion(v).On(l.AdhesiveMass.Weight())
	speed := int64(v)
	if speed < 0 {
		speed = -speed
	}
	// На стоянке мощность не ограничивает вовсе: F = P/v обращается в
	// бесконечность, и настоящий предел трогания — сцепление. Это не крайний
	// случай, который надо обойти, а физика: трогается машина сцеплением.
	if speed == 0 {
		return byAdhesion
	}
	byPower := units.Force(divRound(l.RimPower*1_000_000, speed))
	if byPower < byAdhesion {
		return byPower
	}
	return byAdhesion
}

// Resist — сумма сопротивлений в точке пути: основное, от уклона, от кривой.
//
// Сложение прямое, и это ПТР, а не наше удобство: все три выражены в одной
// безразмерной единице ровно затем, чтобы складываться (разбор — в шапке
// пакета).
//
// milliPermille — уклон со знаком, radius — радиус кривой (0 на прямой).
func (l Locomotive) Resist(v units.Speed, milliPermille int64, radius units.Distance) units.Force {
	w := l.Res.At(v) + GradeResistance(milliPermille) + CurveResistance(radius)
	return w.On(l.Mass.Weight())
}

// divRound — деление с округлением к ближайшему, а не с отбрасыванием.
//
// Заведено функцией, потому что вызывается в каждой формуле пакета, и
// отбрасывание хотя бы в одной из них дало бы систематический сдвиг в одну
// сторону — то есть дрейф, который на длинном прогоне неотличим от ошибки в
// коэффициенте.
//
// Знак делимого учитывается: округление к ближайшему для отрицательных величин
// (уклон на спуске) обязано уводить от нуля так же, как для положительных, иначе
// подъём и спуск одной крутизны дали бы разные по модулю силы.
func divRound(num, den int64) int64 {
	if den == 0 {
		panic("physics: деление на ноль — вызывающий обязан отсеять пустой знаменатель")
	}
	half := den / 2
	if (num < 0) != (den < 0) {
		return (num - half) / den
	}
	return (num + half) / den
}
