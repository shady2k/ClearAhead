// Package match — партия: то, что происходит в мире, пока в него играют.
//
// # Почему это не карта и не набор контента
//
// Три слоя, и путать их дорого (спека строительных транзакций §10):
//
//	карта    — инфраструктура: топология, геометрия, рецепт рельефа. Ревизия.
//	набор    — какие машины бывают: паспорта и виды. Общий на сервер.
//	ПАРТИЯ   — что где стоит и что с ним происходит. Здесь.
//
// Решение владельца 2026-08-13: «Положение локомотива — это точно состояние
// сессии». Довод, который его подтверждает числами: положи расстановку в карту,
// и переставить локомотив на соседний путь можно будет только новой ревизией
// региона — а ревизия стоит в адресе сети и каталога, то есть смена места
// машины обесценила бы клиентам кэш всего региона. Двух партий на одной карте
// при этом не бывает вовсе.
//
// # Партия сегодня одна и безымянна в адресе
//
// Живое состояние отдаётся на /regions/{region}/live, а не на
// /matches/{id}/live, потому что каталога партий не существует и спросить у
// сервера «какие есть партии» сегодня негде. Но идентификатор партии ЕДЕТ В
// ТЕЛЕ ответа: сущность названа раньше, чем адресована, и в тот день, когда
// партий станет две, клиент уже знает слово, а не узнаёт о нём вместе со сменой
// адреса.
//
// Слово «сессия» под это НЕ занимается: в проекте оно означает подключение
// клиента (ключ идемпотентности «session_id, actor_id, command_id», hello с
// session_id при переподключении). Партия и подключение — разные вещи, и одно
// слово на две сущности в соседних строках протокола уже стоило бы разбора.
//
// # Чего здесь нет
//
// Ни скорости, ни ускорения, ни органов управления, ни времени. Ничего не
// движется: тика не существует, командовать нечем. Поля появятся вместе с тем,
// что их считает, а не нулями заранее — ноль в контракте неотличим от
// «не заполнено».
package match

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"os"

	"github.com/shady2k/ClearAhead/server/internal/brake"
	"github.com/shady2k/ClearAhead/server/internal/content"
	"github.com/shady2k/ClearAhead/server/internal/mapfmt"
	"github.com/shady2k/ClearAhead/server/internal/netloc"
	"github.com/shady2k/ClearAhead/server/internal/track"
	"github.com/shady2k/ClearAhead/server/internal/units"
)

// FormatVersion — версия формата файла расстановки.
const FormatVersion = 1

// MaxDocumentBytes — потолок файла расстановки.
const MaxDocumentBytes = 1 << 20

// Unit — подвижная единица в партии: экземпляр, а не тип.
type Unit struct {
	ID string `json:"id"`
	// Name — читаемая метка единицы (расстановка; решение владельца «UUIDv7
	// везде»): тождеством не является, но её клиент показывает игроку вместо
	// UUID.
	Name string `json:"name,omitempty"`
	// Type — идентификатор паспорта в наборе контента.
	Type string `json:"type"`
	// At — ТОЧКА ОТСЧЁТА единицы: середина между плоскостями автосцепок.
	//
	// Определение обязано быть одно на весь проект, потому что кандидатов
	// несколько и каждый даёт другое положение: середина машины, геометрический
	// центр кузова, первая тележка, передняя автосцепка, начало координат
	// ассета. Выбрана середина — она симметрична, не зависит от того, каким
	// концом машина повёрнута, и от неё до каждого конца ровно length/2.
	At netloc.PointU `json:"at"`
}

// Match — состояние партии.
type Match struct {
	// ID — имя партии. Сегодня одно и то же на всё время работы сервера.
	ID     string
	Region string
	Units  []Unit
	// Controls — положение органов управления по единицам, ключ — ID единицы.
	//
	// ОТДЕЛЬНОЙ КАРТОЙ, а не полем внутри Unit, и это не про удобство доступа.
	// Unit — то, что записано в ФАЙЛЕ РАССТАНОВКИ: место, тип, имя. Положение
	// рукояток в файле не пишется и писаться не должно — иначе автор карты
	// раздавал бы машинам ступень тяги, а разбор с DisallowUnknownFields обязан
	// такую расстановку отвергнуть. Документ и состояние живут порознь.
	//
	// Разбор классов фактов — в controls.go.
	Controls map[string]Controls `json:"-"`
	// Motions — состояние физики по единицам: где машина и как быстро идёт.
	// Разбор — в motion.go.
	Motions map[string]Motion `json:"-"`
	// Notches — ФАКТИЧЕСКАЯ позиция главного контроллера по единицам, тысячными
	// позиции.
	//
	// Отдельно от Controls, и это то же разделение, что у давлений: Controls —
	// то, что ЗАДАЛ машинист, а здесь то, что ВСТАЛО на машине. Позиция ЭКГ
	// приходит к заданию своим темпом (content.ControlsSpec.NotchRate), и
	// смешать их значило бы вернуть упрощение «рукоятка есть позиция», ради
	// снятия которого поле и заведено.
	//
	// В ТЫСЯЧНЫХ, потому что за тик 100 мс при темпе 1 позиция в секунду
	// набегает одна десятая позиции: в целых она бы не набежала никогда.
	Notches map[string]int `json:"-"`
	// Air — состояние ПНЕВМАТИКИ по единицам: давления в магистрали, цилиндре и
	// главных резервуарах.
	//
	// Отдельной картой по той же причине, что Controls и Motions: это состояние
	// партии, а не запись файла расстановки. И отдельно ОТ Controls, хотя ручкой
	// крана управляет тот же машинист: положение ручки — команда, давления —
	// следствие, и смешать их значило бы позволить клиенту «выставить» давление
	// в магистрали.
	//
	// Ключа нет у машины без пневматики — та тормозит одним числом, и давлений у
	// неё не существует (content.StockType.AirBrake).
	Air map[string]brake.State `json:"-"`
	// Occupied — ОБРАТНЫЙ ИНДЕКС ЗАНЯТОСТИ: по элементу — ссылки на визиты тел,
	// которые на нём лежат. Разбор — в occupancy.go.
	//
	// Правится только SetMotion, вместе с самим отрезком. Читается через
	// Conflict, OccupiedBy и DeviceBusy — поле остаётся открытым лишь потому,
	// что снимок партии копируется по полям (engine.snapshotLocked), и это
	// единственный способ ничего не забыть при добавлении нового.
	Occupied Occupancy `json:"-"`
	// Turnouts — положение остряков по устройствам: "straight" или "diverging".
	//
	// СОСТОЯНИЕ, А НЕ КОМАНДА. Переводить стрелки — работа диспетчера, и её
	// команда придёт с ClearAhead-duf; но ПОЛОЖЕНИЕ у стрелки есть всегда,
	// независимо от того, кто его меняет, и без него физика не знает, на какую
	// ветвь уводить машину. Умолчание — прямая ветвь: у настоящей стрелки тоже
	// есть плюсовое положение, а не «неизвестно».
	Turnouts map[string]string `json:"-"`
	// TurnoutMoves — стрелки, остряк которых СЕЙЧАС ИДЁТ. Отдельной картой, а не
	// полем в Turnouts: положение есть у каждой стрелки всегда, а перевод — это
	// событие, и держать его пустую запись у каждой значило бы завести признак
	// «перевода нет» вместо отсутствия записи.
	TurnoutMoves map[string]TurnoutMove `json:"-"`
}

// Положения остряка. Строки те же, что у ветви прохода в компиляции
// (mapfmt.Passage.Branch): третьего написания одного и того же не заводится.
const (
	TurnoutStraight  = "straight"
	TurnoutDiverging = "diverging"
)

// AirOf — состояние пневматики единицы. Второе значение ложно у машины без
// магистрали: у неё давлений не существует, и нули под их видом были бы враньём.
func (m Match) AirOf(unitID string) (brake.State, bool) {
	s, ok := m.Air[unitID]
	return s, ok
}

// SetAir — записать состояние пневматики. Заводить ключ здесь НЕЛЬЗЯ: наличие
// пневматики решается паспортом при постановке машины, и молчаливое появление
// магистрали у машины, у которой её нет, — та самая подстановка, которую проект
// запрещает.
func (m *Match) SetAir(unitID string, s brake.State) {
	if _, ok := m.Air[unitID]; !ok {
		return
	}
	m.Air[unitID] = s
}

// NotchOf — фактическая позиция контроллера, тысячными позиции.
func (m Match) NotchOf(unitID string) (int, bool) {
	n, ok := m.Notches[unitID]
	return n, ok
}

// SetNotch — записать фактическую позицию. Ключ здесь НЕ заводится: позиция
// есть у машины с органами управления, и молчаливое появление её у вагона —
// та же подстановка, что молчаливая магистраль.
func (m *Match) SetNotch(unitID string, milli int) {
	if _, ok := m.Notches[unitID]; !ok {
		return
	}
	m.Notches[unitID] = milli
}

// TurnoutAt — положение остряка устройства. Неизвестное устройство — прямая:
// стрелка, о которой партия ничего не знает, стоит по главному пути.
//
// СТРЕЛКА В ПЕРЕВОДЕ НЕ СТОИТ НИГДЕ, и это не педантизм: остряк на полпути не
// прижат ни к одному рамному рельсу, и ехать по такой стрелке нельзя ни прямо,
// ни на боковую. Пустая строка — то самое «ни туда ни сюда», и обход сети
// (sim.next) на ней останавливается, потому что не находит разрешённого прохода.
func (m Match) TurnoutAt(deviceID string) string {
	if mv, ok := m.TurnoutMoves[deviceID]; ok && mv.Left > 0 {
		return ""
	}
	if pos, ok := m.Turnouts[deviceID]; ok {
		return pos
	}
	return TurnoutStraight
}

// document — файл расстановки как он записан.
type document struct {
	FormatVersion int    `json:"format_version"`
	Region        string `json:"region"`
	Units         []Unit `json:"units"`
}

// Start собирает партию из файла начальной расстановки.
//
// Пустой путь означает партию БЕЗ подвижного состава, и это законное состояние
// мира, а не ошибка: станция без единой машины — обычное дело. Отсутствие
// ключа и отсутствие файла — разные вещи: первое молчаливо и законно, второе
// отказ.
func Start(id, path string, net *track.CompiledNetwork, set *content.Set) (*Match, error) {
	m := &Match{ID: id, Region: net.MapID}
	if path == "" {
		return m, nil
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("match: файл расстановки: %w", err)
	}
	if len(raw) > MaxDocumentBytes {
		return nil, fmt.Errorf("match: файл расстановки больше %d байт", MaxDocumentBytes)
	}
	var doc document
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&doc); err != nil {
		return nil, fmt.Errorf("match: разбор %s: %w", path, err)
	}
	if dec.More() {
		return nil, fmt.Errorf("match: после документа %s есть лишние данные", path)
	}
	if doc.FormatVersion != FormatVersion {
		return nil, fmt.Errorf("match: версия формата %d не поддерживается, ожидается %d",
			doc.FormatVersion, FormatVersion)
	}
	// Расстановка называет регион, хотя сервер и так знает свой: несовпадение
	// значит, что подсунули расстановку от другой карты, и элементы в ней
	// случайно совпадут по именам скорее, чем не совпадут.
	if doc.Region != net.MapID {
		return nil, fmt.Errorf("match: расстановка для региона %s, а мир поднят с %s",
			doc.Region, net.MapID)
	}
	if err := m.place(doc.Units, net, set); err != nil {
		return nil, err
	}
	return m, nil
}

// place проверяет расстановку и укладывает единицы.
//
// Проверяется всё, что можно проверить при загрузке: испорченная расстановка
// обязана не подняться, а не доехать до клиента полусобранной.
func (m *Match) place(list []Unit, net *track.CompiledNetwork, set *content.Set) error {
	seen := map[string]bool{}
	for i, u := range list {
		if err := mapfmt.ValidID("подвижная единица", u.ID); err != nil {
			return fmt.Errorf("match: единица %d: %w", i, err)
		}
		if seen[u.ID] {
			return fmt.Errorf("match: единица %s объявлена дважды", mapfmt.Labeled(u.Name, u.ID))
		}
		seen[u.ID] = true
		if err := u.At.Structural(); err != nil {
			return fmt.Errorf("match: единица %s: %w", mapfmt.Labeled(u.Name, u.ID), err)
		}
		// Направление у подвижной единицы ОБЯЗАТЕЛЬНО: пустое значение в
		// netloc означает «объект направления не имеет», и это правда для
		// платформы, но не для машины — у неё есть перёд.
		if !u.At.Direction.Directed() {
			return fmt.Errorf("match: единица %s: направление не задано; "+
				"у машины есть перёд, и пустое направление означало бы обратное", mapfmt.Labeled(u.Name, u.ID))
		}
		st, ok := set.StockType(u.Type)
		if !ok {
			return fmt.Errorf("match: единица %s: тип %s в наборе контента не объявлен", mapfmt.Labeled(u.Name, u.ID), u.Type)
		}
		el, ok := net.Elements[u.At.Element]
		if !ok {
			return fmt.Errorf("match: единица %s: элемента %s в сети нет", mapfmt.Labeled(u.Name, u.ID), u.At.Element)
		}
		if math.IsNaN(u.At.U) || math.IsInf(u.At.U, 0) || u.At.U < 0 {
			return fmt.Errorf("match: единица %s: u = %v", mapfmt.Labeled(u.Name, u.ID), u.At.U)
		}

		// СОСТОЯНИЕ ФИЗИКИ СОБИРАЕТСЯ ЗДЕСЬ, ДО ПРОВЕРКИ НАЛОЖЕНИЯ: проверять
		// надо тот самый отрезок, который ляжет в мир, а не второй, построенный
		// рядом по тем же правилам.
		mo, err := StartMotion(u, st, el)
		if err != nil {
			return err
		}
		// ЗАПРЕТ НАЛОЖЕНИЯ спрашивает ТОТ ЖЕ ИНДЕКС, что и всё остальное в мире.
		//
		// Здесь стояла своя карта занятых интервалов — второй ответ на тот же
		// вопрос, живший ровно до конца загрузки. Он и разошёлся бы первым: у
		// него не было ни визитов, ни элементов, кроме элемента расстановки, то
		// есть тело, легшее на два элемента, он проверил бы наполовину.
		if ref, at, busy := m.Conflict(u.ID, mo.Span); busy {
			// Метка ищется в РАЗБИРАЕМОМ СПИСКЕ, а не в m.Units: тот заполняется
			// в самом конце place, и во время проверки пуст — отказ назвал бы
			// вторую сторону голым UUID ровно тогда, когда имя и нужно.
			other := ref.Unit
			for _, o := range list {
				if o.ID == ref.Unit {
					other = mapfmt.Labeled(o.Name, o.ID)
				}
			}
			return fmt.Errorf("match: единица %s накладывается на %s: элемент %s, [%s, %s)",
				mapfmt.Labeled(u.Name, u.ID), other, at.Element, at.From, at.To)
		}
		// ОРГАНЫ ЗАВОДЯТСЯ ВМЕСТЕ С МАШИНОЙ, а не от первой команды: машина,
		// стоящая на путях, имеет положение рукояток — нулевую тягу и реверсор
		// в нуле, — и «состояния ещё нет» у неё не бывает. Пустая карта тут
		// означала бы, что до первой команды у локомотива нет кабины.
		if st.Controls != nil {
			if m.Controls == nil {
				m.Controls = map[string]Controls{}
			}
			// У машины с пневматикой ручка крана заводится в поездном
			// положении: магистраль заряжена, и держать зарядку умеет только оно.
			if _, hasAir := st.AirBrake(); hasAir {
				m.Controls[u.ID] = StoppedWithAir()
			} else {
				m.Controls[u.ID] = Stopped()
			}
		}
		// СОСТОЯНИЕ ФИЗИКИ ЗАВОДИТСЯ ВМЕСТЕ С МАШИНОЙ, у всего, что катится:
		// стоящая машина имеет положение и нулевую скорость, а «состояния ещё
		// нет» у неё не бывает. Перевод u → s сделан выше и один раз.
		//
		// Через SetMotion, а не прямой записью в карту: занятость перекладывает
		// он, и расстановка, писавшая мимо, оставила бы индекс пустым — то есть
		// следующая единица легла бы на первую беспрепятственно.
		m.SetMotion(u.ID, mo)
		// ПНЕВМАТИКА ЗАВОДИТСЯ ЗАРЯЖЕННОЙ, а не пустой, и это решение о начале
		// партии, а не удобство: машина, поставленная на путь, стоит с заряженной
		// магистралью и отпущенными колодками — так её и оставляют. Пустая
		// магистраль означала бы, что каждая партия начинается с зарядки, которой
		// никто не просил, а машина при этом стояла бы заторможенной наглухо.
		if air, ok := st.AirBrake(); ok {
			if m.Air == nil {
				m.Air = map[string]brake.State{}
			}
			m.Air[u.ID] = brake.Charged(air)
		}
		// Позиция контроллера заводится нулевой вместе с машиной: стоящая машина
		// имеет позицию, и «её ещё нет» у неё не бывает.
		if st.Controls != nil {
			if m.Notches == nil {
				m.Notches = map[string]int{}
			}
			m.Notches[u.ID] = 0
		}
	}
	m.Units = append([]Unit(nil), list...)
	return nil
}

// startSpan — НАЧАЛЬНЫЙ ОТРЕЗОК ПУТИ по записи расстановки.
//
// # Почему в s, а не вычитанием u
//
// Потому что это РАЗНЫЕ величины. u — авторская координата вдоль
// горизонтальной проекции, s — пространственная длина оси; на уклоне ось
// длиннее проекции. Машина занимает длину вдоль ОСИ, и проверка «влезает ли»,
// сделанная вычитанием метров u, при заметном уклоне разрешила бы то, что не
// влезает. Сегодня уклоны в карте нулевые и разницы нет — проверка написана
// правильно не ради сегодняшних чисел, а ради того дня, когда они появятся.
//
// # Почему не влезающая машина — отказ, а не подвинуть
//
// Правило проекта: валидатор отказывает, а не чинит. Подвинуть машину внутрь
// элемента значило бы поставить её не туда, куда сказал автор, и молча.
//
// # ПОЧЕМУ ТРЕБОВАНИЕ «ВЛЕЗТЬ В ОДИН ЭЛЕМЕНТ» ОСТАЛОСЬ, ХОТЯ ОТРЕЗОК ПРИЕХАЛ
//
// Физика хвостом через стрелку теперь проходит: отрезок наращивается через порт
// и лежит на скольких угодно элементах (track.Span). Требование осталось у
// РАССТАНОВКИ, и по своей причине: чтобы положить тело на два элемента, надо
// знать, в какую сторону от точки его продолжать, — а это зависит от положения
// остряка в момент загрузки. Расстановка же ДОКУМЕНТ: она обязана читаться
// одинаково при любом положении стрелок, иначе один и тот же файл давал бы
// разные миры.
//
// Снимется это вместе с тем, кто объявит начальное положение остряков частью
// расстановки. До тех пор отказ честен: он говорит ровно то, что есть.
func startSpan(u Unit, st content.StockType, el track.CompiledElement) (track.Span, error) {
	uMicro, err := units.MetersToDistance(u.At.U)
	if err != nil {
		return nil, fmt.Errorf("смещение u: %w", err)
	}
	if uMicro > el.LengthU {
		return nil, fmt.Errorf("u = %s больше длины элемента %s (%s)", uMicro, el.ID, el.LengthU)
	}
	center, err := el.Prof.UToS(uMicro)
	if err != nil {
		return nil, fmt.Errorf("перевод u в s: %w", err)
	}
	half, err := units.MetersToDistance(st.LengthM / 2)
	if err != nil {
		return nil, fmt.Errorf("полудлина типа %s: %w", st.ID, err)
	}
	from, to := center-half, center+half
	if from < 0 || to > el.LengthS {
		return nil, fmt.Errorf("машина типа %s длиной %.2f м, поставленная серединой на u = %.2f м, "+
			"занимает [%s, %s] элемента %s длиной %s — не помещается; "+
			"расстановка кладёт тело в один элемент (разбор — у startSpan)",
			st.ID, st.LengthM, u.At.U, from, to, el.ID, el.LengthS)
	}
	return track.Span{{Element: el.ID, From: from, To: to, Direction: u.At.Direction}}, nil
}
