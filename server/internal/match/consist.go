package match

// consist.go — СЦЕП: то, что в этом мире движется.
//
// # Почему движется сцеп, а не машина
//
// До В4 движущимся телом была ЕДИНИЦА: у каждой свой отрезок пути, своя
// скорость, свой шаг интегратора. Пока машина одна, разницы нет. Как только их
// две и они сцеплены, разница становится всем: сцеп идёт с ОДНОЙ скоростью, и
// эта скорость выходит из СУММЫ сил всех единиц — тяги локомотивов, тормоза
// всех, сопротивления каждой на ЕЁ участке пути.
//
// Последнее и есть довод, которого не заменить приближением: у сцепа длиной сто
// метров голова уже на подъёме, а хвост ещё на площадке, и середина стоит в
// кривой, которой не касаются концы. Сложить это можно только по единицам —
// «средний уклон под составом» пришлось бы откуда-то взять, и он был бы
// выдумкой.
//
// Отсюда разделение обязанностей, и оно строгое:
//
//	СЦЕП   владеет ходом: скорость, ускорение, пройденный путь. Один на всех.
//	ЕДИНИЦА владеет местом: свой отрезок пути, своя точка отсчёта, свой уклон.
//
// # Порядок членов и концы
//
// Члены перечислены ОТ КОНЦА B К КОНЦУ A — тот же порядок, что у визитов
// отрезка пути (track.Span), и это не совпадение: сцеп двигают, наращивая
// отрезки его единиц в ту же сторону, и два разных порядка на одном движении
// разошлись бы на первом же реверсе.
//
// Концы A и B ПОСТОЯННЫ и не зависят ни от хода, ни от реверсора. Меняется
// только Leading — какой из них сегодня ведёт. Это прямо записано в вехе:
// «постоянные концы EndA/EndB, реверс меняет только Leading».
//
// # Единица всегда в сцепе, даже одна
//
// Одиночная машина — сцеп из одного члена, а не особый случай. Второй путь
// «машина без сцепа» означал бы два интегратора, и разойтись они обязаны:
// сцепка двух одиночек тогда меняла бы не связь между ними, а сам способ их
// считать.

import (
	"fmt"

	"github.com/shady2k/ClearAhead/server/internal/netloc"
	"github.com/shady2k/ClearAhead/server/internal/units"
)

// End — конец сцепа. Постоянен: A — тот, куда смотрит конец A первой единицы в
// порядке перечисления, B — противоположный.
type End string

const (
	EndA End = "a"
	EndB End = "b"
)

// Member — единица в сцепе и то, как она в нём повёрнута.
type Member struct {
	UnitID string `json:"unit"`
	// Flipped — единица стоит в сцепе ЗАДОМ НАПЕРЁД: её конец A смотрит в
	// сторону конца B сцепа.
	//
	// Хранится, а не выводится из геометрии, и это решение: вывести поворот из
	// отрезков можно, но ответ зависел бы от того, на каком элементе единица
	// стоит сейчас, — то есть менялся бы при переезде через встречную стрелку,
	// хотя в сцепе ничего не поворачивалось. Поворот в сцепе — факт СЦЕПКИ, он
	// назначается в момент соединения и живёт до расцепки.
	Flipped bool `json:"flipped,omitempty"`
}

// Consist — сцеп: упорядоченный набор единиц, идущих как одно тело.
type Consist struct {
	ID string `json:"id"`
	// Members — от конца B к концу A. Пустого сцепа не бывает: сцеп без единиц
	// — это не пустое множество, а отсутствие сцепа, и расцепка удаляет его
	// целиком, а не оставляет пустым.
	Members []Member `json:"members"`
	// Speed — скорость вдоль хода B → A, со знаком. ОДНА НА ВЕСЬ СЦЕП.
	//
	// # Почему не по единицам, хотя у Motion скорость есть
	//
	// У Motion.Speed знак привязан к росту u ЭЛЕМЕНТА, под которым стоит
	// единица, а у единиц сцепа элементы разные и оси у них бывают встречны:
	// голова уже на элементе, растущем навстречу, хвост ещё на прежнем. Общей
	// величины «скорость» в этих знаках не существует — есть скорость СЦЕПА
	// вдоль его собственной оси, и она здесь.
	//
	// Motion.Speed при этом остаётся, но становится СЛЕДСТВИЕМ: его пишет шаг
	// сцепа, переводя эту скорость в знак каждой единицы. Единственный
	// писатель — тот же приём, которым удержан кэш точки отсчёта в Motion.
	Speed units.Speed `json:"speed"`
	// Leading — какой конец ведёт. Реверс меняет ТОЛЬКО его: у сцепа не бывает
	// «переднего» конца по природе, бывает тот, с которого сегодня ведут.
	Leading End `json:"leading"`
}

// Single — сцеп из одной единицы: то, чем становится всякая машина расстановки.
//
// Ведущим назначается конец A, и это не выбор из двух зол: у единицы конец A —
// тот, куда смотрит её направление в расстановке (netloc.Point.Direction), то
// есть ровно тот, который автор назвал передом.
//
// # Имя сцепа из одной единицы — ИМЯ ЭТОЙ ЕДИНИЦЫ
//
// Не выдуманный UUID, и довод не в экономии. Расстановка ДЕТЕРМИНИРОВАНА:
// партия, загруженная дважды из одного файла, обязана совпасть до последнего
// поля — на этом стоит канонический хеш состояния (engine/hash.go). Случайный
// идентификатор развёл бы две загрузки одного документа, то есть сделал бы
// воспроизводимость мира ложью ради красоты имени.
//
// Новое имя рождается там, где рождается новая сущность: СЦЕПКА создаёт сцеп,
// которого не было, и вот ему UUID и нужен.
func Single(unitID string) Consist {
	return Consist{ID: unitID, Members: []Member{{UnitID: unitID}}, Leading: EndA}
}

// Validate — сцеп осмыслен: есть члены, они не повторяются, конец назван.
func (c Consist) Validate() error {
	if c.ID == "" {
		return fmt.Errorf("match: сцеп без идентификатора")
	}
	if len(c.Members) == 0 {
		return fmt.Errorf("match: сцеп %s без единиц; пустой сцеп — это отсутствие сцепа", c.ID)
	}
	if c.Leading != EndA && c.Leading != EndB {
		return fmt.Errorf("match: сцеп %s: ведущий конец %q, знаю %q и %q", c.ID, c.Leading, EndA, EndB)
	}
	seen := map[string]bool{}
	for _, mem := range c.Members {
		if mem.UnitID == "" {
			return fmt.Errorf("match: сцеп %s: член без единицы", c.ID)
		}
		if seen[mem.UnitID] {
			return fmt.Errorf("match: сцеп %s: единица %s названа дважды — в одном сцепе она стоит один раз",
				c.ID, mem.UnitID)
		}
		seen[mem.UnitID] = true
	}
	return nil
}

// Has — входит ли единица в этот сцеп.
func (c Consist) Has(unitID string) bool {
	for _, mem := range c.Members {
		if mem.UnitID == unitID {
			return true
		}
	}
	return false
}

// UnitSpeed — скорость ЕДИНИЦЫ вдоль роста u её элемента: то, что уезжает на
// провод и во что смотрит физика этой единицы.
//
// Два переворота знака, и оба обязательны. Первый — поворот единицы В СЦЕПЕ
// (Member.Flipped): у перевёрнутой единицы ход B → A сцепа идёт от её A к её B.
// Второй — поворот единицы НА ЭЛЕМЕНТЕ (Motion.Facing): ось под ней бывает
// встречной ходу. Пропусти любой — и половина состава поедет назад.
func (c Consist) UnitSpeed(mem Member, facing netloc.Direction) units.Speed {
	v := c.Speed
	if mem.Flipped {
		v = -v
	}
	if facing == netloc.DirReverse {
		v = -v
	}
	return v
}

// ConsistOf — сцеп, в котором едет единица.
func (m Match) ConsistOf(unitID string) (Consist, bool) {
	for _, c := range m.Consists {
		if c.Has(unitID) {
			return c, true
		}
	}
	return Consist{}, false
}

// SetConsist — записать сцеп на место одноимённого. Заводит новый, если такого
// ещё нет: сцепка создаёт сцеп, и отдельного «добавить» для этого не нужно.
func (m *Match) SetConsist(c Consist) {
	for i := range m.Consists {
		if m.Consists[i].ID == c.ID {
			m.Consists[i] = c
			return
		}
	}
	m.Consists = append(m.Consists, c)
}

// UnitOf — единица партии по имени. Заведён сцепом: шаг сцепа знает имена своих
// членов, а нужна ему запись расстановки (тип, груз), и искать её перебором у
// каждого вызывающего значило бы завести этот перебор в трёх местах.
func (m Match) UnitOf(unitID string) (Unit, bool) {
	for _, u := range m.Units {
		if u.ID == unitID {
			return u, true
		}
	}
	return Unit{}, false
}
