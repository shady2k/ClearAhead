// Состояние физики: где машина и как быстро идёт.
//
// # Третий класс фактов, и он последний из четырёх
//
// Паспорт (какая машина бывает) живёт в наборе контента, актуаторы (что
// выставлено) — в controls.go, ПРОИЗВОДНОЕ (что показывает прибор) считается из
// того, что здесь. Здесь — то, что вышло из физики.
//
// # Почему положение живёт в S, а не в u расстановки
//
// Unit.At — это ДОКУМЕНТ: где автор поставил машину, в его координате u вдоль
// горизонтальной проекции. Физика же движется вдоль ОСИ, и на уклоне ось длиннее
// проекции: складывать метры u со скоростью значило бы ехать по карте, а не по
// пути.
//
// Поэтому положение состояния — s (микрометры вдоль оси), а u выводится из него
// переводом (Profile.SToU) в тот миг, когда состояние уезжает на провод. Двух
// источников истины при этом не заводится: документ после старта не меняется
// вовсе, а состояние не пишется обратно в него.
//
// # Знак скорости — вдоль РОСТА u элемента, а не «вперёд»
//
// «Вперёд» — свойство машины (куда смотрит), и оно уже записано в Facing. Скорость
// же складывается с положением, поэтому её знак обязан быть привязан к тому же
// направлению, что и положение, — к росту u. Иначе на каждом переходе через
// стрелку пришлось бы помнить, в какую сторону «вперёд» было на прошлом
// элементе.

// Motion — состояние физики одной единицы.
type Motion struct {
	// Span — ОТРЕЗОК ПУТИ, ЗАНЯТЫЙ МАШИНОЙ: цепочка визитов от конца B к концу A.
	//
	// ЭТО ЗАПИСЬ, А ВСЁ ОСТАЛЬНОЕ ЗДЕСЬ — ЕЁ СЛЕДСТВИЕ. Отрезок появился
	// 2026-08-15 (ClearAhead-7n0v) и заменил собой то, чего у машины не было
	// вовсе: знание, где лежат её КОНЦЫ. До него концы выводились полудлиной от
	// точки отсчёта, и это было верно ровно до первой границы элемента.
	//
	// Разбор формы, порядка визитов и того, почему пара портов не хранится, — у
	// track.Span.
	Span track.Span `json:"span"`
	// Element — на каком элементе сети стоит ТОЧКА ОТСЧЁТА машины. Может
	// отличаться от элемента расстановки: она уехала.
	//
	// # ПОЛЕ ХРАНИТСЯ, ХОТЯ ВЫВОДИТСЯ ИЗ ОТРЕЗКА, и цена этого названа
	//
	// Точка отсчёта — середина отрезка (Span.Middle), то есть Element, S и Facing
	// вычислимы и хранить их незачем. Хранятся они потому, что спрашивают их в
	// горячем пути: физика берёт уклон и радиус под точкой отсчёта на каждом из
	// пяти подшагов тика, канонический хеш состояния — на каждом тике, проекция
	// на провод — на каждом снапшоте.
	//
	// Цена — кэш, который вправе разойтись с записью. Она уплачена ЕДИНСТВЕННЫМ
	// ПИСАТЕЛЕМ: поля правит только SetSpan, второго места, где им присваивают,
	// нет, и сторожем этому служит тест (TestReferenceFollowsTheSpan). Другого
	// способа не заводить второй истины у кэша не существует — есть только
	// способ сделать его невозможным к расхождению.
	Element string `json:"element"`
	// S — положение точки отсчёта машины вдоль оси элемента, микрометры.
	S units.Distance `json:"s"`
	// Speed — скорость вдоль роста u элемента, со знаком.
	Speed units.Speed `json:"speed"`
	// Slipping — БУКСУЕТ ЛИ машина: двигатели просят больше, чем удержит
	// сцепление. Состояние, а не команда; на провод уходит признаком, потому что
	// иначе буксование необъяснимо — машина просто едет хуже, чем должна, и
	// машинист ищет неисправность там, где её нет.
	Slipping bool `json:"slipping,omitempty"`
	// Facing — как машина повёрнута относительно роста u ЭТОГО элемента.
	//
	// Меняется при переходе на элемент, встречный по направлению: машина не
	// разворачивается, разворачивается координата под ней.
	Facing netloc.Direction `json:"facing"`
}

// SetSpan — положить новый отрезок и пересчитать по нему точку отсчёта.
//
// ЕДИНСТВЕННЫЙ ПИСАТЕЛЬ полей Element, S и Facing: разбор — у самих полей.
// Скорость здесь не трогается — она принадлежит интегратору, — но ЕЁ ЗНАК
// ПРИВЯЗАН К ЭЛЕМЕНТУ, и при въезде на встречный элемент его надо перевернуть.
// Делает это тот, кто двигает (sim.move): он один знает, куда машина ехала.
func (m *Motion) SetSpan(sp track.Span) error {
	el, at, dir, ok := sp.Middle()
	if !ok {
		return fmt.Errorf("match: отрезок не даёт точки отсчёта: %d визитов, длина %s",
			len(sp), sp.Length())
	}
	m.Span = sp
	m.Element, m.S, m.Facing = el, at, dir
	return nil
}

// Stopped — стоит ли машина.
//
// Отдельным словом, а не сравнением с нулём у каждого вызывающего: «стоит» —
// это состояние мира, и решать его должно одно место. Сегодня это точный ноль:
// интегратор гасит остаток скорости на месте (sim), а не оставляет дрожать
// микрометры в секунду.
func (m Motion) Stopped() bool { return m.Speed == 0 }

// MotionOf — состояние физики единицы.
func (m Match) MotionOf(unitID string) (Motion, bool) {
	mo, ok := m.Motions[unitID]
	return mo, ok
}

// SetMotion кладёт новое состояние физики И ПЕРЕКЛАДЫВАЕТ ЗАНЯТОСТЬ.
//
// Физику не проверяет: проверяет тот, кто считает (sim), и проверяет ДО того,
// как состояние стало состоянием. Проверка здесь была бы второй, и первое же
// расхождение между ними означало бы, что мир умеет быть в состоянии, которое
// сам же считает невозможным.
//
// А вот индекс занятости правится ИМЕННО ЗДЕСЬ и больше нигде — «в той же
// транзакции», что и отрезок. Разбор — в occupancy.go: второй писатель означал
// бы окно, в котором индекс говорит про мир, которого уже нет.
func (m *Match) SetMotion(unitID string, mo Motion) {
	if m.Motions == nil {
		m.Motions = map[string]Motion{}
	}
	before := m.Motions[unitID].Span
	m.Motions[unitID] = mo
	m.setOccupancy(unitID, before, mo.Span)
}

// StartMotion — состояние физики по расстановке: там, где поставил автор, стоя.
//
// Перевод u → s делается ЗДЕСЬ и один раз: дальше физика живёт в s, и второго
// перевода в горячем пути не случается.
//
// ОТРЕЗОК ПУТИ СТРОИТСЯ ЗДЕСЬ ЖЕ, а не приходит готовым, и паспорт для этого
// приходится принять аргументом. Довод тот же, что у перевода u → s: у машины,
// заведённой в партию, отрезок есть всегда, и «состояния ещё нет» у неё не
// бывает. Второй вход, строящий отрезок мимо этого, разошёлся бы с ним ровно
// тогда, когда правило построения сменится.
func StartMotion(u Unit, st content.StockType, el track.CompiledElement) (Motion, error) {
	sp, err := startSpan(u, st, el)
	if err != nil {
		return Motion{}, fmt.Errorf("match: единица %s: %w", u.ID, err)
	}
	mo := Motion{Speed: 0}
	if err := mo.SetSpan(sp); err != nil {
		return Motion{}, fmt.Errorf("match: единица %s: %w", u.ID, err)
	}
	// НАПРАВЛЕНИЕ СВЕРЯЕТСЯ, А НЕ ПРИСВАИВАЕТСЯ. Facing выведен из отрезка
	// (SetSpan), а расстановка объявила своё; расхождение означало бы, что
	// отрезок построен не тем концом, и молча взять любое из двух значило бы
	// поставить машину повёрнутой не так, как написал автор.
	if mo.Facing != u.At.Direction {
		return Motion{}, fmt.Errorf("match: единица %s: отрезок положен направлением %q, "+
			"а расстановка объявила %q", u.ID, mo.Facing, u.At.Direction)
	}
	return mo, nil
}

// UnitState — единица, какой её видит клиент: документ плюс состояние.
//
// # Почему проекция на провод живёт ЗДЕСЬ, а не в транспорте
//
// Транспортов два — канал и оставшаяся ручка живого состояния, — и каждый мог
// бы собрать эту проекцию сам. Именно поэтому она собирается здесь: две сборки
// разошлись бы на первой же правке, и клиент, ходящий двумя дорогами, получил бы
// два разных мира. Конверт вокруг (snapshot_seq, сессия) остаётся транспортным,
// а вот ЧТО в нём лежит — свойство партии.
//
// At — положение СЕЙЧАС, а не то, что записано в расстановке: расстановка
// говорит, где машину поставили, состояние — где она теперь.
type UnitState struct {
	ID   string `json:"id"`
	Name string `json:"name,omitempty"`
	Type string `json:"type"`
	// At — точка отсчёта машины в координатах провода.
	At netloc.PointU `json:"at"`
	// Span — ОТРЕЗОК ПУТИ, ЗАНЯТЫЙ МАШИНОЙ, в координатах провода: цепочка
	// интервалов от конца B к концу A.
	//
	// # Зачем клиенту знать больше, чем точку
	//
	// Потому что рисует он не точку. Машина ставится хордой между шкворнями, а
	// шкворень вправе оказаться на СОСЕДНЕМ элементе; какой элемент соседний,
	// решают сеть и положение остряка, то есть сервер. Без отрезка клиент
	// прижимал шкворень к границе и лечил перекос сжатием хорды — ценой в
	// поправку, которая у конца элемента пропадала (ClearAhead-cc0x).
	//
	// И второе: показ идёт между двумя снимками ПО ПУТИ, а не по одному
	// элементу. Правило «через границу не интерполируем» отдавало на переходе
	// целый промежуток разом — ЗАМЕР 0.72…0.73 м за кадр при 6.9 м/с. Отрезок
	// даёт общую систему отсчёта для двух снимков на разных элементах.
	//
	// ЕДЕТ ВСЕГДА, а не только когда машина стоит на границе: клиент, у которого
	// поле то есть, то нет, обязан был бы иметь два способа поставить машину, и
	// второй проверялся бы только на границе — то есть почти никогда.
	Span netloc.LinearU `json:"span"`
	// Speed — скорость вдоль роста u элемента, микрометры в секунду, СТРОКОЙ
	// (units.Speed): то же правило провода, что у времени и расстояний.
	Speed units.Speed `json:"speed"`
	// Controls — положение органов. Отсутствует у машины без кабины.
	Controls *Controls `json:"controls,omitempty"`
	// Slipping — буксует ли машина. Признак СОСТОЯНИЯ, а не органа: выставить его
	// нельзя, он следствие того, что двигатели просят больше сцепления.
	Slipping bool `json:"slipping,omitempty"`
	// Notch — ФАКТИЧЕСКАЯ позиция главного контроллера, тысячными позиции.
	// Отличается от Controls.Traction, которое есть ЗАДАНИЕ машиниста: позиция
	// идёт к заданию своим темпом, и показывать одно вместо другого значило бы
	// врать про то, чем машина тянет прямо сейчас.
	Notch int `json:"notch"`
	// Air — ДАВЛЕНИЯ пневматики. Отсутствует у машины без тормозной магистрали:
	// у неё их не существует, и нули под их видом были бы приборами, которые
	// врут. Отдельно от Controls, потому что это СЛЕДСТВИЕ, а не орган:
	// выставить давление командой нельзя.
	Air *brake.State `json:"air,omitempty"`
}

// States — все единицы партии в координатах провода.
//
// Порядок — порядок расстановки: он же порядок Units, и он устойчив между
// снимками. Клиент опирается на идентификаторы, но человек, читающий два снимка
// подряд, читает их глазами — и переставленные строки читались бы как движение.
func (m Match) States(net *track.CompiledNetwork) ([]UnitState, error) {
	out := make([]UnitState, 0, len(m.Units))
	for _, u := range m.Units {
		st := UnitState{ID: u.ID, Name: u.Name, Type: u.Type, At: u.At}
		if mo, ok := m.MotionOf(u.ID); ok {
			el, ok := net.Elements[mo.Element]
			if !ok {
				return nil, fmt.Errorf("match: единица %s: элемента %s нет в сети", u.ID, mo.Element)
			}
			at, err := mo.WirePoint(el)
			if err != nil {
				return nil, err
			}
			span, err := mo.Span.ToU(net)
			if err != nil {
				return nil, fmt.Errorf("match: единица %s: %w", u.ID, err)
			}
			st.At = at
			st.Span = span
			st.Speed = mo.Speed
			st.Slipping = mo.Slipping
		}
		if c, ok := m.ControlsOf(u.ID); ok {
			cc := c
			st.Controls = &cc
		}
		if n, ok := m.NotchOf(u.ID); ok {
			st.Notch = n
		}
		if a, ok := m.AirOf(u.ID); ok {
			aa := a
			st.Air = &aa
		}
		out = append(out, st)
	}
	return out, nil
}

// WirePoint — положение машины в координатах провода: элемент, u, направление.
//
// Перевод s → u происходит ЗДЕСЬ, на границе с проводом, и только здесь.
// Клиент получает ту же координату, в которой написана карта, и ничего не
// пересчитывает — правило «длины считает только Go» держится и в движении.
func (m Motion) WirePoint(el track.CompiledElement) (netloc.PointU, error) {
	uMicro, err := el.Prof.SToU(m.S)
	if err != nil {
		return netloc.PointU{}, fmt.Errorf("match: элемент %s: перевод s в u: %w", el.ID, err)
	}
	return netloc.PointU{Element: el.ID, U: uMicro.Meters(), Direction: m.Facing}, nil
}
