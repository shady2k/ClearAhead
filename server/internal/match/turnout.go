// Стрелка как то, чем ИГРАЮТ: положение, занятость и перевод.
//
// # Почему положение живёт в партии, а не в карте
//
// Карта говорит, какие устройства есть и как они устроены; куда переведён
// остряк — событие партии, и после перезапуска сервера стрелка законно
// оказывается там, где её застало начало новой партии, а не там, где её оставил
// прошлый игрок. Тот же довод, по которому в карте нет положения локомотива.
//
// # Перевод — команда, и у неё ровно одно место
//
// Здесь. Клиент шлёт её каналом, движок применяет правкой в фазе приёма, но
// ПРАВИЛО («можно ли перевести») живёт при состоянии — как и правило пределов
// ступеней живёт при органах управления. Вторая дорога к тому же полю (маршрут,
// автопилот) обязана пройти через ту же проверку, а не мимо неё.

// TurnoutState — стрелка, какой её видит клиент.
//
// Едет в снапшоте целым списком, а не по изменившимся: снапшот полный, и
// стрелок на станции единицы. Клиент по этому списку и рисует указатели, и
// показывает пульту, что он переводит.
type TurnoutState struct {
	ID string `json:"id"`
	// Name — читаемая метка: то же, что написано на табличке у самой стрелки.
	Name string `json:"name,omitempty"`
	// Position — положение остряка: TurnoutStraight или TurnoutDiverging.
	Position string `json:"position"`
	// Drive — переводной механизм (mapfmt.DriveManual, DriveElectric). Едет
	// вместе с положением, потому что от него зависит, КАК стрелку переводят, и
	// пульт обязан показывать это, не ходя за вторым ресурсом.
	Drive string `json:"drive"`
	// OccupiedBy — единица, стоящая НА устройстве. Пусто значит «свободна».
	//
	// Едет наружу, потому что отказ «под составом не переводится» обязан быть
	// ВИДЕН ДО НАЖАТИЯ: пульт, предлагающий перевод, который заведомо будет
	// отвергнут, врёт ровно так же, как подсказка о непривязанной клавише.
	OccupiedBy string `json:"occupied_by,omitempty"`
}

// TurnoutStates — все стрелки региона в порядке идентификатора.
//
// Перечень берётся у СЕТИ, а не у карты положений: партия хранит только те
// стрелки, которые переводили, и список по ней был бы списком «тех, кого
// трогали». Умолчание — прямое положение (TurnoutAt).
func (m Match) TurnoutStates(net *track.CompiledNetwork) []TurnoutState {
	out := make([]TurnoutState, 0, len(net.Devices))
	for id, d := range net.Devices {
		out = append(out, TurnoutState{
			ID:         id,
			Name:       d.Name,
			Position:   m.TurnoutAt(id),
			Drive:      d.Drive,
			OccupiedBy: m.TurnoutHeldBy(net, id),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

// SetTurnout переводит остряк устройства.
//
// # Три отказа, и все три — правила мира, а не формы
//
// Неизвестное устройство, неизвестное положение и ЗАНЯТОСТЬ. Форму (строку
// вместо числа, пустое поле) отвергает разбор params; здесь отвергается то, что
// без состояния мира решить нельзя.
//
// # Механизм НЕ различает право на перевод, и это решение владельца
//
// Ручной перевод в жизни делают рукой у самой стрелки, а электропривод — с
// пульта, и напрашивается отказывать в удалённом переводе ручной стрелки.
// Решение владельца 2026-08-15: переводятся удалённо ОБЕ. Механизм остаётся
// различием мира — разные тела в кадре и разный способ, которым игрок до
// стрелки дотягивается, — но не правом.
//
// Проверить «игрок стоит рядом» сервер и не может: человека в мире он не знает
// вовсе (границы клиента, driver.gd), и досягаемость — свойство КЛИЕНТСКОЙ
// подсказки. Записано здесь, чтобы отсутствие проверки не сочли недосмотром.
func (m *Match) SetTurnout(deviceID, position string, net *track.CompiledNetwork) error {
	dev, ok := net.Devices[deviceID]
	if !ok {
		return &protocol.Refusal{Reason: protocol.ReasonUnknownTurnout, ResourceID: deviceID,
			Text: fmt.Sprintf("стрелки %s в регионе нет", deviceID)}
	}
	if position != TurnoutStraight && position != TurnoutDiverging {
		return &protocol.Refusal{Reason: protocol.ReasonUnknownTurnoutPosition, ResourceID: deviceID,
			Text: fmt.Sprintf("положение остряка %q: знаю %q и %q",
				position, TurnoutStraight, TurnoutDiverging)}
	}
	label := mapfmt.Labeled(dev.Name, dev.ID)
	// ПОД СОСТАВОМ СТРЕЛКА НЕ ПЕРЕВОДИТСЯ. В жизни перевод под составом — это
	// сход, а не переключение, и последствия у него не игровые. Моделировать их
	// мы не будем, поэтому команда отвергается целиком.
	//
	// Отказ идёт ДЕРЖАТЕЛЕМ (held_by): это ровно тот случай, ради которого поле
	// заведено, — борьба за ресурс, у которой есть тот, кто его занял.
	if by := m.TurnoutHeldBy(net, deviceID); by != "" {
		return &protocol.Refusal{Reason: protocol.ReasonTurnoutOccupied, ResourceID: deviceID, HeldBy: by,
			Text: fmt.Sprintf("стрелка %s занята единицей %s — под составом не переводится", label, by)}
	}
	// ПОВТОР ТОГО ЖЕ ПОЛОЖЕНИЯ — НЕ ОТКАЗ. Команда идемпотентна по смыслу:
	// остряк уже там, куда просят, и мир после неё тот же самый.
	if m.Turnouts == nil {
		m.Turnouts = map[string]string{}
	}
	m.Turnouts[deviceID] = position
	return nil
}

// AheadTurnout — ближайшая стрелка ПО ХОДУ машины.
//
// # Зачем это едет с сервера, а не считается клиентом
//
// Потому что это обход СЕТИ, а сеть — факт о мире. Клиент, выводящий «какая
// стрелка следующая» из присланной геометрии, выдумывал бы связность: закон
// клиента (ClearAhead-sjq) запрещает ему это ровно так же, как запрещает
// выводить крестовину и решётку.
//
// Потребитель у поля один и он конкретный: пульт показывает игроку, КАКУЮ
// стрелку он переведёт клавишей, — и без этого «переключить следующую» означало
// бы «переключить какую-то».
type AheadTurnout struct {
	// Turnout — идентификатор устройства.
	Turnout string `json:"turnout"`
	// DistanceM — сколько до него ехать ОТ КОНЦА МАШИНЫ, метры вдоль пути.
	//
	// От конца, а не от точки отсчёта: игрок смотрит вперёд из кабины, и
	// расстояние, отсчитанное от середины машины, врало бы на полдлины — у ВЛ80
	// это 16.4 м, то есть половина стрелочного перевода.
	DistanceM float64 `json:"distance"`
}

// NextTurnout — ближайшее устройство впереди машины и расстояние до него.
//
// # Куда «вперёд»
//
// Едущая машина смотрит туда, куда едет (знак скорости); стоящая — туда, куда
// повёрнута (Facing). Реверсор здесь не спрашивается: он говорит, куда машина
// ПОЕДЕТ, когда наберут тягу, а стоящая машина с реверсором назад стоит носом
// туда же, куда стояла.
//
// # Положение остряков обход НЕ учитывает, и это нарочно
//
// sim.next пропускает проход, по которому остряк не стоит: физике важно, куда
// МОЖНО ехать. Здесь вопрос другой — какая стрелка ближайшая, — и стрелка,
// стоящая не по нашему ходу, ближайшей быть не перестаёт. Наоборот: именно её и
// надо перевести, и не показать её значило бы прятать от игрока ровно ту
// стрелку, ради которой он потянулся к пульту.
//
// # Границы обхода
//
// Восемь переходов и ни одним больше — тот же потолок, что у движения в sim, и
// та же его причина: он стоит против петли в сети, а не против длинной станции.
// Развилка без устройства (в порту сходятся три ребра) обход прекращает: такой
// карты валидатор не пропустит, но обход не полагается на то, что его позвали
// после валидатора.
func (m Match) NextTurnout(net *track.CompiledNetwork, u Unit) *AheadTurnout {
	mo, ok := m.MotionOf(u.ID)
	if !ok {
		return nil
	}
	passages := passageOwners(net)
	// Куда растёт путь под нами: по росту u элемента точки отсчёта или против.
	up := mo.Facing != netloc.DirReverse
	if mo.Speed > 0 {
		up = true
	} else if mo.Speed < 0 {
		up = false
	}
	// ОТСЧЁТ ИДЁТ ОТ НАСТОЯЩЕГО КОНЦА МАШИНЫ, а не от полудлины.
	//
	// Здесь стояло `mo.S ± halfLength` с прижатием отрицательного остатка к нулю,
	// и прижимать было что: середина уже свисала за границу, а конец лежал на
	// соседнем элементе, которого этот расчёт не видел вовсе. Отрезок пути
	// (track.Span) знает, где конец лежит на самом деле, — и обход начинается
	// оттуда, с ТОГО элемента, а не с элемента середины.
	//
	// Какой из концов ведущий: ход к концу A совпадает с ростом u ровно там, где
	// направление визита под точкой отсчёта — forward.
	toA := up == (mo.Facing != netloc.DirReverse)
	edge := mo.Span.Length()
	if !toA {
		edge = 0
	}
	endEl, endS, endDir, ok := mo.Span.PointAt(edge)
	if !ok {
		return nil
	}
	el, ok := net.Elements[endEl]
	if !ok {
		return nil
	}
	// На элементе ВЕДУЩЕГО КОНЦА рост u может быть встречен тому, что под
	// серединой: оси соседних элементов бывают встречны, и знак назначается
	// заново — по направлению того визита, в котором лежит конец.
	upEnd := (endDir != netloc.DirReverse) == toA
	dist := el.LengthS - endS
	port := el.To
	if !upEnd {
		dist = endS
		port = el.From
	}
	for range 8 {
		next, ok := singleNeighbour(net, port, el.ID)
		if !ok {
			return nil // упор, край карты или развилка без устройства
		}
		if dev, isPassage := passages[next.ID]; isPassage {
			return &AheadTurnout{Turnout: dev, DistanceM: dist.Meters()}
		}
		dist += next.LengthS
		// Вошли началом — идём к его концу, и наоборот.
		if next.From == port {
			port = next.To
		} else {
			port = next.From
		}
		el = next
	}
	return nil
}

// singleNeighbour — единственный сосед по порту, кроме исключённого элемента.
//
// «Единственный» — часть ответа, а не удобство: в порту, где сходятся три
// элемента, продолжение неоднозначно, и обход обязан остановиться, а не выбрать
// первый попавшийся. Обход всей карты элементов — тот же замер, что у
// addPortNeighbours: сеть станции мала, а спрашивают её при сборке снапшота.
func singleNeighbour(net *track.CompiledNetwork, port, exclude string) (track.CompiledElement, bool) {
	var found track.CompiledElement
	n := 0
	for id, e := range net.Elements {
		if id == exclude {
			continue
		}
		if e.From == port || e.To == port {
			found = e
			n++
		}
	}
	return found, n == 1
}

// passageOwners — проход устройства в его владельца.
//
// Строится ПО ТАБЛИЦЕ УСТРОЙСТВ, а не разбором имени элемента: имя разбирает
// sim, и там это законно (соглашение об именах у него же), но здесь под рукой
// есть сама таблица переходов, а она источник, а не соглашение.
func passageOwners(net *track.CompiledNetwork) map[string]string {
	out := make(map[string]string, 2*len(net.Devices))
	for id, d := range net.Devices {
		for _, tr := range d.Traversals {
			out[tr.Passage] = id
		}
	}
	return out
}

// TurnoutHeldBy — единица, накрывающая устройство. Пусто, если свободно.
//
// # Здесь было ПРИБЛИЖЕНИЕ, и оно умерло по объявленному условию
//
// Занятость считалась от точки отсчёта полудлиной в обе стороны, со свесом на
// один элемент и во ВСЕ элементы порта сразу — то есть строже правды на один
// проход. Границы были названы вслух, и там же было сказано, чем это лечится:
// «НАСТОЯЩЕЕ РЕШЕНИЕ — занятость сегментов с обратным индексом
// (ClearAhead-7n0v)». Оно приехало, и приближение снято целиком.
//
// Разница не косметическая. Отрезок пути знает, ГДЕ ЛЕЖАТ КОНЦЫ тела и через
// какие порты оно ФАКТИЧЕСКИ прошло: свес больше не гадает по портам, состав
// длиннее двух элементов виден весь, а переставленный остряк не переписывает
// того, что уже под колёсами. Ровно этого и требует правило «стрелку под
// составом не перевести»: оно про то, где состав ЕСТЬ, а не про то, где он
// мог бы быть.
//
// Набор контента больше не нужен: длина тела уже учтена в его отрезке.
func (m Match) TurnoutHeldBy(net *track.CompiledNetwork, deviceID string) string {
	by, _ := m.DeviceBusy(net, deviceID)
	return by
}
