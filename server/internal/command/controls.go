// Package command — доменные команды: правки партии, которые движок применяет
// в фазе приёма.
//
// # Почему отдельный пакет, а не «рядом с каналом»
//
// Канал (internal/channel) — транспорт: сокет, кадры, сессии, идемпотентность.
// Команда — домен: что именно меняется в мире и по каким правилам. Положи
// первую команду в канал — и туда же лягут стрелки, маршруты и цели ведения,
// то есть транспорт станет местом, где живёт игра.
//
// Расщепление вехи В2 (ClearAhead-wa51) сделано ровно по этому шву, и этот
// пакет — его вторая сторона: канал закрылся, не назвав ни одной команды, а
// команды называются здесь.
//
// # Почему не в match
//
// Потому что engine.Mutation — интерфейс движка, а движок владеет партией:
// match, реализующий его, получил бы обратную зависимость на того, кто им
// управляет.
package command

import (
	"github.com/shady2k/ClearAhead/server/internal/content"
	"github.com/shady2k/ClearAhead/server/internal/match"
)

// SetControls — поставить органы управления машины.
//
// Первая доменная правка проекта. Она же первая реализация engine.Mutation:
// до неё интерфейс существовал с поддельной правкой в тестах, и это было
// объявленной границей вехи канала, а не задел впрок.
type SetControls struct {
	// Unit — какой машиной управляют.
	Unit string
	// Controls — положение ВСЕХ органов. Разбор, почему всех разом, — в
	// protocol.ControlsRequest.
	Controls match.Controls
	// Set — набор контента: в нём паспорт, а в паспорте пределы ступеней.
	//
	// Правка носит его с собой, потому что Apply получает только партию.
	// Набор неизменяем после загрузки, и общий указатель на него — не
	// разделяемое изменяемое состояние, а разделяемая константа.
	Set *content.Set
}

// Name — имя правки для журнала и логов.
func (SetControls) Name() string { return "controls.set" }

// Apply ставит органы управления, проверив их паспортом.
//
// Проверка живёт в match.SetControls, а не здесь, и это не перекладывание:
// пределы — свойство партии и её машин, и правило «валидатор отказывает, а не
// чинит» обязано стоять там, где состояние, а не там, где команда. Иначе вторая
// дорога к тому же полю (автопилот В6) прошла бы мимо проверки.
func (c SetControls) Apply(m *match.Match) error {
	return m.SetControls(c.Unit, c.Controls, c.Set)
}
