package command

import (
	"github.com/shady2k/ClearAhead/server/internal/match"
	"github.com/shady2k/ClearAhead/server/internal/track"
)

// SetTurnout — перевести остряк стрелки.
//
// Вторая доменная правка проекта и первая, которая принадлежит НЕ КАБИНЕ:
// органы управления адресуются машине, стрелка — пути. Отсюда и другой набор
// того, что правка носит с собой.
type SetTurnout struct {
	// Turnout — какое устройство переводим.
	Turnout string
	// Position — в какое положение: match.TurnoutStraight или TurnoutDiverging.
	Position string
	// Net — сеть региона. Правка носит её с собой по той же причине, по которой
	// правка кабины носит набор контента: Apply получает только партию, а
	// перечень устройств и связность живут в сети. Сеть неизменна после
	// загрузки, и общий указатель на неё — разделяемая константа, а не
	// разделяемое изменяемое состояние.
	//
	// НАБОРА КОНТЕНТА ЗДЕСЬ НЕТ, хотя занятость и зависит от длины машины: с
	// приходом отрезка пути (ClearAhead-7n0v) длина уже учтена в самом отрезке,
	// и спрашивать её у паспорта второй раз незачем.
	Net *track.CompiledNetwork
}

// Name — имя правки для журнала и логов.
func (SetTurnout) Name() string { return "turnout.set" }

// Apply переводит остряк, проверив правила партией.
//
// Проверка живёт в match.SetTurnout, а не здесь, и это то же правило, что у
// органов управления: «валидатор отказывает, а не чинит» обязано стоять там,
// где состояние. Иначе вторая дорога к тому же полю — замыкание маршрута,
// которое придёт с централизацией, — прошла бы мимо проверки занятости.
func (c SetTurnout) Apply(m *match.Match) error {
	return m.SetTurnout(c.Turnout, c.Position, c.Net)
}
