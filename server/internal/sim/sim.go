// Package sim — движение: то, что превращает положение рукояток в пройденный
// путь.
//
// # Место в картине
//
// Движок владеет партией и даёт такты (engine), актуаторы держат положение
// рукояток (match), паспорт даёт силы (physics), сеть даёт уклон и радиус
// (track). Здесь всё это встречается и превращается в скорость и место.
//
// Это ФАЗА ХОДА тика — та самая, которая до сегодня была объявлена пустой
// вслух: «между приёмом и печатью обязано быть названо место, куда встанет
// физика, иначе первый же её автор поставит её после печати».
//
// # Шаг физики отделён от тика, и это не украшение
//
// Тик координации — 100 мс: на нём принимаются команды и рассылаются снапшоты.
// Шаг физики — 20 мс, пять подшагов внутри тика. Довод записан в эскизе ядра §9
// и он количественный: сопротивление, тяга и тормозная сила зависят от
// СКОРОСТИ, поэтому интегрирование при замороженных силах — кусочно-постоянная
// аппроксимация, и её ошибка растёт с длиной шага.
//
// ЗАМЕР, а не рассуждение (TestStepSizeError): разгон ВЛ80 с места до сотни
// секунд на шаге 100 мс и на шаге 20 мс расходится по пройденному пути на
// доли процента; на шаге 1 с — на проценты. Двадцать миллисекунд взяты как
// верхняя граница диапазона, названного спекой (10–20 мс).
//
// # ЗАНЯТОСТЬ ПРИЕХАЛА 2026-08-15, и она изменила здесь главное
//
// Машина перестала быть точкой. У неё есть ОТРЕЗОК ПУТИ (track.Span), движение
// ведёт его, а точка отсчёта — середина отрезка, то есть следствие. Разбор — у
// move; форма отрезка и порядок визитов — у track.Span; обратный индекс и
// запрет наложения — в match/occupancy.go.
//
// Условие, по которому это откладывалось («у занятости нет потребителя»),
// наступило не с той стороны, с какой ждали: первым потребителем оказался не
// диспетчер, а ПОКАЗ. Клиент ставит машину хордой между шкворнями, а шкворень
// вправе стоять на соседнем элементе; и показ между снимками идёт по ПУТИ, а не
// по одному элементу. Обоим нужны концы тела, а не его середина.
//
// # Чего здесь НЕТ
//
// ТОЧНЫХ СОБЫТИЙ ВНУТРИ ШАГА. Момент пересечения границы не решается: отрезок
// наращивается на путь, пройденный за подшаг целиком, и «когда именно» ведущий
// конец занял следующий элемент, известно с точностью до подшага — 20 мс, то
// есть 0.14 м при 6.9 м/с. Для геометрии это неразличимо (отрезок в конце
// подшага верен до микрометра), для ОЧЕРЁДНОСТИ — нет: двое, занявшие секцию в
// одном подшаге, неразличимы по времени. Станет важным там, где момент занятия
// решает, кого пускать, — то есть в централизации (ClearAhead-duf).
package sim

