// Package edit — строительные транзакции: макет строителя и приёмка мира.
//
// Редактор карт: игрок тянет мышью, решатель на сервере считает законную
// трассу, этот пакет применяет результат к макету строителя. Каждая
// операция проходит mapfmt.Validate — вердикт валидатора, а не наша
// уверенность. Применение атомарно: неудачная операция не оставляет следа
// ни в журнале, ни в мире.
//
// МАКЕТ — ЖУРНАЛ ОПЕРАЦИЙ, А НЕ СНИМОК МИРА (.internal/specs/
// 2026-08-11-build-transactions-design.md, §1): транзакция хранит
// «разрезать E_MAIN на 140-м метре», а не «вот новая карта целиком».
// Коммит переигрывает журнал на текущей закоммиченной базе; отбитый коммит
// возвращает макет автору целиком — частично принятого состояния не бывает
// (§4). Снимок мира пришлось бы мержить, журнал — переигрывать.
//
// У строителя макет есть ВСЕГДА — это его рабочая доска, а не режим.
// Режима прямой правки закоммиченного мира не существует вовсе; прежний
// тип Store, правивший одну карту напрямую, снят. Макет принадлежит
// учётной записи, создаётся сессией строителя и переживает разрыв связи —
// сессия лишь ручка, макет живёт в Service (tx.go).
//
// ОТМЕНЫ НЕТ И НЕ БУДЕТ. Решение владельца от 2026-08-11 (§0 и §11): её
// место занимает «не закоммитить». Стек ревизий в памяти, на котором
// отмена стояла, снят целиком — он был один на процесс, и Ctrl+Z одного
// строителя откатывал правку другого. Заводить его обратно нельзя ни под
// каким именем: ни стеком ревизий, ни «откатом последней операции».
// Проверяется это механически (TestUndoRemoved), а не комментарием.
//
// КОММИТ — ПРИЁМКА В ЭКСПЛУАТАЦИЮ (§3). Предусловие: затронутая
// протяжённость не несёт движения. Сегодня мир не знает ни занятости, ни
// маршрутов, ни ДСП — состояние существующего элемента проверить нечем,
// и коммит, трогающий его, честно отказывает (ErrClosureRequired); новый
// элемент движения не нёс по построению. Конфликт — отбой НА КОММИТЕ, как
// в git: занятия участка вперёд нет (§4), проигравший переигрывает журнал
// на новой базе. Производный рельеф НЕ конфликтует: в этой модели его нет
// вовсе — он функция закоммиченных осей, и пересчёт живёт в компиляторе
// (worldgen), а не здесь.
//
// Видимость фильтруется СЕРВЕРНО (§2): строители видят закоммиченное и все
// открытые макеты, ДСП и машинисты — только закоммиченное. Клиент не
// фильтрует; Service.Views — шов, за который будущий транспорт (httpapi,
// шаг 12 эпика) отдаёт срезы по ролям.
//
// Пересборка проекций сюда не входит: предпросмотр макета — без
// пересборки, авторитетный пересчёт — по коммиту, и делает его
// компилятор-потребитель, а не edit (компилятор проекций готов и замерен
// в worldgen: адресная пересборка одной стрелки — 12 адресов, ~97 мс).
//
// Закоммиченное пакет пишет на диск сам — в sourcestore, хранилище
// АВТОРИТЕТНЫХ ИСХОДНИКОВ (sqym.18): закоммиченный мир обязан переживать
// перезапуск и пересев, а память процесс не переживает. Макеты (черновики)
// остаются в памяти — их срок жизни решает будущий транспорт (шаг 12 эпика).
//
// Входной тип узкий и свой: тип результата решателя ещё не готов, поэтому
// Intent несёт намерение + цепочку примитивов + куда прикладывать.
// Сшивание с решателем — отдельная задача.
package edit

import (
	"encoding/json"
	"fmt"

	"github.com/shady2k/ClearAhead/server/internal/geom"
	"github.com/shady2k/ClearAhead/server/internal/mapfmt"
	"github.com/shady2k/ClearAhead/server/internal/terrain"
)

// Op — вид правки.
type Op int

const (
	OpExtend Op = iota // продлить путь от порта
	OpBranch           // ответвиться от существующего элемента (появляется стрелка)
	OpCap              // замкнуть конец тупиковым упором
	OpPlace            // положить платформу на участок
	OpErase            // стереть
	OpGrade            // прямой терраморфинг: правка высот по клеткам
)

// Intent — намерение игрока, готовое к применению: что сделать, цепочка
// примитивов и куда прикладывать. Поля заполняются по Op; остальные
type Intent struct {
	Op Op

	Extend ExtendIntent // OpExtend
	Branch BranchIntent // OpBranch
	Cap    CapIntent    // OpCap
	Place  PlaceIntent  // OpPlace
	Erase  EraseIntent  // OpErase
	Grade  GradeIntent  // OpGrade
}

// ExtendIntent — продлить путь от порта.
//
// Порт обязан быть листом (ровно одно ребро) и концом приходящего пути (ребро
// заканчивается в порту): направление продолжения — по приходящему пути.
// Новое ребро начинается в порту, новый конец получает назначение.
type ExtendIntent struct {
	// Port — порт, от которого продолжаем.
	Port string
	// Chain — цепочка примитивов нового ребра в системе позы порта.
	Chain geom.Chain
	// EndPurpose — назначение нового конца: "" — buffer_stop.
	EndPurpose string
}

// BranchIntent — ответвиться от существующего ребра стрелкой.
//
// Ребро Edge режется в точке AtU (строго внутри): подходная часть остаётся
// ребром Edge и приходит в общий порт новой стрелки, продолжение — новое ребро
// от прямого порта, ветвь — новое ребро от отклонённого порта.
type BranchIntent struct {
	Edge string  // существующее ребро
	AtU  float64 // точка ответвления, метры в координате u
	Hand string  // "left" | "right"

	// Straight и Diverging — геометрия проходов стрелки: прямого и
	// отклонённого. Branch — геометрия ветви после отклонённого прохода.
	// Проходы задаёт намерение: законную геометрию считает решатель.
	Straight  geom.Chain
	Diverging geom.Chain
	Branch    geom.Chain
	// EndPurpose — назначение конца ветви: "" — buffer_stop.
	EndPurpose string
}

// CapIntent — замкнуть конец тупиковым упором: порт получает purpose
// buffer_stop.
type CapIntent struct {
	Port string
}

// PlaceIntent — положить платформу на участок элемента.
type PlaceIntent struct {
	Element string  // элемент (ребро или проход стрелки)
	From    float64 // начало интервала, метры u
	To      float64 // конец интервала, метры u
	Side    string  // "left" | "right"; "" — "right"
	Offset  float64 // от оси пути до ближней кромки, метры
	Width   float64 // поперёк пути, метры
	// Вертикаль платформы (контракт отрисовки, редакция 6, §4.1). Обязательна,
	// и это не строгость ради строгости: платформа без высоты валидатором
	// отвергается, а строитель, порождающий невалидную карту, — это транзакция,
	// которая не может закоммититься. Умолчания здесь быть не может по той же
	// причине, по которой его нет в клиенте: «обычно 1100 мм» — выдумка.
	Height        float64 // верх плиты над поверхностью катания, метры
	SlabThickness float64 // толщина плиты, метры
}

// GradeIntent — прямой терраморфинг: правка высот по клеткам.
//
// Прямая правка делает высоты РЕДАКТИРУЕМЫМИ ДАННЫМИ (спека транзакций §5,
// решение владельца 2026-08-13): клетка уровня 0 получает АБСОЛЮТНУЮ отметку
// земли, и наложение ДВУХ правок одной клетки — конфликт. Это другой класс,
// чем производные земляные работы под путём: те функция закоммиченных осей,
// отдельно не хранятся и коридорами не конфликтуют (§5, тест
// TestEarthworksCorridorsDoNotConflict). Форма правки — клетка целиком:
// частичная правка клетки модель не выражает, и это цена, названная в
// terrain/grading.go. Уровень правки ровно ноль — клетки уровня 0
// пространственно непересекающиеся, и только на них конфликт «по клетке»
// однозначен.
type GradeIntent struct {
	Cells []terrain.GradeCell
}

// EraseMode — режим стирки.
type EraseMode int

const (
	// EraseSelection — удалить только выбранное, если граф остаётся
	// допустимым: каскад не может уносить элементы сверх выбранного.
	EraseSelection EraseMode = iota
	// EraseCascade — удалить конструкцию целиком с показанными зависимостями:
	// каскад добирает всё, что осиротеет вместе с целью.
	EraseCascade
)

// EraseIntent — стереть элемент (ребро или стрелку).
type EraseIntent struct {
	Target string // ID ребра или стрелки
	Mode   EraseMode
}

// Result — итог применения операции к макету.
type Result struct {
	// Map — состояние макета после операции: журнал, переигранный на
	// закоммиченной базе. Мировая ревизия здесь не двигается — макет не
	// принятое состояние, номер растёт только на коммите (tx.go).
	Map mapfmt.Map
	// Cascade — предпросмотр каскада стирки; nil для остальных операций.
	Cascade *ErasePreview
}

// ErasePreview — каскад стирки: что уходит, чьи спаны порвались, какие концы
// закрываются упором.
//
// Предпросмотр обязан совпадать с фактическим результатом — игрок принимает
// решение по нему. Списки отсортированы по ID.
type ErasePreview struct {
	RemovedElements   []string // рёбра и стрелки, которые уходят (включая цель)
	RemovedStructures []string // сооружения, чьи спаны порвались
	CappedPorts       []string // концы, ставшие висящими и закрытые упором
}

// cloneMap — глубокая копия карты. Карта в Service и карта в Result обязаны
// быть независимы: мутация выданной копии не должна трогать хранимую.
// JSON-круговорот точен для float64 и покрывает все поля формата; карта
// всегда сериализуема.
//
// Это способ копирования, а не формат хранения: карта нигде не лежит JSON'ом.
func cloneMap(m *mapfmt.Map) mapfmt.Map {
	raw, err := json.Marshal(m)
	if err != nil {
		panic(fmt.Sprintf("edit: копирование карты: %v", err))
	}
	var c mapfmt.Map
	if err := json.Unmarshal(raw, &c); err != nil {
		panic(fmt.Sprintf("edit: копирование карты: %v", err))
	}
	return c
}
