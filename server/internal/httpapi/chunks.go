// HeaderChunkBaseZ — опорная высота чанка, целые миллиметры, десятичное число
// со знаком.
//
// Заголовок обязателен в каждом успешном ответе и не является служебной
// мелочью: тело несёт int16 сантиметров ОТНОСИТЕЛЬНО base_z (контракт чанков
// §5), и без базы отсчёты не значат ничего. В тело база не кладётся сознательно
// — блоб остаётся ровно chunk.HeightsBytes байт и одинаковым на любом уровне,
// а клиент выделяет буфер один раз.
//
// Единица — миллиметр, а не метр: в хранилище база лежит целым числом
// миллиметров (worldstore.Chunk.BaseZmm) именно затем, чтобы ни сравнение, ни
// хеш не зависели от представления float. Печатать её дробью значило бы вернуть
// на провод ту самую неопределённость, ради ухода от которой она целая.
const HeaderChunkBaseZ = "X-Chunk-Base-Z-Mm"

// ChunkMaker считает чанк, которого в базе не оказалось, и кладёт его туда.
//
// Интерфейс объявлен ЗДЕСЬ, у потребителя, а не в worldgen у реализации: ручке
// нужен ровно один вопрос, и описывать его она вправе сама. Обратный порядок —
// импортировать конкретный тип конвейера — привязал бы отдачу чанков к тому,
// как именно мир порождается, и сделал бы невозможной проверку ручки без
// карты, рельефа и распространения поз.
//
// Три исхода не сливаются, и это главное требование к реализации:
//
//	(чанк, true, nil)  — посчитан;
//	(_, false, nil)    — законная пустота: земли по этому адресу нет ни для кого;
//	(_, false, ошибка) — сбой: посчитать не смогли.
type ChunkMaker interface {
	// MakeChunk считает чанк ПОД ВЕРСИЕЙ МИРА: строка обязана лечь ровно под
	// неё (ключ хранилища несёт версию), иначе устаревший писатель дописал бы
	// чужую версию в текущий мир.
	MakeChunk(a chunk.Address, worldVersion int64) (worldstore.Chunk, bool, error)
}

// chunksAPI — отдача статического яруса чанков.
//
// Хранилище приходит аргументом, а не берётся из глобала: обработчиков может
// оказаться несколько (тест поднимает свою базу во временном каталоге), и
// общий изменяемый пакетный уровень тут не нужен ничему.
type chunksAPI struct {
	store *worldstore.Store
	maker ChunkMaker
}

// NewChunksHandler собирает ручку чанков над открытой базой мира.
//
// Маршрут: GET /regions/{region}/chunks/{level}/{cx}/{cz}
//
// Ключ чанка — (region, level, cx, cz) (world-storage §4), и путь повторяет его
// сегмент в сегмент: адрес чанка виден в URL целиком, без скрытых умолчаний.
//
// # База — кэш, а не единственный источник
//
// maker — то, чем считается недостающее. С ним база из единственного источника
// рельефа становится кэшем: промах перестал быть ответом «здесь пусто» и стал
// поводом посчитать. Ради чего — в шапке worldgen.Lazy: подробность обязана
// быть свойством того, куда смотрит камера, а не близости к рельсам.
//
// maker == nil ЗАКОНЕН и означает «база — единственный источник»: так ручка
// работала до появления ленивого порождения, и так её поднимают проверки,
// которым нужна отдача, а не порождение. Это выбор того, кто собирает сервер
// (main.go), а не умолчание внутри: сервер, который молча перестал бы считать,
// отвечал бы пустотой там, где земля есть, и отличить это от края мира было бы
// нечем.
func NewChunksHandler(store *worldstore.Store, maker ChunkMaker) http.Handler {
	return &chunksAPI{store: store, maker: maker}
}

func (a *chunksAPI) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	// Разбор пути идёт первым: путь приходит снаружи и недоверен, поэтому
	// сначала выясняется, адресован ли вообще чанк, и лишь потом — можно ли
	// его так спрашивать. Синтаксически чужой путь — это «нет такого ресурса»
	// при любом методе.
	addr, tail, ok := chunkPath(r.URL.Path)
	if !ok {
		http.NotFound(w, r)
		return
	}

	// HEAD обязателен наравне с GET: RFC 9110 требует его от сервера общего
	// назначения, и на нём держится проверка кэша прокси и клиентов. Тело для
	// HEAD подавляет net/http сам, поэтому дальше ветвление не нужно — но
	// Content-Length приходится выставить руками, иначе на HEAD он не доедет.
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		w.Header().Set("Allow", "GET, HEAD")
		http.Error(w, "только GET и HEAD", http.StatusMethodNotAllowed)
		return
	}

	// Существование региона проверяется отдельно от наличия чанка, и это
	// главное различение всей ручки (контракт чанков §6): опечатка в имени
	// региона — неверный адрес, а пустота внутри существующего региона —
	// законное состояние разреженного хранилища. Клиент обязан вести себя
	// по-разному, значит и ответы обязаны различаться.
	reg, ok, err := a.store.GetRegion(addr.Region)
	if err != nil {
		http.Error(w, "хранилище недоступно", http.StatusInternalServerError)
		return
	}
	if !ok {
		http.NotFound(w, r)
		return
	}

	// Текущая версия мира — из головы проекций: неверсионный адрес отдаёт
	// ТЕКУЩИЙ мир, а не замороженную публикацию. Без головы ответить нечем —
	// это база прежней сборки без бутстрапа, а не законное состояние.
	head, ok, err := a.store.GetProjectionHead(addr.Region)
	if err != nil {
		http.Error(w, "хранилище недоступно", http.StatusInternalServerError)
		return
	}
	if !ok {
		http.Error(w, "голова проекций не заведена", http.StatusInternalServerError)
		return
	}

	// Уровень вне правила ЭТОГО региона — 404, а не 204, и решается это здесь,
	// а не при разборе пути: с 2026-08-12 охват задаёт карта, поэтому у разных
	// регионов последний уровень разный, и форма адреса о нём знать не может
	// (chunkPath отвергает лишь заведомый мусор, chunk.MaxLevelLimit).
	//
	// Различие то же, что было: 204 обещал бы, что чанк там когда-нибудь
	// появится, а на несуществующем уровне он не появится никогда.
	if addr.Level > reg.Rule.MaxLevel {
		http.NotFound(w, r)
		return
	}

	c, ok, err := a.store.GetChunk(addr, head.WorldVersion)
	if err != nil {
		http.Error(w, "хранилище недоступно", http.StatusInternalServerError)
		return
	}
	if !ok && a.maker != nil {
		// Промах базы — не ответ, а повод посчитать ПОД ТЕКУЩЕЙ ВЕРСИЕЙ.
		// База здесь кэш: рельеф выводится из рецепта детерминированно,
		// поэтому посчитанное сейчас байт в байт равно тому, что положил бы
		// прогрев при старте, и разницы между «лежало» и «посчитали» для
		// клиента не существует — она видна только по времени ответа.
		c, ok, err = a.maker.MakeChunk(addr, head.WorldVersion)
		if err != nil {
			if errors.Is(err, worldgen.ErrQueueFull) {
				// 503 + Retry-After, а не 500: очередь порождения переполнена —
				// состояние ВРЕМЕННОЕ и честно названное, и клиент повторит
				// через секунду (дренаж очереди: 64 × 5.5 мс ≈ 350 мс, замер
				// worldgen). 500 спутал бы «сейчас не могу» со «сломано
				// навсегда», и клиент не знал бы, спрашивать ли снова.
				w.Header().Set("Retry-After", "1")
				http.Error(w, "очередь порождения переполнена", http.StatusServiceUnavailable)
				return
			}
			// СБОЙ, А НЕ ПУСТОТА. Рецепт, который не удалось посчитать, — это
			// поломка сервера, и 204 выдал бы её за край мира: клиент нарисовал
			// бы базовую поверхность и никогда бы не переспросил. Тело отказа
			// причину не называет: наружу она клиенту не нужна, а внутрь её
			// несёт сама ошибка.
			http.Error(w, "чанк не посчитан", http.StatusInternalServerError)
			return
		}
	}
	if !ok {
		// 204, а НЕ 404. Отсутствующий чанк не хранится и не является сбоем:
		// «ресурс адресован верно, содержимого нет — рисуй базовую
		// поверхность». 404 здесь был бы неотличим от опечатки в имени
		// региона, а опечатка и пустота требуют от клиента разного.
		// Края мира как границы не существует — есть область, где чанков нет.
		//
		// Смысл этой пустоты с появлением ленивого порождения СУЗИЛСЯ, и это
		// улучшение, а не изменение контракта. Раньше 204 значил «прогрев сюда
		// не дошёл» — то есть и «мира здесь нет», и «мир есть, но подробность
		// такую не заказывали». Теперь второе считается по требованию, и 204
		// остаётся ровно за первым: земли по этому адресу нет ни для кого
		// (worldgen.selector.inExtent). Код ответа тот же, поведение клиента то
		// же, а вот область, на которую он приходится, стала честной.
		w.WriteHeader(http.StatusNoContent)
		return
	}

	// Блоб собирается кодеком пакета chunk, а не здесь: порядок байт
	// (little-endian) и порядок обхода (строками по возрастанию j, внутри
	// строки по возрастанию i) — часть контракта, и вторая их реализация рано
	// или поздно разошлась бы с первой.
	// Лес существует только на уровне 0, и уровень выше — 404, а не 204.
	// Различие то же, что у уровня вне правила подробности: 204 обещал бы, что
	// лес там когда-нибудь появится, а он там не появится никогда — деревья за
	// коридором рассыпает клиент по покрову, потому что рубить их некому.
	if tail == "forest" && addr.Level != chunk.ForestLevel {
		http.NotFound(w, r)
		return
	}

	var blob []byte
	switch tail {
	case "forest":
		if len(c.Forest) == 0 {
			w.WriteHeader(http.StatusNoContent)
			return
		}
		blob = c.Forest
	case "cover":
		// Покрова нет — 204, тот же ответ, что у отсутствующего чанка, и по той
		// же причине: адрес верен, содержимого нет. 404 здесь означал бы
		// «такого ресурса не бывает» и был бы неотличим от опечатки в уровне.
		//
		// Карта без рецепта покрова — законное состояние, а не недоделка, и
		// клиент обязан отличить его от «покров есть и весь луг».
		if len(c.Cover) == 0 {
			w.WriteHeader(http.StatusNoContent)
			return
		}
		blob = c.Cover
	default:
		blob, err = chunk.EncodeHeights(c.Heights)
		if err != nil {
			http.Error(w, "чанк повреждён", http.StatusInternalServerError)
			return
		}
	}

	// ETag — хеш чанка из хранилища; он считается там же, где пишется тело
	// (worldstore.PutChunk), поэтому не может описать чужие байты.
	//
	// Кэш — no-cache, и это не описка вместо no-store: no-cache разрешает
	// хранить копию и запрещает отдавать её без проверки, no-store запретил бы
	// хранить вовсе и убил бы дешёвый 304 вместе с ним. Родственная запись
	// «max-age=0, must-revalidate» значит то же самое, но двумя токенами и с
	// оговорками у старых прокси; здесь нужна ровно одна мысль — «кэшируй, но
	// всегда спрашивай», — и её выражает no-cache. Такой же выбор и по той же
	// причине уже сделан у манифеста карты (api.go) и у манифеста региона
	// (regions.go).
	//
	// immutable (RFC 8246) здесь был бы ложью, и ценой ей — навсегда устаревший
	// рельеф у того, кто чанк уже загрузил. immutable означает «год не шли
	// условный запрос»: клиент, которому так сказали, не предъявит ни
	// If-None-Match, ни что-либо ещё, и ETag становится некому показать.
	// Обещать неизменность вправе только адрес, называющий версию, а этот её не
	// называет: (region, level, cx, cz) — место, а не состояние места.
	// Содержимое же обязано меняться: земляные работы запечены в высоты, и
	// проложенный игроком путь переписывает чанки в коридоре вокруг новой оси.
	//
	// Ревизия у чанка в базе есть (worldstore.Chunk.Revision), наружу она не
	// выходит. Ход второй — вывести её в URL, как уже сделано у сети региона
	// (/regions/{region}/revisions/{n}/network), и тогда immutable перестанет
	// врать.
	// Делать это до появления самих мутаций рано: версия в адресе — контракт с
	// клиентом, и вводить её стоит вместе с тем, что её меняет.
	etag := `"` + c.Hash + `"`
	w.Header().Set("ETag", etag)
	w.Header().Set("Cache-Control", "public, no-cache")
	w.Header().Set("Content-Type", "application/octet-stream")
	// База высот у покрова не имеет смысла: класс поверхности не отсчитывается
	// ни от чего. Заголовок ставится только там, где он что-то значит — лишний
	// заголовок читается как «здесь есть высоты» и врёт.
	if tail == "" {
		w.Header().Set(HeaderChunkBaseZ, strconv.FormatInt(c.BaseZmm, 10))
	}
	if match := r.Header.Get("If-None-Match"); match == etag {
		w.WriteHeader(http.StatusNotModified)
		return
	}
	w.Header().Set("Content-Length", strconv.Itoa(len(blob)))
	w.Write(blob)
}

// chunkPath разбирает /regions/{region}/chunks/{level}/{cx}/{cz}[/cover|/forest].
//
// Здесь проверяется только форма адреса — то, при чём ответ обязан быть 404:
// лишние или недостающие сегменты, нечисловые и переполняющие координаты,
// уровень вне хранимого диапазона. Существование региона и наличие чанка — не
// форма, и решаются они выше.
//
// # Почему покров — ХВОСТ адреса, а не отдельная ручка и не поле в теле
//
// Не поле в теле: блобы разной природы и разной длины (8450 против 4096), и
// склеить их значило бы заставить клиента, которому нужен только рельеф,
// возить покров, а клиента без покрова — разбирать заголовок длины.
//
// Не отдельная ручка /regions/{r}/cover/{level}/{cx}/{cz}: у покрова ТОТ ЖЕ
// АДРЕС, что у высот — тот же чанк, тот же уровень, та же клетка. Два разных
// пути к одной клетке развели бы её тождество на два, и первый же вопрос «а
// совпадают ли уровни у cover и heights» пришлось бы отвечать соглашением
// вместо построения.
//
// Ничего не паникует и ничего не предполагает о входе: путь приходит снаружи.
func chunkPath(p string) (chunk.Address, string, bool) {
	parts := strings.Split(strings.Trim(p, "/"), "/")
	tail := ""
	if len(parts) == 7 && (parts[6] == "cover" || parts[6] == "forest") {
		tail = parts[6]
		parts = parts[:6]
	}
	if len(parts) != 6 || parts[0] != "regions" || parts[2] != "chunks" {
		return chunk.Address{}, "", false
	}
	region := parts[1]
	if region == "" {
		return chunk.Address{}, "", false
	}
	level, ok := parseInt32(parts[3])
	if !ok || level < 0 || level > chunk.MaxLevelLimit {
		// Уровень вне [0, MaxLevelLimit] — заведомый мусор: такого уровня
		// подробности не бывает НИ У КАКОГО региона ни при какой карте.
		//
		// Здесь проверяется потолок ФОРМЫ, а не охват региона: последний уровень
		// у каждого региона свой (охват приезжает картой), и разбор пути, который
		// брал бы его из базы, стал бы вторым местом, знающим про регионы. Свой
		// уровень региона проверяет ServeHTTP, уже прочитав регион.
		return chunk.Address{}, "", false
	}
	cx, ok := parseInt32(parts[4])
	if !ok {
		return chunk.Address{}, "", false
	}
	cz, ok := parseInt32(parts[5])
	if !ok {
		return chunk.Address{}, "", false
	}
	return chunk.Address{Region: region, Level: level, CX: cx, CZ: cz}, tail, true
}

// parseInt32 разбирает десятичное целое, помещающееся в int32.
//
// Ширина ограничена сознательно: на стороне 256 м int32 покрывает координату
// чанка до полумиллиарда километров, а всё, что не влезло, — заведомо мусор в
// пути, а не адрес далёкого угла мира. Переполнение обязано стать 404, а не
// молча завернуться.
func parseInt32(s string) (int, bool) {
	v, err := strconv.ParseInt(s, 10, 32)
	if err != nil {
		return 0, false
	}
	return int(v), true
}
