// Package brake — ПНЕВМАТИКА АВТОМАТИЧЕСКОГО ТОРМОЗА: магистраль, краны,
// цилиндр.
//
// # Зачем пакет заведён
//
// До 2026-08-15 тормоз был ОДНИМ ЧИСЛОМ: physics.BrakeForce давала полное
// служебное нажатие по таблице ПТР, а машинист выбирал ступень от 0 до 5, и доля
// ступени становилась долей силы. Число ступеней при этом не было взято ни из
// какой машины — так и записано в спеке кабины §2: «НАША МОДЕЛЬ ЦЕЛИКОМ».
//
// Владелец потребовал настоящую магистраль, и требование законно: у настоящего
// тормоза глубина торможения задаётся РАЗРЯДКОЙ МАГИСТРАЛИ и непрерывна, а
// приборы кабины показывают давления — без них манометр на пульте был бы
// стрелкой, которая врёт.
//
// # Что здесь есть и чего нет
//
// ЕСТЬ: главные резервуары с компрессором, уравнительный резервуар, тормозная
// магистраль, воздухораспределитель, тормозной цилиндр, кран машиниста (шесть
// положений) и кран вспомогательного тормоза локомотива.
//
// НЕТ, и каждое названо с причиной:
//
//   - РАСПРОСТРАНЕНИЕ ПО ПОЕЗДУ. Волна разрядки идёт по магистрали составом со
//     скоростью порядка 280 м/с, и хвост тормозит позже головы. Сегодня в партии
//     ОДНА машина: распространять нечего, а объявленная форма без потребителя
//     оказывается неверной (правило проекта). Магистраль здесь — магистраль
//     ЛОКОМОТИВА, и это сказано вслух, а не подразумевается.
//   - РЕОСТАТНОЕ (динамическое) ТОРМОЖЕНИЕ. Ему нужна своя характеристика —
//     семейство кривых тормозной силы по скорости и возбуждению, — а её у нас
//     нет. Поставить правдоподобную значило бы то же, что пять ступеней:
//     правдоподобное вместо верного.
//   - РУЧНОЙ ТОРМОЗ. Винтовой тормоз держит СТОЯЩУЮ машину, то есть его
//     потребитель — удержание на уклоне, а не остановка. Он приедет вместе с
//     ним.
//   - ЮЗ. Превышение сцепления тормозной силой — событие модели (ползуны,
//     потеря торможения), и оно уже названо в physics.BrakeForce как
//     сознательно не обрезаемое. Пневматика этого не меняет.
//
// # Целые, а не float
//
// Давление — величина СОСТОЯНИЯ СИМА, а float в состоянии запрещён правилом
// проекта (куплено потерей эталона контракта на расхождении 1e-13).
//
// ШКАЛА — МИКРО-кгс/см², то есть миллионные доли: зарядное давление 5.4 кгс/см²
// это 5 400 000. Та же мелкость, что у units.Distance (микрометры), и выбрана
// она НЕ ЗАПАСОМ, А ЗАМЕРОМ: на тысячных первый же тест показал потерю десятой
// части темпа. Служебная разрядка 0.22 кгс/см² в секунду на шаге физики 20 мс —
// это 4.4 тысячных за шаг, целое деление роняет их до 4, и за пять секунд
// магистраль опускалась на 1.00 вместо 1.10. Ошибка систематическая: она
// копится в одну сторону на каждом из 250 шагов. На микро тот же темп даёт ровно
// 4400 за шаг, и остатка нет вовсе.
//
// # Почему кгс/см², а не паскали
//
// Потому что в кабине написано именно так. Манометр ВЛ80 проградуирован в
// кгс/см², инструкции и уставки — в них же, и перевод в СИ на границе показа
// означал бы, что число на приборе не совпадает ни с одним числом в документе.
// СИ здесь ничего не покупает: давление не участвует ни в одном уравнении
// механики — оно переводится в ДОЛЮ полного нажатия, а доля безразмерна.
package brake

import (
	"fmt"
	"math"
	"strconv"

	"github.com/shady2k/ClearAhead/server/internal/units"
)

// Pressure — давление в микро-кгс/см² (миллионных долях). Разбор шкалы — в
// шапке пакета.
type Pressure int64

// Kgf — давление в кгс/см² числом с дробью. Только для показа и текстов отказов:
// в арифметике пакета float не участвует нигде.
func (p Pressure) Kgf() float64 { return float64(p) / 1e6 }

// MilliKgf — давление в тысячных кгс/см². ШКАЛА ПРОВОДА И ПРИБОРА: манометр
// кабины читают до сотых, и миллионные доли на нём — шум, который иначе
// пришлось бы округлять на каждой стороне порознь.
func (p Pressure) MilliKgf() int64 { return divRound(int64(p), 1000) }

func (p Pressure) String() string { return fmt.Sprintf("%.2f кгс/см²", p.Kgf()) }

// Handle — положение ручки крана машиниста № 395.
//
// Шесть положений настоящего крана, и они НЕ ступени: между ними нет порядка
// «больше — меньше», у каждого своё действие с магистралью. Именно поэтому здесь
// перечисление, а не число, — ступенчатая рукоятка на этом месте и была тем
// упрощением, которое пакет отменяет.
type Handle string

const (
	// HandleRelease — I, отпуск и зарядка. Магистраль сообщается с главными
	// резервуарами напрямую: самый быстрый темп зарядки, каким машина
	// располагает.
	HandleRelease Handle = "release"
	// HandleRun — II, поездное. Кран САМ поддерживает зарядное давление:
	// утечки восполняются, лишнее стравливается. Основное положение в пути.
	HandleRun Handle = "run"
	// HandleLap — III, перекрыша БЕЗ питания. Магистраль заперта и утечки не
	// восполняются: давление ползёт вниз само.
	HandleLap Handle = "lap"
	// HandleHold — IV, перекрыша С питанием. Держит то, что есть, восполняя
	// утечки, — этим и отличается от III.
	HandleHold Handle = "hold"
	// HandleService — V, служебное торможение. Разрядка магистрали объявленным
	// темпом, пока ручку не переведут.
	HandleService Handle = "service"
	// HandleEmergency — VI, экстренное. Разрядка в атмосферу полным сечением;
	// темп на порядок выше служебного, и остановить её перекрышей нельзя —
	// магистраль уходит в ноль.
	HandleEmergency Handle = "emergency"
)

// Handles — все положения в порядке ручки: от отпуска к экстренному. Порядок
// нужен клавише, которая ведёт ручку соседним положением, и он же порядок на
// пульте.
var Handles = []Handle{HandleRelease, HandleRun, HandleLap, HandleHold, HandleService, HandleEmergency}

// Known — известно ли положение. Неизвестное — отказ на входе, а не молчаливое
// «поездное»: команда с опечаткой обязана получить отказ.
func (h Handle) Known() bool {
	for _, k := range Handles {
		if k == h {
			return true
		}
	}
	return false
}

// Spec — числа пневматики из паспорта машины, переведённые в домен.
//
// # Откуда числа
//
// Уставки автоматического тормоза грузового поезда: зарядное 5.3–5.5 кгс/см²,
// первая ступень служебного торможения 0.5–0.6, полное служебное — разрядка
// около 1.5–1.7, темп служебной разрядки 0.2–0.25 кгс/см² за секунду, темп
// экстренной — не менее 0.8 за секунду. Главные резервуары ВЛ80 — 7.5…9.0 с
// автоматическим пуском компрессора.
//
// НАЗВАНЫ ПРЕДВАРИТЕЛЬНЫМИ, ровно как профиль норм и эпюра брусьев: источник не
// назначен, числа взяты как типовые уставки и дают правдоподобное поведение. Что
// о них можно сказать честно — то и сказано; проверка их по документу остаётся
// работой автора набора, и форма для этого есть: они лежат в паспорте машины, а
// не в коде.
type Spec struct {
	// Charge — зарядное давление магистрали: то, к чему ведёт поездное
	// положение и от чего отсчитывается разрядка.
	Charge Pressure
	// FullServiceDrop — разрядка магистрали, дающая ПОЛНОЕ служебное нажатие.
	// Именно она превращает давление в долю силы: воздухораспределитель
	// наполняет цилиндр пропорционально разрядке, пока не упрётся.
	FullServiceDrop Pressure
	// CylinderFull — давление цилиндра при полном служебном. Верх шкалы
	// манометра ТЦ и знаменатель доли тормозной силы.
	CylinderFull Pressure
	// ServiceRate, EmergencyRate — темпы разрядки, тысячных кгс/см² в секунду.
	ServiceRate   Pressure
	EmergencyRate Pressure
	// ChargeRate — темп зарядки магистрали от главных резервуаров.
	ChargeRate Pressure
	// Overcharge — ПРЕДЕЛЬНОЕ СВЕРХЗАРЯДНОЕ ДАВЛЕНИЕ: потолок первого положения.
	//
	// # Почему потолок не может быть давлением главных резервуаров
	//
	// Так и было до 2026-08-19, и это был дефект, а не упрощение. Магистраль
	// сообщалась с резервуарами напрямую, и первое положение поднимало её до
	// 9.0 — давления, которого в тормозной магистрали не бывает. Хуже
	// неправдоподобия оказалось следствие: воздухораспределитель отсчитывает
	// нажатие от ЗАРЯДНОГО, значит при 9.0 служебной разрядке (0.22 в секунду)
	// надо шестнадцать секунд, только чтобы вернуться к зарядному, — и всё это
	// время кран машиниста не делает ничего. Владелец увидел ровно это:
	// «тормоза как-то странно работают».
	Overcharge Pressure
	// StabilizerRate — темп ЛИКВИДАЦИИ СВЕРХЗАРЯДКИ поездным положением.
	//
	// Отдельное число, а не ChargeRate наоборот: сверхзарядку снимает
	// стабилизатор крана, и он на три порядка медленнее зарядки (0.002 против
	// 0.6 в секунду у ВЛ80). Пока темп был общим, сверхзарядка снималась за две
	// секунды вместо девяти минут — то есть первого положения как бы и не было.
	StabilizerRate Pressure
	// LeakRate — утечка магистрали при перекрыше без питания. Не «неисправность»,
	// а свойство длинной трубы с уплотнениями: именно из-за неё III положение
	// отличается от IV, и без утечки эта разница была бы неотличима.
	LeakRate Pressure
	// MainMin, MainMax — пороги пуска и остановки компрессора.
	MainMin, MainMax Pressure
	// CompressorRate — темп накачки главных резервуаров.
	CompressorRate Pressure
	// CylinderRate — темп наполнения и опорожнения тормозного цилиндра.
	// Цилиндр не отзывается на разрядку мгновенно: наполнение занимает секунды, и
	// без этого числа тормоз хватал бы в тот же миг, когда тронули ручку.
	CylinderRate Pressure
	// IndependentMax — предельное давление, которое держит кран вспомогательного
	// тормоза локомотива. НОЛЬ ОЗНАЧАЕТ, ЧТО КРАНА НА МАШИНЕ НЕТ.
	//
	// # Почему присутствие органа — тоже число паспорта
	//
	// Владелец назвал это прямо: «у разных локомотивов своя тормозная система».
	// Различаются не только уставки, но и НАБОР органов: у грузового электровоза
	// есть кран № 254, у моторвагонной секции — электропневматический тормоз со
	// своими положениями, у маневрового может не быть ни того, ни другого. Пакет
	// поэтому не спрашивает «какая это машина» — он читает, ЧТО У НЕЁ ЕСТЬ.
	//
	// Ноль здесь — законное состояние, а не пропуск: команда на кран, которого
	// нет, получает отказ (Spec.SetIndependent), а пульт такой рукоятки не рисует.
	// Это и есть разница между «органа нет» и «орган в нуле».
	IndependentMax Pressure
}

// SetIndependent — поставить кран вспомогательного тормоза, если он на машине
// есть. Отказ, а не молчаливое обрезание: рукоятка, которой нет, не обязана
// делать вид, будто послушалась.
func (sp Spec) SetIndependent(want Pressure) (Pressure, error) {
	if sp.IndependentMax <= 0 {
		return 0, fmt.Errorf("brake: у машины нет крана вспомогательного тормоза")
	}
	if want < 0 {
		return 0, fmt.Errorf("brake: давление вспомогательного тормоза %s отрицательно", want)
	}
	if want > sp.IndependentMax {
		return 0, fmt.Errorf("brake: давление вспомогательного тормоза %s выше предельного %s",
			want, sp.IndependentMax)
	}
	return want, nil
}

// HasIndependent — есть ли на машине кран вспомогательного тормоза. Спрашивает
// пульт: рукоятку, которой нет, рисовать нельзя.
func (sp Spec) HasIndependent() bool { return sp.IndependentMax > 0 }

// State — состояние пневматики одной машины.
type State struct {
	// Main — главные резервуары: запас, из которого заряжают всё остальное.
	Main Pressure `json:"main"`
	// Pipe — тормозная магистраль.
	Pipe Pressure `json:"pipe"`
	// Cylinder — тормозной цилиндр: то, что прижимает колодки.
	Cylinder Pressure `json:"cylinder"`
}

// Charged — состояние заряженной машины: магистраль под зарядным давлением,
// цилиндр пуст, резервуары полны. То, с чего начинается партия.
func Charged(sp Spec) State {
	return State{Main: sp.MainMax, Pipe: sp.Charge, Cylinder: 0}
}

// Step — продвинуть пневматику на dt при данном положении ручки крана.
//
// Чистая функция: то же состояние и та же ручка дают тот же ответ. Ни времени,
// ни случайности внутри нет — иначе повтор партии по журналу разошёлся бы с
// первым прогоном.
//
// # Порядок действий, и он значим
//
//  1. КОМПРЕССОР — первым: остальное черпает из главных резервуаров, и качать
//     после разбора значило бы отдавать воздух, которого в этот момент не было.
//  2. МАГИСТРАЛЬ — по положению ручки.
//  3. ЦИЛИНДР — по разрядке магистрали и по крану вспомогательного, ПОСЛЕ
//     магистрали: воздухораспределитель следит за ней, а не наоборот.
func Step(s State, sp Spec, h Handle, independent Pressure, dt units.SimTime) State {
	s.Main = stepMain(s.Main, sp, dt)
	s.Pipe = stepPipe(s.Pipe, s.Main, sp, h, dt)
	s.Cylinder = stepCylinder(s, sp, independent, dt)
	return s
}

// stepMain — компрессор. Гистерезис, а не одно пороговое значение: с одним
// порогом компрессор включался бы и выключался на каждом шаге, стоя ровно на
// нём.
func stepMain(main Pressure, sp Spec, dt units.SimTime) Pressure {
	if main >= sp.MainMax {
		return main
	}
	// Ниже нижнего порога качаем всегда; между порогами — тоже, потому что
	// состояние «компрессор работает» отдельным флагом не заведено: он ничего не
	// решает, пока нет расхода энергии и нагрева.
	return min(main+rate(sp.CompressorRate, dt), sp.MainMax)
}

// stepPipe — магистраль по положению ручки крана машиниста.
func stepPipe(pipe, main Pressure, sp Spec, h Handle, dt units.SimTime) Pressure {
	switch h {
	case HandleRelease:
		// ДВА ПОТОЛКА, И НУЖНЫ ОБА. Предельное сверхзарядное — свойство КРАНА:
		// выше него первое положение магистраль не поднимает, сколько бы воздуха
		// ни было. Давление главных резервуаров — свойство ЗАПАСА: выше него не
		// зарядить, воздуху взяться неоткуда. Который из них ниже, тот сегодня и
		// решает, и подменять один другим нельзя: у машины с полными
		// резервуарами работает первый, у машины с просевшими — второй.
		return min(pipe+rate(sp.ChargeRate, dt), min(sp.Overcharge, main))
	case HandleRun:
		// Поездное ведёт к ЗАРЯДНОМУ с двух сторон, НО РАЗНЫМИ ТЕМПАМИ: недобор
		// восполняется зарядкой, перебор снимает стабилизатор, и он на три
		// порядка медленнее. Один темп на оба направления был упрощением, и оно
		// стоило первому положению смысла — сверхзарядка снималась быстрее, чем
		// машинист успевал заметить, что она была.
		if pipe < sp.Charge {
			return min(pipe+rate(sp.ChargeRate, dt), min(sp.Charge, main))
		}
		return max(pipe-rate(sp.StabilizerRate, dt), sp.Charge)
	case HandleLap:
		// Перекрыша БЕЗ питания: заперто, и труба травит.
		return max(pipe-rate(sp.LeakRate, dt), 0)
	case HandleHold:
		// Перекрыша С питанием: держит достигнутое. Утечка восполняется, поэтому
		// давление не ползёт вниз — этим IV и отличается от III.
		return pipe
	case HandleService:
		return max(pipe-rate(sp.ServiceRate, dt), 0)
	case HandleEmergency:
		return max(pipe-rate(sp.EmergencyRate, dt), 0)
	}
	// Неизвестное положение до сюда не доходит: команда отвергается на входе
	// (Handle.Known). Держим давление, а не обнуляем: молчаливое экстренное
	// торможение из-за опечатки — худший из возможных ответов.
	return pipe
}

// stepCylinder — цилиндр: воздухораспределитель по магистрали плюс кран
// вспомогательного тормоза.
//
// # Почему БОЛЬШЕЕ из двух, а не сумма
//
// Потому что оба наполняют ОДИН цилиндр, а не два. Кран № 254 у локомотива —
// повторитель: он держит в цилиндре своё давление, и если автоматический тормоз
// уже создал большее, вспомогательный ничего не добавляет. Сумма дала бы
// удвоенное нажатие при одновременном действии обоих — то есть тормоз, которого
// у машины нет.
func stepCylinder(s State, sp Spec, independent Pressure, dt units.SimTime) Pressure {
	// Воздухораспределитель: наполнение пропорционально разрядке магистрали
	// относительно зарядного давления, до полного служебного.
	drop := sp.Charge - s.Pipe
	var auto Pressure
	if drop > 0 && sp.FullServiceDrop > 0 {
		auto = Pressure(divRound(int64(drop)*int64(sp.CylinderFull), int64(sp.FullServiceDrop)))
		auto = min(auto, sp.CylinderFull)
	}
	target := max(auto, independent)
	// Цилиндр ИДЁТ К ЦЕЛИ ТЕМПОМ, а не прыгает: наполнение и отпуск занимают
	// секунды, и мгновенный цилиндр давал бы тормоз, хватающий в тот же миг,
	// когда тронули ручку.
	step := rate(sp.CylinderRate, dt)
	if s.Cylinder < target {
		return min(s.Cylinder+step, target)
	}
	return max(s.Cylinder-step, target)
}

// Effort — ДОЛЯ полного служебного нажатия, тысячными.
//
// Это и есть та граница, о которой написано в physics.BrakeForce: сила остаётся
// её, а пневматика отвечает только на вопрос «какая часть её приложена сейчас».
// Ломать physics для этого не пришлось — ровно как там и обещано.
func (s State) Effort(sp Spec) int64 {
	if sp.CylinderFull <= 0 {
		return 0
	}
	e := divRound(int64(s.Cylinder)*1000, int64(sp.CylinderFull))
	if e > 1000 {
		// Цилиндр выше полного служебного бывает: кран № 254 держит до 4.0, а
		// полное служебное автоматическим — 3.8. Сила при этом больше расчётной,
		// и обрезать её здесь ЗАКОННО: таблица ПТР даёт нажатие полного
		// служебного, и что там сверх него — за пределами таблицы.
		return 1000
	}
	return e
}

// Validate — числа паспорта, без которых пневматика бессмысленна.
func (sp Spec) Validate() error {
	if sp.Charge <= 0 {
		return fmt.Errorf("brake: зарядное давление %s: магистраль нечем заряжать", sp.Charge)
	}
	if sp.FullServiceDrop <= 0 || sp.FullServiceDrop >= sp.Charge {
		return fmt.Errorf("brake: разрядка на полное служебное %s вне (0, зарядное %s)",
			sp.FullServiceDrop, sp.Charge)
	}
	if sp.CylinderFull <= 0 {
		return fmt.Errorf("brake: давление цилиндра при полном служебном %s", sp.CylinderFull)
	}
	if sp.MainMin <= 0 || sp.MainMax <= sp.MainMin {
		return fmt.Errorf("brake: пороги компрессора %s…%s", sp.MainMin, sp.MainMax)
	}
	if sp.MainMax <= sp.Charge {
		return fmt.Errorf("brake: главные резервуары %s не выше зарядного %s — заряжать магистраль нечем",
			sp.MainMax, sp.Charge)
	}
	// СВЕРХЗАРЯДНОЕ ОБЯЗАНО БЫТЬ ВЫШЕ ЗАРЯДНОГО И НЕ ВЫШЕ РЕЗЕРВУАРОВ. Равное
	// зарядному означало бы, что первого положения у крана нет вовсе, а выше
	// резервуаров — потолок, до которого не дотянуться: и то и другое — паспорт,
	// написанный не про эту машину.
	if sp.Overcharge <= sp.Charge {
		return fmt.Errorf("brake: сверхзарядное давление %s не выше зарядного %s — "+
			"отпуску первым положением некуда завышать", sp.Overcharge, sp.Charge)
	}
	if sp.Overcharge > sp.MainMax {
		return fmt.Errorf("brake: сверхзарядное давление %s выше главных резервуаров %s — "+
			"столько в магистраль взять неоткуда", sp.Overcharge, sp.MainMax)
	}
	for _, r := range []struct {
		name string
		v    Pressure
	}{
		{"темп служебной разрядки", sp.ServiceRate},
		{"темп ликвидации сверхзарядки", sp.StabilizerRate},
		{"темп экстренной разрядки", sp.EmergencyRate},
		{"темп зарядки", sp.ChargeRate},
		{"темп наполнения цилиндра", sp.CylinderRate},
		{"темп накачки компрессора", sp.CompressorRate},
	} {
		if r.v <= 0 {
			return fmt.Errorf("brake: %s %s: величина обязана быть положительной", r.name, r.v)
		}
	}
	if sp.EmergencyRate <= sp.ServiceRate {
		return fmt.Errorf("brake: экстренная разрядка %s не быстрее служебной %s — экстренное торможение теряет смысл",
			sp.EmergencyRate, sp.ServiceRate)
	}
	return nil
}

// rate — сколько тысячных набежит за dt при темпе r в секунду.
func rate(r Pressure, dt units.SimTime) Pressure {
	return Pressure(divRound(int64(r)*int64(dt), int64(units.Second)))
}

// FromKgf — перевод авторского числа паспорта в домен. ЕДИНСТВЕННОЕ место, где
// float входит в пневматику: дальше только целые.
func FromKgf(v float64) Pressure { return Pressure(math.Round(v * 1e6)) }

// divRound — деление с округлением к ближайшему, half away from zero. Своё, а не
// из physics: тащить ради одной функции зависимость на пакет механики значило бы
// связать пневматику с ней навсегда.
func divRound(a, b int64) int64 {
	if b == 0 {
		return 0
	}
	if (a < 0) != (b < 0) {
		return (a - b/2) / b
	}
	return (a + b/2) / b
}

// MarshalJSON — давление на проводе: ЦЕЛОЕ СТРОКОЙ, в ТЫСЯЧНЫХ кгс/см².
//
// Строкой — по общему правилу провода: GDScript читает числа JSON как float, и
// целое, доехавшее числом, теряет точность молча (то же лечение у
// units.Distance).
//
// В ТЫСЯЧНЫХ, а не в микро, хотя внутри пакета счёт идёт в микро: провод несёт
// то, что показывает ПРИБОР, а манометр кабины читают до сотых. Миллионные доли
// на нём — шум, который иначе пришлось бы округлять на каждой стороне порознь, и
// две стороны округлили бы по-разному.
func (p Pressure) MarshalJSON() ([]byte, error) {
	return []byte(`"` + strconv.FormatInt(p.MilliKgf(), 10) + `"`), nil
}

// UnmarshalJSON читает давление из строки тысячных кгс/см².
func (p *Pressure) UnmarshalJSON(b []byte) error {
	if len(b) < 2 || b[0] != '"' || b[len(b)-1] != '"' {
		return fmt.Errorf("brake: давление ожидается строкой тысячных кгс/см², получено %s", b)
	}
	v, err := strconv.ParseInt(string(b[1:len(b)-1]), 10, 64)
	if err != nil {
		return fmt.Errorf("brake: разбор давления: %w", err)
	}
	*p = Pressure(v * 1000)
	return nil
}
