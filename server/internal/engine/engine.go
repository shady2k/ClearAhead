// Package engine — ход модельного времени и единственный владелец состояния
// партии.
//
// # Зачем время появилось раньше того, что движется
//
// Довод НЕ в том, что кому-то нужны часы в углу экрана. Он в переезде владения.
//
// До этого пакета обработчик живого состояния держал *match.Match и читал его
// поля прямо в ServeHTTP. Пока партия неподвижна, это законно. Первое же
// изменение партии из другой горутины превращает это в гонку — и лечится оно
// одинаково что сегодня, что через две вехи: читатели перестают держать
// указатель и начинают просить КОПИЮ. Разница только в цене: сегодня это ОДИН
// обработчик, после В2 их пять и рядом команды.
//
// Это шов 4 вертикального среза («единственный владелец состояния и
// фиксированные фазы движка»), и он пересекается рабочим кодом с первого дня, а
// не объявлен впрок.
//
// # Главный инвариант: настенные часы решают КОГДА, а не НА СКОЛЬКО
//
// Модельное время не выводится из разницы показаний часов. Никогда. Написать
// dt := time.Since(last) и проинтегрировать на нём — самая дешёвая строка в
// мире и конец воспроизводимости: восьмичасовой прогон перестанет повторяться,
// и перестанет МОЛЧА, потому что расхождение будет в младших разрядах и вылезет
// через месяц на золотом журнале.
//
// Поэтому форма выбрана так, чтобы нарушить инвариант было НЕЛЬЗЯ, а не просто
// запрещено: первичен НОМЕР ТИКА, а модельное время выводится из него
// (Tick.Time). Дрейфу неоткуда взяться — не потому, что его сторожит проверка,
// а потому, что второго слагаемого не существует.
//
// Отсюда же деление пакета надвое:
//
//	Step  ЧИСТОЕ ЯДРО: продвигает мир ровно на один тик. Часов не читает,
//	      в лог не пишет, длительности не принимает. Это зовут тесты и реплей.
//	Run   ИМПУРНАЯ ОБОЛОЧКА (Pacer вертикального среза §8): решает, КОГДА
//	      позвать Step. Ей и только ей позволено смотреть на настенные часы и
//	      говорить вслух.
//
// Вертикальный срез §8 записывает это же одной строкой: «Интегратор Pacer не
// видит вовсе и wall clock не читает».
//
// # Отставание: отстаём, но не прыгаем
//
// Приём стандартный и старый — накопитель с потолком (канонический разбор:
// Glenn Fiedler, «Fix Your Timestep!»): накопили настенное время, отдали его
// целыми тиками, остаток оставили до следующего раза, накопитель ограничили
// сверху — иначе одно долгое пробуждение порождает лавину шагов, и она делает
// следующее пробуждение ещё длиннее («спираль смерти»).
//
// А вот что делать с временем СВЕРХ потолка — это выбор, и в отрасли он сделан
// в обе стороны:
//
//	Minecraft   ПРОПУСКАЕТ тики и пишет об этом в лог («Can't keep up!
//	            Skipping N ticks»). Мир прыгает вперёд.
//	Factorio    НЕ пропускает: частота обновлений падает, модельное время
//	            отстаёт от настенного, и счётчик UPS честно это показывает.
//
// Берём сторону Factorio, и довод у нас свой: пропущенный тик — это
// пропущенный шаг физики и дыра в журнале, то есть цена платится не картинкой,
// а воспроизводимостью. Отставание же не стоит ничего, кроме того, что мир идёт
// медленнее часов, — и об этом говорится вслух.
//
// ПОТРЕБИТЕЛЬ У ПОТОЛКА ЕСТЬ УЖЕ СЕГОДНЯ, хотя пустой тик отстать не может:
// крышка ноутбука. Процесс, проснувшийся через час, увидит час настенного
// времени разом, и без потолка отдал бы его тридцатью шестью тысячами шагов
// подряд.
//
// # Чего здесь НЕТ и почему
//
// Правило проекта — объявленная форма без потребителя окажется неверной, — и
// оно применяется к собственному списку так же, как к чужому:
//
//   - ФАЗЫ ВНУТРИ ТИКА ПОЯВИЛИСЬ 2026-08-14, и появились по объявленному
//     условию: «фазы приходят со своим содержимым». Содержимое приехало с
//     каналом команд (ClearAhead-wa51) — приём очереди и печать состояния.
//     Их три, а не четыре, и одна из них (ход) объявлена пустой вслух: разбор
//     у Step.
//   - ПАУЗЫ нет. Она записана швом 8 («пауза — состояние сервера»), но сегодня
//     паузила бы ничто.
//   - МАСШТАБА ВРЕМЕНИ нет ЧИСЛОМ, хотя прошлая редакция среза поплатилась за
//     его удаление («вырезала масштаб времени целиком и тем сломала тестовый
//     шов — это была ошибка»). Сломан был не множитель, а РАЗДЕЛЕНИЕ: тесту не
//     нужен коэффициент 28800, ему нужен вызов Step без часов. Разделение здесь
//     есть и стоит ноль строк; коэффициент приезжает со сценариями, которым
//     он принадлежит.
//   - ЖУРНАЛА И JournalSeq по-прежнему нет, хотя приём команд появился.
//     Порядок поступления у правки есть (pending.order), но он живёт ровно до
//     конца тика и никуда не записывается: журнал нужен реплею и
//     восстановлению ключей идемпотентности после перезагрузки, а ни того ни
//     другого сегодня не существует. Заводить номер, который никто не хранит,
//     значило бы обещать порядок, которого после перезапуска не будет.
//
// # Почему мьютекс, а не горутина с каналами
//
// Актор с собственной горутиной и каналами — это бида ClearAhead-zz9 («изоляция
// симуляции: своя горутина, супервизор, каналы»), и она про изоляцию отказов, а
// не про доступ к полю. Сегодня писатель ровно один (Run), читателей N
// (обработчики HTTP и подписчики канала), а работа в тике появилась, но вся
// лежит под тем же замком — RWMutex здесь и есть честный минимум.
// Он ничего не закрывает: снаружи видны Step и Snapshot, и заменить их
// внутренности на переписку по каналам можно, не тронув ни одного вызывающего.
package engine

import (
	"context"
	"log"
	"sync"
	"time"

	"github.com/shady2k/ClearAhead/server/internal/match"
	"github.com/shady2k/ClearAhead/server/internal/units"
)

// TickDuration — сколько модельного времени продвигает один тик.
//
// Сто миллисекунд — число эскиза ядра §9, и это частота КООРДИНАЦИИ, а не шага
// физики: на ней принимаются команды, замыкания и снапшоты. Шаг физики (10–20
// мс) отделён от неё нарочно и приезжает вместе с физикой.
//
// Разделение «медленный тик координации плюс частый шаг внутри» — не наша
// выдумка, так устроены сетевые симуляции вообще: у Source тикрейт 64–66 Гц при
// заметно более редкой отправке снапшотов, у Overwatch симуляция около 63 Гц
// при своей частоте сети. Мы стоим на другом конце того же ряда, и это законно:
// у нас координируется не стрельба, а поезд, у которого инерция многосекундная.
const TickDuration = 100 * units.Millisecond

// MaxCatchUp — сколько модельного времени движок готов отдать одним
// пробуждением. Всё, что накопилось сверх, ТЕРЯЕТСЯ: мир отстаёт от настенных
// часов на эту величину и не догоняет её никогда (разбор — в шапке пакета).
//
// Секунда выбрана как граница между двумя разными событиями, а не «на глаз».
// Ниже неё лежат обычные заминки — пауза сборщика мусора, медленный обработчик,
// вытеснение планировщиком; их надо ДОГНАТЬ, иначе модельное время уползает от
// настенного на каждой заминке и за час набирает заметное. Выше неё лежит
// приостановка процесса целиком, которую догонять НЕЛЬЗЯ.
const MaxCatchUp = 10 * TickDuration

// wallPeriod — как часто оболочка просыпается. Настенная величина, и потому
// time.Duration, а не units.SimTime: это период таймера, а не время мира.
//
// Равен TickDuration, потому что темп сегодня 1:1. Совпадение чисел здесь
// СЛУЧАЙНО по смыслу, и поэтому их два, а не одно: в тот день, когда у сценария
// появится коэффициент времени, менять придётся именно этот период, и общая
// константа увезла бы вместе с ним длительность тика — то есть переписала бы
// физику вместо темпа показа.
const wallPeriod = 100 * time.Millisecond

// Tick — номер тика от начала партии. Он же EngineTick вертикального среза §8.
//
// Первичен: модельное время выводится из него, а не хранится рядом. Разбор — в
// шапке пакета.
type Tick int64

// Time — модельное время НАЧАЛА этого тика.
//
// Единственное место, где номер превращается во время. Вторая такая формула,
// написанная где-нибудь ещё, разошлась бы с этой на первой же правке
// длительности тика, и разошлась бы молча.
//
// ПЕРЕПОЛНЕНИЯ НЕТ, и это замер, а не надежда: int64 микросекунд кончается на
// 9.2e18, то есть на 9.2e13 тиков при ста миллисекундах — 292 миллиона лет
// модельного времени. Проверять его в горячем пути незачем; правило эскиза ядра
// §8 о запрете молчаливого переполнения относится к произведениям сил на время,
// а не к счётчику, у которого запас в тринадцать порядков.
func (t Tick) Time() units.SimTime {
	return units.SimTime(t) * TickDuration
}

// Snapshot — состояние партии на границе тика. КОПИЯ, а не вид на живое
// состояние: читатель, получивший указатель, читал бы то, что в этот же миг
// правит движок.
type Snapshot struct {
	Tick Tick
	Time units.SimTime
	// Hash — канонический хеш состояния (см. hash.go). Едет вместе со снимком,
	// а не считается читателем: считать его заново означало бы иметь второе
	// место, где объявлен канонический порядок полей.
	Hash string
	// Match — копия партии со СВОИМ срезом единиц. Копия структуры сама по себе
	// разделила бы массив под срезом с движком, и правка снимка доехала бы до
	// мира — то есть снимок оказался бы записью.
	Match match.Match
}

// Physics — то, что двигает мир в ФАЗЕ ХОДА.
//
// Интерфейс, а не прямой вызов пакета sim, и это не развязка ради развязки:
// движок обязан оставаться чистым ядром, которое зовут тесты, — а физике нужны
// сеть и набор контента, то есть весь мир. Тест времени поднимает движок без
// физики (nil) и по-прежнему прогоняет восемь часов за долю секунды.
//
// Ошибка означает ПОЛОМКУ МИРА (элемент исчез из сети, паспорт из набора), а не
// отказ игроку: команды сюда не доходят, они применены раньше, в фазе приёма.
type Physics interface {
	Advance(m *match.Match, dt units.SimTime) error
}

// Engine — движок партии: владеет её состоянием и двигает её время.
type Engine struct {
	mu sync.RWMutex
	// tick, m, hash и очередь правятся только под mu.
	tick Tick
	m    *match.Match
	hash string
	phys Physics
	// broken — поломка мира, случившаяся в фазе хода.
	//
	// Хранится, а не пишется в лог на месте: Step обязан молчать (это чистое
	// ядро, его зовут тесты и реплей), а говорить вслух вправе только оболочка.
	// Она же и говорит — один раз, а не каждый тик: мир, сломавшийся однажды,
	// ломается затем в каждом тике, и лог превратился бы в сплошную строку.
	broken error
	// brokenSaid — сказали ли о поломке вслух. Отдельным признаком, а не
	// затиранием ошибки: ошибка нужна дальше (физика больше не зовётся), а
	// сказать о ней надо один раз.
	brokenSaid bool
	// queue и nextOrder — приём команд (mutation.go).
	queue     []pending
	nextOrder uint64
	// subs — подписчики на границу тика. Ключ — номер подписки, чтобы отписка
	// была O(1) и не зависела от сравнимости каналов.
	subs    map[uint64]chan Snapshot
	nextSub uint64
}

// New берёт партию во владение.
//
// Именно ВО ВЛАДЕНИЕ: после этого вызова читать и править партию по прежнему
// указателю нельзя. Отобрать его у вызывающего система типов не даёт (это Go), и
// сторожа этому нет — есть правило, записанное здесь и соблюдаемое в main тем,
// что указатель туда больше не передаётся никуда.
func New(m *match.Match, phys Physics) *Engine {
	// Хеш считается СРАЗУ, а не при первом тике: партия существует и до первого
	// шага, и подписчик, спросивший снимок нулевого тика, обязан получить
	// хеш того состояния, которое видит, а не пустую строку.
	return &Engine{m: m, phys: phys, hash: StateHash(m), subs: map[uint64]chan Snapshot{}}
}

// Step продвигает мир РОВНО НА ОДИН ТИК.
//
// Часов не читает, длительности не принимает, в лог не пишет — это чистое ядро,
// и его же зовут тесты, чтобы прогнать восемь часов модельного времени за долю
// секунды реального. Ни одного аргумента у него нет нарочно: аргумент-дельта и
// есть тот самый способ протащить сюда настенное время.
//
// # ФАЗЫ ТИКА, и порядок между ними — часть контракта детерминизма (шов 4)
//
//  1. ПРИЁМ    очередь команд опустошается целиком, в порядке поступления
//  2. ХОД      физика — сегодня пусто, приезжает с движением (ClearAhead-fcy)
//  3. ПЕЧАТЬ   канонический хеш состояния, затем рассылка снимка подписчикам
//
// Фаз стало три в тот день, когда у них появилось содержимое: до канала команд
// их не было НАРОЧНО («список из четырёх пустых фаз был бы формой без
// содержимого»). Пустой осталась одна — ход, и она объявлена пустой вслух, а не
// пропущена: между приёмом и печатью обязано быть названо место, куда встанет
// физика, иначе первый же её автор поставит её после печати и будет рассылать
// состояние на тик устаревшее.
//
// ПОЧЕМУ ПРИЁМ ПОСЛЕ tick++, А НЕ ДО. Команда, поданная во время тика N,
// применяется на границе тика N+1 и в его времени. Обратный порядок означал бы,
// что команда применяется в прошлом — во времени тика, который уже прожит и уже
// разослан подписчикам.
func (e *Engine) Step() {
	e.mu.Lock()
	defer e.mu.Unlock()
	e.tick++
	e.intake()
	// ФАЗА ХОДА. Шаг физики (20 мс) живёт внутри неё — пять подшагов на тик
	// координации; разбор деления — в пакете sim.
	if e.phys != nil && e.broken == nil {
		if err := e.phys.Advance(e.m, TickDuration); err != nil {
			e.broken = err
		}
	}
	e.seal()
}

// seal — ФАЗА 3: печать состояния и рассылка.
//
// Хеш считается ОДИН РАЗ за тик и здесь, а не у каждого читателя: канал решает
// по нему, слать ли снапшот, и два подписчика, посчитавшие его порознь, стоили
// бы двух проходов по всем единицам мира на каждом тике.
//
// Рассылка НЕБЛОКИРУЮЩАЯ, и это не оптимизация, а тот же инвариант, что у
// очереди команд: мир не ждёт сети. Подписчик, не успевший забрать прошлый
// снимок, пропускает его — и не теряет ничего, потому что снимок ПОЛНЫЙ:
// следующий содержит всё, что содержал пропущенный. Разностные снапшоты такого
// права не дали бы, и в тот день, когда они появятся, эта строка обязана
// смениться вместе с ними.
func (e *Engine) seal() {
	e.hash = StateHash(e.m)
	if len(e.subs) == 0 {
		return
	}
	snap := e.snapshotLocked()
	for _, ch := range e.subs {
		select {
		case ch <- snap:
		default:
			// Буфер занят прошлым снимком — он УСТАРЕЛ, и место занимает
			// новый. Обратный выбор (оставить старый, выбросить новый)
			// показывал бы подписчику прошлое как настоящее и тем тормозил
			// картинку ровно у того, кто и так не поспевает.
			//
			// Оба обмена неблокирующие: замок движка держится здесь, и
			// ожидание читателя остановило бы мир. Проигранная гонка (читатель
			// забрал снимок между двумя строками) стоит одного пропущенного
			// снимка — того самого, который он только что забрал.
			select {
			case <-ch:
			default:
			}
			select {
			case ch <- snap:
			default:
			}
		}
	}
}

// takeBroken — забрать поломку для лога, оставив мир остановленным.
//
// Возвращает её ОДИН раз: физика после поломки не зовётся вовсе (см. Step), и
// повторять одну и ту же строку каждый тик значило бы залить лог.
func (e *Engine) takeBroken() error {
	e.mu.Lock()
	defer e.mu.Unlock()
	if e.broken == nil || e.brokenSaid {
		return nil
	}
	e.brokenSaid = true
	return e.broken
}

// Snapshot — копия состояния для читателей.
func (e *Engine) Snapshot() Snapshot {
	e.mu.RLock()
	defer e.mu.RUnlock()
	return e.snapshotLocked()
}

// snapshotLocked собирает копию под уже взятым замком.
func (e *Engine) snapshotLocked() Snapshot {
	m := *e.m
	m.Units = append([]match.Unit(nil), e.m.Units...)
	// КАРТА ОРГАНОВ КОПИРУЕТСЯ ТОЖЕ, и по той же причине, что срез единиц:
	// копия структуры делит с движком и срез, и карту, а карта ещё и правится
	// командами — то есть читатель снимка и фаза приёма писали бы в одну карту
	// из разных горутин. Это не теория: гонку ловит -race на первой же команде.
	if e.m.Controls != nil {
		m.Controls = make(map[string]match.Controls, len(e.m.Controls))
		for id, c := range e.m.Controls {
			m.Controls[id] = c
		}
	}
	return Snapshot{Tick: e.tick, Time: e.tick.Time(), Hash: e.hash, Match: m}
}

// Subscribe подписывает на границу тика.
//
// Возвращает канал снимков и отписку. Отписка ОБЯЗАТЕЛЬНА: подписчик, забывший
// её вызвать, оставляет движку канал, в который тот будет складывать снимки до
// конца партии, — то есть утечку в самом горячем месте.
//
// Буфер на один снимок: подписчику нужен ПОСЛЕДНИЙ, а не очередь прошлых.
// Больший буфер накапливал бы устаревшие состояния и отдавал бы их клиенту
// по очереди — то есть показывал бы прошлое как настоящее.
func (e *Engine) Subscribe() (<-chan Snapshot, func()) {
	e.mu.Lock()
	defer e.mu.Unlock()
	e.nextSub++
	id := e.nextSub
	ch := make(chan Snapshot, 1)
	e.subs[id] = ch
	// Первый снимок кладётся СРАЗУ: подписчик, пришедший в неподвижный мир,
	// иначе ждал бы первого изменения состояния, чтобы узнать хоть что-то.
	ch <- e.snapshotLocked()
	return ch, func() {
		e.mu.Lock()
		defer e.mu.Unlock()
		// Канал не закрывается: отписка идёт из горутины подписчика, а
		// закрытие канала, в который движок в этот же миг пишет, — паника.
		// Удаления из карты достаточно, дальше канал соберёт сборщик.
		delete(e.subs, id)
	}
}

// Run — настенный кран: крутит Step в темпе 1:1 до отмены контекста.
//
// Здесь и только здесь читаются настенные часы. Возвращается по ctx.Done, и
// другого способа его остановить нет: срок жизни петли принадлежит тому, кто её
// запустил.
func (e *Engine) Run(ctx context.Context) {
	ticker := time.NewTicker(wallPeriod)
	defer ticker.Stop()
	// Отсчёт ведётся от МОМЕНТА ПРОБУЖДЕНИЯ к моменту пробуждения, а не от
	// старта петли: складывать номер пробуждения с периодом значило бы копить
	// ошибку таймера, который просыпается не ровно тогда, когда просили.
	last := time.Now()
	var acc units.SimTime
	for {
		select {
		case <-ctx.Done():
			return
		case now := <-ticker.C:
			// Sub на значениях time.Now монотонен: часы, переведённые назад
			// (синхронизация времени, смена зоны), отрицательного промежутка
			// здесь не дают.
			acc += wallToSim(now.Sub(last))
			last = now
			steps, rest, dropped := plan(acc)
			acc = rest
			if dropped > 0 {
				// ОТСТАВАНИЕ НЕ МОЛЧИТ. Мир, тихо отставший от часов на минуту,
				// снаружи неотличим от подвисшего сервера, и первым это заметит
				// не автор, а игрок, у которого «что-то не так со временем».
				log.Printf("движок отстал: %s модельного времени потеряно (потолок догона %s) — "+
					"мир идёт медленнее настенных часов и догонять не будет", dropped, MaxCatchUp)
			}
			for range steps {
				e.Step()
			}
			// ПОЛОМКА МИРА ГОВОРИТСЯ ВСЛУХ И ОДИН РАЗ. Молчащий сломанный мир
			// выглядит как замерший: снапшоты идут, время идёт, а машина стоит.
			if err := e.takeBroken(); err != nil {
				log.Printf("физика остановлена поломкой мира: %v — "+
					"движение прекращено, время идёт дальше", err)
			}
		}
	}
}

// wallToSim переводит настенный промежуток в модельный.
//
// Тождество сегодня, и функция существует ровно затем, чтобы это тождество было
// НАЗВАНО и имело одно место. Сценарный коэффициент времени (вертикальный срез
// §8: «один модельный час за 15–30 реальных минут, задан автором, одинаков для
// всех участников») приезжает сюда и никуда больше — в частности, не в Step,
// который о темпе не знает вовсе.
func wallToSim(d time.Duration) units.SimTime {
	return units.SimTime(d.Microseconds()) * units.Microsecond
}

// plan — сколько целых тиков отдать за это пробуждение, что оставить в
// накопителе и что потерять.
//
// Вынесена отдельной ЧИСТОЙ функцией не ради красоты, а ради проверяемости:
// иначе поведение потолка проверялось бы сном в тесте, то есть таймингом, то
// есть мигающим тестом. Здесь оно проверяется арифметикой.
//
// Отрицательный накопитель невозможен (монотонность Sub, см. Run), и потому не
// лечится: подстановка нуля вместо невозможного значения спрятала бы поломку
// часов, а не исправила её.
func plan(acc units.SimTime) (steps int, rest, dropped units.SimTime) {
	if acc > MaxCatchUp {
		dropped = acc - MaxCatchUp
		acc = MaxCatchUp
	}
	steps = int(acc / TickDuration)
	rest = acc - units.SimTime(steps)*TickDuration
	return steps, rest, dropped
}
