// Канонический хеш состояния партии — шов 10a вертикального среза.
//
// # У него есть потребитель СЕГОДНЯ, и это не сверка реплея
//
// Хеш заводился как средство доказать детерминизм: два прогона одной
// последовательности команд обязаны дать одинаковое состояние. Реплея пока нет,
// и одного этого довода не хватило бы — форма без потребителя в проекте
// запрещена. Потребитель другой и работает уже: КАНАЛ РЕШАЕТ ПО ХЕШУ, СЛАТЬ ЛИ
// СНАПШОТ. Состояние не изменилось — снапшот не идёт; изменилось — идёт
// немедленно, не дожидаясь очередного срока.
//
// Это ровно тот приём, который записан решением ClearAhead-t5h как правильный
// («обновление ПО ПОРОГУ ОШИБКИ плюс максимальный возраст», IEEE 1278 DIS), в
// его сегодняшнем вырожденном виде: пока ничто не движется, порог ошибки
// вырождается в «состояние побитово другое». Настоящий порог — расхождение
// серверной копии с dead-reckoned копией клиента — приезжает вместе с
// движением, и приезжает СЮДА ЖЕ, в место принятия решения, а не в новое.
//
// # Float64 в хеш не попадает
//
// Правило проекта: float64 не сверяется байт в байт — не переживает смены
// машины (проект уже потерял на этом эталон контракта, коммит 4b4d6a7,
// расхождение ~1e-13 при неизменном коде). Хеш от битов float64 воспроизвёл бы
// ту же ошибку в худшем месте: он ЕСТЬ сверка байт в байт по определению.
//
// Поэтому смещение вдоль элемента квантуется в микрометры — ту самую
// объявленную точность, в которой проект уже хранит длины (units.Distance).
// Два состояния, различающиеся меньше чем на микрометр, дают один хеш, и это не
// потеря: микрометр — заявленная разрешающая способность мира, а не округление
// ради удобства.
//
// # Почему своя запись, а не JSON
//
// JSON не канонизирован: порядок полей в объекте по стандарту незначим, а
// запись float допускает варианты. Здесь пишутся длины и байты в объявленном
// порядке, поэтому у одного состояния ровно одна запись. Строки идут с
// префиксом длины, а не с разделителем: разделитель обязан быть символом,
// которого не бывает в строке, а такого символа у нас нет — идентификаторы
// приходят из карты, и запрет на символ пришлось бы держать в валидаторе карты
// ради формата хеша.
const hashVersion = 1

// StateHash — канонический хеш состояния партии.
//
// Единицы сортируются по идентификатору: порядок в срезе — это порядок
// расстановки в файле, то есть свойство ДОКУМЕНТА, а не состояния мира.
// Перестановка двух строк в файле расстановки не меняет мир и не должна менять
// хеш.
func StateHash(m *match.Match) string {
	h := sha256.New()
	var num [8]byte
	writeUint := func(v uint64) {
		binary.BigEndian.PutUint64(num[:], v)
		h.Write(num[:])
	}
	writeStr := func(s string) {
		writeUint(uint64(len(s)))
		h.Write([]byte(s))
	}
	writeUint(hashVersion)
	writeStr(m.ID)
	writeStr(m.Region)

	sorted := append([]match.Unit(nil), m.Units...)
	slices.SortFunc(sorted, func(a, b match.Unit) int {
		switch {
		case a.ID < b.ID:
			return -1
		case a.ID > b.ID:
			return 1
		default:
			return 0
		}
	})
	writeUint(uint64(len(sorted)))
	for _, u := range sorted {
		writeStr(u.ID)
		writeStr(u.Name)
		writeStr(u.Type)
		writeStr(u.At.Element)
		writeStr(string(u.At.Direction))
		writeUint(uint64(quantize(u.At.U)))
		// ОРГАНЫ УПРАВЛЕНИЯ — ЧАСТЬ СОСТОЯНИЯ, и попадают в хеш наравне с
		// местом. Иначе переведённая рукоятка не меняла бы хеш, канал не слал
		// бы снапшот (рассылка идёт ПО СМЕНЕ ХЕША), и машинист видел бы, как
		// его команда принята сервером и не доехала обратно до секундного
		// биения. Проверено тестом, а не рассуждением.
		//
		// Читаются они у ЕДИНИЦЫ, а не обходом карты: порядок обхода карты в Go
		// случаен, а хеш обязан быть каноническим. Единицы уже отсортированы.
		c, has := m.Controls[u.ID]
		writeUint(boolBit(has))
		if has {
			writeUint(uint64(c.Traction))
			writeUint(uint64(c.Brake))
			writeStr(string(c.Reverser))
		}
	}
	return hex.EncodeToString(h.Sum(nil))
}

// boolBit — признак одним разрядом: «органы есть» и «органов нет» обязаны
// давать разные записи, иначе вагон и локомотив с нулевыми рукоятками
// сложились бы в один хеш.
func boolBit(v bool) uint64 {
	if v {
		return 1
	}
	return 0
}

// quantize переводит метры в микрометры для хеша.
//
// Непереводимое значение (NaN, бесконечность, выход за диапазон) даёт ноль, и
// это не подстановка правдоподобного вместо неверного: такое значение в партию
// не попадает — match.place отвергает его при загрузке, а правки идут через
// Apply, который тоже обязан проверять. Ноль здесь — признак того, что
// невозможное всё-таки случилось, и он делает хеш ОДИНАКОВЫМ для всех
// испорченных значений; ловить порчу — работа валидатора, а не хеша.
func quantize(meters float64) units.Distance {
	d, err := units.MetersToDistance(meters)
	if err != nil {
		return 0
	}
	return d
}
