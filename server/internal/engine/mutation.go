package engine

import (
	"fmt"

	"github.com/shady2k/ClearAhead/server/internal/match"
)

// Приём команд: очередь между сетью и тиком.
//
// # Тик не ждёт сети НИКОГДА
//
// Это требование записано бидой ClearAhead-zz9 одной строкой («команды в
// очередь, разбирает фаза тика»), и оно определяет форму здесь. Обратный
// порядок — обработчик соединения зовёт правку партии прямо из своей горутины —
// означал бы, что скорость мира зависит от того, сколько клиентов сейчас
// говорят: одно медленное соединение растягивает тик, а модельное время
// начинает зависеть от сети. Очередь разрывает эту связь: сеть кладёт, тик
// разбирает, и ни одна сторона не ждёт другую.
//
// # Почему интерфейс, а не функция-замыкание
//
// Замыкание func(*match.Match) error было бы короче на десять строк и хуже
// двумя способами. Во-первых, оно непечатаемо: журнал команд (JournalSeq
// вертикального среза §8) обязан записать, ЧТО применялось, а у замыкания нет
// имени — в журнал уехал бы адрес функции. Во-вторых, замыкание захватывает
// окружение отправителя, то есть протаскивает в единственного владельца
// состояния ссылки на то, чем владеет транспорт, — ровно та разделяемая
// изменяемая память, которой в проекте не должно быть.
//
// # Домашних правок здесь НЕТ
//
// Ни одной реализации Mutation в боевом коде сегодня не существует, и это
// объявленная граница вехи ClearAhead-wa51: канал команд закрывается, не назвав
// НИ ОДНОЙ доменной команды. Первая приезжает с органами управления кабины
// (ClearAhead-6ygr) — позиция контроллера тяги, реверсор, кран машиниста.
// Механизм проверяется поддельной правкой в тестах, и это не то же самое, что
// «форма без потребителя»: у формы потребитель отсутствует, а здесь он назван,
// стоит следующим в очереди работ и определяет форму.

// Mutation — правка партии, пришедшая командой.
//
// Apply зовётся ПОД ЗАМКОМ движка, в фазе приёма, и получает партию во
// временное пользование. Держать *match.Match после возврата нельзя: за
// пределами фазы это тот самый указатель на состояние, которое правит другая
// горутина.
//
// Ошибка, возвращённая Apply, есть ОТКАЗ КОМАНДЫ: партия при этом обязана
// остаться нетронутой. Правка, упавшая на середине, оставила бы мир в
// состоянии, которого не порождает ни одна законная последовательность команд,
// и воспроизвести его потом было бы нечем.
type Mutation interface {
	// Name — имя правки для журнала и логов. Не идентификатор команды: имён
	// конечное число, команд бесконечно много.
	Name() string
	Apply(m *match.Match) error
}

// pending — правка, ждущая своей фазы приёма.
type pending struct {
	// order — номер поступления. Порядок применения ДЕТЕРМИНИРОВАН именно им,
	// а не порядком, в котором горутины успели взять замок при разборе очереди
	// (шов 10a: детерминированный порядок команд).
	order uint64
	mut   Mutation
	// done — исход правки её отправителю. Буфер на единицу и ровно одна
	// отправка: фаза приёма не имеет права заблокироваться на отправителе,
	// который уже ушёл (клиент отключился, не дождавшись ответа).
	done chan error
}

// Submit ставит правку в очередь и возвращает канал её исхода.
//
// Возвращается КАНАЛ, а не ошибка, потому что ответ рождается не здесь:
// команда применяется в ближайшей фазе приёма, то есть до 100 мс спустя.
// Отправитель ждёт исход со своим контекстом и вправе перестать ждать — тик от
// этого не изменится, правка всё равно применится. Это и есть смысл границы:
// применение принадлежит миру, ожидание — соединению.
//
// Задержка до тика названа и принята: вертикальный срез §6 меряет её тем, что
// «задержка команды до 250 мс на фоне зарядки магистрали в десятки секунд не
// ощущается», а положение рукоятки клиент показывает локально и немедленно, не
// дожидаясь снапшота.
func (e *Engine) Submit(m Mutation) <-chan error {
	done := make(chan error, 1)
	if m == nil {
		// Пустая правка — ошибка вызывающего, а не состояние мира. Отвечаем
		// сразу и в очередь не кладём: тик не должен встретить nil.
		done <- fmt.Errorf("engine: пустая правка")
		return done
	}
	e.mu.Lock()
	defer e.mu.Unlock()
	e.nextOrder++
	e.queue = append(e.queue, pending{order: e.nextOrder, mut: m, done: done})
	return done
}

// intake — ФАЗА 1 ТИКА: приём команд.
//
// Зовётся под уже взятым замком. Очередь опустошается ЦЕЛИКОМ: ограничить
// приём числом правок за тик значило бы завести очередь, которая при наплыве
// команд растёт быстрее, чем разбирается, и мир начинает отставать от игрока
// молча. Если такой потолок понадобится, он придёт вместе с замером, а не
// вместо него.
func (e *Engine) intake() {
	if len(e.queue) == 0 {
		return
	}
	// Порядок в срезе и есть порядок поступления: append под тем же замком,
	// который держит счётчик. Сортировка была бы честной страховкой ровно до
	// того дня, когда кто-то положил бы в очередь правку мимо Submit.
	for _, p := range e.queue {
		err := p.mut.Apply(e.m)
		// Неблокирующая отправка не нужна: буфер на единицу, отправка одна.
		p.done <- err
		close(p.done)
	}
	// Срез обнуляется, а не переиспользуется усечением до нуля: удержанные
	// ссылки на Mutation мешали бы сборщику ровно столько, сколько живёт
	// движок, то есть всю партию.
	e.queue = nil
}
