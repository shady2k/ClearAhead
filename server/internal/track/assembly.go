// assembly.go — СБОРКА: путь как поимённые детали с портами и обязательствами.
//
// # Зачем это заведено
//
// До 2026-08-16 сервер отдавал РЕЦЕПТ: нитки прохода плюс правила вычитания
// (RenderTurnoutRailGap) плюс отдельные списки остряков и ниток крестовины. Тела
// из этого не было — тело собирал клиент. Два следствия, и оба были дырами:
//
//	 1. Единственным местом, где можно спросить «сомкнулся ли металл», оказался
//	    Godot: проверка 44_mesh_shell.gd режет ТРЕУГОЛЬНИКИ плоскостью и меряет
//	    занятые интервалы. Свойство домена проверялось через рендер.
//	 2. Проверка перечисляла ДЕТАЛИ (остряки), а не СТЫКИ, и потому не увидела
//	    нитку, у которой остряка нет вовсе. Замер: у бокового прохода вырезаны обе
//	    нитки на длину остряка, а остряк дан один; наружная нитка возобновляется в
//	    0.1145 м от рамного рельса — при головке 0.075 м это 39.5 мм чистого
//	    воздуха, то есть рельс с открытым торцом, начинающийся ниоткуда.
//
// Третьим доказательством того, что рецепт не держит собственность, служит
// BladeRootJoint (blade.go): накладки, «которыми закрыт стык», объявлены
// константой и разобраны в комментарии — а деталей таких нет ни в данных, ни в
// построении. Соединение существовало в тексте и не существовало в модели.
//
// # Почему список стыков НЕ ОБЪЯВЛЯЕТСЯ автором
//
// Соблазн был прямой: рядом с деталями положить записи вида «A смыкается с B».
// Это завело бы ТРЕТИЙ рецепт, врущий наравне с первыми двумя: ничто не мешает
// такой записи утверждать смычку там, где зазор. Ошибка переехала бы с клиента в
// декларацию сервера и осталась бы ошибкой.
//
// Поэтому здесь наоборот:
//
//	порт ВЫВОДИТСЯ из границы детали — автор его не пишет;
//	смычка ДОКАЗЫВАЕТСЯ непрерывностью металла — автор её не утверждает;
//	объявляется только НАМЕРЕНИЕ разорвать (желоб, изолирующий стык), потому что
//	намерение из геометрии не выводится ничем.
//
// # Вопрос задаётся о МЕСТЕ, а не о паре деталей
//
// Первая редакция спрашивала «примкнул ли этот порт к ближайшему чужому». Это
// отвергало бы верную починку: стык вправе быть закрыт ТРЕТЬИМ телом — накладки
// в корне остряка ровно таковы, — а их концы лежат не на шве, и парная проверка
// их не зачла бы. Хуже того, у самой накладки концы оказывались бы «внутренними
// и несомкнутыми», то есть починка порождала бы два новых дефекта.
//
// Поэтому вопрос стоит о СТАНЦИИ: сравнивается весь металл элемента чуть до и
// чуть после неё. Чем он держится — смычкой двух деталей или перекрытием
// третьей, — проверке безразлично, и это правильно: колесу тоже.
//
// # Почему ValidatedAssembly непрозрачна
//
// Поля неэкспортируемые, конструктор один — Validate. Значения «сборка, которую
// не проверяли» в типах не существует, и потребитель не может его получить,
// забыв позвать проверку. Это то же правило, что «валидатор отказывает, а не
// чинит», перенесённое с ЗНАЧЕНИЙ на ГЕОМЕТРИЮ.
//
// # Словарь взят у IFC 4.3, а не выдуман
//
// STOCKRAIL, BLADE, CHECKRAIL, GUARDRAIL, FROG — типы IfcRail и
// IfcTrackElementTypeEnum; ATSTART/ATEND — виды примыкания
// IfcRelConnectsPathElements. Разбор приор арта (2026-08-16) показал, что
// словарь у отрасли есть, а доказательства смычки нет ни у кого: у Trainz,
// OpenRails, Cities:Skylines и OpenDRIVE стык означает «поезд может перейти», а
// не «ходовая поверхность сомкнулась». Словарь берём готовым, доказательство
// делаем сами.

// Виды деталей. Строки — словарь IFC 4.3, чтобы имя не пришлось переводить
// дважды при первом же обмене.
const (
	PartRail        = "rail"
	PartStockRail   = "stock_rail"
	PartBlade       = "blade"
	PartWingRail    = "wing_rail"
	PartCheckRail   = "check_rail"
	PartFrogCasting = "frog_casting"
)

// Концы детали. Те же два слова, что у IfcRelConnectsPathElements.
const (
	PortAtStart = "start"
	PortAtEnd   = "end"
)

// RunningFaceTol — допуск смыкания РАБОЧИХ ГРАНЕЙ, метры.
//
// Миллиметр, и это не оценка точности счёта: обе точки считаются из одной оси
// одной арифметикой, и разойтись на большее они могут только потому, что модель
// их развела. Настоящий рельсовый стык имеет температурный зазор до ~20 мм — но
// он ОБЪЯВЛЕН, и объявленный разрыв проверку проходит отдельным путём. Здесь
// проверяется необъявленное, а необъявленного зазора не бывает.
const RunningFaceTol = 0.001

// StationEps — на сколько отступить ВДОЛЬ пути, чтобы спросить «что было до
// станции и что стало после», метры.
//
// Величина продольная и с поперечным допуском смыкания не связана ничем, кроме
// совпадения числа. Первая редакция брала одну константу на оба, и совпадение
// читалось как связь, которой нет: миллиметр здесь выбран потому, что детали
// устройства короче полуметра не бывают, а не потому, что столько же разрешено
// разъехаться граням.
const StationEps = 0.001

// MergeTol — на сколько два тела могут не касаться, чтобы считаться сплошным
// металлом, метры.
//
// Тоже поперечная величина, но вопрос другой: не «сомкнулись ли рабочие грани»,
// а «есть ли просвет между соседними телами». Совпадение с RunningFaceTol
// сегодня случайно, и разводятся они здесь затем, чтобы правка одного не
// двигала другое молча.
const MergeTol = 0.001

// MinMetalOverlap — какая доля поперечного сечения обязана быть общей у двух
// сомкнувшихся деталей.
//
// # Зачем этого мало — совпадения граней
//
// Совпадение рабочих граней проверяет, что колесо не провалится: гребень ведёт
// по грани, и грань продолжается. Но ТЕЛО может при этом прыгнуть вбок на всю
// свою ширину — рабочая грань у остряка и у нитки за его корнем одна, а растут
// они в РАЗНЫЕ стороны: остряк внутрь колеи, нитка наружу. Замер на SW1: грани
// сходятся точно (расстояние 0), а сечения перекрываются на 50 % — до шва металл
// на [0.647, 0.797], после на [0.722, 0.872].
//
// В кадре это и есть «рельсы идут разными сегментами, которые не соединены».
//
// # Почему 0.9, а не 1.0
//
// Единица потребовала бы тождественных сечений, а законная смена сечения на шве
// существует: остряк в корне уже вышел на полное, но накладка или переход марки
// вправе дать иной профиль. Девять десятых оставляют место такому переходу и не
// оставляют — прыжку на ширину головки.
//
// Число взято у проверки 44_mesh_shell.gd, которая мерила ровно это по
// треугольникам: порог переезжает вместе с самим вопросом, чтобы две стороны не
// начали требовать разного.
const MinMetalOverlap = 0.9

// Part — деталь сборки: протяжка вдоль интервала элемента.
//
// FaceFrom/FaceTo — вынос РАБОЧЕЙ ГРАНИ по левой нормали на концах интервала.
// Именно грань, а не ось детали: смыкаются рабочие грани, по ним катится
// колесо, и сравнивать оси значило бы объявить смычку у двух рельсов разной
// ширины головки.
//
// Grow, Near/Far и ScaleFrom/ScaleTo описывают ТЕЛО детали поперёк пути —
// ровно столько, сколько нужно, чтобы спросить «продолжает ли металл металл».
// Полного многоугольника здесь нет намеренно: вопрос о смычке решается
// ЗАНЯТЫМ ОТРЕЗКОМ, а высота и форма шейки на него не влияют. Возить сюда весь
// профиль значило бы обещать проверку, которой нет.
type Part struct {
	ID       string
	Kind     string
	Owner    string
	Element  string
	FromU    float64
	ToU      float64
	FaceFrom float64
	FaceTo   float64
	// Grow — в какую сторону от рабочей грани растёт тело: +1 или −1 по левой
	// нормали элемента. У нитки наружу от оси, у остряка внутрь колеи — и именно
	// в этой разнице сидит прыжок тела на шве корня.
	Grow float64
	// Near, Far — пределы сечения от рабочей грани В СТОРОНУ РОСТА, метры.
	// Near обычно отрицателен: подошва выступает и назад, за рабочую грань.
	Near, Far float64
	// Head — ширина ГОЛОВКИ от рабочей грани в сторону роста, метры.
	//
	// Пока только возится. Решение о смычке принимается по ВСЕМУ сечению, и это
	// объявленное упрощение — разбор у findBreaks.
	Head float64
	// ScaleFrom, ScaleTo — во сколько раз сечение уже полного на концах детали.
	// Единица у обычного рельса; у остряка меньше — он острогана (blade_section.go).
	ScaleFrom, ScaleTo float64
}

// Port — конец детали. ВЫВОДИТСЯ, а не задаётся.
//
// Конструктора у Port снаружи нет намеренно: единственный способ его получить —
// спросить у детали (Part.ports). Порт, написанный руками, был бы ровно тем
// объявлением, ради отказа от которого файл и заведён.
type Port struct {
	Part    string
	Kind    string
	End     string
	Element string
	U       float64
	// X, Y, Z — точка РАБОЧЕЙ ГРАНИ в координатах региона.
	X, Y, Z float64
	// MetalFrom, MetalTo — отрезок, занятый телом детали, в выносе по левой
	// нормали элемента. Считается из грани, стороны роста и сечения; автором не
	// задаётся, как и всё остальное в порту.
	MetalFrom, MetalTo float64
	// Interior — порт лежит ВНУТРИ элемента, а не на его конце.
	//
	// Различие несёт всю силу проверки. Порт на конце элемента законно бывает
	// свободным: там кончается ребро, и что дальше — вопрос топологии сети, а не
	// сборки устройства. Порт ВНУТРИ элемента свободным не бывает никогда: он
	// возник потому, что деталь здесь кончилась, и обязан назвать, что дальше.
	Interior bool
}

// Gap — ОБЪЯВЛЕННЫЙ разрыв: место, где металла нет НАРОЧНО.
//
// Единственное, что в этой модели объявляется автором, и объявляется по
// необходимости: желоб крестовины, изолирующий стык и температурный зазор из
// геометрии не выводятся ничем — это намерение, а намерения в числах нет.
//
// Вид назван отдельным словом, а не одним «разрывом»: у желоба и у изолирующего
// стыка разные последствия для ведения поезда, и однажды их придётся различать.
type Gap struct {
	Kind    string // flangeway | insulated | thermal
	Element string
	Face    float64
	From    float64
	To      float64
	Why     string
}

// Break — НЕСМЫКАНИЕ: порт, которому не к чему примкнуть.
//
// Возвращается перечнем, а не первым найденным: перечень несмыканий — это и
// есть список работ, а отказ по первому скрыл бы остальные до следующего
// запуска.
// Виды несмыкания. Различие не для отчёта: у них РАЗНЫЕ причины и разные
// починки, и одно слово на оба заставляло бы разбирать каждое заново.
const (
	// BreakOpen — детали нет вовсе: рабочей грани не к чему примкнуть. Так
	// выглядит нитка, начинающаяся ниоткуда.
	BreakOpen = "open"
	// BreakStep — грани сошлись, а ТЕЛА разошлись: детали растут в разные
	// стороны от общей грани. Так выглядит корень остряка.
	BreakStep = "step"
)

type Break struct {
	// Kind — open | step, см. константы выше.
	Kind string
	Port Port
	// Nearest — ближайший чужой порт и расстояние до него. Пустой Part значит,
	// что чужих портов нет вовсе.
	Nearest  Port
	Distance float64
	// Overlap — доля общего сечения у смежных тел. Осмысленна при BreakStep.
	Overlap float64
}

// Assembly — детали одного устройства и объявленные разрывы.
type Assembly struct {
	Owner string
	Parts []Part
	Gaps  []Gap
}

// ValidatedAssembly — сборка, ПРОШЕДШАЯ проверку.
//
// Поля неэкспортируемые, конструктор один. Значения «непроверенная сборка» в
// типах не существует — потребитель не может забыть позвать проверку, потому
// что без неё у него не будет чего потреблять.
type ValidatedAssembly struct {
	owner string
	parts []Part
	ports []Port
}

// Owner называет устройство проверенной сборки.
func (v *ValidatedAssembly) Owner() string { return v.owner }

// Parts отдаёт КОПИЮ деталей: проверенная сборка не вправе измениться после
// проверки, а общий срез отдал бы потребителю доступ в её внутренности.
func (v *ValidatedAssembly) Parts() []Part {
	out := make([]Part, len(v.parts))
	copy(out, v.parts)
	return out
}

// Ports отдаёт копию выведенных портов — по тому же доводу.
func (v *ValidatedAssembly) Ports() []Port {
	out := make([]Port, len(v.ports))
	copy(out, v.ports)
	return out
}

// Validate доказывает сборку и только при успехе отдаёт её значение.
//
// Правило полноты: ВНУТРЕННИЙ порт обязан либо сомкнуться с чужим портом в
// пределах RunningFaceTol, либо попасть в объявленный разрыв. Третьего не дано,
// и «ничего» третьим не считается — именно «ничего» и стояло на корне остряка.
func Validate(a Assembly, els map[string]Element) (*ValidatedAssembly, error) {
	ports, err := derivePorts(a, els)
	if err != nil {
		return nil, err
	}
	breaks := findBreaks(a.Parts, ports, a.Gaps)
	if len(breaks) > 0 {
		return nil, breaksError(a.Owner, breaks)
	}
	return &ValidatedAssembly{owner: a.Owner, parts: append([]Part(nil), a.Parts...), ports: ports}, nil
}

// Breaks находит несмыкания, НЕ отказывая.
//
// Заведено ради разбора, а не ради обхода отказа: перечень несмыканий на
// нынешней модели — это список работ следующего шага, и его надо уметь
// напечатать, не роняя сборку. Потребителям геометрии эта дорога закрыта: она
// не отдаёт ValidatedAssembly.
func Breaks(a Assembly, els map[string]Element) ([]Break, error) {
	ports, err := derivePorts(a, els)
	if err != nil {
		return nil, err
	}
	return findBreaks(a.Parts, ports, a.Gaps), nil
}

// derivePorts выводит по два порта на деталь. Порядок канонический: детали по
// ID, у детали сперва начало, потом конец — сборка попадёт в хеш геометрии, а
// обход Go-map недетерминирован.
func derivePorts(a Assembly, els map[string]Element) ([]Port, error) {
	parts := append([]Part(nil), a.Parts...)
	sort.Slice(parts, func(i, j int) bool { return parts[i].ID < parts[j].ID })

	out := make([]Port, 0, len(parts)*2)
	for _, p := range parts {
		el, ok := els[p.Element]
		if !ok {
			return nil, fmt.Errorf("track: сборка %s: деталь %s ссылается на элемент %s, которого нет среди скомпилированных",
				a.Owner, p.ID, p.Element)
		}
		lengthU := el.Prof.LengthU().Meters()
		for _, end := range []string{PortAtStart, PortAtEnd} {
			u, face := p.FromU, p.FaceFrom
			if end == PortAtEnd {
				u, face = p.ToU, p.FaceTo
			}
			x, y, z, err := facePoint(el, u, face)
			if err != nil {
				return nil, fmt.Errorf("track: сборка %s: деталь %s, конец %s: %w", a.Owner, p.ID, end, err)
			}
			scale := p.ScaleFrom
			if end == PortAtEnd {
				scale = p.ScaleTo
			}
			lo, hi := metalSpan(face, p.Grow, p.Near, p.Far, scale)
			out = append(out, Port{
				Part: p.ID, Kind: p.Kind, End: end, Element: p.Element, U: u,
				X: x, Y: y, Z: z,
				MetalFrom: lo, MetalTo: hi,
				// Допуск сравнения с концом элемента — тот же миллиметр: u приходит
				// из счёта, и «ровно ноль» здесь означало бы сравнение float64 байт
				// в байт, что проект уже терял.
				Interior: u > StationEps && u < lengthU-StationEps,
			})
		}
	}
	return out, nil
}

// facePoint — точка рабочей грани на элементе: поза оси плюс вынос по ЛЕВОЙ
// нормали. Та же адресация, что у брусьев, привода и разрывов, — второго языка
// «где это поперёк пути» проект не держит.
func facePoint(el Element, u, face float64) (x, y, z float64, err error) {
	du, err := units.MetersToDistance(u)
	if err != nil {
		return 0, 0, 0, err
	}
	plan, err := el.Plan.PoseAt(el.Start.Plan, du)
	if err != nil {
		return 0, 0, 0, fmt.Errorf("план на %v м: %w", u, err)
	}
	rise, _, err := el.Prof.At(du)
	if err != nil {
		return 0, 0, 0, fmt.Errorf("профиль на %v м: %w", u, err)
	}
	nx, ny := -math.Sin(plan.Heading), math.Cos(plan.Heading)
	return plan.X + nx*face, plan.Y + ny*face, el.Start.Z + rise, nil
}

// metalSpan — отрезок, занятый телом, в выносе по левой нормали.
//
// Сечение отмеряется ОТ РАБОЧЕЙ ГРАНИ в сторону роста и масштабируется долей
// строжки. Масштаб множит оба предела, а не один: острогана вся деталь, и
// сужение одной головки при полной подошве дало бы у рамного рельса второй
// профиль с подошвой в 150 мм (тот же довод, что у клиента до переезда).
func metalSpan(face, grow, near, far, scale float64) (lo, hi float64) {
	if scale <= 0 {
		scale = 1
	}
	if grow == 0 {
		grow = 1
	}
	a := face + grow*near*scale
	b := face + grow*far*scale
	return math.Min(a, b), math.Max(a, b)
}

// span — отрезок, занятый металлом поперёк пути.
type span struct{ lo, hi float64 }

// at — грань и доля сечения детали в станции u.
//
// Обе меняются вдоль детали линейно — так же, как их читает клиент между
// станциями сечения. Второго правила интерполяции проект не держит.
func (p Part) at(u float64) (face, scale float64) {
	t := 0.0
	if l := p.ToU - p.FromU; l > 0 {
		t = math.Min(math.Max((u-p.FromU)/l, 0), 1)
	}
	return p.FaceFrom + (p.FaceTo-p.FaceFrom)*t, p.ScaleFrom + (p.ScaleTo-p.ScaleFrom)*t
}

// metalAt — отрезок ТЕЛА детали в станции u.
func (p Part) metalAt(u float64) span {
	face, scale := p.at(u)
	lo, hi := metalSpan(face, p.Grow, p.Near, p.Far, scale)
	return span{lo, hi}
}

// headAt — отрезок ГОЛОВКИ детали в станции u: то, по чему катится колесо.
//
// Заведён вместе с полем Head и пока не участвует в решении. Причина названа
// замером, а не вкусом: перевод вопроса на головку — правильный ход, но он
// немедленно требует знать, НЕСЁТ ЛИ ДЕТАЛЬ КОЛЕСО. Контррельс не несёт, он
// ведёт; у сердечника колесо переходит с усовика на отливку, опираясь на оба
// разом. Без этих различий головочное правило дало на затравке ложные отказы у
// контррельсов и у обеих граней сердечника — там, где настоящий перевод исправен.
func (p Part) headAt(u float64) span {
	face, scale := p.at(u)
	lo, hi := metalSpan(face, p.Grow, 0, p.Head, scale)
	return span{lo, hi}
}

// metalUnionAt — ВЕСЬ металл элемента в станции u, попавший в окно вокруг грани.
//
// # Почему объединение, а не одна деталь
//
// Стык вправе быть закрыт ТРЕТЬИМ телом. Накладки в корне остряка — ровно такой
// случай: их концы лежат не на шве, а по обе стороны от него, и проверка,
// сравнивающая пару деталей, отвергла бы верную починку. Спрашивать надо не
// «продолжает ли эта деталь ту», а «продолжен ли МЕТАЛЛ».
//
// # Почему окно
//
// Без него в отрезок попадает и нитка с другой стороны колеи, «металл до шва»
// оказывается полутора метрами шириной, перекрытие выходит стопроцентным всегда
// и проверка зеленеет всегда. Довод найден не здесь: его записала проверка
// мешей, наступив на это первой.
//
// # Почему только СВОЙ элемент, и что из-за этого НЕ ДОКАЗАНО
//
// Тела соседнего прохода лежат в его собственной системе выносов, и свести их в
// одну плоскость значило бы завести проекцию — то есть приближение — там, где
// сейчас точная арифметика.
//
// Цена названа прямо, потому что она есть: МЕЖЭЛЕМЕНТНАЯ НЕПРЕРЫВНОСТЬ ЭТОЙ
// ПРОВЕРКОЙ НЕ ДОКАЗЫВАЕТСЯ. Расстояние до ближайшего чужого порта считается и
// печатается в отказе, но на решение не влияет — это диагностика, а не довод.
// Рамные рельсы стрелки, физически общие для двух проходов, попадают именно в
// эту дыру.
func metalUnionAt(parts []Part, element string, u, face, window float64) []span {
	var out []span
	for _, p := range parts {
		if p.Element != element || u < p.FromU || u > p.ToU {
			continue
		}
		s := p.metalAt(u)
		if s.hi < face-window || s.lo > face+window {
			continue
		}
		out = append(out, s)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	// Слияние касающихся: два тела, лежащие вплотную, есть сплошной металл, и
	// считать их порознь значило бы объявить дефектом ровно ту починку, ради
	// которой заведено объединение.
	var merged []span
	for _, s := range out {
		if n := len(merged); n > 0 && s.lo <= merged[n-1].hi+MergeTol {
			merged[n-1].hi = math.Max(merged[n-1].hi, s.hi)
			continue
		}
		merged = append(merged, s)
	}
	return merged
}

func totalLen(ss []span) float64 {
	var l float64
	for _, s := range ss {
		l += s.hi - s.lo
	}
	return l
}

// overlapShare — какая доля МЕНЬШЕГО из двух объединений у них общая.
//
// # ОБЪЯВЛЕННАЯ ДЫРА: сжатие металла проходит молча
//
// Деление на меньшее пропускает исчезновение: было 150 мм, осталось 10 мм ВНУТРИ
// прежнего отрезка — общего 10 из 10, сто процентов, и девяносто три процента
// тела испарились бы незамеченными.
//
// Деление на большее эту дыру закрывает и открывает худшую: тогда не проходит
// НИ ОДНА деталь, начинающаяся или кончающаяся рядом со сплошным металлом, — а
// именно такова накладка, ради которой правило и переведено со сравнения пар на
// сравнение станций. Проверено: с делением на большее падает
// TestFishplateBridgesTheSeam на собственных концах накладки.
//
// Настоящий выход не в выборе делителя, а в том, чтобы спрашивать про ХОДОВУЮ
// ПОВЕРХНОСТЬ и знать, несёт ли деталь колесо (headAt, поле Head). Это отдельная
// работа: у контррельса функция ведения, у сердечника опора делится с усовиком,
// и без этих различий головочное правило даёт ложные отказы. До неё делитель
// остаётся меньшим, а дыра — названной.
func overlapShare(before, after []span) float64 {
	var common float64
	for _, a := range before {
		for _, b := range after {
			if d := math.Min(a.hi, b.hi) - math.Max(a.lo, b.lo); d > 0 {
				common += d
			}
		}
	}
	narrow := math.Min(totalLen(before), totalLen(after))
	if narrow <= 0 {
		return 0
	}
	return common / narrow
}

// findBreaks ищет внутренние порты, у которых металл не продолжен.
//
// Два вопроса подряд, и второй имеет смысл только после первого: сперва есть ли
// чему примыкать (грань), затем продолжено ли тело (сечение). Обратный порядок
// сравнивал бы сечения у деталей, стоящих в метре друг от друга.
func findBreaks(parts []Part, ports []Port, gaps []Gap) []Break {
	var out []Break
	for i, p := range ports {
		if !p.Interior || coveredByGap(p, gaps) {
			continue
		}
		best := -1
		bestD := math.Inf(1)
		for j, q := range ports {
			// Свои же порты не считаются: у детали два конца, и «примкнула сама к
			// себе» смычкой не является.
			if i == j || q.Part == p.Part {
				continue
			}
			d := math.Hypot(math.Hypot(p.X-q.X, p.Y-q.Y), p.Z-q.Z)
			if d < bestD {
				best, bestD = j, d
			}
		}
		// ОКНО — РАДИУС в две ширины собственного сечения, вокруг его середины.
		// Соседняя нитка колеи отстоит на gauge и в окно не попадает; тело,
		// уехавшее вбок на свою ширину, ещё попадает — иначе прыжок выглядел бы
		// пустотой, то есть другим дефектом.
		mid := (p.MetalFrom + p.MetalTo) / 2
		window := 2 * (p.MetalTo - p.MetalFrom)
		before := metalUnionAt(parts, p.Element, p.U-StationEps, mid, window)
		after := metalUnionAt(parts, p.Element, p.U+StationEps, mid, window)
		if share := overlapShare(before, after); share >= MinMetalOverlap {
			continue
		} else {
			b := Break{Kind: BreakStep, Port: p, Distance: bestD, Overlap: share}
			// Пустая сторона — это ОТСУТСТВИЕ детали, а не прыжок тела: у неё
			// другая починка (завести деталь, а не сдвинуть её), и звать оба
			// одним словом значило бы разбирать каждое заново.
			if len(before) == 0 || len(after) == 0 {
				b.Kind = BreakOpen
			}
			if best >= 0 {
				b.Nearest = ports[best]
			}
			out = append(out, b)
		}
	}
	return out
}

// coveredByGap — попадает ли порт в объявленный разрыв.
//
// ГРАНЬ СРАВНИВАЕТСЯ, и это не педантизм: разрыв объявляют НИТКОЙ, а не
// областью. Первая редакция грань не смотрела, хотя комментарий обещал обратное,
// и любой объявленный разрыв на элементе освобождал бы ЛЮБОЙ порт того же
// элемента — в том числе на другой нитке колеи, в полутора метрах. Объявление
// одного намерения гасило бы чужой дефект.
//
// Сравнивается с телом порта, а не с точкой: грань разрыва объявлена ниткой
// (±gauge/2), а порт знает свой занятый отрезок, и попадание грани в него и есть
// «это та самая нитка».
func coveredByGap(p Port, gaps []Gap) bool {
	for _, g := range gaps {
		if g.Element != p.Element {
			continue
		}
		if p.U < g.From-StationEps || p.U > g.To+StationEps {
			continue
		}
		if g.Face < p.MetalFrom-RunningFaceTol || g.Face > p.MetalTo+RunningFaceTol {
			continue
		}
		return true
	}
	return false
}

// breaksError собирает отказ. Текст называет расстояние и ближайшего соседа:
// без них отказ сообщает «где-то не сошлось» и разбирать его приходится
// снимком, то есть ровно тем способом, от которого файл уводит.
func breaksError(owner string, breaks []Break) error {
	sort.Slice(breaks, func(i, j int) bool {
		if breaks[i].Port.Part != breaks[j].Port.Part {
			return breaks[i].Port.Part < breaks[j].Port.Part
		}
		return breaks[i].Port.End < breaks[j].Port.End
	})
	msg := fmt.Sprintf("track: сборка %s: несомкнутых портов %d", owner, len(breaks))
	for _, b := range breaks {
		switch {
		case b.Nearest.Part == "":
			msg += fmt.Sprintf("\n  %s[%s] на %s u=%.3f: примыкать не к чему — других портов нет",
				b.Port.Part, b.Port.End, b.Port.Element, b.Port.U)
		case b.Kind == BreakStep:
			// Отказ называет ОБА отрезка, а не только долю: доля говорит «плохо», а
			// отрезки — куда именно уехало тело.
			msg += fmt.Sprintf("\n  %s[%s] на %s u=%.3f: металл не продолжен — до [%.3f, %.3f], после [%.3f, %.3f], общего %.0f %% (нужно %.0f %%)",
				b.Port.Part, b.Port.End, b.Port.Element, b.Port.U,
				b.Port.MetalFrom, b.Port.MetalTo, b.Nearest.MetalFrom, b.Nearest.MetalTo,
				b.Overlap*100, MinMetalOverlap*100)
		default:
			msg += fmt.Sprintf("\n  %s[%s] на %s u=%.3f: с одной стороны металла нет вовсе; ближайший порт %s[%s] в %.4f м",
				b.Port.Part, b.Port.End, b.Port.Element, b.Port.U,
				b.Nearest.Part, b.Nearest.End, b.Distance)
		}
	}
	return fmt.Errorf("%s", msg)
}
