package track

import (
	"fmt"
	"math"
	"sort"
)

// track_rails.go — ПУТЕВЫЕ НИТКИ ДЕТАЛЯМИ: рельсы перегона порождает сервер.
//
// # Что здесь закончилось
//
// До 2026-08-17 рельсы обычного пути НЕ СУЩЕСТВОВАЛИ как данные. Сервер слал
// рецепт — прогон (тип решётки плюс интервалы по элементам), — а нитки строил
// клиент: брал ось участка и откладывал две символические линии на ±gauge/2.
// Контракт отрисовки §3 это прямо и предписывал.
//
// Оставалось это ровно до тех пор, пока рельс был линией. Как только у детали
// появилось тело — сечение, сторона роста, ходовая поверхность, — рецепт стал
// вторым автором формы: у стрелки рельсы уже приезжали поимёнными деталями, а
// у перегона рядом клиент по-прежнему выводил их сам. Два пути построения
// одного и того же в одном кадре, и разойтись они могли молча.
//
// Владелец закрыл вопрос одной фразой: «все рельсы должны генериться процедурно
// на сервере».
//
// # Почему по ПРОГОНАМ, а не по элементам
//
// Рельс лежит там, где авторинг положил решётку, и нигде больше. Элемент без
// прогона — это ось, у которой ещё нет пути: по ней ездит адресация, но металла
// на ней нет. Порождай мы нитки по элементам, карта в середине авторинга
// получала бы рельсы там, где автор их не клал, и отличить это от готовой было
// бы нечем.
//
// Проходы стрелок прогонами не покрываются по самой спеке (§6), и потому здесь
// не появляются: их детали кладёт turnout_running.go.
//
// # Одна деталь на спан, а не рельсовые плети
//
// Настоящий путь собран из плетей с зазорами, и стыки — не украшение: они
// греются, разряжаются, изолируют рельсовые цепи. Здесь их нет, и это
// ОБЪЯВЛЕННОЕ упрощение, а не забывчивость: длина плети и место стыка суть
// решения проекта пути, которых у нас нет ни в карте, ни в каталоге. Появятся
// вместе с генератором повторения (ClearAhead-ax7m.5), и тогда деталь сменится
// перечнем плетей — форма провода к этому готова, потому что деталь уже
// адресуется отрезком, а не целым элементом.

// buildTrackRails кладёт в геометрию нитки всех прогонов.
//
// Порядок вывода канонический — по элементу, грани и началу: обход прогонов
// зависит от порядка в карте, а хеш геометрии обязан зависеть от содержимого.
func buildTrackRails(rg *RenderGeometry) error {
	types := make(map[string]RenderTrackType, len(rg.TrackTypes))
	for _, t := range rg.TrackTypes {
		types[t.ID] = t
	}
	for _, run := range rg.ConstructionRuns {
		tt, ok := types[run.Type]
		if !ok {
			return fmt.Errorf("track: прогон %s: тип %q не разрешается — нитки построить не из чего",
				labeled(run.Name, run.ID), run.Type)
		}
		if tt.Gauge <= 0 {
			return fmt.Errorf("track: прогон %s: у типа %s колея %v", labeled(run.Name, run.ID), tt.ID, tt.Gauge)
		}
		half := tt.Gauge / 2
		for i, span := range run.Spans {
			from, to := span.From, span.To
			if to < from {
				// Направление спана — свойство ПРОГОНА (фаза шпал считается по
				// нему), а не нитки: рельс лежит одинаково, куда бы ни шёл отсчёт.
				from, to = to, from
			}
			if to <= from+RunningFaceTol {
				continue
			}
			// ДВЕ НИТКИ НА КАЖДЫЙ СПАН, и обе объявляются здесь поимённо. Левая
			// на +gauge/2, правая на −gauge/2; тело у обеих растёт ПРОЧЬ ОТ ОСИ —
			// рабочая грань смотрит в колею, металл уходит от неё.
			for _, side := range []float64{+1, -1} {
				rg.Rails = append(rg.Rails, RenderRailPart{
					ID:          fmt.Sprintf("%s|%d|%s", run.ID, i, sideName(side)),
					Element:     span.Element,
					Kind:        TrackRailRunning,
					Type:        run.Type,
					From:        from,
					To:          to,
					Face:        side * half,
					EndFaceFrom: side * half,
					EndFaceTo:   side * half,
					Grow:        math.Copysign(1, side*half),
				})
			}
		}
	}
	sortRails(rg.Rails)
	return nil
}

// sideName — имя нитки в идентификаторе детали. Левая и правая называются так
// же, как их откладывает показ: по левой нормали оси.
func sideName(side float64) string {
	if side > 0 {
		return "left"
	}
	return "right"
}

// sortRails — канонический порядок деталей: сперва перегонные (владельца нет),
// затем устройства, внутри — по элементу, виду и началу.
func sortRails(rails []RenderRailPart) {
	sort.Slice(rails, func(i, j int) bool {
		a, b := rails[i], rails[j]
		if a.Owner != b.Owner {
			return a.Owner < b.Owner
		}
		if a.Element != b.Element {
			return a.Element < b.Element
		}
		if a.Kind != b.Kind {
			return a.Kind < b.Kind
		}
		if a.From != b.From {
			return a.From < b.From
		}
		return a.ID < b.ID
	})
}

// labeled — метка рядом с идентификатором в текстах отказов. Своя, а не
// mapfmt.Labeled: сюда приезжает уже провод, а не карта.
func labeled(name, id string) string {
	if name == "" {
		return id
	}
	return name + " (" + id + ")"
}
