package track

// ride.go — ПОЛОСА НАКАТА: одно число на весь мир.
//
// # Что здесь закончилось
//
// До 2026-08-18 ширину наката объявляли ДВА места, и они отвечали по-разному.
//
// Сервер говорил метрами: BladeRideWidth = 0.035 у остряка, CastingRideWidth =
// 0.035 у сердечника, и довод стоял рядом — это след колеса, свойство
// подвижного состава, а не рельса.
//
// Клиент говорил долей головки: RAILHEAD_WIDTH = 0.72 в track_view.gd, то есть
// 0.054 м при головке 75 мм, и брал её у всякой нитки, которой сервер станций не
// прислал, — то есть у ВСЕГО перегона.
//
// В одном кадре, на стыке остряка с ниткой, сходились 35 мм и 54 мм. Расхождение
// в полтора раза видно глазом, и ни одно из чисел не было замером: серверное
// пришло из модели CA-1/9-R65-v1, клиентское — из отношения 0.062/0.071,
// снятого со снесённого спайка, у которого и головка была выдумана.
//
// Закон эпика ClearAhead-ax7m: ни один потребитель не принимает доменных
// решений о ходовой функции детали. Ширина наката — ровно про ходовую функцию:
// она говорит, ГДЕ ИДЁТ КОЛЕСО. Поэтому число здесь одно и едет с геометрией.
//
// # Почему на весь мир, а не на тип пути и не на деталь
//
// Потому что это след КОЛЕСА. Ширина полосы есть поперечный разбег колёсной
// пары плюс пятно контакта; ни то, ни другое не является свойством рельса, и
// рельс другого типа полосу не сдвинет. Поле у типа пути означало бы, что накат
// на подъездном пути предприятия и на главном разный по природе, а не по износу.
//
// ГДЕ ПОЛОСА ВСЁ-ТАКИ МЕНЯЕТСЯ ПО ДЛИНЕ — у остряка и сердечника, — она едет
// станциями (RenderSectionStation.RideWidth), и станция здешнее число замещает:
// там колесо принимает деталь постепенно, и это факт о ДЕТАЛИ, а не о колесе.
// Ноль в станции по-прежнему означает «колесо сюда не встаёт вовсе».
//
// # Статус числа: НАЗВАН ДИАПАЗОН, взято его число
//
// Владелец 2026-08-18 назвал норму: ширина полосы наката на головке рельса в
// НОРМАЛЬНОМ состоянии — от 20 до 40 мм, и проходит она примерно по центру
// головки.
//
// Это первый источник по накату за всю историю вопроса, и он тут же рассудил
// спор: серверные 35 мм лежат в диапазоне, клиентские 54 мм — вне его целиком.
// То есть доля головки была неверна не только по способу (показ решал, где идёт
// колесо), но и по числу.
//
// ВЗЯТО 35 ММ, А НЕ СЕРЕДИНА 30. Диапазон описывает разброс СОСТОЯНИЙ — свежий
// путь, изношенный, разная нагрузка, — а нам нужно одно число на весь мир.
// Внутри диапазона выбрано то, которое в проекте уже стояло с моделью
// CA-1/9-R65-v1 за спиной: менять его на середину значило бы завести НОВОЕ
// объявленное число там, где источник подтвердил старое. Ближе к верху
// диапазона оно и по существу: 35 мм — это накатанный путь под движением, а не
// только что уложенный.
//
// ПОЛОСА ПО ЦЕНТРУ ГОЛОВКИ, и это тоже из источника. Положение полосы —
// диагностика подуклонки: смещение к наружному краю означает избыточную
// подуклонку, к внутреннему — недостаточную либо боковые силы. Центр значит
// «подуклонка нормальная», и это ОБЪЯВЛЕНИЕ, а не отсутствие мысли: подуклонки
// в модели пути у нас нет вовсе (рельс стоит вертикально), и когда она появится,
// смещение полосы станет её видимым следствием, а не отдельным числом.
// Центрирование делает head_bands в клиенте: band_i = (head − band) / 2.
//
// ЧЕГО ИСТОЧНИК НЕ РЕШАЕТ. Он же называет ширину верха головки — Р50 70.2, Р65
// 73.0, Р75 72.0 мм, — а затравочный тип объявляет 75. Расхождение сюда НЕ
// переносится, и вот почему: у Р75, рельса более тяжёлого, число вышло меньше
// Р65, то есть меряются разные вещи (ширина верхней ПЛОЩАДКИ против полной
// ширины головки по выкружкам) либо разные редакции сортамента. Разбираться с
// этим — отдельный вопрос к чертежу, и решать его молча, попутно, значило бы
// сдвинуть колею всех карт ради числа, происхождение которого не выяснено.
//
// # ЧТО ЗДЕСЬ СТОЯЛО ДО ЭТОГО ИСТОЧНИКА, и почему запись остаётся
//
// Первая редакция этого файла (тот же день, часом раньше) выбрала 0.054 и
// привела три довода: широкое число обрезается сечением острогана само; 0.035
// оставили бы по 20 мм ржавчины с каждой стороны; 0.054 — то, что стоит в кадре
// сегодня.
//
// Первый довод верен и остаётся в силе — он про механику обрезки, а не про
// число. Второй и третий опровергнуты: 20 мм ржавчины с каждой стороны и есть
// нормальный вид головки при полосе 35 мм на 75-миллиметровой головке, а «стоит
// в кадре сегодня» доказывало ровно то, что и было дефектом, — что число выбрал
// показ.
//
// Запись оставлена, потому что это второй за сутки случай, когда правдоподобное
// рассуждение о числе разошлось с источником в полтора раза. Правило проекта
// (числа проверяются замером, а не рассуждением) написано про такие случаи, и
// здесь оно сработало ровно так, как задумано: сперва число было названо
// объявленным и посажено в одно место, а через час источник его поправил одной
// правкой.
//
// # ФАСКА ПРИЕХАЛА СЮДА ЖЕ, и первая редакция ошиблась, оставив её показу
//
// Час назад здесь было записано, что фаска остаётся в клиенте: она-де вопрос
// материала, а не металла, и отвечает не на «где идёт колесо», а на «каким
// цветом стыкуются полосы».
//
// Владелец отменил это одной фразой: «у клиента вообще такой информации быть не
// должно, только на сервере». И он прав по существу, а не только по праву. У
// фаски есть ШИРИНА, то есть размер детали; в клиенте она к тому же стояла
// ДОЛЕЙ головки — 0.075, — и это ровно тот способ записи, ради отмены которого
// накат сюда и переезжал: доля не единица СИ, а отношение к числу, которое
// живёт в другом месте.
//
// Довод «это материал, а не металл» не спасает: даже если фаска не режет тело
// рельса, она говорит, ГДЕ КОНЧАЕТСЯ СЛЕД КОЛЕСА и начинается нетронутая
// поверхность. Это утверждение о ходовой функции — того же класса, что сам
// накат.

const (
	// RailRideWidth — ширина чистой полосы наката поверху головки, метры.
	//
	// ЧИСТОЙ значит без окаймления: у настоящей головки край скруглён, колесо
	// задевает его вскользь, и полоса там не зеркальная и не ржавая. Это
	// окаймление — RailFilletWidth ниже.
	RailRideWidth = 0.035

	// RailFilletWidth — ширина фаски С КАЖДОЙ СТОРОНЫ наката, метры.
	//
	// Заведена 2026-08-16 словом владельца: «переход какой-то должен быть, не
	// может же быть ржавчина и тут же уже накат». По существу верно: край
	// головки скруглён, колесо задевает его вскользь, и полоса там серая,
	// потёртая — ни зеркало, ни ржавчина.
	//
	// МЕТРАМИ, А НЕ ДОЛЕЙ ГОЛОВКИ, и это правка того же дня. В клиенте стояло
	// 0.075 доли, что при головке 75 мм давало 5.6 мм. Доля тут была не единицей
	// измерения, а ссылкой на чужое число, и стоило головке приехать другой —
	// фаска ехала следом без всякого основания: скругление края головки задаётся
	// профилем проката, а не пропорцией.
	//
	// ЧИСЛО ОБЪЯВЛЕНО и округлено до 6 мм с прежних 5.6: разница ниже того, что
	// различимо в кадре, а круглое число не изображает точности, которой у
	// источника нет. Источника у фаски нет вовсе — в отличие от наката, которому
	// владелец назвал норму 20…40 мм: чертёж скругления головки задаёт радиусами
	// выкружек, а не шириной потёртой полоски.
	//
	// Сумма на затравочном рельсе: 35 наката + 2 × 6 фаски = 47 мм из 75.
	RailFilletWidth = 0.006
)
