// blade.go — ОСТРЯКИ СТРЕЛКИ: какая нитка каждого прохода подвижна.
//
// # Зачем это на сервере
//
// Тот же довод, что у крестовины (frog.go) и брусьев (timbers.go): «какая из
// четырёх ниток подвижна» выводится из рукости и колеи, и два клиента,
// выводящие это порознь, дадут два разных ответа. Здесь довод даже сильнее: у
// крестовины расхождение дало бы кривую картинку, а тут — стрелку, которая у
// одного клиента переводится, а у другого нет.
//
// # Какие нитки подвижны, и почему это ровно те же две
//
// Остряк лежит НА ВНУТРЕННЕЙ нитке своего прохода — на той, что смотрит в
// сторону соседнего прохода. У правой стрелки это прямой проход на −gauge/2 и
// боковой на +gauge/2; у левой наоборот. Те же самые две нитки пересекаются в
// крестовине (§5), и это не совпадение: остряк и крестовина — начало и конец
// одной пары.
//
// # Остряк — ДЕТАЛЬ, а не подвижный участок нитки (переделано 2026-08-16)
//
// Сперва было проще: остряк — это отрезок нитки своего прохода, который клиент
// отводит в сторону. Читалось стройно, а в кадре давало кашу, и вот почему.
//
// Прижатый остряк занимал ровно тот объём, что рамный рельс, — значит рамного
// рельса не существовало вовсе, его роль играл сам остряк. При переводе он
// уезжал, и на освободившемся месте оставалась НАРУЖНАЯ НИТКА СОСЕДНЕГО
// ПРОХОДА, которая там оказалась случайно: проходы выходят из одной точки одним
// курсом, и пока оси разошлись меньше ширины головки, два рельса занимают один
// объём. Замер по ST_A: R = 300 м, головка 0.075 м — 6.7 метра взаимного
// проникновения, видимых дракой за z-буфер.
//
// Теперь остряк — СВОЁ тело: рабочая грань там же (±gauge/2 своего прохода),
// а растёт оно К ОСИ, внутрь колеи. Прижатый лежит вплотную к неподвижному
// рамному рельсу, отведённый отходит от него на ход — как на настоящем
// переводе. Рамными рельсами стали обе нитки ПРЯМОГО прохода: они больше не
// двигаются вовсе.
//
// Второе следствие: у бокового прохода на участке остряка СВОИХ НИТОК НЕТ. У
// настоящего перевода их там тоже нет — колесо идёт по рамному рельсу и
// остряку, а рельсы бокового пути начинаются за корнем. Это и уезжает разрывами
// (RenderTurnoutRailGap).
//
// # Чего здесь нет
//
// Криволинейного остряка, строжки, упорных накладок, контррельсов и связных
// тяг. Отвод принят линейным по длине (объявление — у mapfmt.TrackSwitch), и
// длина остряка приходит от ТИПА ПУТИ, а не от марки. Оба приближения названы
// там же, где заведены, и снимутся вместе с каталогом типов устройств
// (ClearAhead-qyf).
//
// Нет и сужения остряка к острию: настоящий острогается на клин и в острие
// ниже головки рамного рельса. У нас он полного сечения по всей длине — видно
// вплотную, не видно с десяти метров.

// BladeRootJoint — длина корневых накладок, метры, и то, чем закрыт стык.
//
// # Нахлёста рельсов в корне НЕТ (переделано 2026-08-16)
//
// Сперва шов закрывался нахлёстом: нитка захо́дила под остряк на 0.8 м. Это
// снимало скачок формы, но означало ДВА ПОЛНЫХ РЕЛЬСА в одном месте — то, чего
// на переводе не бывает. Правильно иначе: остряк к корню уже вышел на полное
// сечение (модель CA-1/9-R65-v1: полная ширина головки с u = 6.00 м), поэтому
// торцы сходятся ВСТЫК на одном u, а стык держат накладки — отдельные тела
// сбоку шейки, не дублирующие ни головку, ни подошву.
//
// Накладка симметрична стыку: по 0.4 м в каждую сторону.
const BladeRootJoint = 0.8

// buildTurnoutBlades считает остряки каждой стрелки и кладёт их в геометрию.
//
// Порядок вывода — по владельцу и ветви: у карты нет причин отдавать стрелки в
// порядке обхода, а хеш геометрии обязан зависеть от содержимого, а не от него.
func buildTurnoutBlades(m *mapfmt.Map, els map[string]Element, rg *RenderGeometry) error {
	c := m.Construction
	if c == nil {
		// Без блока construction нет ни типа, ни колеи — значит нечем сказать, на
		// какой нитке лежит остряк. То же молчание, что у крестовины и привода:
		// чего измерить нечем, того не отдаём.
		return nil
	}
	types := make(map[string]mapfmt.TrackType, len(c.Types))
	for i := range c.Types {
		types[c.Types[i].ID] = c.Types[i]
	}
	for _, t := range m.Topology.Turnouts {
		dt, err := m.TurnoutTypeByID(t.TurnoutType)
		if err != nil {
			return fmt.Errorf("track: стрелка %s: %w", mapfmt.Labeled(t.Name, t.ID), err)
		}
		bs, gaps, err := turnoutBlades(els, types, c, t, dt)
		if err != nil {
			return fmt.Errorf("track: стрелка %s: %w", mapfmt.Labeled(t.Name, t.ID), err)
		}
		rg.TurnoutBlades = append(rg.TurnoutBlades, bs...)
		rg.TurnoutRailGaps = append(rg.TurnoutRailGaps, gaps...)
	}
	sort.Slice(rg.TurnoutBlades, func(i, j int) bool {
		a, b := rg.TurnoutBlades[i], rg.TurnoutBlades[j]
		if a.Owner != b.Owner {
			return a.Owner < b.Owner
		}
		return a.Branch < b.Branch
	})
	return nil
}

// sortRailGaps — канонический порядок разрывов: (owner, element, offset, from).
//
// Зовётся ПОСЛЕ всех, кто разрывы кладёт: их два источника — остряк и сердечник,
// — и сортировка внутри каждого дала бы порядок, зависящий от того, кого позвали
// первым. Хеш геометрии считается от байтов ответа, и такой порядок стал бы
// хешем порядка вызовов, а не содержимого.
func sortRailGaps(rg *RenderGeometry) {
	sort.Slice(rg.TurnoutRailGaps, func(i, j int) bool {
		a, b := rg.TurnoutRailGaps[i], rg.TurnoutRailGaps[j]
		if a.Owner != b.Owner {
			return a.Owner < b.Owner
		}
		if a.Element != b.Element {
			return a.Element < b.Element
		}
		if a.Offset != b.Offset {
			return a.Offset < b.Offset
		}
		return a.From < b.From
	})
}

// threadPeelU — где наружная нитка бокового прохода ОТСЛАИВАЕТСЯ от рамного
// рельса: первое u, на котором она отошла от одноимённой нитки прямого прохода
// на ширину головки.
//
// # Почему ширина головки, а не ноль и не колея
//
// Пока расхождение меньше головки, два рельса занимают один объём — рисовать там
// два значит рисовать один дважды. Как только расхождение сравнялось с головкой,
// они стоят вплотную и дальше расходятся: нитка начинается касаясь рамного
// рельса, и шва в кадре нет.
//
// # Почему двоичным поиском, а не формулой
//
// Расхождение считается по ПОСТРОЕННЫМ осям, а у них начальный угол остряка и две
// дуги разного радиуса. Замкнутая формула была бы третьим описанием той же кривой
// и разошлась бы с ней при первой правке эпюры.
//
// Монотонность расхождения здесь не предполагается доказанной, а обеспечивается
// доменом: поиск идёт по участку остряка, где проходы только расходятся.
func threadPeelU(els map[string]Element, t mapfmt.Turnout, passage string, offset, head, length float64) (float64, error) {
	dv, ok := els[passage]
	if !ok {
		return 0, fmt.Errorf("проход %s не скомпилирован", passage)
	}
	st, ok := els[t.ID+mapfmt.PassageStraight]
	if !ok {
		return 0, fmt.Errorf("прямой проход стрелки не скомпилирован")
	}
	// ДОМЕН ПОИСКА ОГРАНИЧЕН ОБОИМИ ПРОХОДАМИ. Остряк обрезан длиной своего
	// прохода (выше), но прямой проход бывает короче бокового, а расхождение
	// меряется по обоим. Карта, доехавшая сюда мимо валидатора, не должна ронять
	// компилятор выходом за цепочку — тот же довод, что у обрезки остряка.
	if l := dv.Plan.Length().Meters(); length > l {
		length = l
	}
	if l := st.Plan.Length().Meters(); length > l {
		length = l
	}
	apart := func(u float64) (float64, error) {
		du, err := units.MetersToDistance(u)
		if err != nil {
			return 0, err
		}
		a, err := threadPoint(dv, offset, du)
		if err != nil {
			return 0, err
		}
		b, err := threadPoint(st, offset, du)
		if err != nil {
			return 0, err
		}
		return math.Hypot(a.X-b.X, a.Y-b.Y), nil
	}
	// Разошлись уже на конце остряка — отслаивание не наступает вовсе, и нитка
	// начинается там же, где кончается остряк. Это законный случай пологой марки,
	// а не поломка.
	if d, err := apart(length); err != nil {
		return 0, err
	} else if d < head {
		return length, nil
	}
	lo, hi := 0.0, length
	for i := 0; i < 60; i++ {
		mid := (lo + hi) / 2
		d, err := apart(mid)
		if err != nil {
			return 0, err
		}
		if d < head {
			lo = mid
		} else {
			hi = mid
		}
	}
	return hi, nil
}

// threadPoint — точка нитки на выносе offset в координате u.
func threadPoint(el Element, offset float64, u units.Distance) (geom.Pose, error) {
	p, err := el.Plan.PoseAt(el.Start.Plan, u)
	if err != nil {
		return geom.Pose{}, err
	}
	nx, ny := -math.Sin(p.Heading), math.Cos(p.Heading)
	return geom.Pose{X: p.X + nx*offset, Y: p.Y + ny*offset, Heading: p.Heading}, nil
}

// turnoutBlades считает пару остряков одной стрелки и разрывы ниток, которые из
// них следуют.
//
// Одной функцией, а не двумя: разрыв ниток бокового прохода кончается ровно там,
// где кончается остряк, и посчитай их порознь — два ответа на вопрос «где корень»
// разъехались бы у первой же карты с коротким проходом, где остряк обрезан.
func turnoutBlades(els map[string]Element, types map[string]mapfmt.TrackType,
	c *mapfmt.Construction, t mapfmt.Turnout, dt mapfmt.TurnoutType) ([]RenderTurnoutBlade, []RenderTurnoutRailGap, error) {
	typ := t.Type
	if typ == "" {
		typ = c.DefaultType
	}
	tt, ok := types[typ]
	if !ok {
		return nil, nil, fmt.Errorf("тип %q не разрешается — колею и остряк взять неоткуда", typ)
	}
	// ОСТРЯК БЕРЁТСЯ У ТИПА УСТРОЙСТВА, А КОЛЕЯ — У ТИПА ПУТИ, и это разные
	// источники по существу: рельс Р65 лежит и в 1/9, и в 1/11, а длина остряка
	// у них разная. До 2026-08-16 оба числа жили у типа пути, и на карте с двумя
	// марками обе получали один остряк.
	half := tt.Gauge / 2

	// Внутренние нитки — те же, что пересекаются в крестовине (§5).
	var offS, offD float64
	switch t.Hand {
	case mapfmt.HandRight:
		offS, offD = -half, +half
	case mapfmt.HandLeft:
		offS, offD = +half, -half
	default:
		return nil, nil, fmt.Errorf("рукость %q, ожидается right или left", t.Hand)
	}

	// Проходы спрашиваются У САМОЙ СТРЕЛКИ (Passages), а не собираются из
	// суффиксов: это единственное место, где записано, какие проходы у неё есть,
	// и второй сборки имён проект не держит.
	out := make([]RenderTurnoutBlade, 0, 2)
	gaps := make([]RenderTurnoutRailGap, 0, 2)
	for _, p := range t.Passages() {
		offset := offS
		if p.ID == t.ID+mapfmt.PassageDiverging {
			offset = offD
		}
		el, ok := els[p.ID]
		if !ok {
			return nil, nil, fmt.Errorf("проход %s не скомпилирован", mapfmt.Labeled(t.Name, p.ID))
		}
		// ОСТРЯК НЕ ДЛИННЕЕ ТОГО, НА ЧЁМ ЛЕЖИТ. Длина приходит от типа пути, а
		// проход — от геометрии устройства, и у короткого перевода второе меньше
		// первого. Обрезка честнее отказа: карта законна, а остряк во всю длину
		// прохода — это по-прежнему остряк.
		// ДЛИНА СВОЯ У КАЖДОЙ ВЕТВИ: кривой остряк длиннее прямого, потому что
		// мерится по дуге (у проекта 2434 — 6.515 против 6.500).
		length := dt.Switch.BladeLengthStraight
		if p.ID == t.ID+mapfmt.PassageDiverging {
			length = dt.Switch.BladeLengthDiverging
		}
		if l := el.Plan.Length().Meters(); length > l {
			length = l
		}
		out = append(out, RenderTurnoutBlade{
			Owner:   t.ID,
			Passage: p.ID,
			Branch:  p.Branch,
			Offset:  offset,
			Length:  length,
			Throw:   dt.Switch.Throw,
			// Тело растёт К ОСИ — против знака выноса. Остряк лежит ВНУТРИ колеи и
			// прижимается к рамному рельсу гранью; расти наружу ему некуда, там сам
			// рамный рельс (разбор — в шапке файла).
			// ТЕЛО РАСТЁТ НАРУЖУ, как у всякого рельса: рабочая грань смотрит
			// внутрь колеи, там едет колесо, металл уходит в другую сторону.
			//
			// До 2026-08-16 стояло обратное — тело росло К ОСИ, — и довод был
			// такой: иначе остряк лезет в рамный рельс. Довод был верен для той
			// модели и неверен по существу. Замер: при росте наружу проникновение
			// доходило до 100 мм, при росте к оси — до 52 мм, и НИ ОДНА постоянная
			// сторона не годилась. Неверна была не сторона, а профиль.
			//
			// С ОР65 вопрос снят: остряк ниже рамного рельса на 40 мм и лежит на
			// стрелочной подушке в ту же толщину, поэтому подошвы расходятся ПО
			// ВЫСОТЕ, а не в плане. В корне тело остряка (132 мм) целиком
			// укладывается в тело закорневой нитки (150 мм) — как и положено стыку.
			Grow: math.Copysign(1, offset),
			// Строжка считается ЗДЕСЬ, а не у клиента, и умножается на головку
			// ЭТОГО типа пути: до 2026-08-16 таблица жила константой класса Blade
			// в клиенте и кончалась на 0.075 — ширине головки затравочного типа,
			// то есть несла необъявленное допущение про рельс. Разбор —
			// blade_section.go.
			// Профиль и строжка — ОБА от типа устройства: остряк катают из ОР65,
			// и масштабировать строжку головкой путевого рельса значило бы мерить
			// одну деталь чужой линейкой.
			Rail:    renderRail(dt.BladeRail),
			Section: bladeSection(dt.BladeRail),
		})
		// РАЗРЫВЫ НИТОК БОКОВОГО ПРОХОДА, И У ДВУХ ЕГО НИТОК ОНИ РАЗНЫЕ.
		//
		// Прямой проход своих ниток не теряет: это и есть рамные рельсы, они лежат
		// от острия до конца перевода и никуда не деваются.
		//
		// ВНУТРЕННЯЯ нитка бокового кончается там же, где остряк: остряк ЕСТЬ эта
		// нитка на своём протяжении, за корнем её продолжает закорневой рельс.
		//
		// НАРУЖНАЯ — иначе, и до 2026-08-16 здесь была ошибка. Разрыв ей клали по
		// длине остряка, и нитка возникала в корне В ПУСТОТЕ: замер дал 0.227 м до
		// ближайшего металла. У настоящего перевода наружная нить бокового пути НЕ
		// НАЧИНАЕТСЯ — она ОТСЛАИВАЕТСЯ от рамного рельса там, где расхождение
		// перестаёт быть меньше рельса. Так это нарисовано на всякой схеме
		// перевода, и так это на фотографии горловины.
		//
		// Поэтому её разрыв кончается ПО ГЕОМЕТРИИ, а не по длине остряка: в
		// точке, где нитки разошлись на ширину головки. На затравке это 2.647 м
		// против 6.515 м корня. Там нитка начинается ВПЛОТНУЮ к рамному рельсу, и
		// шва в кадре нет.
		if p.ID != t.ID+mapfmt.PassageDiverging || length <= 0 {
			continue
		}
		inner, outer := offD, -offD
		gaps = append(gaps, RenderTurnoutRailGap{
			Owner: t.ID, Element: p.ID, Kind: GapStock,
			Offset: inner, From: 0, To: length,
		})
		peel, err := threadPeelU(els, t, p.ID, outer, tt.Rail.HeadWidth, length)
		if err != nil {
			return nil, nil, err
		}
		gaps = append(gaps, RenderTurnoutRailGap{
			Owner: t.ID, Element: p.ID, Kind: GapStock,
			Offset: outer, From: 0, To: peel,
		})
	}
	return out, gaps, nil
}
