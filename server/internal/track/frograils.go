// frograils.go — УСОВИКИ И КОНТРРЕЛЬСЫ: нитки, лежащие вокруг крестовины.
//
// # Что здесь считается
//
// Четыре коротких нитки на устройство: два усовика и два контррельса. Каждая —
// отрезок вдоль ОДНОГО прохода, с постоянным выносом рабочей грани и отгибами на
// обоих концах.
//
// Место берётся у самой крестовины (buildFrogFeatures): её адреса называют u
// точки пересечения НА КАЖДОМ проходе, и вокруг этих двух u всё и строится.
// Второго вычисления точки крестовины не заводится — оно уже сделано, и два
// ответа на один вопрос разошлись бы.
//
// # Анатомия, и что из неё выражено
//
// Нитки прохода в крестовине ПЕРЕСЕКАЮТСЯ — это и есть сердечник у нас: две
// нитки, сходящиеся в точку. Настоящий сердечник — цельная отливка с горлом и
// хвостом, и она НЕ выражена; из чисел типа её форма не выводится.
//
// УСОВИК показан отдельной ниткой СНАРУЖИ нитки прохода, отделённой желобом.
// У настоящего усовик — это сама нитка, отведённая наружу; здесь она добавлена
// рядом. Приближение видно с двух метров и не видно с двадцати; названо оно
// затем, чтобы день, когда его будут снимать, начинался не с раскопок.
//
// КОНТРРЕЛЬС показан ниткой ВНУТРИ противоположной нитки того же прохода — там
// он и лежит на самом деле, и здесь приближения нет, кроме отгиба прямой линией
// вместо кривой.
//
// # Почему это уровень 3, и почему потребитель появился
//
// Спека §4 относит контррельсы к уровню 3 — «заводится только при появлении
// конкретного потребителя». Потребитель назван владельцем 2026-08-16: на вопрос
// «что за красное пятно» — снимок настоящей крестовины и «делаем вот так».
// Красным пятном была плоская метка теоретической точки, приём схемы сверху.

// FrogPointOffset — на сколько ФИЗИЧЕСКОЕ ОСТРИЁ сердечника отстоит от
// математической точки крестовины, метры.
//
// У настоящей крестовины остриё не бывает острым: его срезают до ширины 9–12 мм,
// и приходится эта ширина на 80–120 мм позади точки пересечения граней. Перед
// остриём металла сердечника НЕТ — там горло между усовиками, и колесо идёт по
// ним.
//
// Число ОБЪЯВЛЕНО, а не выведено: ширина острия — свойство марки и технологии
// отливки, а марки в карте нет. Десять сантиметров — середина названного
// диапазона; при угле 1/9 они дают остриё шириной 11 мм.
const FrogPointOffset = 0.10

// Нахлёста у крестовины НЕТ: внутренняя нитка не существует на всём протяжении
// от начала усовика до хвоста сердечника, и стыкуются они встык (модель
// CA-1/9-R65-v1, §Д). Нахлёст в 0.15 м, стоявший здесь до 2026-08-16, прятал
// открытый торец ценой двойного рельса.

// buildTurnoutFrogRails считает нитки крестовины каждой стрелки.
//
// Зовётся ПОСЛЕ buildFrogFeatures и читает её результат: адреса крестовины уже
// посчитаны, и считать их заново значило бы завести второй ответ.
func buildTurnoutFrogRails(m *mapfmt.Map, els map[string]Element, rg *RenderGeometry) error {
	c := m.Construction
	if c == nil {
		return nil
	}
	types := make(map[string]mapfmt.TrackType, len(c.Types))
	for i := range c.Types {
		types[c.Types[i].ID] = c.Types[i]
	}
	// Крестовины по владельцу: их только что посчитал buildFrogFeatures.
	frogs := make(map[string]RenderFeature, len(m.Topology.Turnouts))
	for _, f := range rg.Features {
		if f.Kind == FeatureFrog {
			frogs[f.Owner] = f
		}
	}
	for _, t := range m.Topology.Turnouts {
		f, ok := frogs[t.ID]
		if !ok {
			// Крестовины нет — считать не от чего. Молчание то же, что у привода
			// без блока construction: чего измерить нечем, того не отдаём.
			continue
		}
		rails, gaps, err := frogRails(els, types, c, t, f)
		if err != nil {
			return fmt.Errorf("track: стрелка %s: %w", mapfmt.Labeled(t.Name, t.ID), err)
		}
		rg.TurnoutRails = append(rg.TurnoutRails, rails...)
		rg.TurnoutRailGaps = append(rg.TurnoutRailGaps, gaps...)
	}
	sort.Slice(rg.TurnoutRails, func(i, j int) bool {
		a, b := rg.TurnoutRails[i], rg.TurnoutRails[j]
		if a.Owner != b.Owner {
			return a.Owner < b.Owner
		}
		if a.Element != b.Element {
			return a.Element < b.Element
		}
		return a.Kind < b.Kind
	})
	return nil
}

// frogRails считает нитки одной крестовины и разрывы ниток проходов под её
// сердечником.
//
// Разрывы считаются здесь же, а не отдельным проходом, по доводу остряка: конец
// разрыва есть конец отливки, и второе вычисление той же величины разошлось бы с
// первым у первой же карты.
func frogRails(els map[string]Element, types map[string]mapfmt.TrackType,
	c *mapfmt.Construction, t mapfmt.Turnout, f RenderFeature) ([]RenderTurnoutRail, []RenderTurnoutRailGap, error) {
	typ := t.Type
	if typ == "" {
		typ = c.DefaultType
	}
	tt, ok := types[typ]
	if !ok {
		return nil, nil, fmt.Errorf("тип %q не разрешается — крестовину отмерить нечем", typ)
	}
	if tt.Frog == nil {
		return nil, nil, fmt.Errorf("у типа %s нет блока frog", mapfmt.Labeled(tt.Name, typ))
	}
	fr := tt.Frog
	half := tt.Gauge / 2

	// Какая нитка прохода ВНУТРЕННЯЯ — та, что образует крестовину. Те же две,
	// что подвижны у остряка (blade.go) и что пересекаются в frogFeature: одна
	// пара ниток на всё устройство.
	inner := map[string]float64{}
	switch t.Hand {
	case mapfmt.HandRight:
		inner[t.ID+mapfmt.PassageStraight] = -half
		inner[t.ID+mapfmt.PassageDiverging] = +half
	case mapfmt.HandLeft:
		inner[t.ID+mapfmt.PassageStraight] = +half
		inner[t.ID+mapfmt.PassageDiverging] = -half
	default:
		return nil, nil, fmt.Errorf("рукость %q, ожидается right или left", t.Hand)
	}

	out := make([]RenderTurnoutRail, 0, 6)
	gaps := make([]RenderTurnoutRailGap, 0, 2)
	for _, a := range f.Addresses {
		in, ok := inner[a.Element]
		if !ok {
			return nil, nil, fmt.Errorf("адрес крестовины на элементе %s, который не проход этой стрелки", a.Element)
		}
		el, ok := els[a.Element]
		if !ok {
			return nil, nil, fmt.Errorf("проход %s не скомпилирован", a.Element)
		}
		length := el.Plan.Length().Meters()
		// НАРУЖУ — прочь от оси прохода: знак внутренней нитки и есть эта сторона.
		side := 1.0
		if in < 0 {
			side = -1.0
		}
		// УСОВИК — ОТОГНУТАЯ НИТКА, А НЕ РЕЙКА РЯДОМ С НЕЙ (переделано 2026-08-16).
		//
		// Прежде усовик лежал отдельной короткой ниткой снаружи, а сама нитка
		// прохода шла под ним насквозь: в кадре два рельса в ладони друг от друга.
		// У настоящей крестовины усовика как отдельной детали нет вовсе — это САМА
		// нитка, отведённая наружу перед сердечником и возвращающаяся за ним.
		//
		// Выражается это тем же отгибом, что и был, только концы усовика теперь
		// садятся РОВНО НА НИТКУ (EndFace = in), а нитка на его протяжении
		// вырезается. Тогда металл идёт непрерывно: нитка — отгиб — рабочая часть с
		// желобом — отгиб — нитка.
		wing := RenderTurnoutRail{
			Owner:   t.ID,
			Element: a.Element,
			Kind:    FrogRailWing,
			Face:    in + side*fr.Flangeway,
			EndFace: in,
			Grow:    side,
		}
		setSpan(&wing, a.U, fr.WingLength, fr.Flare, length)
		// КОНТРРЕЛЬС: у ПРОТИВОПОЛОЖНОЙ нитки того же прохода, ВНУТРИ колеи.
		//
		// Желоб у него — между ним и рабочей ниткой, поэтому рабочая грань
		// смотрит НАРУЖУ, на нитку, а тело растёт К ОСИ: наружу ему расти
		// некуда, там сама нитка.
		//
		// Он ОСТАЁТСЯ отдельной деталью, в отличие от усовика: контррельс и на
		// настоящем переводе прикручен к своей нитке сбоку, а не является ею.
		opp := -in
		oside := -side // сторона противоположной нитки
		check := RenderTurnoutRail{
			Owner:   t.ID,
			Element: a.Element,
			Kind:    FrogRailCheck,
			Face:    opp - oside*fr.CheckFlangeway,
			EndFace: opp - oside*fr.FlareGap,
			Grow:    -oside,
		}
		setSpan(&check, a.U, fr.CheckLength, fr.Flare, length)
		// СЕРДЕЧНИК НАЧИНАЕТСЯ ЗА МАТЕМАТИЧЕСКОЙ ТОЧКОЙ, А НЕ ВОКРУГ НЕЁ.
		//
		// Это вторая половина той же ошибки. Отливка клалась симметрично точке
		// пересечения — по 0.9 м в обе стороны, — то есть металл стоял и ТАМ, ГДЕ
		// ДОЛЖНО БЫТЬ ГОРЛО: перед сердечником нитки расходятся усовиками, и
		// сплошного металла между ними нет.
		//
		// У настоящей крестовины остриё отстоит от математической точки на 80–120 мм
		// и имеет там ширину 9–12 мм; дальше отливка расширяется как 2·s·tan(α/2),
		// то есть у марки 1/9 примерно 0.111·s. Ширину даёт само расхождение граней,
		// считать её незачем — она получается из геометрии проходов. Отдельно
		// объявлено только НАЧАЛО (FrogPointOffset) и длина хвоста.
		casting := RenderTurnoutRail{
			Owner:   t.ID,
			Element: a.Element,
			Kind:    FrogRailCasting,
			Face:    in,
			EndFace: in,
			Grow:    side,
		}
		// Не setSpan: тот кладёт отрезок СИММЕТРИЧНО вокруг точки, а сердечник
		// лежит только за ней.
		casting.From = a.U + FrogPointOffset
		casting.To = a.U + FrogPointOffset + 2*fr.CastingLength
		if casting.To > length {
			casting.To = length
		}
		casting.Flare = 0
		out = append(out, wing, check, casting)
		// НИТКИ ПОД ОТЛИВКОЙ НЕТ, и это главная правка крестовины 2026-08-16.
		//
		// Сердечник заводился как перемычка МЕЖДУ гранями, но сами нитки под ним
		// оставались и по-прежнему шли сквозь друг друга: отливка легла поверх
		// пересечения, а не вместо него. В кадре это семь тел в пятне четыре метра
		// — то, что владелец назвал кашей.
		//
		// Разрыв идёт ОТ НАЧАЛА УСОВИКА ДО ХВОСТА ОТЛИВКИ: на этом протяжении
		// нитки нет ни метра — сперва её заменяет собой усовик (он и есть она,
		// отведённая), потом сердечник. Границы берутся у них же, чтобы второго
		// ответа на вопрос «докуда» не завелось.
		//
		from := wing.From
		to := casting.To
		gaps = append(gaps, RenderTurnoutRailGap{
			Owner:   t.ID,
			Element: a.Element,
			Kind:    GapCasting,
			Offset:  in,
			From:    from,
			To:      to,
		})
	}
	return out, gaps, nil
}

// setSpan кладёт нитку симметрично вокруг точки крестовины и прижимает её к
// элементу.
//
// ПРИЖИМАЕТ, А НЕ ОТКАЗЫВАЕТ: длина нитки приходит от ТИПА ПУТИ, а проход — от
// геометрии устройства, и связи между ними нет. У короткого перевода контррельс
// не помещается целиком, и обрезка честнее отказа — тот же довод, что у остряка
// (blade.go). Отгиб при этом не растягивается: он свойство конца нитки, а не
// доля её длины.
func setSpan(r *RenderTurnoutRail, at, length, flare, elementLength float64) {
	half := length / 2
	from := at - half
	to := at + half
	if from < 0 {
		from = 0
	}
	if to > elementLength {
		to = elementLength
	}
	r.From = from
	r.To = to
	r.Flare = flare
	// Отгиб не длиннее половины того, что осталось: иначе два отгиба
	// перекрылись бы и нитка вывернулась бы серединой наружу.
	if half := (to - from) / 2; r.Flare > half {
		r.Flare = half
	}
}
