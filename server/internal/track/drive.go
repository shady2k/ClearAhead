// drive.go — ПЕРЕВОДНОЙ МЕХАНИЗМ СТРЕЛКИ: где он стоит и какой он.
//
// # Что здесь считается, а что нет
//
// Считается МЕСТО: у какого прохода, на каком u и на сколько в сторону от оси
// стоит станина привода вместе с указателем и табличкой. Место — факт о
// станции: два клиента, каждый выводящий его из топологии сам, дадут два разных
// ответа, и это ровно тот довод, по которому сервер считает крестовину (§5) и
// брусья (timbers.go).
//
// НЕ считается ТЕЛО: высота станины, размер противовеса, толщина щитка
// указателя, размер таблички. Это решения художника того же класса, что длина
// крыла крестовины (контракт отрисовки §1, таблица владения): пока привод —
// нарисованный клиентом предмет, а не ассет, его размеры принадлежат клиенту.
// День, когда появится каталог ассетов, заберёт их у него вместе с крестовиной.
//
// # Сторона выбирается, а не пишется автором
//
// Привод стоит С НАРУЖНОЙ стороны, противоположной сходу: между расходящимися
// путями его ставить некуда — там сходятся два габарита, и человек, который
// переводит стрелку рукой, стоял бы в междупутье.
//
// Сторона выведена ИЗ ГЕОМЕТРИИ (расхождение осей), а не из t.Hand, и это то же
// решение, что в timbers.go: рукость — авторская пометка о том, куда уходит
// боковой путь, а брусья и привод обязаны согласоваться с тем, куда он уходит
// НА САМОМ ДЕЛЕ. Разойдись они — привод встал бы посреди бокового пути, и
// причину пришлось бы искать в двух источниках вместо одного.
//
// Расхождение берётся В КОНЦЕ устройства, а не у острия: у острия оно
// миллиметровое (на марке 1/9 и радиусе 300 м — 7 мм на двух метрах), и знак
// такой величины перевернулся бы от первой же правки арифметики. В конце
// перевода оно около двух метров, и знак у него однозначен.

// DriveAtU — где вдоль прямого прохода стоит станина привода, метры от острия.
//
// ОБЪЯВЛЕННАЯ ПОСТАНОВКА, а не норма: настоящее место привода задаётся эпюрой
// перевода вместе с длиной остряков, а эпюры в карте нет — есть правило (см.
// timbers.go). Два метра ставят станину у корня остряков и не выносят её за
// первый десяток брусьев ни у одной марки.
//
// Число НАЗВАНО ЗДЕСЬ, а не спрятано в функции, чтобы объявленная величина была
// видна списком, — так же, как это сделано у клиента с длиной крыла крестовины.
const DriveAtU = 2.0

// DriveClearance — на сколько станина отнесена от конца ОБЫЧНОЙ шпалы, метры.
//
// ОЦЕНКА, и она названа оценкой: привод ставится так, чтобы не мешать подбивке
// и чтобы у стоящего рядом человека была земля под ногами. Полметра за концом
// шпалы — это габарит человека, а не измеренная норма.
const DriveClearance = 0.5

// DriveTimberReach — на сколько брус выходит ЗА станину, метры.
//
// # Привод стоит НА брусьях, а не рядом с ними (2026-08-16)
//
// До этого дня решётка про привод не знала вовсе, и получалось вот что. Брус в
// сечении привода на ST_A — 2.757 м, то есть полудлина 1.378; станина отнесена
// на 1.875; полуширина балласта 1.75. Станина оказывалась ЗА концом бруса и ЗА
// бровкой призмы — на откосе, ни на что не опираясь. В кадре это ящик, стоящий
// на краю щебня, и владелец нашёл это глазами.
//
// У настоящего перевода наоборот: брусья под приводом СПЕЦИАЛЬНО удлинены (на
// сети это 4.5–5.5 м против 2.75 обычной шпалы) — они и есть то, на чём привод
// держится вместе со всей гарнитурой.
//
// Число ОЦЕНКА: тела привода сервер не знает вовсе (оно ассет, разбор — у
// RenderTurnoutDrive), поэтому «докуда корпус» вывести неоткуда. Три четверти
// метра за вынос станины — это запас на корпус и гарнитуру, а не норма.
const DriveTimberReach = 0.75

// DriveTimberWindow — полуокно вдоль пути, в котором брусья удлинены, метры.
//
// ОБЪЯВЛЕННАЯ ПОСТАНОВКА, как и DriveAtU: настоящий привод стоит на двух-трёх
// брусьях, и при шаге 0.5 м окно в ±0.8 м даёт ровно столько. Меньше — станина
// повисла бы между брусьями; больше — под приводом вырос бы помост.
const DriveTimberWindow = 0.8

// handOf — в какую руку уходит боковой проход при таком расхождении осей.
//
// Положительное расхождение — по ЛЕВОЙ нормали (одно правило на весь контракт,
// см. axisSpread), то есть сход влево.
func handOf(spread float64) string {
	if spread > 0 {
		return mapfmt.HandLeft
	}
	return mapfmt.HandRight
}

// buildTurnoutDrives считает привод каждой стрелки и кладёт его в геометрию.
//
// Порядок вывода — по владельцу: у карты нет причин отдавать стрелки в порядке
// обхода, а хеш геометрии обязан зависеть от содержимого, а не от него.
func buildTurnoutDrives(m *mapfmt.Map, els map[string]Element, rg *RenderGeometry) error {
	c := m.Construction
	if c == nil {
		// Без блока construction нет ни типа, ни длины шпалы — а значит нечем
		// отмерить, куда в сторону отнести станину. Привода нет, и это то же
		// молчание, что у крестовины: чего измерить нечем, того не отдаём.
		return nil
	}
	types := make(map[string]mapfmt.TrackType, len(c.Types))
	for i := range c.Types {
		types[c.Types[i].ID] = c.Types[i]
	}
	for _, t := range m.Topology.Turnouts {
		d, err := turnoutDrive(els, types, c, t)
		if err != nil {
			return fmt.Errorf("track: стрелка %s: %w", mapfmt.Labeled(t.Name, t.ID), err)
		}
		if d != nil {
			rg.TurnoutDrives = append(rg.TurnoutDrives, *d)
		}
	}
	sort.Slice(rg.TurnoutDrives, func(i, j int) bool {
		return rg.TurnoutDrives[i].Owner < rg.TurnoutDrives[j].Owner
	})
	return nil
}

// turnoutDrive считает привод одной стрелки.
func turnoutDrive(els map[string]Element, types map[string]mapfmt.TrackType,
	c *mapfmt.Construction, t mapfmt.Turnout) (*RenderTurnoutDrive, error) {
	typ := t.Type
	if typ == "" {
		typ = c.DefaultType
	}
	tt, ok := types[typ]
	if !ok {
		return nil, fmt.Errorf("тип %q не разрешается — вынос привода отмерить нечем", typ)
	}

	straightID := t.ID + mapfmt.PassageStraight
	divergingID := t.ID + mapfmt.PassageDiverging
	sEl, okS := els[straightID]
	dEl, okD := els[divergingID]
	if !okS || !okD {
		return nil, fmt.Errorf("проходы %s и %s не скомпилированы",
			mapfmt.Labeled(t.Name, straightID), mapfmt.Labeled(t.Name, divergingID))
	}

	sLen := sEl.Plan.Length().Meters()
	dLen := dEl.Plan.Length().Meters()
	if sLen <= 0 {
		return nil, fmt.Errorf("прямой проход нулевой длины")
	}
	// Знак стороны — по расхождению в конце устройства (разбор в шапке файла).
	spread, err := axisSpread(sEl, sLen, dEl, math.Min(sLen, dLen))
	if err != nil {
		return nil, err
	}
	if spread == 0 {
		return nil, fmt.Errorf("проходы не расходятся вовсе — стороны у привода нет")
	}
	// РУКОСТЬ СВЕРЯЕТСЯ С ГЕОМЕТРИЕЙ, А НЕ ПРИНИМАЕТСЯ НА ВЕРУ.
	//
	// t.Hand — авторская пометка о том, куда уходит боковой путь; расхождение с
	// тем, куда он уходит НА САМОМ ДЕЛЕ, до сегодня оставалось незамеченным:
	// брусья и привод считались по геометрии, крестовина (frog.go) — по пометке,
	// и разойдись они, нитки пересекались бы не те. Теперь это отказ на входе.
	//
	// Проверка стоит ЗДЕСЬ, потому что здесь уже посчитано расхождение осей, и
	// второго места, где его считают, заводить незачем. Цена названа: у карты без
	// блока construction привода нет вовсе, и пометка у неё не сверяется ничем.
	if hand := handOf(spread); hand != t.Hand {
		return nil, fmt.Errorf("в карте написана рукость %q, а боковой проход уходит %s — "+
			"крестовина строится по пометке, а брусья и привод по геометрии, и разойтись им нельзя",
			t.Hand, hand)
	}
	side := -1.0 // левая нормаль положительна: сход вправо ставит привод влево
	if spread < 0 {
		side = 1.0
	}
	at := math.Min(DriveAtU, sLen)
	offset := side * (tt.Sleeper.Length/2 + DriveClearance)
	d := &RenderTurnoutDrive{
		Owner:   t.ID,
		Name:    t.Name,
		Drive:   t.Drive,
		Element: straightID,
		U:       at,
		Offset:  offset,
	}
	// ДЛИНА ПЕРЕВОДНОЙ ТЯГИ — до ДАЛЬНЕГО остряка, а не до ближнего: тяга
	// проходит под путём и связывает станину с обоими остряками сразу, как на
	// настоящем переводе. Считается только там, где есть остряк: без блока
	// switch тяге не до чего тянуться, и нули здесь означают «нет тяги».
	if tt.Switch != nil {
		reach(d, offset, tt.Gauge/2, tt.Switch.Throw)
	}
	return d, nil
}

// reach — длина тяги в каждом из двух положений стрелки.
//
// # Почему ДВА числа, а не одно с поправкой у клиента
//
// Остряки связаны тягами в одно целое и ходят вместе: перевод сдвигает всю пару
// на ход остряка. Значит и тяга то длиннее, то короче ровно на этот ход —
// 152 мм на двух с половиной метрах.
//
// Клиент мог бы вычесть ход сам: и вынос, и ход ему присланы. Но «в каком
// положении вычитать» — это знание о том, с какой стороны стоит привод и какой
// остряк дальний, то есть факт о станции. Два числа снимают вопрос целиком:
// клиенту остаётся выбрать по положению, которое у него и так есть.
//
// # Дальний остряк — всегда у ПРЯМОГО прохода
//
// Привод стоит с наружной стороны, противоположной сходу (см. шапку файла), а
// внутренняя нитка прямого прохода лежит как раз со стороны схода. Поэтому
// дальний от станины остряк — прямого прохода, у любой рукости.
func reach(d *RenderTurnoutDrive, offset, half, throw float64) {
	side := math.Copysign(1, offset)
	// Внутренняя нитка прямого прохода — со стороны схода, то есть напротив
	// станины.
	far := -side * half
	// Прижат — стоит на своём месте; отведён — уходит к оси своего прохода.
	d.ReachStraight = math.Abs(offset - far)
	d.ReachDiverging = math.Abs(offset - (far + side*throw))
}
