package track

import "github.com/shady2k/ClearAhead/server/internal/mapfmt"

// blade_section.go — СТРОЖКА ОСТРЯКА: сечение как функция расстояния от острия.
//
// # Почему это переехало сюда с клиента
//
// До 2026-08-16 таблица строжки жила в client/scripts/track_build.gd константой
// класса Blade — ширина головки и понижение верха на семи станциях. Это значит,
// что ФОРМУ ХОДОВОЙ ПОВЕРХНОСТИ выбирал клиент. Не рисовал присланное, а
// проектировал деталь.
//
// Хуже того, сервер об этом не знал и утверждал обратное: blade.go до сих пор
// писал «нет и сужения остряка к острию: настоящий острогается на клин, у нас он
// полного сечения по всей длине». Два места в одном проекте говорили про одну
// деталь противоположное, и разошлись они молча.
//
// Закон, по которому это разрешается (эпик ClearAhead-ax7m): ни один потребитель
// не принимает доменных решений, влияющих на существование детали, её сопряжение
// или её ХОДОВУЮ ФУНКЦИЮ. Строжка — ровно про ходовую функцию: она решает, с
// какого места колесо переходит с рамного рельса на остряк.
//
// # Почему таблицей, а не формулой
//
// Таблицей её задаёт сама модель (CA-1/9-R65-v1 §А): у настоящей строжки нет
// одного закона на всю длину — сперва ширина растёт быстро, затем медленно, а
// понижение сходит на нет вчетверо раньше, чем ширина выходит на полную.
//
// # Почему ДОЛЯМИ головки, а не метрами
//
// В клиенте таблица стояла в метрах и кончалась на 0.075 — ширине головки
// затравочного типа. То есть в ней сидело НЕОБЪЯВЛЕННОЕ допущение: «головка
// именно такая». Тип с другим рельсом получил бы остряк, который в корне уже или
// шире собственного рамного рельса, и заметить это было бы нечем.
//
// Здесь модель хранится долями и умножается на головку ТОГО ТИПА, для которого
// считается. Допущение исчезло, а не переехало.
//
// # Что здесь ОБЪЯВЛЕНО, а не выведено
//
// Сами числа. Настоящая строжка — свойство марки и типа остряка, а в карте есть
// только длина и ход (mapfmt.TrackSwitch). Тот же случай, что FrogPointOffset в
// frograils.go, и то же обещание: числа уедут в каталог типов устройств
// (ClearAhead-qyf), когда он появится. До тех пор они здесь, названы моделью и
// названы приближением.

// bladeTaperStation — одна станция модели строжки.
//
// HeadShare — доля полной ширины головки; Sink — насколько верх остряка ниже
// поверхности катания, метры.
//
// Понижение оставлено МЕТРАМИ, а не долей высоты рельса, и это разное по смыслу:
// оно есть зазор между верхом острогана и головкой рамного рельса, то есть
// свойство самой строжки, а не пропорция профиля. Доля высоты дала бы у высокого
// рельса вдвое более глубокую выемку без всякого основания.
type bladeTaperStation struct {
	U         float64
	HeadShare float64
	Sink      float64
}

// bladeTaperModel — модель CA-1/9-R65-v1 §А, переведённая в доли.
//
// Станции 1.5 и 3.0 стоят здесь не ради строжки, а ради НАКАТА: он ломается
// именно там, и без этих узлов кусочно-линейная таблица провода не смогла бы его
// выразить. Иначе клиенту пришлось бы держать вторую пару констант — то самое
// доменное решение, которое отсюда и убирается.
var bladeTaperModel = []bladeTaperStation{
	{U: 0.0, HeadShare: 0.006 / 0.075, Sink: 0.025},
	{U: 0.5, HeadShare: 0.012 / 0.075, Sink: 0.018},
	{U: 1.0, HeadShare: 0.020 / 0.075, Sink: 0.010},
	{U: 1.5, HeadShare: 0.030 / 0.075, Sink: 0.004},
	{U: 2.0, HeadShare: 0.042 / 0.075, Sink: 0.0},
	{U: 3.0, HeadShare: 0.051 / 0.075, Sink: 0.0},
	{U: 4.0, HeadShare: 0.060 / 0.075, Sink: 0.0},
	{U: 6.0, HeadShare: 1.0, Sink: 0.0},
}

// Накат на остряке: до BladeRideFrom его нет вовсе — колесо идёт по рамному
// рельсу, — а к BladeRideFull полоса выходит на полную ширину.
//
// Ширина наката МЕТРАМИ и не масштабируется головкой: это след колеса, свойство
// подвижного состава, а не рельса. Головка ýже наката бывает только у острогана,
// и тогда полосу обрезает само сечение.
const (
	BladeRideFrom  = 1.5
	BladeRideFull  = 3.0
	BladeRideWidth = 0.035
)

// bladeSection считает станции сечения остряка для типа пути.
//
// Возвращается ГОТОВАЯ кусочно-линейная таблица в метрах: клиент только
// интерполирует между станциями. Ни одного порога, ни одной константы, из
// которой ему пришлось бы что-то выводить, на той стороне не остаётся — иначе
// переезд был бы половинчатым и второй автор формы сохранился бы.
//
// Станции ДЛИННЕЕ САМОГО ОСТРЯКА не отбрасываются. Остряк короткого устройства
// обрезан по длине прохода (blade.go), и обрезанная таблица означала бы, что в
// корне он остался острогана — то есть обрезка длины молча меняла бы форму. Клиент
// берёт таблицу целиком и читает её на своём отрезке.
func bladeSection(tt mapfmt.TrackType) []RenderSectionStation {
	head := tt.Rail.HeadWidth
	out := make([]RenderSectionStation, 0, len(bladeTaperModel))
	for _, s := range bladeTaperModel {
		out = append(out, RenderSectionStation{
			U:         s.U,
			HeadWidth: s.HeadShare * head,
			Sink:      s.Sink,
			RideWidth: bladeRideAt(s.U),
		})
	}
	return out
}

// bladeRideAt — ширина наката на расстоянии u от острия.
func bladeRideAt(u float64) float64 {
	switch {
	case u >= BladeRideFull:
		return BladeRideWidth
	case u <= BladeRideFrom:
		return 0
	default:
		return BladeRideWidth * (u - BladeRideFrom) / (BladeRideFull - BladeRideFrom)
	}
}
