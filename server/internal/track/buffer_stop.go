// Спрашивать у автора третий размер значило бы заставить его проектировать
// деталь, которой он не выбирал.
//
// Настоящий ответ — каталог типов упоров, и он придёт вместе с каталогом тел
// предметов (ClearAhead-yfu3): у упора есть вид (тупиковая призма, брусовой,
// гидравлический), и вид этот несёт все три размера сразу. До тех пор длина
// живёт здесь — ОДНИМ объявлением, у которого написано, откуда оно.
//
// # Число, и КАДР ПРИ ЭТОМ МЕНЯЕТСЯ
