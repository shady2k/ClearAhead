package track

// frog_profile.go — ХОДОВАЯ ПОВЕРХНОСТЬ КРЕСТОВИНЫ: понижение сердечника,
// накат на нём и подъём контррельса.
//
// # Почему это переехало сюда с клиента
//
// Тот же переезд, что у строжки остряка (blade_section.go), и по тому же закону
// эпика ClearAhead-ax7m: ни один потребитель не принимает доменных решений о
// ходовой функции детали. До 2026-08-17 пять чисел жили константами в
// client/scripts/track_build.gd — CHECK_LIFT_M, CASTING_SINK_M,
// CASTING_SINK_RUN_M, CASTING_RIDE_FROM_M, CASTING_RIDE_FULL_M,
// CASTING_RIDE_WIDTH_M, — и клиент по ним ВЫВОДИЛ форму: с какого места колесо
// принимает отливка и где оно на неё встаёт целиком.
//
// Долг был записан в биде ax7m.3 прямым текстом: «та же болезнь у сердечника…
// клиент по-прежнему выбирает форму ходовой поверхности крестовины. Переносить
// тем же способом, что строжку остряка: моделью на сервере, станциями на
// проводе».
//
// # Что каждое число означает
//
// СЕРДЕЧНИК опущен в острие и выходит на отметку постепенно: колесо переходит на
// отливку не скачком, а по мере того, как она принимает вес. Накат по той же
// причине начинается не с острия — до первой станции его нет вовсе.
//
// КОНТРРЕЛЬС стоит ВЫШЕ головки: он держит гребень, а не несёт колесо, и наката
// у него нет. Подъём выражен отрицательным Sink — тем же полем, что и понижение,
// потому что вопрос один: где верх детали относительно поверхности катания.
//
// УСОВИК — обычная ходовая нитка: ни подъёма, ни понижения, ни особого наката.
// Своих станций он не получает, и это не пропуск: у него их нет.
//
// # Статус чисел
//
// ОБЪЯВЛЕНЫ, а не выведены, — как и у строжки. Это модель CA-1/9-R65-v1 (§Б, §В,
// §Г), пришедшая с клиента как есть; проверить её нечем, пока у нас нет чертежа
// крестовинного комплекта. Числа названы моделью и названы приближением, но
// живут теперь в одном месте, а не в двух.

// Модель ходовой поверхности крестовины, метры.
const (
	// CastingSink — понижение острия сердечника, CastingSinkRun — длина, на
	// которой оно сходит на нет.
	CastingSink    = 0.008
	CastingSinkRun = 0.80
	// Накат на сердечнике: до CastingRideFrom его нет вовсе, к CastingRideFull
	// полоса выходит на полную ширину.
	//
	// ЗДЕСЬ ТОЛЬКО ГРАНИЦЫ ПО ДЛИНЕ. Сама ширина — общая (RailRideWidth): это
	// след колеса, а колесо на отливке то же самое. Своё число стояло здесь до
	// 2026-08-18; разбор, почему их стало одно, — в ride.go.
	CastingRideFrom = 0.40
	CastingRideFull = 0.80
	// CheckLift — насколько верх контррельса ВЫШЕ поверхности катания.
	CheckLift = 0.020
)

// frogRailSection — станции ходовой поверхности одной нитки крестовины.
//
// Возвращает nil для усовика: у него верх на отметке и накат обычный, и пустая
// таблица честнее таблицы из нулей — та утверждала бы, что накат ЗАМЕРЕН нулём.
//
// Станции отсчитываются от НАЧАЛА ДЕТАЛИ, как и у остряка: клиент читает их на
// своём отрезке и между ними интерполирует линейно (RenderSectionStation).
func frogRailSection(kind string, head float64) []RenderSectionStation {
	switch kind {
	case FrogRailCasting:
		return []RenderSectionStation{
			{U: 0, HeadWidth: head, Sink: CastingSink, RideWidth: 0},
			{U: CastingRideFrom, HeadWidth: head,
				Sink: CastingSink * (1 - CastingRideFrom/CastingSinkRun), RideWidth: 0},
			{U: CastingRideFull, HeadWidth: head, Sink: 0, RideWidth: RailRideWidth},
		}
	case FrogRailCheck:
		// Подъём постоянен по всей длине: контррельс не несёт колесо нигде.
		// Ride нулевой по той же причине — накату на нём взяться неоткуда.
		return []RenderSectionStation{
			{U: 0, HeadWidth: head, Sink: -CheckLift, RideWidth: 0},
		}
	default:
		return nil
	}
}
