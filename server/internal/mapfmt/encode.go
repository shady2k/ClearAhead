package mapfmt

import (
	"encoding/json"
	"fmt"
	"io"
)

// Encode записывает документ карты в авторском виде: с отступами, чтобы файл
// правили руками и читали diff'ом.
//
// # Почему обратная дорога вообще есть
//
// Ею выгружена боевая ST_A из фабрики seedmap при переходе с кода на файл, и ею
// же спека просит делать дифф и экспорт (`world-storage` §6). Без неё переход
// свёлся бы к «агент однажды набрал восемьсот строк руками», то есть к файлу без
// происхождения.
//
// # Чего эта дорога НЕ делает
//
// Она ведёт из ПАМЯТИ в файл, а не из базы. Выгрузить карту из `world.db`
// нельзя вовсе: документа карты там нет — база держит развёрнутые чанки, а
// топология, геометрия и рецепты в неё не пишутся (бида ClearAhead-c0o).
//
// # Форма записи
//
// Отступ два пробела; ключи объектов Go сортирует сам (map'ы якорей и геометрии
// пишутся в порядке ключей), поэтому запись одной и той же карты дважды даёт
// один и тот же файл. Смысла КАНОНИЧЕСКОЙ формы это не несёт и нести не должно:
// хеши считаются от нормализованной модели, а не от байтов файла
// (`map-format-design` §5), и полагаться на побайтовое равенство файлов проект
// уже пробовал — эталон контракта не пережил смены машины (4b4d6a7).
//
// Проверки СМЫСЛА здесь нет намеренно: Encode — зеркало Decode, а Decode
// проверяет форму, не смысл. Валидировать обязан тот, кто выгружает, и это
// делает cmd/mapexport перед записью, а не сериализатор задним числом.
func Encode(w io.Writer, m *Map) error {
	b, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return fmt.Errorf("mapfmt: сериализация карты: %w", err)
	}
	// Перевод строки в конце: файл в репозитории, и его читают инструментами,
	// которые считают строки.
	b = append(b, '\n')
	if _, err := w.Write(b); err != nil {
		return fmt.Errorf("mapfmt: запись карты: %w", err)
	}
	return nil
}
