// TurnoutProjectByID разрешает ссылку стрелки на каталог.
//
// Возвращает ошибку, а не признак: ссылка на несуществующий проект — не
// состояние, а поломка карты, и молчаливое умолчание здесь запрещено тем же
// правилом, что и везде.
func TurnoutProjectByID(id string) (TurnoutType, error) {
	for _, t := range turnoutProjects {
		if t.ID == id {
			// ЗАПИСЬ ОТДАЁТСЯ КОПИЕЙ, ВКЛЮЧАЯ СРЕЗЫ. Копия структуры делится с
			// каталогом массивами эпюры и сечения, и правка одного элемента у
			// вызвавшего меняет каталог всего процесса — то есть все переводы
			// всех карт до перезапуска.
			//
			// Найдено не рассуждением: тест, портивший угол второй дуги ради
			// проверки марки, испортил его НАВСЕГДА, и следующий тест намерил
			// боковой проход длиннее прямого на 0.64 м. То же правило записано у
			// сечения рельса в track/construction.go — «контракт живёт дольше
			// разбора, и общий массив дал бы двум сторонам одну память».
			t.Passages.Straight = append([]HPrim(nil), t.Passages.Straight...)
			t.Passages.Diverging = append([]HPrim(nil), t.Passages.Diverging...)
			t.BladeRail.Section = append([]SectionPoint(nil), t.BladeRail.Section...)
			return t, nil
		}
	}
	return TurnoutType{}, fmt.Errorf("mapfmt: проект перевода %q не найден в каталоге сервера", id)
}

// TurnoutProjectIDs — все проекты каталога, в порядке объявления. Нужен тем, кто
// показывает автору выбор, и тесту, который проверяет каталог целиком.
func TurnoutProjectIDs() []string {
	out := make([]string, 0, len(turnoutProjects))
	for _, t := range turnoutProjects {
		out = append(out, t.ID)
	}
	return out
}

// Alignments — план обоих проходов, ПОДПИСАННЫЙ РУКОСТЬЮ.
//
// У правой стрелки боковой проход отклоняется по часовой стрелке — курс
// убывает, и углы дуг отрицательны; у левой наоборот. Знак ставится здесь и
// только здесь: то же правило для начального угла живёт в track/propagate.go, и
// разойдись они — перевод пришёл бы в крестовину зеркально своей рукости.
func (t TurnoutType) Alignments(hand string) (straight, diverging Alignments, err error) {
	var sign float64
	switch hand {
	case HandRight:
		sign = -1
	case HandLeft:
		sign = +1
	default:
		return Alignments{}, Alignments{},
			fmt.Errorf("mapfmt: проект %s: рукость %q, ожидается %s или %s", t.ID, hand, HandRight, HandLeft)
	}
	return Alignments{Horizontal: signedChain(t.Passages.Straight, sign)},
		Alignments{Horizontal: signedChain(t.Passages.Diverging, sign)}, nil
}

// signedChain — копия цепочки с подписанными углами дуг.
//
// КОПИЯ, А НЕ ПРАВКА НА МЕСТЕ: каталог один на весь процесс, и подписанная в нём
// дуга досталась бы следующей стрелке уже со знаком.
func signedChain(src []HPrim, sign float64) []HPrim {
	out := make([]HPrim, len(src))
	for i, p := range src {
		out[i] = p
		if p.Kind == "arc" {
			out[i].Angle = sign * p.Angle
		}
	}
	return out
}
