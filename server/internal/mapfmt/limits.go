// Package mapfmt — форма файла карты, строгий разбор и проверки формы.
//
// Здесь живёт float в метрах и радианах: это авторские данные. Всё, что уходит
// дальше в компилятор, переводится в целые микрометры (units.Distance).
//
// Формат внутренний: читатель один, всё неизвестное — отказ. Согласования
// возможностей и минорных версий нет (спека §2, правило 2).
package mapfmt

// FormatVersion — единственная поддерживаемая версия формата.
//
// Согласования возможностей нет: читатель один, всё неизвестное — отказ. Любое
// добавление поля несовместимо со старым читателем по построению, поэтому
// расширение — это подъём версии, а не необязательное поле (спека §2).
//
//	2 — блок construction: типы, run'ы, размеры решётки, тип устройства
//	3 — направление у интервала протяжённости (netloc), общий тип на все слои
//	4 — блок terrain: рецепт рельефа; kind моста и тоннеля у сооружения
//	5 — вертикальный стек типа пути и высоты сооружений (контракт отрисовки,
//	    редакция 6): датум z объявлен поверхностью катания, и от него стало что
//	    откладывать
//	6 — блок cover в рецепте рельефа и блок objects: покров и постройки
//	7 — переводной механизм стрелки (drive): механический или электрический.
//	    Полем, а не умолчанием, потому что это ФАКТ О СТАНЦИИ: одна и та же
//	    горловина бывает и на ручных переводах, и на электроприводах, и по
//	    геометрии их не различить
const FormatVersion = 7

// Лимиты парсера. Карта — недоверенный вход: она может прийти рукой, старой
// версией редактора, импортёром или, позже, командой от клиента.
const (
	MaxDocumentBytes = 32 << 20 // 32 МиБ
	MaxNestingDepth  = 32
	MaxIDLength      = 128
	MaxElements      = 100000
	MaxPrimitives    = 1000000
)

// Лимиты блока construction. Карта — недоверенный вход: миллион run'ов или
// миллион спанов в одном run'е валиден по форме, но кладёт клиент.
const (
	MaxTrackTypes       = 64   // типов больше реальная станция не объявит
	MaxConstructionRuns = 1024 // run'ов на карту
	MaxRunSpans         = 4096 // спанов в одном run'е
)

// Диапазоны величин типа путевой конструкции (спека §3, план волны 2a, задача
// 2). Проверка знака недостаточна: шаг шпал 0.001 м проходит «строго
// положительно» и даёт 1.8 млн шпал на километр — клиент ложится без ошибки.
// Границы — правдоподобные пределы реальной рельсошпальной решётки, метры.
const (
	MinGauge, MaxGauge                       = 0.5, 2.5 // реальные колеи 1067–1676 мм
	MinSleeperPitch, MaxSleeperPitch         = 0.2, 2.0 // реальный шаг 0.4–1.0 м
	MinSleeperLength, MaxSleeperLength       = 1.0, 4.0 // поперёк пути
	MinSleeperWidth, MaxSleeperWidth         = 0.1, 0.6 // вдоль пути
	MinBallastHalfWidth, MaxBallastHalfWidth = 0.5, 8.0 // по верху призмы
)

// Диапазоны вертикального стека (контракт отрисовки, редакция 6, §7.1). Числа
// ПРЕДВАРИТЕЛЬНЫЕ в том же смысле, что и профиль норм: источник не назначен,
// границы отвергают заведомо невозможное, а не проверяют проект.
//
// CribDepth в перечень не входит: его верхняя граница — не константа, а
// Sleeper.Height того же типа (шпалу нельзя утопить глубже её собственной
// высоты), и проверяется она согласованностью, а не диапазоном.
const (
	MinRailHeight, MaxRailHeight             = 0.10, 0.30 // Р50 — 0.152, Р65 — 0.180, Р75 — 0.192
	MinRailHeadWidth, MaxRailHeadWidth       = 0.03, 0.12 // Р50 — 0.072, Р65 — 0.075
	MinSleeperHeight, MaxSleeperHeight       = 0.10, 0.40 // деревянная около 0.18, железобетонная около 0.20
	MinBallastDepth, MaxBallastDepth         = 0.10, 1.00 // станционные пути от 0.20, главные до 0.50 с подушкой
	MinBallastSideSlope, MaxBallastSideSlope = 0.5, 4.0   // 1:1,5 обычен; вне этого — не откос призмы
)

// Границы СЕЧЕНИЯ РЕЛЬСА (TrackRail.Section).
//
// Нижняя граница по точкам — не «замкнутая фигура вообще», а «рельс»: тремя
// точками задаётся треугольник, головки с шейкой и подошвой в нём нет. Восемь —
// столько, сколько нужно самому грубому прямоугольному «рельсу» с шейкой:
// четыре угла головки и четыре подошвы. Потолок стоит против карты, привезшей
// оцифрованный ГОСТ точка в точку: у неё сечение в сотни вершин, и экструзия
// такого профиля вдоль каждой нитки станции — не отрисовка, а обморок.
//
// Допуск согласования — полмиллиметра. Он МЕНЬШЕ разрешения любого сегодняшнего
// вида и БОЛЬШЕ шума округления автора, записавшего размеры в миллиметрах.
const (
	MinRailSectionPoints = 8
	MaxRailSectionPoints = 64
	// MinRailSectionArea — площадь Р65 около 82.65 см² = 0.008265 м². Граница
	// стоит на порядок ниже: она отвергает вырожденное и обход по часовой
	// стрелке (у него площадь отрицательна), а не проверяет марку рельса.
	MinRailSectionArea = 1e-4
	// MaxRailSectionY — потолок y. Ровно ноль: поверхность катания и есть
	// начало отсчёта, металла выше неё не бывает.
	MaxRailSectionY = 0.0
	RailSectionTol  = 5e-4
)

// Диапазоны переводных брусьев (контракт отрисовки §4, уровень 3). Границы шире
// шпальных, и это не небрежность: брус длиннее шпалы по построению (он несёт оба
// пути сразу) и толще её, потому что нагружен несимметрично.
const (
	MinTimberPitch, MaxTimberPitch   = 0.2, 2.0  // у эпюры перевода тот же порядок, что у шпальной
	MinTimberLength, MaxTimberLength = 2.0, 12.0 // комплект 1/9 Р65 — от 3.00 до 5.50
	MinTimberWidth, MaxTimberWidth   = 0.1, 0.6  // вдоль пути, как у шпалы
	MinTimberHeight, MaxTimberHeight = 0.10, 0.40
)

// Диапазоны ОСТРЯКА (TrackSwitch). Границы отвергают заведомо невозможное, а не
// проверяют проект: остряк короче метра не остряк, а длиннее двадцати не бывает
// ни у одной марки; ход меньше пяти сантиметров колесо не удержит, больше
// полуметра — не перевод, а разрыв пути.
const (
	MinBladeLength, MaxBladeLength = 1.0, 20.0 // Р65 1/9 — около 8.3 м
	MinBladeThrow, MaxBladeThrow   = 0.05, 0.5 // норма ПТЭ — 0.152 м
	// BladeThrowHeads — во сколько ширин головки укладывается ход остряка.
	// Норма ПТЭ 152 мм при головке Р65 75 мм — это 2.03, и граница поставлена с
	// запасом в полторы нормы: она отвергает описку в разряде, а не проверяет
	// проект перевода.
	BladeThrowHeads = 3.0
)

// Границы КРЕСТОВИНЫ (TrackFrog). Желоба — нормы ПТЭ (46 и 44 мм), и границы
