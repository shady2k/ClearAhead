// Package mapfmt — форма файла карты, строгий разбор и проверки формы.
//
// Здесь живёт float в метрах и радианах: это авторские данные. Всё, что уходит
// дальше в компилятор, переводится в целые микрометры (units.Distance).
//
// Формат внутренний: читатель один, всё неизвестное — отказ. Согласования
// возможностей и минорных версий нет (спека §2, правило 2).
package mapfmt

// FormatVersion — единственная поддерживаемая версия формата.
//
// Версия 2 добавляет блок construction (типы, run'ы, размеры решётки) и тип
// устройства на стрелке: старый читатель отверг бы эти поля, поэтому две
// несовместимые формы не называют одной версией (спека §10).
const FormatVersion = 3

// Лимиты парсера. Карта — недоверенный вход: она может прийти рукой, старой
// версией редактора, импортёром или, позже, командой от клиента.
const (
	MaxDocumentBytes = 32 << 20 // 32 МиБ
	MaxNestingDepth  = 32
	MaxIDLength      = 128
	MaxElements      = 100000
	MaxPrimitives    = 1000000
)

// Лимиты блока construction. Карта — недоверенный вход: миллион run'ов или
// миллион спанов в одном run'е валиден по форме, но кладёт клиент.
const (
	MaxTrackTypes       = 64   // типов больше реальная станция не объявит
	MaxConstructionRuns = 1024 // run'ов на карту
	MaxRunSpans         = 4096 // спанов в одном run'е
)

// Диапазоны величин типа путевой конструкции (спека §3, план волны 2a, задача
// 2). Проверка знака недостаточна: шаг шпал 0.001 м проходит «строго
// положительно» и даёт 1.8 млн шпал на километр — клиент ложится без ошибки.
// Границы — правдоподобные пределы реальной рельсошпальной решётки, метры.
const (
	MinGauge, MaxGauge                       = 0.5, 2.5 // реальные колеи 1067–1676 мм
	MinSleeperPitch, MaxSleeperPitch         = 0.2, 2.0 // реальный шаг 0.4–1.0 м
	MinSleeperLength, MaxSleeperLength       = 1.0, 4.0 // поперёк пути
	MinSleeperWidth, MaxSleeperWidth         = 0.1, 0.6 // вдоль пути
	MinBallastHalfWidth, MaxBallastHalfWidth = 0.5, 8.0 // по верху призмы
)
