// TrackType — тип путевой конструкции (контракт отрисовки, редакция 6, §3).
//
// Семантика чисел задана точно, иначе два рендерера реализуют разное:
// gauge — между внутренними рабочими гранями головок рельсов; символические
// нитки схемы ставятся на ±gauge/2 от осевой; sleeper.length — поперёк пути,
// sleeper.width — вдоль; ballast.half_width — по верху призмы.
//
// # Вертикальный стек: всё отсчитывается ВНИЗ от поверхности катания
//
// Датум z — ПОВЕРХНОСТЬ КАТАНИЯ, то есть верх головки рельса (редакция 6 §2).
// Земляное полотно не авторится, а вычисляется:
//
//	formation_z(u) = z(u) − (ballast.depth + sleeper.height + rail.height)
//
// Отсюда правило чтения всех полей ниже: они складываются в одну высоту, и ни
// одно из них не является отметкой само по себе.
//
// sleeper.type и подробный профиль рельса по-прежнему НЕ заводятся (§8
// редакции 6): одного rail.height мало для честного рельса, и клиент рисует
// ОБЪЯВЛЕННОЕ упрощение — прямоугольник, — а не выдумывает форму.
type TrackType struct {
	ID string `json:"id"`
	// Name — читаемая метка типа решётки. Тождеством не является: ссылки идут
	// по UUID, метка попадает в тексты отказов рядом с ним.
	Name    string       `json:"name,omitempty"`
	Gauge   float64      `json:"gauge"`
	Rail    TrackRail    `json:"rail"`
	Sleeper TrackSleeper `json:"sleeper"`
	Ballast TrackBallast `json:"ballast"`
	// Timber — переводные брусья. Необязателен у типа обычного пути и ОБЯЗАТЕЛЕН
	// у типа, на который ссылается стрелка: под устройством лежат не шпалы, и
	// взять их эпюру больше неоткуда.
	//
	// Здесь, а не отдельным ресурсом, по тому же доводу, по которому здесь лежит
	// колея для крестовины (§4): тип устройства и есть место, где живёт описание
	// его конструкции. Отдельный ресурс добавил бы третью ссылку и третье
	// умолчание ради четырёх чисел.
	Timber *TrackTimber `json:"timber,omitempty"`
	// Switch — ОСТРЯКИ перевода. Необязателен у типа обычного пути и ОБЯЗАТЕЛЕН
	// у типа, на который ссылается стрелка, — по тому же доводу, что и timber:
	// без него перевод стрелки не виден в кадре ничем, кроме указателя, а это
	// ровно тот дефект, которым блок и заведён (ClearAhead-86mb, слово владельца
	// 2026-08-15: «перевод стрелки ничего не меняет на рельсах»).
	Switch *TrackSwitch `json:"switch,omitempty"`
	// Frog — КРЕСТОВИНА: желоба, усовики, контррельсы. Необязателен у типа
	// обычного пути и ОБЯЗАТЕЛЕН у типа, на который ссылается стрелка, — по тому
	// же доводу, что timber и switch.
	//
	// Заведён 2026-08-16 словом владельца: на вопрос «что за красное пятно» он
	// ответил снимком настоящей крестовины и словами «делаем вот так». Красным
	// пятном была ГАЛОЧКА — плоская метка теоретической точки, приём схемы
	// сверху, доживший до вида от первого лица (ClearAhead-byoq).
	Frog *TrackFrog `json:"frog,omitempty"`
}

// TrackFrog — крестовина: то, что лежит вокруг точки пересечения ниток.
//
// # В типе лежит правило, а не чертёж
//
// Третий блок того же рода, что timber и switch: тип несёт размеры, а ГДЕ всё
// это лежит, считает сервер по точке крестовины и рукости. Список ниток —
// производная, а производную в карту не кладут.
//
// # Что выражено и что нет
//
// Выражены УСОВИКИ и КОНТРРЕЛЬСЫ — отдельными нитками рядом с нитками прохода,
// с отгибами на концах. Не выражен СЕРДЕЧНИК как отливка: у нас он остаётся
// пересечением самих ниток, сходящихся в точку. Настоящий сердечник — цельная
// отливка с горлом и хвостом, и его форма из этих чисел не выводится.
//
// Не выражены также: подуклонка в крестовине, вкладыши, болтовые крепления
// контррельса и переменная ширина желоба по длине (у настоящего желоб сужается
// к горлу). Всё это объявленные упрощения, а не молчание.
type TrackFrog struct {
	// Flangeway — ШИРИНА ЖЕЛОБА В КРЕСТОВИНЕ: просвет между усовиком и рабочей
	// гранью нитки прохода. Норма ПТЭ — 46 мм.
	Flangeway float64 `json:"flangeway"`
	// CheckFlangeway — ширина желоба между контррельсом и рабочей гранью нитки.
	// Норма ПТЭ — 44 мм.
	CheckFlangeway float64 `json:"check_flangeway"`
	// WingLength и CheckLength — длины усовика и контррельса ЦЕЛИКОМ, считая
	// отгибы, симметрично относительно точки крестовины.
	//
	// Симметрия — упрощение: у настоящего комплекта усовик длиннее в хвост, чем
	// в горло. Объявлено здесь, чтобы не искать потом, откуда взялась середина.
	WingLength  float64 `json:"wing_length"`
	CheckLength float64 `json:"check_length"`
	// CastingLength — длина СЕРДЕЧНИКА в каждую сторону от точки крестовины.
	//
	// Сердечник — цельная отливка, в которой обе нитки перестают быть нитками:
	// они входят в неё и выходят её крыльями. Без него нитки просто ПЕРЕСЕКАЮТСЯ
	// и месят друг друга — так и было до 2026-08-16, и владелец сказал прямо:
	// «крестовина неправильно нарисована».
	CastingLength float64 `json:"casting_length"`
	// Flare — длина ОТГИБА на каждом конце: на ней желоб раскрывается от рабочей
	// ширины до раструба. Отгиб есть у обоих концов и у усовика, и у
	// контррельса: колесо входит в желоб с любой стороны.
	Flare float64 `json:"flare"`
	// FlareGap — ширина желоба В РАСТРУБЕ, то есть на самом конце отгиба.
	// Обязана быть больше рабочей ширины: раструб на то и раструб.
	FlareGap float64 `json:"flare_gap"`
}

// TrackSwitch — ОСТРЯКИ: подвижная часть перевода (спека контракта отрисовки §4,
// уровень 3, у которого появился потребитель).
//
// # В типе лежит ПРАВИЛО, а не эпюра
//
// Ровно тот же выбор, что у брусьев: тип несёт два числа, а ГДЕ лежит остряк и
// куда он отходит, считает сервер. Список положений остряка — производная, а
// производную в карту не кладут.
//
// # Чего эти два числа НЕ выражают, и это названо
//
// Длина остряка на самом деле свойство МАРКИ (у Р65 1/9 она одна, у 1/11
// другая), а здесь она свойство ТИПА ПУТИ. Приближение то же и той же цены, что
// у timber.length_max, и снимется оно тем же днём: когда появится каталог типов
// устройств (ClearAhead-qyf), обе величины переедут туда вместе.
//
// Не выражены также: криволинейный остряк (здесь он прямой), корневое крепление,
// упорные накладки и связные тяги. Отвод остряка от рамного рельса принят
// ЛИНЕЙНЫМ по длине — у настоящего он определяется строжкой, и это объявленное
// упрощение, а не измеренная форма.
type TrackSwitch struct {
	// BladeLength — длина остряка от острия до корня, метры.
	BladeLength float64 `json:"blade_length"`
	// Throw — ХОД ОСТРЯКА: на сколько отведён от рамного рельса тот остряк, по
	// которому стрелка НЕ стоит. Отсчитывается в острие; к корню отвод сходит на
	// нет.
	//
	// Норма ПТЭ — 152 мм; здесь это число карты, а не константа кода, потому что
	// у ручного перевода узкой колеи оно другое.
	Throw float64 `json:"throw"`
}

// TrackTimber — переводные брусья: решётка УСТРОЙСТВА (спека контракта отрисовки
// §4, уровень 3 — «нерегулярные конструкции: отдельный рецепт устройства»).
//
// # Почему четыре числа, а не полный комплект
//
// Настоящий перевод описывается эпюрой: поимённым списком брусьев с их длинами.
// Здесь задаётся ПРАВИЛО, по которому список считает сервер, и правило названо в
// спеке: брус перекрывает оба пути, значит его длина есть длина шпалы этого же
// типа плюс расхождение осей в этом сечении. Отсюда в карте нет ни длины
// каждого бруса, ни их числа — они производные, а производную в карту не кладут
// (тот же довод, что у FormationToRail).
//
// LengthMax — единственное, чего из расхождения не вывести: комплект кончается.
// За хвостом крестовины пути расходятся дальше, а брусья длиннее самого длинного
// не бывают — там начинается обычная решётка на двух отдельных путях.
type TrackTimber struct {
	// Pitch — шаг брусьев вдоль ПРЯМОГО прохода. Своё число, а не шпальный шаг:
	// эпюра перевода гуще путевой.
	Pitch float64 `json:"pitch"`
	// LengthMax — самый длинный брус комплекта. Расхождение осей растёт по всей
	// длине устройства, длина бруса — только до этого предела.
	LengthMax float64 `json:"length_max"`
	// Width — вдоль пути. Height — от постели до верха, как у шпалы: брус лежит в
	// том же вертикальном стеке и на той же постели.
	Width  float64 `json:"width"`
	Height float64 `json:"height"`
}

// TrackRail — рельс: высота, ширина головки и СЕЧЕНИЕ.
//
// Отдельная структура заведена нарочно. Профиль рельса был названным открытым
// вопросом (§8 редакции 6): «понадобятся либо размеры головки, шейки и подошвы,
// либо идентификатор стандартного профиля». Условие закрыто 2026-08-15 словом
// владельца «рельс — это не прямоугольник»: понадобились размеры, и они пришли
// многоугольником (Section), а не идентификатором. Почему многоугольником —
// у самого поля.
type TrackRail struct {
	// Height — от подошвы рельса до поверхности катания. Подошва лежит на верхе
	// шпалы: прокладка отдельным числом не заводится (ниже разрешения любого
	// сегодняшнего вида).
	Height float64 `json:"height"`
	// HeadWidth — ширина ГОЛОВКИ рельса поверху.
	//
	// # Почему одно число профиля всё-таки заведено
	//
	// Профиль рельса отложен целиком (редакция 6 §8), и это поле выглядит
	// исключением из отказа. Оно им и является, и вот условие, по которому
	// исключение сделано: БЕЗ ШИРИНЫ ГОЛОВКИ РЕЛЬС НЕЛЬЗЯ НАРИСОВАТЬ ВООБЩЕ.
	// gauge задан между внутренними рабочими гранями; чтобы поставить рельс,
	// надо знать, сколько он занимает наружу от этой грани. Клиент, которому
	// ширину не прислали, обязан её выдумать — то есть ровно то, что контракт
	// запрещает.
	//
	// Цена умолчания ИЗМЕРЕНА, а не предположена: у снесённого спайка ширины
	// головки не было, нитки поставили по осям головок вместо рабочих граней, и
	// колея вышла 1.335 вместо 1.435 (разбор спайка §3.4). Числа замера — того
	// дня, когда мир был колеи 1.435; переход на 1.520 (ClearAhead-3ay) их не
	// отменяет и не пересчитывает, промах остаётся ширины головки.
	//
	// Ширина головки ОСТАЁТСЯ при сечении, и это не дубль: она задаёт, где
	// проходит рабочая грань относительно оси рельса, то есть ставит сечение на
	// место. Расхождение с сечением — отказ валидации, а не молчаливый выбор
	// одного из двух.
	HeadWidth float64 `json:"head_width"`
	// Section — СЕЧЕНИЕ РЕЛЬСА многоугольником, метры.
	//
	// # Оси сечения
	//
	// x — поперёк пути ОТ ВНУТРЕННЕЙ РАБОЧЕЙ ГРАНИ ГОЛОВКИ, наружу от оси пути
	// положительно. y — от ПОВЕРХНОСТИ КАТАНИЯ вниз, то есть y ≤ 0.
	//
	// Оба датума уже контрактные и заведены не здесь: gauge задан между
	// рабочими гранями (§3), z — верх головки (§2). Третий датум («от оси
	// рельса», «от подошвы») потребовал бы перевода между двумя языками
	// профиля — ровно того, чего контракт избегает у вертикальной цепочки.
	//
	// # Одно сечение на обе нитки
	//
	// Нитки зеркальны, и второго многоугольника не заводится: два описания
	// одного рельса рано или поздно разойдутся, и разойдутся они колеёй. Клиент
	// отражает сечение знаком наружной нормали — тем же знаком, каким он уже
	// разводит нитки.
	//
	// # Обход — против часовой стрелки
	//
	// В осях (x наружу, y вверх). Это не оформление: по обходу клиент строит
	// нормали боковой поверхности, и обход наизнанку даёт вывернутый рельс —
	// тот же класс ошибки, что коробки домов изнанкой (2026-08-12), которую
	// нашли глазами владельца. Валидатор считает знак площади и отказывает.
	//
	// # Числа предварительные, происхождение названо
	//
	// Р65 по ГОСТ Р 51685-2013: высота 180, головка 75, подошва 150, шейка 18,
	// головка по высоте 45 мм. Скругления и подуклонка не выражены — сечение
	// прямолинейное по участкам, и это ОБЪЯВЛЕННОЕ упрощение, а не профиль по
	// ГОСТ точка в точку.
	Section []SectionPoint `json:"section"`
}

// SectionPoint — точка сечения рельса. Оси и датумы — у TrackRail.Section.
//
// Массивом из двух чисел, а не парой полей: точек в сечении дюжина, и запись
// {"x": …, "y": …} двенадцать раз читается хуже, чем таблица пар. Тот же приём,
// что у геометрии знака на щитке (content.Mark.Polygon).
type SectionPoint [2]float64

// X — поперёк пути от рабочей грани, наружу положительно.
func (p SectionPoint) X() float64 { return p[0] }

// Y — вниз от поверхности катания, y ≤ 0.
func (p SectionPoint) Y() float64 { return p[1] }

type TrackSleeper struct {
	Pitch  float64 `json:"pitch"`
	Length float64 `json:"length"`
	Width  float64 `json:"width"`
	// Height — от постели до верха шпалы, в подрельсовом сечении.
	Height float64 `json:"height"`
}

type TrackBallast struct {
	// HalfWidth — полуширина ПО ВЕРХУ призмы.
	HalfWidth float64 `json:"half_width"`
	// Depth — от верха основной площадки до НИЗА ШПАЛЫ.
	//
	// Именно «под шпалой», а не «толщина призмы»: толщина есть сумма
	// Depth + CribDepth, и хранить сумму рядом со слагаемыми — завести второй
	// источник истины и допуск согласования между ними.
	Depth float64 `json:"depth"`
	// CribDepth — насколько шпальный ящик засыпан ВЫШЕ низа шпалы. Верх призмы
	// = низ шпалы + CribDepth.
	//
	// Число нужно потому, что видно именно верх призмы, а не постель. Ноль —
	// призма вровень с постелью шпалы; CribDepth == Sleeper.Height — ящик
	// засыпан вровень с верхом шпалы. Больше высоты шпалы — отказ.
	CribDepth float64 `json:"crib_depth"`
	// SideSlope — заложение откоса призмы: метров по горизонтали на метр по
	// вертикали. 1.5 означает откос 1:1,5.
	//
	// Единица та же, что у Earthworks.SideSlope, и это сделано нарочно: два
	// заложения в одной карте, записанные в разных единицах, — заготовленная
	// ошибка. Нижняя полуширина выводится:
	// HalfWidth + SideSlope·(Depth + CribDepth).
	SideSlope float64 `json:"side_slope"`
}

// ConstructionRun — run размещения решётки (спека §4).
//
// Run — авторитетный факт о физической решётке, независимый от нарезки на
// RenderElement: смена внутренней сегментации карты не должна переставлять
// шпалы. Пишет run'ы строитель (инструмент), а не человек.
type ConstructionRun struct {
	// Type необязателен в карте: опущен — применяется Construction.DefaultType.
	// Компилятор обязан разрешить умолчание ДО провода.
	ID string `json:"id"`
	// Name — читаемая метка run'а. Тождеством не является: ссылки идут по
	// UUID, метка попадает в тексты отказов рядом с ним.
	Name       string  `json:"name,omitempty"`
	Type       string  `json:"type,omitempty"`
	Coordinate string  `json:"coordinate"`
	Phase      float64 `json:"phase"`
	// Spans — координата размещения только u: клиент не имеет цепочки
	// вертикального профиля и восстановить размещение по s не способен
	// (спека §4). Спаны — в авторском порядке прохождения, направление у
	// каждого ОБЯЗАТЕЛЬНО: run укладывается по ходу, и спан без направления в
	// нём недоописан, а не «без направления».
	Spans netloc.LinearU `json:"spans"`
}
