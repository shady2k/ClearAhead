package mapfmt

import "github.com/shady2k/ClearAhead/server/internal/netloc"

// Map — файл карты как он записан. Метры, радианы, промилле.
type Map struct {
	FormatVersion int               `json:"format_version"`
	MapID         string            `json:"map_id"`
	MapRevision   int               `json:"map_revision"`
	Georeference  *Georeference     `json:"georeference,omitempty"`
	Anchors       map[string]Anchor `json:"anchors"`
	Topology      Topology          `json:"topology"`
	Geometry      Geometry          `json:"geometry"`
	// Construction — рецепт путевой решётки (спека контракта отрисовки §3–4).
	// Блок соседствует с topology и geometry; отсутствие блока означает, что
	// авторинг ещё не породил решётку, и валидатор пропускает модуль (решение
	// зафиксировано в construction.go).
	Construction *Construction `json:"construction,omitempty"`
	// Terrain — РЕЦЕПТ рельефа, а не отсчёты (бида ClearAhead-9k7).
	//
	// Клиент рецепта не видит никогда: сервер разворачивает его в отсчёты,
	// вычитает земляные работы и отдаёт готовые высоты. Двойной реализации
	// шума в Go и на клиенте не нужно, а «клиент ничего не придумывает»
	// остаётся в силе — придумывает сервер, одинаково для всех и один раз.
	//
	// Отсутствие блока означает карту без рельефа: это законно, отсчётов
	// просто нет. Базовую поверхность рисует клиент.
	Terrain *Terrain `json:"terrain,omitempty"`
	// Objects — семантические объекты региона: постройки и вода.
	//
	// Третий ресурс рядом с сетью и чанками, и место у него своё по КРИТЕРИЮ
	// ПОЛОЖЕНИЯ (спека 2026-08-12-region-objects-design §1.3): вещь ложится
	// туда, чем задано её положение. Клеткой — в чанк; парой (элемент, u) — в
	// сеть; плоскими координатами и собственной формой — сюда.
	//
	// Критерий именно положения, а не «есть ли стабильный ID»: у платформы ID
	// есть, и тело своё есть, а лежит она в structures контракта сети, потому
	// что её положение задано span'ом. ID есть у всех трёх классов и
	// различителем быть не может.
	Objects *Objects `json:"objects,omitempty"`
}

// Objects — семантические объекты региона.
//
// Вода сюда ещё не заведена: у неё нет потребителя (ни один клиент её не
// рисовал с момента сноса спайка), а форма без потребителя окажется неверной.
// Поле не объявляется заранее по той же причине — перечень полей есть часть
// контракта, и объявленное пустое поле делает версию ложью.
type Objects struct {
	Buildings []Building `json:"buildings"`
}

// Building — постройка: место, поворот, габарит.
//
// # Что здесь мир, а что нет
//
// Место, поворот и габарит — МИР: растущий город есть семантический объект со
// стабильным ID (map-content-design §5), его габарит меряется, и второй клиент
// обязан показать дом там же и такого же размера.
//
// Форма крыши, цвет стен, напуск карниза, число окон — НЕ мир: их выбирает
// рендерер, как выбирает меш ели. Отсюда и отсутствие этих полей.
//
// # Отметка вычисляется сервером, а не клиентом
//
// Направление авторитета здесь ОБРАТНОЕ пути, и это названо: путь диктует
// отметку земле, а дом её принимает. Считает сервер по рабочей поверхности
// уровня 0 и везёт явно. Довод замерен спекой объектов: посадка дома клиентом
// на присланные высоты даёт расхождение между уровнем 0 и уровнем 4 в среднем
// 0.39 м и до 2.30 м — то есть дом на дальнем уровне повис бы в воздухе или
// утонул, и это зависело бы от того, какой чанк клиент успел загрузить.
type Building struct {
	ID string `json:"id"`
	// X, Y — плановые координаты центра застроенного пятна.
	X float64 `json:"x"`
	Y float64 `json:"y"`
	// Heading — поворот вокруг вертикали, радианы.
	Heading float64 `json:"heading"`
	// Width — размер поперёк, Depth — вдоль, Height — до карниза.
	Width  float64 `json:"width"`
	Depth  float64 `json:"depth"`
	Height float64 `json:"height"`
}

// Terrain — рецепт рельефа карты.
//
// Высота земли — вход ТОЛЬКО рендера; уклон пути — вход физики. Авторитет у
// пути: рельеф согласуется с проектной осью насыпью и выемкой, обратное
// направление запрещено, иначе сила от уклона начнёт зависеть от разрешения
// сетки высот (map-format-design §5).
type Terrain struct {
	// Seed — затравка шума. Одна затравка даёт один и тот же рельеф на любой
	// машине: шум считается целочисленным хешем и арифметикой без
	// трансцендентных функций, а результат квантуется в сантиметры.
	Seed uint64 `json:"seed"`
	// BaseZ — опорная высота региона в метрах. Отсчёты хранятся и едут как
	// целые сантиметры ОТНОСИТЕЛЬНО неё: int16 покрывает ±327 м вокруг базы,
	// чего хватает на чанк 256 м в любых горах.
	BaseZ float64 `json:"base_z"`
	// Octaves — слои шума, от крупного к мелкому. Порядок значим: сумма
	// считается в записанном порядке, и перестановка меняет последний бит.
	Octaves []TerrainOctave `json:"octaves"`
	// Earthworks — как рельеф примиряется с осью пути.
	Earthworks Earthworks `json:"earthworks"`
	// Cover — рецепт ПОКРОВА: что растёт и лежит на поверхности.
	//
	// Здесь, а не отдельным блоком карты, по той же причине, по которой здесь
	// живут октавы рельефа: покров считается тем же шумом от тех же координат и
	// клиенту НЕ ПОКАЗЫВАЕТСЯ НИКОГДА. Сервер разворачивает рецепт в классы и
	// отдаёт готовые ячейки — двойной реализации шума в Go и на клиенте не
	// нужно, а «клиент ничего не придумывает» остаётся в силе.
	//
	// Отсутствие блока означает карту без покрова: ресурс покрова тогда просто
	// не существует, и клиент рисует землю нейтрально. Это законно и отличимо
	// от «покров есть, но пустой».
	Cover *Cover `json:"cover,omitempty"`
}

// Cover — рецепт покрова.
//
// Модель НАМЕРЕННО грубая и названа грубой: две маски шума и три порога. Она не
// описывает ни подлеска, ни опушки, ни зависимости от высоты над уровнем моря —
// всё это содержимое отдельного слоя, когда у него появится потребитель.
//
// Числа ПРЕДВАРИТЕЛЬНЫЕ, и происхождение у них честное: длины волн и пороги
// сняты с констант снесённого спайка (разбор .internal/briefs/
// 2026-08-12-spike-data-requirements.md §1.2, §1.3). Происхождение не есть
// норма: у спайка это были решения художника, здесь они стали данными о мире, и
// подбирать их придётся заново, когда появится, по чему подбирать.
type Cover struct {
	// Seed — затравка масок покрова. ОТДЕЛЬНАЯ от затравки рельефа: одна
	// затравка на два независимых поля дала бы корреляцию между высотой и
	// лесом, которой в природе нет, а на карте она читалась бы как «лес растёт
	// строго по горбам».
	Seed uint64 `json:"seed"`
	// ForestWavelengthM — длина волны маски леса. У спайка период массива около
	// 312 м.
	ForestWavelengthM float64 `json:"forest_wavelength"`
	// ForestThreshold — с какого значения маски начинается лес, в долях
	// [-1, 1] шума.
	ForestThreshold float64 `json:"forest_threshold"`
	// SpeciesWavelengthM — длина волны маски породы. Порода — свойство МЕСТА:
	// роща берёзы за ельником не выражается хешем по ячейке, у него нет
	// пространственной корреляции (разбор §3.2). У спайка период около 180 м.
	SpeciesWavelengthM float64 `json:"species_wavelength"`
	// VegWavelengthM — длина волны маски низового покрова: она же рисует
	// плешины голой почвы. У спайка период около 45 м.
	VegWavelengthM float64 `json:"veg_wavelength"`
	// BareThreshold — ниже этого значения маски низовой покров исчезает вовсе и
	// остаётся голая почва.
	BareThreshold float64 `json:"bare_threshold"`
	// ClearHalfWidthM — полуширина полосы отчуждения вдоль оси пути: ближе неё
	// лес не растёт. Это НЕ решение художника и не украшение: полосу отчуждения
	// вырубают, и её ширина — факт о дороге. У спайка 34 м.
	ClearHalfWidthM float64 `json:"clear_half_width"`
}

// TerrainOctave — один слой шума: длина волны и размах.
type TerrainOctave struct {
	WavelengthM float64 `json:"wavelength"`
	AmplitudeM  float64 `json:"amplitude"`
}

// Earthworks — земляные работы: основная площадка и откосы.
//
// Модель намеренно грубая и named honestly: площадка постоянной полуширины
// плюс откос постоянного заложения. Реальные насыпи имеют бермы, кюветы и
// переменное заложение по грунтам; всё это — содержимое отдельного слоя, когда
// у него появится потребитель. Здесь важно одно: под путём земля лежит на
// отметке оси, а не там, где её нарисовал шум.
type Earthworks struct {
	// FormationHalfWidth — полуширина основной площадки, метры.
	FormationHalfWidth float64 `json:"formation_half_width"`
	// SideSlope — заложение откоса: сколько метров по горизонтали на метр по
	// вертикали. Значение 1.5 означает откос 1:1,5.
	SideSlope float64 `json:"side_slope"`
}

// Georeference — метаданные привязки. В В1 сохраняется и проверяется по форме,
// компилятором не используется (спека §4).
type Georeference struct {
	Datum            string            `json:"datum"`
	Origin           Origin            `json:"origin"`
	OriginHeightKind string            `json:"origin_height_kind"`
	XAxisAzimuthDeg  float64           `json:"x_axis_azimuth_deg"`
	GroundToGrid     float64           `json:"ground_to_grid"`
	Provenance       map[string]string `json:"provenance,omitempty"`
}

type Origin struct {
	Lat float64 `json:"lat"`
	Lon float64 `json:"lon"`
	H   float64 `json:"h"`
}

// Anchor — единственная абсолютная поза связной компоненты. Позы остальных
// портов выводятся распространением (спека §7).
type Anchor struct {
	// Element — элемент, ВНУТРЬ которого смотрит Heading.
	//
	// Обязателен, когда в порту сходится больше одного конца: у общего порта
	// стрелки их три, и «направление порта» там не определено. На порту с одним
	// элементом поле избыточно и может отсутствовать.
	Element string  `json:"element,omitempty"`
	X       float64 `json:"x"`
	Y       float64 `json:"y"`
	Z       float64 `json:"z"`
	Heading float64 `json:"heading"`
}

type Topology struct {
	Nodes      []Node      `json:"nodes"`
	Turnouts   []Turnout   `json:"turnouts"`
	Edges      []Edge      `json:"edges"`
	Structures []Structure `json:"structures"`
}

type Node struct {
	ID    string `json:"id"`
	Ports []Port `json:"ports"`
}

// Port.Purpose пуст у обычного порта. "buffer_stop" и "map_boundary" делают
// висящее ребро законным (спека §10.3).
type Port struct {
	ID      string `json:"id"`
	Purpose string `json:"purpose,omitempty"`
}

type Turnout struct {
	ID string `json:"id"`
	// Kind — вид пути устройства, тот же перечень, что у ребра (KindRail).
	// Обязателен по той же причине и, сверх того, потому что проходы стрелки
	// берут вид ОТСЮДА: их порождает компилятор, автор их не пишет и приписать
	// им вид больше негде (см. Map.ElementKinds).
	Kind string `json:"kind"`
	Hand string `json:"hand"`
	Frog string `json:"frog,omitempty"`
	// Type — тип путевой конструкции самого устройства (спека §4): опущен —
	// применяется construction.default_type, компилятор разрешает умолчание и в
	// проводе ссылка всегда явная. Крестовина (§5) считается по колее ИМЕННО
	// этого типа, а не типов примыкающих run'ов.
	Type  string       `json:"type,omitempty"`
	Ports TurnoutPorts `json:"ports"`
}

type TurnoutPorts struct {
	Common    string `json:"common"`
	Straight  string `json:"straight"`
	Diverging string `json:"diverging"`
}

// Edge — ребро: линейный элемент сети между двумя портами.
type Edge struct {
	ID string `json:"id"`
	// Kind — ВИД пути: чем этот элемент является физически. Обязателен, см.
	// KindRail.
	Kind string `json:"kind"`
	From string `json:"from"`
	To   string `json:"to"`
}

// KindRail — единственный вид элемента сети, который принимается сегодня.
//
// # Почему поле заведено раньше, чем появился второй вид
//
// Ресурс называется network, а не track, потому что он называет КЛАСС
// содержимого: решением владельца автомобильные дороги приедут В ТОТ ЖЕ ответ.
// Отсюда элементу нужен различитель вида, и вопрос только в том, когда его
// заводить.
//
// Возражение «объявленная форма без потребителя окажется неверной»
// (map-format-design §8) сюда НЕ применяется, и это стоит запомнить, потому что
// здесь сталкиваются два правила проекта:
//
//   - §8 — правило про ВОЗМОЖНОСТИ: не строй механизм, которым никто не
//     пользуется. Механизма тут и нет: kind ничего не включает и ни на что не
//     влияет, компилятор его только переносит;
//   - различитель в ПЕРСИСТЕНТНЫХ и контрактных данных подчиняется обратному
//     правилу, уже записанному про пространство имён выше по файлу (id.go) и
//     про шов 6 (ClearAhead-4he): дешевле всего сделать вслепую, дороже всего
//     мигрировать. Пока карт мало и они свои, поле бесплатно; после импорта и
//     пользовательских карт каждая такая карта станет миграцией.
//
// # Поле — это миграция, значение — нет
//
// Отсюда объём: поле обязательное с сегодня, перечень значений — из одного.
// Добавить "road" потом — строка в switch ниже. Добавить САМО ПОЛЕ потом —
// разбирать, что значит его отсутствие в старых картах, и жить с неявным
// умолчанием «без kind значит рельсы», то есть с молчаливым враньём про каждую
// карту, где автор просто забыл поле.
const KindRail = "rail"

// Structure — сооружение сети: построенное, привязанное к её протяжённости.
// Виды на сегодня: platform, buffer_stop, bridge, tunnel (перечень — в
// validateStructures).
//
// # Почему не Trackside
//
// Звалось Trackside до 2026-08-11. Имя врало не про будущее, а про собственное
// СЕГОДНЯШНЕЕ содержимое: мост и тоннель стоят не сбоку от пути — они путь
// НЕСУТ. Различие не словесное, на нём держится рельеф: terrain.carriedSpans
// берёт ровно bridge и tunnel и вычитает их протяжённость из выборки оси, чтобы
// земля не сравнялась под мостом и не была прокопана над тоннелем
// (map-content-design §9а). Имя, отрицающее то, на чём стоит расчёт, дороже
// любой правки.
//
// Переименовано ИМЕННО СЕЙЧАС по доводу шва 6 (ClearAhead-4he, id.go): карт не
// существует — server/maps/st_a.json удалён, всё строится кодом через seedmap,
// — и мигрировать нечего. После импорта и авторских карт то же переименование
// стало бы миграцией формата на проводе и на диске.
//
// # Два смысла слова «сооружение», и это оговорка, а не недосмотр
//
// В map-content-design §9а «сооружение» употреблено УЗКО: им названы ровно мост
// и тоннель («пролётное строение, опоры, обделка тоннеля, портал»). Здесь тем же
// корнем назван КЛАСС. Развести раз и навсегда:
//
//   - Structure — КЛАСС: всё построенное на протяжённости сети. Платформа сюда
//     входит, упор тоже;
//   - «искусственное сооружение» — это Kind из подмножества {bridge, tunnel}:
//     то, что путь НЕСЁТ. Ровно оно исключается из земляных работ, и никакое
//     другое.
//
// Цена названа прямо: у слова два объёма, и различает их только прилагательное.
// Проект уже лечил двойные имена одной вещи (ClearAhead-0jq, ClearAhead-8kx),
// поэтому лечение выбрано обратное — одно имя с записанной оговоркой, а не
// второе имя. ОТВЕРГНУТО: оставить trackside за классом — имя врёт про мост уже
// сегодня; назвать класс Object или Feature — «объект» не называет ничего, а
// Feature занято проводом (RenderFeature — особенности устройств), и получилась
// бы ровно та пара смыслов, от которой уходим.
//
// Узкое имя понадобится, когда у геометрии сооружений появится свой слой (§9а:
// пролётное строение и обделка в рельеф не входят вовсе) — вот он и назовётся
// узко, а класс останется классом.
type Structure struct {
	ID string `json:"id"`
	// Kind — вид сооружения. bridge и tunnel — и есть «искусственное
	// сооружение» в узком смысле: только они меняют поведение рельефа.
	Kind string `json:"kind"`
	// Span — протяжённость сооружения. Отдельные SpanInterval и RunSpan
	// упразднены 2026-08-11: они различались ровно наличием направления, и
	// различие было случайным (map-content-design §3, бида ClearAhead-xm7).
	// У платформы направления нет, и поле у её интервалов пустое.
	Span   netloc.LinearU `json:"span"`
	Side   string         `json:"side,omitempty"`
	Offset float64        `json:"offset,omitempty"`
	Width  float64        `json:"width,omitempty"`
	// Height — верх сооружения НАД ПОВЕРХНОСТЬЮ КАТАНИЯ (редакция 6 §4).
	//
	// У платформы величина нормируемая и принадлежит платформе, а не типу пути:
	// у соседних платформ одной станции она законно разная (низкая грузовая и
	// высокая пассажирская). Выводить её из Offset нельзя, а зашивать в клиент
	// «обычно 1100 мм» — тем более: это ровно то выдумывание, которое запрещено.
	//
	// У упора — высота самого упора над головкой рельса.
	Height float64 `json:"height,omitempty"`
	// SlabThickness — толщина плиты платформы.
	//
	// Нужна затем, что платформа видна СБОКУ: торец плиты и просвет под ним —
	// то, чем платформа отличается от прямоугольника, нарисованного на земле.
	SlabThickness float64 `json:"slab_thickness,omitempty"`
}

type Geometry struct {
	Turnouts map[string]TurnoutGeometry `json:"turnouts"`
	Edges    map[string]Alignments      `json:"edges"`
}

type TurnoutGeometry struct {
	Straight  Alignments `json:"straight"`
	Diverging Alignments `json:"diverging"`
}

// Alignments — три функции над общим доменом [0, U]. Cant отложен целиком и
// поля под него не заводятся (спека §6).
type Alignments struct {
	Horizontal []HPrim `json:"horizontal"`
	Vertical   []VPrim `json:"vertical,omitempty"`
}

// HPrim — примитив плана. Kind: "straight" | "arc".
type HPrim struct {
	Kind   string  `json:"kind"`
	Length float64 `json:"length,omitempty"`
	Radius float64 `json:"radius,omitempty"`
	Angle  float64 `json:"angle,omitempty"`
}

// VPrim — примитив профиля. Kind: "grade" | "vertical_curve".
//
// У grade постоянный уклон SlopePermille. У vertical_curve уклон меняется по u
// линейно от уклона предыдущего элемента до EndSlopePermille — это парабола.
type VPrim struct {
	Kind             string  `json:"kind"`
	Length           float64 `json:"length"`
	SlopePermille    float64 `json:"slope_permille,omitempty"`
	EndSlopePermille float64 `json:"end_slope_permille,omitempty"`
}

// Construction — блок рецепта путевой решётки (спека контракта отрисовки §3–4).
//
// Типы, run'ы и умолчание живут в файле карты, а не отдельным ресурсом и не в
// коде сервера: привязка к ревизии получается по построению — правка типа
// меняет тело геометрии и обязана сменить ревизию карты.
type Construction struct {
	// DefaultType — тип по умолчанию: применяется к run'у с опущенным type и к
	// устройству с опущенным type. В проводе ссылка всегда явная — умолчание
	// разрешает компилятор, клиент скрытого умолчания не применяет никогда.
	DefaultType string            `json:"default_type"`
	Types       []TrackType       `json:"types"`
	Runs        []ConstructionRun `json:"runs"`
}

// TrackType — тип путевой конструкции (контракт отрисовки, редакция 6, §3).
//
// Семантика чисел задана точно, иначе два рендерера реализуют разное:
// gauge — между внутренними рабочими гранями головок рельсов; символические
// нитки схемы ставятся на ±gauge/2 от осевой; sleeper.length — поперёк пути,
// sleeper.width — вдоль; ballast.half_width — по верху призмы.
//
// # Вертикальный стек: всё отсчитывается ВНИЗ от поверхности катания
//
// Датум z — ПОВЕРХНОСТЬ КАТАНИЯ, то есть верх головки рельса (редакция 6 §2).
// Земляное полотно не авторится, а вычисляется:
//
//	formation_z(u) = z(u) − (ballast.depth + sleeper.height + rail.height)
//
// Отсюда правило чтения всех полей ниже: они складываются в одну высоту, и ни
// одно из них не является отметкой само по себе.
//
// sleeper.type и подробный профиль рельса по-прежнему НЕ заводятся (§8
// редакции 6): одного rail.height мало для честного рельса, и клиент рисует
// ОБЪЯВЛЕННОЕ упрощение — прямоугольник, — а не выдумывает форму.
type TrackType struct {
	ID      string       `json:"id"`
	Gauge   float64      `json:"gauge"`
	Rail    TrackRail    `json:"rail"`
	Sleeper TrackSleeper `json:"sleeper"`
	Ballast TrackBallast `json:"ballast"`
}

// TrackRail — рельс. Сегодня одно число: высота.
//
// Отдельная структура при одном поле заведена нарочно. Профиль рельса —
// названный открытый вопрос (§8 редакции 6): понадобятся либо размеры головки,
// шейки и подошвы, либо идентификатор стандартного профиля. Класть их потом в
// корень типа значило бы держать rail_height рядом с rail_profile и объяснять,
// почему одно с префиксом, а другое без.
type TrackRail struct {
	// Height — от подошвы рельса до поверхности катания. Подошва лежит на верхе
	// шпалы: прокладка отдельным числом не заводится (ниже разрешения любого
	// сегодняшнего вида).
	Height float64 `json:"height"`
	// HeadWidth — ширина ГОЛОВКИ рельса поверху.
	//
	// # Почему одно число профиля всё-таки заведено
	//
	// Профиль рельса отложен целиком (редакция 6 §8), и это поле выглядит
	// исключением из отказа. Оно им и является, и вот условие, по которому
	// исключение сделано: БЕЗ ШИРИНЫ ГОЛОВКИ РЕЛЬС НЕЛЬЗЯ НАРИСОВАТЬ ВООБЩЕ.
	// gauge задан между внутренними рабочими гранями; чтобы поставить рельс,
	// надо знать, сколько он занимает наружу от этой грани. Клиент, которому
	// ширину не прислали, обязан её выдумать — то есть ровно то, что контракт
	// запрещает.
	//
	// Цена умолчания ИЗМЕРЕНА, а не предположена: у снесённого спайка ширины
	// головки не было, нитки поставили по осям головок вместо рабочих граней, и
	// колея вышла 1.335 вместо 1.435 (разбор спайка §3.4).
	//
	// Остальной профиль — шейка, подошва, подуклонка — по-прежнему отложен, и
	// отказ не тронут: без них рельс рисуется ОБЪЯВЛЕННЫМ упрощением
	// (прямоугольник head_width × height), и упрощение названо вслух.
	HeadWidth float64 `json:"head_width"`
}

type TrackSleeper struct {
	Pitch  float64 `json:"pitch"`
	Length float64 `json:"length"`
	Width  float64 `json:"width"`
	// Height — от постели до верха шпалы, в подрельсовом сечении.
	Height float64 `json:"height"`
}

type TrackBallast struct {
	// HalfWidth — полуширина ПО ВЕРХУ призмы.
	HalfWidth float64 `json:"half_width"`
	// Depth — от верха основной площадки до НИЗА ШПАЛЫ.
	//
	// Именно «под шпалой», а не «толщина призмы»: толщина есть сумма
	// Depth + CribDepth, и хранить сумму рядом со слагаемыми — завести второй
	// источник истины и допуск согласования между ними.
	Depth float64 `json:"depth"`
	// CribDepth — насколько шпальный ящик засыпан ВЫШЕ низа шпалы. Верх призмы
	// = низ шпалы + CribDepth.
	//
	// Число нужно потому, что видно именно верх призмы, а не постель. Ноль —
	// призма вровень с постелью шпалы; CribDepth == Sleeper.Height — ящик
	// засыпан вровень с верхом шпалы. Больше высоты шпалы — отказ.
	CribDepth float64 `json:"crib_depth"`
	// SideSlope — заложение откоса призмы: метров по горизонтали на метр по
	// вертикали. 1.5 означает откос 1:1,5.
	//
	// Единица та же, что у Earthworks.SideSlope, и это сделано нарочно: два
	// заложения в одной карте, записанные в разных единицах, — заготовленная
	// ошибка. Нижняя полуширина выводится:
	// HalfWidth + SideSlope·(Depth + CribDepth).
	SideSlope float64 `json:"side_slope"`
}

// ConstructionRun — run размещения решётки (спека §4).
//
// Run — авторитетный факт о физической решётке, независимый от нарезки на
// RenderElement: смена внутренней сегментации карты не должна переставлять
// шпалы. Пишет run'ы строитель (инструмент), а не человек.
type ConstructionRun struct {
	// Type необязателен в карте: опущен — применяется Construction.DefaultType.
	// Компилятор обязан разрешить умолчание ДО провода.
	ID         string  `json:"id"`
	Type       string  `json:"type,omitempty"`
	Coordinate string  `json:"coordinate"`
	Phase      float64 `json:"phase"`
	// Spans — координата размещения только u: клиент не имеет цепочки
	// вертикального профиля и восстановить размещение по s не способен
	// (спека §4). Спаны — в авторском порядке прохождения, направление у
	// каждого ОБЯЗАТЕЛЬНО: run укладывается по ходу, и спан без направления в
	// нём недоописан, а не «без направления».
	Spans netloc.LinearU `json:"spans"`
}
