//
// Отсюда объём: поле обязательное с сегодня, перечень значений — из одного.
// Добавить "road" потом — строка в switch ниже. Добавить САМО ПОЛЕ потом —
// разбирать, что значит его отсутствие в старых картах, и жить с неявным
// умолчанием «без kind значит рельсы», то есть с молчаливым враньём про каждую
// карту, где автор просто забыл поле.
const KindRail = "rail"

// Structure — сооружение сети: построенное, привязанное к её протяжённости.
// Виды на сегодня: platform, buffer_stop, bridge, tunnel (перечень — в
// validateStructures).
//
// # Почему не Trackside
//
// Звалось Trackside до 2026-08-11. Имя врало не про будущее, а про собственное
// СЕГОДНЯШНЕЕ содержимое: мост и тоннель стоят не сбоку от пути — они путь
// НЕСУТ. Различие не словесное, на нём держится рельеф: terrain.carriedSpans
// берёт ровно bridge и tunnel и вычитает их протяжённость из выборки оси, чтобы
// земля не сравнялась под мостом и не была прокопана над тоннелем
// (map-content-design §9а). Имя, отрицающее то, на чём стоит расчёт, дороже
// любой правки.
//
// Переименовано ИМЕННО СЕЙЧАС по доводу шва 6 (ClearAhead-4he, id.go): карт не
// существует — server/maps/st_a.json удалён, всё строится кодом через seedmap,
// — и мигрировать нечего. После импорта и авторских карт то же переименование
// стало бы миграцией формата на проводе и на диске.
//
// # Два смысла слова «сооружение», и это оговорка, а не недосмотр
//
// В map-content-design §9а «сооружение» употреблено УЗКО: им названы ровно мост
// и тоннель («пролётное строение, опоры, обделка тоннеля, портал»). Здесь тем же
// корнем назван КЛАСС. Развести раз и навсегда:
//
//   - Structure — КЛАСС: всё построенное на протяжённости сети. Платформа сюда
//     входит, упор тоже;
//   - «искусственное сооружение» — это Kind из подмножества {bridge, tunnel}:
//     то, что путь НЕСЁТ. Ровно оно исключается из земляных работ, и никакое
//     другое.
//
// Цена названа прямо: у слова два объёма, и различает их только прилагательное.
// Проект уже лечил двойные имена одной вещи (ClearAhead-0jq, ClearAhead-8kx),
// поэтому лечение выбрано обратное — одно имя с записанной оговоркой, а не
// второе имя. ОТВЕРГНУТО: оставить trackside за классом — имя врёт про мост уже
// сегодня; назвать класс Object или Feature — «объект» не называет ничего, а
// Feature занято проводом (RenderFeature — особенности устройств), и получилась
// бы ровно та пара смыслов, от которой уходим.
//
// Узкое имя понадобится, когда у геометрии сооружений появится свой слой (§9а:
// пролётное строение и обделка в рельеф не входят вовсе) — вот он и назовётся
// узко, а класс останется классом.
type Structure struct {
	ID string `json:"id"`
	// Name — читаемая метка сооружения. Тождеством не является: ссылки идут по
	// UUID, метка попадает в тексты отказов рядом с ним.
	Name string `json:"name,omitempty"`
	// Kind — вид сооружения. bridge и tunnel — и есть «искусственное
	// сооружение» в узком смысле: только они меняют поведение рельефа.
	Kind string `json:"kind"`
	// Span — протяжённость сооружения. Отдельные SpanInterval и RunSpan
	// упразднены 2026-08-11: они различались ровно наличием направления, и
	// различие было случайным (map-content-design §3, бида ClearAhead-xm7).
	// У платформы направления нет, и поле у её интервалов пустое.
	Span   netloc.LinearU `json:"span"`
	Side   string         `json:"side,omitempty"`
	Offset float64        `json:"offset,omitempty"`
	Width  float64        `json:"width,omitempty"`
	// Height — верх сооружения НАД ПОВЕРХНОСТЬЮ КАТАНИЯ (редакция 6 §4).
	//
	// У платформы величина нормируемая и принадлежит платформе, а не типу пути:
	// у соседних платформ одной станции она законно разная (низкая грузовая и
	// высокая пассажирская). Выводить её из Offset нельзя, а зашивать в клиент
	// «обычно 1100 мм» — тем более: это ровно то выдумывание, которое запрещено.
	//
	// У упора — высота самого упора над головкой рельса.
	Height float64 `json:"height,omitempty"`
	// SlabThickness — толщина плиты платформы.
	//
	// Нужна затем, что платформа видна СБОКУ: торец плиты и просвет под ним —
	// то, чем платформа отличается от прямоугольника, нарисованного на земле.
	SlabThickness float64 `json:"slab_thickness,omitempty"`
}

