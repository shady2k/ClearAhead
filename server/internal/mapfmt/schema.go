package mapfmt

import "github.com/shady2k/ClearAhead/server/internal/netloc"

// Map — файл карты как он записан. Метры, радианы, промилле.
type Map struct {
	FormatVersion int               `json:"format_version"`
	MapID         string            `json:"map_id"`
	MapRevision   int               `json:"map_revision"`
	Georeference  *Georeference     `json:"georeference,omitempty"`
	Anchors       map[string]Anchor `json:"anchors"`
	Topology      Topology          `json:"topology"`
	Geometry      Geometry          `json:"geometry"`
	// Construction — рецепт путевой решётки (спека контракта отрисовки §3–4).
	// Блок соседствует с topology и geometry; отсутствие блока означает, что
	// авторинг ещё не породил решётку, и валидатор пропускает модуль (решение
	// зафиксировано в construction.go).
	Construction *Construction `json:"construction,omitempty"`
	// Terrain — РЕЦЕПТ рельефа, а не отсчёты (бида ClearAhead-9k7).
	//
	// Клиент рецепта не видит никогда: сервер разворачивает его в отсчёты,
	// вычитает земляные работы и отдаёт готовые высоты. Двойной реализации
	// шума в Go и на клиенте не нужно, а «клиент ничего не придумывает»
	// остаётся в силе — придумывает сервер, одинаково для всех и один раз.
	//
	// Отсутствие блока означает карту без рельефа: это законно, отсчётов
	// просто нет. Базовую поверхность рисует клиент.
	Terrain *Terrain `json:"terrain,omitempty"`
	// Objects — семантические объекты региона: постройки и вода.
	//
	// Третий ресурс рядом с сетью и чанками, и место у него своё по КРИТЕРИЮ
	// ПОЛОЖЕНИЯ (спека 2026-08-12-region-objects-design §1.3): вещь ложится
	// туда, чем задано её положение. Клеткой — в чанк; парой (элемент, u) — в
	// сеть; плоскими координатами и собственной формой — сюда.
	//
	// Критерий именно положения, а не «есть ли стабильный ID»: у платформы ID
	// есть, и тело своё есть, а лежит она в structures контракта сети, потому
	// что её положение задано span'ом. ID есть у всех трёх классов и
	// различителем быть не может.
	Objects *Objects `json:"objects,omitempty"`
}

// Objects — семантические объекты региона.
//
// Здесь стояло «вода сюда ещё не заведена: у неё нет потребителя, а форма без
// потребителя окажется неверной». Условие наступило 2026-08-12 — потребитель
// появился вместе с ролью строителя, — и предсказание сбылось буквально: первая
// форма реки оказалась неверной и была переделана, потому что берегом дело не
// обходится (разбор — у River.ValleyM).
type Objects struct {
	Buildings []Building `json:"buildings"`
	Rivers    []River    `json:"rivers,omitempty"`
}

// River — река: ось, ширина, глубина и отметка поверхности.
//
// # Почему линейный объект, а не содержимое чанка
//
// Ровно тот же довод, по которому путь не режется по тайлам (контракт чанков
// §7): разрезание разрушает объект. Река, нарезанная на клетки, перестаёт быть
// рекой — у неё нет ни начала, ни направления течения, ни единого уреза, а
// склеивать её обратно клиенту пришлось бы по стыкам, которых он не видит.
//
// Цена замерена разбором раскладки (§3.3): ось 2 км с точкой через 20 м — сто
// точек, то есть порядка 800 байт на регион при 3604 байтах всей сети. Против
// 8450 байт ОДНОГО чанка рельефа это ничто.
//
// # Что делает сервер и что достаётся клиенту даром
//
// РУСЛО ВРЕЗАЕТСЯ В РЕЛЬЕФ на сервере (terrain.carveRiver), и берег приезжает
// клиенту в высотах, не стоя ни одного лишнего байта. Это половина работы,
// сделанная бесплатно, и она же — причина, по которой река живёт в карте, а не
// только в проводе: форма земли есть свойство мира.
//
// Клиенту остаётся ПОВЕРХНОСТЬ: лента по оси на отметке уреза. Её сервер
// описывает, но не рисует — цвет воды, блеск, рябь и прозрачность суть решения
// художника, как цвет луга и меш ели.
type River struct {
	ID string `json:"id"`
	// Name — читаемая метка (например, ST_A_E1). Тождеством не является: в
	// ссылках не участвует, дубликаты меток законны. Обязана попадать в тексты
	// отказов — валидатор называет реку меткой, а не только UUID.
	Name string `json:"name,omitempty"`
	// Axis — ось русла. Z каждой точки — отметка ПОВЕРХНОСТИ ВОДЫ здесь, а не
	// дна: урез — то, что видно и что меряют, а дно выводится из него глубиной.
	//
	// Отметка своя у каждой точки, а не одна на реку, и это не запас на будущее:
	// река течёт под уклон, и общий урез дал бы на длинном русле либо
	// затопленный верх, либо сухой низ. Отдельным «ломаным профилем» (разбор
	// §3.3) он не заводится потому, что точка оси уже несёт три числа, и
	// третье было бы вторым местом, где записана одна и та же высота.
	Axis []RiverPoint `json:"axis"`
	// HalfWidthM — полуширина русла по дну: внутри неё дно плоское.
	HalfWidthM float64 `json:"half_width"`
	// BankM — ширина берега: от кромки дна до БРОВКИ.
	BankM float64 `json:"bank"`
	// DepthM — глубина дна ниже уреза.
	DepthM float64 `json:"depth"`
	// RimM — высота бровки над урезом.
	//
	// Не украшение: бровка выше воды — это и есть то, что держит реку в русле.
	// При нулевой бровке урез совпадал бы с краем берега, и любая неровность
	// шума выпускала бы воду в поле.
	RimM float64 `json:"rim"`
	// ValleyM — ширина ДОЛИНЫ: от бровки до природной поверхности.
	//
	// # Почему без неё не обошлось
	//
	// Первая редакция реки берегом и ограничивалась, и это дало разлив: замер
	// природной земли вдоль меандра ST_A показал разброс 127…157 м, то есть
	// никакого понижения по руслу нет вовсе. Подбор прямой уреза замером
	// (перебор по двум параметрам с шагом 0.1 м) не нашёл НИ ОДНОЙ прямой с
	// положительным запасом: лучшая уходила в край диапазона, то есть в каньон.
	//
	// Вывод не про числа, а про модель: РЕЛЬЕФ ИЗ ОДНОГО ШУМА НЕ ИМЕЕТ ДОЛИН, а
	// река без долины — это канава, прорезанная поперёк холмов. Долину пришлось
	// назвать явно, потому что порождать её нечему: в природе долину промывает
	// сама река, а у нас рецепт рельефа о реке не знает.
	ValleyM float64 `json:"valley"`
	// SandBandM — ширина песчаного пояса ЗА урезом.
	//
	// Пояс привязан к урезу, а не к отметке, и это правка ошибки спайка,
	// записанной им же: проверка песка была чисто по высоте, и на ровном месте
	// вылезал песчаный поясок там, где воды нет. Песок — там, где река его
	// намыла, то есть у русла.
	SandBandM float64 `json:"sand_band"`
}

// RiverPoint — точка оси русла: план и отметка уреза.
type RiverPoint struct {
	X float64 `json:"x"`
	Y float64 `json:"y"`
	Z float64 `json:"z"`
}

// Building — постройка: место, поворот, габарит.
//
// # Что здесь мир, а что нет
//
// Место, поворот и габарит — МИР: растущий город есть семантический объект со
// стабильным ID (map-content-design §5), его габарит меряется, и второй клиент
// обязан показать дом там же и такого же размера.
//
// Форма крыши, цвет стен, напуск карниза, число окон — НЕ мир: их выбирает
// рендерер, как выбирает меш ели. Отсюда и отсутствие этих полей.
//
// # Отметка вычисляется сервером, а не клиентом
//
// Направление авторитета здесь ОБРАТНОЕ пути, и это названо: путь диктует
// отметку земле, а дом её принимает. Считает сервер по рабочей поверхности
// уровня 0 и везёт явно. Довод замерен спекой объектов: посадка дома клиентом
// на присланные высоты даёт расхождение между уровнем 0 и уровнем 4 в среднем
// 0.39 м и до 2.30 м — то есть дом на дальнем уровне повис бы в воздухе или
// утонул, и это зависело бы от того, какой чанк клиент успел загрузить.
type Building struct {
	ID string `json:"id"`
	// Name — читаемая метка постройки. Тождеством не является, в ссылках не
	// участвует; попадает в тексты отказов рядом с UUID.
	Name string `json:"name,omitempty"`
	// X, Y — плановые координаты центра застроенного пятна.
	X float64 `json:"x"`
	Y float64 `json:"y"`
	// Heading — поворот вокруг вертикали, радианы.
	Heading float64 `json:"heading"`
	// Width — размер поперёк, Depth — вдоль, Height — до карниза.
	Width  float64 `json:"width"`
	Depth  float64 `json:"depth"`
	Height float64 `json:"height"`
}

// Terrain — рецепт рельефа карты.
//
// Высота земли — вход ТОЛЬКО рендера; уклон пути — вход физики. Авторитет у
// пути: рельеф согласуется с проектной осью насыпью и выемкой, обратное
// направление запрещено, иначе сила от уклона начнёт зависеть от разрешения
// сетки высот (map-format-design §5).
type Terrain struct {
	// Seed — затравка шума. Одна затравка даёт один и тот же рельеф на любой
	// машине: шум считается целочисленным хешем и арифметикой без
	// трансцендентных функций, а результат квантуется в сантиметры.
	Seed uint64 `json:"seed"`
	// BaseZ — опорная высота региона в метрах. Отсчёты хранятся и едут как
	// целые сантиметры ОТНОСИТЕЛЬНО неё: int16 покрывает ±327 м вокруг базы,
	// чего хватает на чанк 256 м в любых горах.
	BaseZ float64 `json:"base_z"`
	// Octaves — слои шума, от крупного к мелкому. Порядок значим: сумма
	// считается в записанном порядке, и перестановка меняет последний бит.
	Octaves []TerrainOctave `json:"octaves"`
	// Earthworks — как рельеф примиряется с осью пути.
	Earthworks Earthworks `json:"earthworks"`
	// Extent — ОХВАТ: докуда вокруг пути порождается земля и с какой
	// подробностью. Блок обязателен, умолчания у него нет.
	Extent Extent `json:"extent"`
	// Domain — ДОМЕН: где мир существует вообще. Прямоугольник в координатах
	// региона, обязателен (нуль — забытая строка, отказ валидации).
	//
	// Разделение с Extent не случайно и называется здесь: extent задаёт
	// ПИРАМИДУ ПРОГРЕВА — какие клетки кладёт в базу прогрев и насколько близко
	// к оси; domain задаёт СУЩЕСТВОВАНИЕ — что вправе посчитать порождение по
	// требованию. До 2026-08-13 охват считался от ОСИ (радиус уровней), и мир
	// без единого метра пути не имел ни габарита, ни критерия существования
	// (разбор спеки §0.2 п. 6). Существование решает домен, а не ось; габарит
	// оси и axis_step_m остались параметрами земляных работ и прогрева
	// (worldgen: covers против inExtent). Форма домена — прямоугольник, и почему
	// именно он — у типа Domain.
	Domain Domain `json:"domain"`
	// Cover — рецепт ПОКРОВА: что растёт и лежит на поверхности.
	//
	// Здесь, а не отдельным блоком карты, по той же причине, по которой здесь
	// живут октавы рельефа: покров считается тем же шумом от тех же координат и
	// клиенту НЕ ПОКАЗЫВАЕТСЯ НИКОГДА. Сервер разворачивает рецепт в классы и
	// отдаёт готовые ячейки — двойной реализации шума в Go и на клиенте не
	// нужно, а «клиент ничего не придумывает» остаётся в силе.
	//
	// Отсутствие блока означает карту без покрова: ресурс покрова тогда просто
	// не существует, и клиент рисует землю нейтрально. Это законно и отличимо
	// от «покров есть, но пустой».
	Cover *Cover `json:"cover,omitempty"`
}

// Cover — рецепт покрова.
//
// Модель НАМЕРЕННО грубая и названа грубой: две маски шума и три порога. Она не
// описывает ни подлеска, ни опушки, ни зависимости от высоты над уровнем моря —
// всё это содержимое отдельного слоя, когда у него появится потребитель.
//
// Числа ПРЕДВАРИТЕЛЬНЫЕ, и происхождение у них честное: длины волн и пороги
// сняты с констант снесённого спайка (разбор .internal/briefs/
// 2026-08-12-spike-data-requirements.md §1.2, §1.3). Происхождение не есть
// норма: у спайка это были решения художника, здесь они стали данными о мире, и
// подбирать их придётся заново, когда появится, по чему подбирать.
type Cover struct {
	// Seed — затравка масок покрова. ОТДЕЛЬНАЯ от затравки рельефа: одна
	// затравка на два независимых поля дала бы корреляцию между высотой и
	// лесом, которой в природе нет, а на карте она читалась бы как «лес растёт
	// строго по горбам».
	Seed uint64 `json:"seed"`
	// ForestWavelengthM — длина волны маски леса. У спайка период массива около
	// 312 м.
	ForestWavelengthM float64 `json:"forest_wavelength"`
	// ForestOctaves — сколько октав в маске леса. У спайка 3.
	ForestOctaves int `json:"forest_octaves"`
	// ForestThreshold — с какого значения маски начинается лес, в долях
	// [-1, 1] шума.
	ForestThreshold float64 `json:"forest_threshold"`
	// ForestDenseThreshold — с какого значения маски массив СОМКНУТ: гуще него
	// лес уже не становится. Между ним и ForestThreshold плотность растёт
	// линейно, и это опушка.
	//
	// Порог заведён 2026-08-12, когда выяснилось, что плотность посадки бралась
	// из сомкнутости низового покрова, — то есть лес рос гуще там, где гуще
	// трава. У спайка это были разные поля: маска леса давала вероятность
	// clamp((mask − 0.02)·5, 0, 0.96), а низовой покров не участвовал вовсе.
	// Множитель 5 и есть расстояние между порогами: 0.02 + 1/5 = 0.22.
	ForestDenseThreshold float64 `json:"forest_dense_threshold"`
	// SpeciesWavelengthM — длина волны маски породы. Порода — свойство МЕСТА:
	// роща берёзы за ельником не выражается хешем по ячейке, у него нет
	// пространственной корреляции (разбор §3.2). У спайка период около 180 м.
	SpeciesWavelengthM float64 `json:"species_wavelength"`
	// SpeciesOctaves — сколько октав в маске породы. У спайка 2.
	SpeciesOctaves int `json:"species_octaves"`
	// VegWavelengthM — длина волны маски низового покрова: она же рисует
	// плешины голой почвы. У спайка период около 45 м.
	VegWavelengthM float64 `json:"veg_wavelength"`
	// VegOctaves — сколько октав в маске низового покрова. У спайка 2.
	//
	// # Почему октавы вообще названы, а не приняты за единицу
	//
	// Одна октава — не «то же самое, но проще». Значение шума в соседних узлах
	// решётки независимо, и низина одной октавы легко занимает две-три ячейки
	// подряд: при длине волны 45 м плешины выходили связными пятнами по
	// 100–150 м, то есть покров рисовал не мозаику, а материки. У спайка все три
	// маски были фрактальными (`fractal_octaves` 3 / 2 / 2), и при переносе
	// 2026-08-12 это потеряли вместе с верхними порогами.
	//
	// Затухание и сгущение НЕ заведены полями: 0.5 и 2.0 — это FastNoiseLite по
	// умолчанию, то есть ровно то, чем считал спайк. Заводить их отдельно
	// значило бы предложить крутить то, чего никто не крутил.
	VegOctaves int `json:"veg_octaves"`
	// BareThreshold — ниже этого значения маски низовой покров исчезает вовсе и
	// остаётся голая почва.
	BareThreshold float64 `json:"bare_threshold"`
	// ClosedThreshold — с какого значения маски покров СОМКНУТ: гуще него
	// дернина уже не становится. Между ним и BareThreshold сомкнутость растёт
	// плавно, и это переход от плешины к дернине.
	//
	// # Почему без него картинка была коричневой
	//
	// Порог заведён 2026-08-12. До него сомкнутость была самим шумом, линейно
	// развёрнутым в [0, 15], и это подменяло величину её аргументом: земля
	// получала среднюю сомкнутость 0.49 от полной, а полной (15) достигала на
	// 1.0 % площади. Клиент смешивает цвет класса с голым грунтом по этой
	// самой доле — и весь луг выходил наполовину грунтовым.
	//
	// У спайка сомкнутость была НАСЫЩАЮЩЕЙСЯ функцией шума —
	// smoothstep(VEG_BARE 0.26, VEG_FULL 0.42) по шуму, развёрнутому в [0, 1],
	// то есть по порогам −0.48 и −0.16 в единицах шума. BareThreshold — это
	// перенесённый VEG_BARE; VEG_FULL при переносе потеряли, и потерю было
	// видно: замер той же карты по правилу спайка даёт среднюю 0.73 и полную
	// сомкнутость на 64.8 % площади.
	ClosedThreshold float64 `json:"closed_threshold"`
	// ClearHalfWidthM — полуширина полосы отчуждения вдоль оси пути: ближе неё
	// лес не растёт. Это НЕ решение художника и не украшение: полосу отчуждения
	// вырубают, и её ширина — факт о дороге. У спайка 34 м.
	ClearHalfWidthM float64 `json:"clear_half_width"`
}

// Extent — охват мира вокруг пути.
//
// # Почему это данные карты, а не константы сервера
//
// До 2026-08-12 оба числа были константами пакета chunk, и охват мира — 8192 м
// — задавал компилятор. Владелец спросил «зачем нам такая большая карта, давай
// маленькую и большую»; разбор показал, что двумя файлами карты это не
// решается: вторая карта получила бы тот же охват, каким бы ни был её путь.
//
// Уехали ровно эти два числа, и граница проведена по вопросу, на который число
// отвечает: «как далеко тянется мир» — свойство карты, «какова форма чанка»
// (сторона 256 м, шаг 4 м, 65 отсчётов) — свойство протокола и остаётся в
// chunk. Полный разбор с ценой каждого выбора — у типа chunk.Rule.
//
// # Оба поля обязательны, и оба отвергают нуль
//
// Нуль здесь — это забытая строка, а не значение: карта без блока extent
// разобралась бы молча и получила бы мир радиусом ноль. Поэтому Levels
// считается ШТУКАМИ, а не номером последнего уровня: max_level = 0 законен
// (единственный уровень, мир размером с радиус), и будь поле записано номером,
// забытая строка была бы неотличима от осмысленного выбора.
type Extent struct {
	// Level0RadiusM — радиус самого подробного уровня от оси пути, метры.
	//
	// Не произвольное число: оно обязано покрывать ВЫЛЕТ СОБСТВЕННЫХ ОТКОСОВ
	// этой карты (полуширина площадки плюс суммарный размах шума на заложение).
	// Меньший радиус означал бы, что подошва насыпи ложится на грубую сетку —
	// то есть уровень 0 не делает того единственного, ради чего он есть.
	// Валидатор это проверяет и называет оба числа.
	Level0RadiusM float64 `json:"level0_radius"`
	// Levels — сколько уровней подробности хранится. Самый грубый имеет номер
	// Levels−1, охват мира равен Level0RadiusM·2^(Levels−1).
	Levels int `json:"levels"`
}

// MaxLevel — номер последнего уровня. Ноль уровней — состояние, отвергнутое
// валидатором, и здесь оно даёт −1: правило, которое не покрывает ничего.
func (e Extent) MaxLevel() int { return e.Levels - 1 }

// ReachM — охват мира: радиус последнего уровня.
func (e Extent) ReachM() float64 {
	if e.Levels < 1 {
		return 0
	}
	return e.Level0RadiusM * float64(int64(1)<<(e.Levels-1))
}

// Domain — прямоугольник домена региона: где мир существует вообще, в
// координатах региона, метры. Блок обязателен, нуль — забытая строка, а не
// значение: валидатор отвергает вырожденный прямоугольник (validateDomain).
//
// # Почему прямоугольник, а не полигон и не набор тайлов
//
// Решение владельца от 2026-08-13, и оно не очевидно — его будут переоткрывать,
// поэтому довод записан здесь целиком.
//
// Разреженный набор тайлов — форма железнодорожных симов (MSTS, Open Rails,
// Trainz), и причина у неё складская: там тайл — нарисованный руками ассет на
// диске. У нас чанк — чистая функция рецепта, считается по требованию, и
// хранилище ему кэш, а не источник. Пустая площадь прямоугольника стоит НОЛЬ,
// пока в неё никто не посмотрел, поэтому единственное преимущество тайлов у нас
// уже обеспечено ленивым порождением. Набор тайлов вдобавок превращает домен из
// РЕЦЕПТА в изменяемое состояние, а карта по §1 спеки — рецепт природы.
//
// Полигон — форма без потребителя (правило проекта запрещает её заводить), а
// прямоугольник ничего не закрывает: и полигон, и маска — ограничение ВНУТРИ
// прямоугольника, а габаритный прямоугольник обходу уровней (worldgen.walk)
// нужен в любом случае.
//
// # Честная цена
//
// Остров или излучина реки получат запас пустоты по краям, и игрок доедет до
// невидимой стены там, где по смыслу вода. Когда станет заметно — маска поверх
// прямоугольника, а не смена формы домена.
type Domain struct {
	MinX float64 `json:"min_x"`
	MinZ float64 `json:"min_z"`
	MaxX float64 `json:"max_x"`
	MaxZ float64 `json:"max_z"`
}

// Known сообщает, что домен действительно задан, а не пришёл нулями.
//
// Нужно ровно одному месту — чтению региона из базы, засеянной сборкой, которая
// домен ещё не записывала. Молча подставить прямоугольник нельзя: чанки в такой
// базе порождены НЕИЗВЕСТНЫМ доменом, и выдавать их за свой — выдача чужих
// чанков под видом исправного мира. Проверкой карты это не является: диапазоны
// проверяет mapfmt (validateDomain), и второе место с теми же порогами
// разошлось бы с первым.
func (d Domain) Known() bool { return d.MinX < d.MaxX && d.MinZ < d.MaxZ }

