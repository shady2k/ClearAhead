package mapfmt

import (
	"encoding/hex"
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Правило «чего в идентификаторе не бывает».
//
// # Зачем
//
// Составные адреса собираются конкатенацией через разделители: порт — это
// node.port, проход — turnout:straight, ресурс — RES_turnout, строка хеша —
// поля через вертикальную черту. До 2026-08-11 в идентификаторах НЕ
// проверялся ни один символ, и из этого следовали два подтверждённых дефекта:
//
//  1. ребро, названное как проход стрелки (SW:straight), молча подменяло
//     геометрию прохода в общей таблице элементов — объявленная автором
//     геометрия ребра просто исчезала;
//  2. идентификатор с вертикальной чертой или переводом строки позволял двум
//     разным картам дать один network_model_hash, притом что манифест обещает «пара
//     (map_id, revision) определяет ровно один манифест — иначе immutable-URL
//     лжёт».
//
// Оба закрываются одним правилом: разделителя не бывает внутри имени. Чинить
// каждое следствие по отдельности — значит оставить класс открытым.
//
// # Почему это нельзя отложить
//
// Правило сужающее: оно объявляет незаконным то, что раньше принималось.
// Пока карт мало и они свои, оно бесплатно; после появления импорта и
// пользовательских карт каждая такая карта станет миграцией.
//
// # Про пространства имён
//
// Неймспейс НЕ приезжает префиксом в строке идентификатора. Префикс вида
// osm:relation/12345 немедленно ломает три вещи: URL геометрии (map_id —
// сегмент пути), разделитель потока хеша и это самое правило.
//
// Тождество и без того двухчастное: идентификатор уникален В ПРЕДЕЛАХ КАРТЫ,
// а глобально сущность адресуется парой (map_id, id). Пространство имён уже
// существует и называется map_id — его надо признать частью адреса, а не
// заводить второй механизм. Происхождение и лицензия живут на наборе данных и
// приезжают вместе с импортом (map-content-design §11).
//
// Бида ClearAhead-4he.

// Разделители составных адресов. Внутри авторского идентификатора не
// допускаются: иначе конкатенация перестаёт быть обратимой, а разбор строкой
// (HasSuffix, TrimSuffix, HasPrefix) начинает находить чужое.
const (
	// SepPort разделяет узел и порт: ST_A_W.P1.
	SepPort = "."
	// SepPassage разделяет устройство и его проход: ST_A_SW_1:straight.
	SepPassage = ":"
	// SepHash разделяет поля в потоке, по которому считается хеш компиляции.
	SepHash = "|"
)

// forbiddenInID — символы, запрещённые внутри авторского идентификатора.
//
// Помимо разделителей запрещены косые черты и процент: map_id уезжает
// сегментом URL геометрии, и такой идентификатор сделал бы карту недостижимой
// молча, а не отказом. Собачка запрещена, потому что редактор уже использует
// её при разрезании ребра.
const forbiddenInID = SepPort + SepPassage + SepHash + "/\\@%"

// ValidID проверяет авторский идентификатор.
//
// kind — что именно проверяется, попадает в текст отказа: валидатор обязан
// называть, где ошибка, а не только что она есть.
//
// Производные идентификаторы — квалифицированный порт, проход, ресурс — этой
// проверке НЕ подлежат: разделители в них законны по построению. Проверяются
// части, из которых они собраны.
func ValidID(kind, id string) error {
	if id == "" {
		return fmt.Errorf("mapfmt: %s: пустой идентификатор", kind)
	}
	if len(id) > MaxIDLength {
		return fmt.Errorf("mapfmt: %s %q: длина %d байт больше %d", kind, id, len(id), MaxIDLength)
	}
	if !utf8.ValidString(id) {
		return fmt.Errorf("mapfmt: %s: идентификатор не является корректным UTF-8", kind)
	}
	if i := strings.IndexAny(id, forbiddenInID); i >= 0 {
		return fmt.Errorf("mapfmt: %s %q: символ %q запрещён в идентификаторе — он разделяет составные адреса",
			kind, id, string(id[i]))
	}
	for _, r := range id {
		// Управляющие символы ломают построчный поток хеша и делают сообщения
		// об ошибках нечитаемыми. Направляющие Unicode (RTL-override и
		// родственные) позволяют двум разным идентификаторам выглядеть
		// одинаково в любом редакторе.
		if unicode.IsControl(r) || unicode.Is(unicode.Bidi_Control, r) {
			return fmt.Errorf("mapfmt: %s %q: управляющий символ U+%04X в идентификаторе", kind, id, r)
		}
	}
	if strings.TrimSpace(id) != id {
		return fmt.Errorf("mapfmt: %s %q: пробелы по краям идентификатора", kind, id)
	}
	return nil
}

// Нормализация Unicode (NFC) НЕ проверяется: в стандартной библиотеке её нет,
// а golang.org/x/text стал бы зависимостью, которую проект пока не берёт
// (первой сознательно назначена modernc.org/sqlite). Следствие названо честно:
// два визуально одинаковых идентификатора в разных формах нормализации
// остаются разными ключами. Для ASCII-имён, которыми написаны сегодняшние
// карты, вопрос не встаёт; он встанет вместе с импортом, и там же решится.

// Тождество и метка (решение владельца 2026-08-13 «UUIDv7 везде»).
//
// Тождество элемента — UUIDv7, и только оно. Метка (name) — отдельное
// необязательное поле: тождеством не является, в ссылках не участвует, две
// одинаковые метки законны и безвредны. Ссылки (порты, якоря, проходы
// стрелок) идут по UUID и только по UUID.
//
// Проверяется не только форма строки, но и биты: версия и вариант. Строка из
// 36 символов с дефисами в нужных местах ещё не UUIDv7, и принять UUIDv4 под
// видом седьмого — значит потерять временной порядок, ради которого версия и
// выбрана.
//
// РУЧНОЕ АВТОРСТВО КАРТЫ ОГРАНИЧЕНО. Проект держит JSON авторским форматом
// ради «ручного авторства небольшой станции», а выдумывать UUID руками нельзя.
// Ответ на это — инструмент: автор пишет метки, UUID проставляет импорт один
// раз. Задача W3-A это ограничение НЕ закрывает — оно остаётся открытым
// вопросом следующего автора, и комментарий здесь стоит затем, чтобы вопрос
// не считали решённым.

// ValidUUIDv7 проверяет идентификатор по форме RFC 9562 §5.7: 36 символов в
// канонической записи 8-4-4-4-12 строчными шестнадцатеричными цифрами,
// версия 7, вариант RFC 4122/9562.
func ValidUUIDv7(kind, id string) error {
	if len(id) != 36 {
		return fmt.Errorf("mapfmt: %s: не UUIDv7: %q (длина %d вместо 36)", kind, id, len(id))
	}
	for _, i := range []int{8, 13, 18, 23} {
		if id[i] != '-' {
			return fmt.Errorf("mapfmt: %s: не UUIDv7: %q (дефисы не на местах)", kind, id)
		}
	}
	for i := range id {
		if i == 8 || i == 13 || i == 18 || i == 23 {
			continue
		}
		c := id[i]
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return fmt.Errorf("mapfmt: %s: не UUIDv7: %q (не строчная шестнадцатеричная запись)", kind, id)
		}
	}
	raw, err := hex.DecodeString(strings.ReplaceAll(id, "-", ""))
	if err != nil {
		return fmt.Errorf("mapfmt: %s: не UUIDv7: %q", kind, id)
	}
	if v := raw[6] >> 4; v != 7 {
		return fmt.Errorf("mapfmt: %s: не UUIDv7: %q (версия %d, ожидалась 7)", kind, id, v)
	}
	if v := raw[8] >> 6; v != 0b10 {
		return fmt.Errorf("mapfmt: %s: не UUIDv7: %q (вариант %d, ожидался RFC 4122/9562)", kind, id, v)
	}
	return nil
}

// ValidName проверяет необязательную метку элемента. Пустая метка законна:
// элемент без имени адресуется UUID, и тексты отказов называют его только им.
// Метка в ссылках не участвует и в поток хеша модели не входит, поэтому
// разделители составных адресов в ней не запрещены; запрещены управляющие и
// направляющие символы (ломают тексты отказов и могут выглядеть одинаково в
// любом редакторе) и пробелы по краям.
func ValidName(kind, name string) error {
	if name == "" {
		return nil
	}
	if len(name) > MaxIDLength {
		return fmt.Errorf("mapfmt: %s: метка %q: длина %d байт больше %d", kind, name, len(name), MaxIDLength)
	}
	if !utf8.ValidString(name) {
		return fmt.Errorf("mapfmt: %s: метка не является корректным UTF-8", kind)
	}
	if strings.TrimSpace(name) != name {
		return fmt.Errorf("mapfmt: %s: метка %q: пробелы по краям", kind, name)
	}
	for _, r := range name {
		if unicode.IsControl(r) || unicode.Is(unicode.Bidi_Control, r) {
			return fmt.Errorf("mapfmt: %s: метка %q: управляющий символ U+%04X", kind, name, r)
		}
	}
	return nil
}

// Labeled — метка элемента для текста отказа: «метка (uuid)», а без метки —
// только uuid. Правило проекта требует называть элемент в ошибке, и
// «ребро 01936a7f-…: не указан kind» не читается — метка рядом с UUID читается.
func Labeled(name, id string) string {
	if name == "" {
		return id
	}
	return name + " (" + id + ")"
}

// checkEntity — форма тождества и метки одного элемента карты. Отказывает, не
// чинит: id не в форме UUIDv7 — отказ, называющий метку (если есть) и
// пришедшее значение; метка с управляющими символами — отказ. kind — что
// проверяется, попадает в текст отказа.
func checkEntity(kind, name, id string) error {
	k := kind
	if name != "" {
		k = kind + " " + name
	}
	if err := ValidUUIDv7(k, id); err != nil {
		return err
	}
	return ValidName(kind, name)
}
