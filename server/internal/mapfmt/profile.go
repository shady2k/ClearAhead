package mapfmt

// Профиль инженерных норм. Спека §10.4: держится в коде, версионируется целым
// номером, манифест ревизии записывает, каким профилем карта проверена.
//
// ЭТО ЗАГЛУШКА, поставленная координатором как точка подключения волны
// валидации: она существует, чтобы Validate не правили две волны сразу.
// Реализация — план .internal/plans/2026-08-09-validation-profile.md.
//
// Числа профиля будут ПРЕДВАРИТЕЛЬНЫМИ: источник норм не назначен. Менять их
// можно только вместе с ProfileVersion, иначе одна карта начнёт приниматься
// одной сборкой и отвергаться другой, а причину не увидеть.

const ProfileVersion = 0

type Profile struct {
	Version          int
	MinRadiusM       float64 // минимальный радиус кривой в плане
	MaxGrade         float64 // предельный уклон, доля (0.030 = 30 промилле)
	MinTrackSpacingM float64 // минимальное междупутье вне горловин
}

func DefaultProfile() Profile {
	return Profile{Version: ProfileVersion}
}

