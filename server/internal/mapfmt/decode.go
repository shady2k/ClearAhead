// Разбор документа карты. Файл вернулся, и вернулся не целиком — ниже сказано,
// что именно из решения 96ccacf отменено, а что осталось в силе.
//
// # Что отменяется
//
// Отменяется seedmap как БОЕВАЯ ЗАТРАВКА. Карта мира есть ДАННЫЕ, и держать её
// кодом значит, что править русло, посёлок или рецепт рельефа может только тот,
// кто пересобирает сервер. Вместе с этим отменяется и запись `world-storage` §6
// «JSON удалён из проекта целиком»: авторский формат снова существует, и это
// решение владельца, а не возврат к прежнему по недосмотру.
//
// # Что остаётся в силе
//
// Остаётся seedmap как ФАБРИКА ФИКСТУР ДЛЯ ТЕСТОВ. Три её довода (шапка пакета
// seedmap) относились именно к фикстурам и никуда не делись: тест не ломается от
// правки боевой карты; намерение видно в вызове; сломанную карту нельзя получить
// случайно. Ни один из них не требовал, чтобы боевая карта тоже была кодом.
//
// Остаётся в силе и ГЛАВНЫЙ довод, решивший спор в 96ccacf: «карта, собранная
// кодом, не может разойтись со схемой — она перестаёт компилироваться, тогда как
// JSON расходится молча. Именно это в проекте и произошло: единственную карту
// репозитория не грузил ни один тест, и смена версии формата сломала бы её
// незаметно». Довод верен, и он не про формат, а про ПРОВЕРКУ: расходится не
// JSON, а файл, которого не читает ни один тест. Отсюда цена возврата, и она
// уплачена здесь же, а не обещана: карту репозитория грузит и проводит через
// полный вход shipped_test.go. Файл, который перестал разбираться, валидироваться
// или компилироваться, роняет `go test ./...`, а не сервер владельца.
//
// # Что осталось невозможным
//
// Клиент по-прежнему НЕ МОЖЕТ прислать серверу карту документом: ручек приёма
// карты нет, и они не возвращаются. Карта входит в мир только с диска сервера,
// то есть решением того, кто сервер запускает. Направление обмена с клиентом
// осталось одно — карта уезжает.

// Decode разбирает документ карты СТРОГО: всё неизвестное и всё неоднозначное —
// отказ.
//
// Три прохода по одному буферу, потому что каждый проверяет своё и смешивать их
// в один означало бы получать невнятные ошибки: токены ловят то, чего модель не
// видит (дубликат ключа), модель ловит то, чего не видят токены (чужое поле),
// обход разобранного ловит то, что прошло оба (нечисло в float).
func Decode(r io.Reader) (*Map, error) {
	raw, err := io.ReadAll(io.LimitReader(r, MaxDocumentBytes+1))
	if err != nil {
		return nil, fmt.Errorf("mapfmt: чтение: %w", err)
	}
	if len(raw) > MaxDocumentBytes {
		return nil, fmt.Errorf("mapfmt: документ больше %d байт", MaxDocumentBytes)
	}

	if err := checkTokens(raw); err != nil {
		return nil, err
	}

	var m Map
	dec := json.NewDecoder(bytes.NewReader(raw))
	// DisallowUnknownFields — и есть исполнение правила «валидатор отказывает, а
	// не чинит» на уровне разбора. Без него encoding/json МОЛЧА выбрасывает
	// незнакомое поле: карта с опечаткой в имени `half_widht` загрузилась бы, и
	// река получила бы нулевую полуширину вместо отказа. Это ровно то
	// правдоподобное умолчание, которое в проекте запрещено.
	dec.DisallowUnknownFields()
	if err := dec.Decode(&m); err != nil {
		if name, ok := unknownFieldName(err); ok {
			return nil, fmt.Errorf("mapfmt: неизвестное поле %s: формат не знает такого имени, "+
				"опечатка или карта новее читателя", name)
		}
		return nil, fmt.Errorf("mapfmt: разбор: %w", err)
	}
	if dec.More() {
		return nil, fmt.Errorf("mapfmt: после документа есть лишние данные")
	}

	if m.FormatVersion != FormatVersion {
		return nil, fmt.Errorf("mapfmt: версия формата %d не поддерживается, ожидается %d",
			m.FormatVersion, FormatVersion)
	}
	if err := checkFinite(reflect.ValueOf(m), "map"); err != nil {
		return nil, err
	}
	return &m, nil
}

