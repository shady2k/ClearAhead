// Package uuidv7 — генератор идентификаторов UUIDv7 (RFC 9562).
//
// Проект держит инвариант «чанк, посчитанный при старте, и чанк,
// посчитанный через час, выходят байт в байт одинаковыми»: идентификаторы
// нужны там, где мир строится кодом (правки карты), и генератор обязан быть
// ВНЕДРЯЕМЫМ — источник тождества приходит параметром, а не читается из
// глобала. Глобальный uuid.New() в теле операции — провал задачи: тест не
// сможет получить воспроизводимый результат, а детерминированность проекта
// окажется зависимой от времени и случайности.
//
// Формат (RFC 9562 §5.7): 48 бит миллисекундной метки unix, 4 бита версии
// (0111), 12 бит, 2 бита варианта (10), 62 бита случайности. Случайность —
// crypto/rand, версия и вариант закладываются в те же 16 байт битовыми
// операциями; никаких зависимостей, кроме стандартной библиотеки.
package uuidv7

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"time"
)

// Source — источник тождества: выдаёт новый UUIDv7 за вызов.
//
// Функция, а не интерфейс: у правок один потребитель, а функция — самый
// узкий контракт, который тест может подменить предсказуемой
// последовательностью.
type Source func() (string, error)

// New выдаёт один UUIDv7 из системного источника случайности.
func New() (string, error) {
	return from(randRead, time.Now())
}

// Deterministic возвращает внедряемый источник с внутренним состоянием:
// монотонная метка времени от фиксированной базы и счётчик в случайных
// битах. Два подряд выданных идентификатора упорядочены по времени и не
// совпадают, а последовательность воспроизводима между прогонами — тесты
// правок подставляют его и получают эталонную карту.
func Deterministic() Source {
	ms := int64(1_700_000_000_000)
	seq := uint32(0)
	return func() (string, error) {
		ms++
		seq++
		return from(func(b []byte) error {
			for i := range b {
				b[i] = 0x42
			}
			// Счётчик в байтах 10..12: младшие 24 бита случайной части
			// меняются от вызова к вызову, старшие биты времени растут.
			b[10] = byte(seq >> 16)
			b[11] = byte(seq >> 8)
			b[12] = byte(seq)
			return nil
		}, time.UnixMilli(ms))
	}
}

// randRead — crypto/rand.Read с проверкой полноты: Reader не обязан
// заполнять весь буфер за один вызов.
func randRead(b []byte) error {
	_, err := rand.Read(b)
	return err
}

// from собирает UUIDv7 из метки времени и случайного источника. Разбор битов
// закреплён тестом TestLayout: метка — старшие 48 бит, версия 7 — биты
// 12..15, вариант RFC — биты 64..65.
func from(randBytes func([]byte) error, now time.Time) (string, error) {
	var raw [16]byte
	if err := randBytes(raw[:]); err != nil {
		return "", fmt.Errorf("uuidv7: случайность: %w", err)
	}
	ms := now.UnixMilli()
	raw[0] = byte(ms >> 40)
	raw[1] = byte(ms >> 32)
	raw[2] = byte(ms >> 24)
	raw[3] = byte(ms >> 16)
	raw[4] = byte(ms >> 8)
	raw[5] = byte(ms)
	raw[6] = (raw[6] & 0x0f) | 0x70 // версия 7
	raw[8] = (raw[8] & 0x3f) | 0x80 // вариант RFC 4122/9562
	return format(raw), nil
}

// format печатает 16 байт в канонической форме 8-4-4-4-12.
func format(raw [16]byte) string {
	var buf [36]byte
	hex.Encode(buf[0:8], raw[0:4])
	buf[8] = '-'
	hex.Encode(buf[9:13], raw[4:6])
	buf[13] = '-'
	hex.Encode(buf[14:18], raw[6:8])
	buf[18] = '-'
	hex.Encode(buf[19:23], raw[8:10])
	buf[23] = '-'
	hex.Encode(buf[24:36], raw[10:16])
	return string(buf[:])
}
