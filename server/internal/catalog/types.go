// Package catalog — каталог типов путевых устройств.
//
// Каталог хранит ТИПЫ УСТРОЙСТВ, а не марки крестовин. Марка характеризует угол,
// но перевод однозначно не задаёт: два перевода одной марки бывают с разными
// радиусами переводной кривой, длинами остряков и допустимыми скоростями.
// Решатель выбирает DeviceType.ID, а не вычисляет перевод из строки "1/9".
//
// Каждый проход несёт ГОТОВУЮ геометрию примитивами. Это нужно, чтобы в клиенте
// не завелось ни одной формулы: призрак под курсором рисуется существующим кодом
// отрисовки из присланных примитивов (спека 2026-08-09-map-editor-design §4).
//
// ВНИМАНИЕ: числа каталога ПРЕДВАРИТЕЛЬНЫЕ, как и числа mapfmt.Profile. Источник
// норм не назначен. Каталог версионируется ОДНИМ номером вместе с профилем:
// иначе одна карта принимается одной сборкой и отвергается другой, а причину не
// видно.
//
// Настоящий файл — только объявления. Наполнение и сериализация — ClearAhead-qyf.
package catalog

import "github.com/shady2k/ClearAhead/server/internal/geom"

// Catalog — набор типов устройств, доступных редактору.
type Catalog struct {
	// Version — общий номер с mapfmt.Profile. Разъехаться они не должны.
	Version int
	Devices []DeviceType
}

// DeviceType — тип путевого устройства как изделия.
type DeviceType struct {
	ID string
	// Gauge — колея между внутренними гранями головок, метры.
	Gauge float64
	// FrogMark — марка крестовины как ПРОИСХОЖДЕНИЕ, а не ограничение
	// (map-format-design §8). Пусто у устройств без крестовины.
	FrogMark string
	// Hand — "left" | "right" | "symmetric".
	Hand string
	// Passages — адресуемые проходы устройства с готовой геометрией.
	Passages []Passage
	// Envelope — занимаемая область в системе координат устройства: контур, за
	// который устройство не выходит. Нужен, чтобы решатель не ставил перевод
	// туда, где он не помещается.
	Envelope []geom.Pose
	// ApproachM, ExitM — требуемые прямые участки до и после устройства.
	ApproachM float64
	ExitM     float64
}

// Passage — один адресуемый проход устройства.
type Passage struct {
	// ID — идентификатор прохода в пределах типа: "straight", "diverging".
	// Модель сознательно допускает N проходов, а не пару: симметричный перевод
	// заставляет автора соврать, назвав прямым проход, которого нет
	// (ClearAhead-y9p). В v1 используются два.
	ID string
	// From, To — порты, которые проход соединяет.
	From, To string
	// Geometry — готовая цепочка примитивов от From к To.
	Geometry geom.Chain
	// MaxSpeedKmh — допустимая скорость по этому проходу. Предварительное число.
	MaxSpeedKmh float64
}
