// Земляной эффект постройки: жёсткая площадка под габаритом и мягкий откос
// до природной поверхности (ClearAhead-sqym.11).
//
// Контракт §1.3 объявляет «Здание, площадка -> поверхность»: постройка —
// исходник с земляным эффектом, как путь и прямой терраморфинг. До этой
// правки код первой стрелки не имел: постройка порождала только полосу
// вырубки (cleared) и стояла на природной земле как есть. Отсюда же вторая
// беда: у постройки не было жёсткого габарита, и пост-инвариант §2.2.2 для
// неё был вакуумно истинен.
//
// # Форма эффекта — тот же прецедент, что у пути
//
// pathEffect (terrain.go) уже устроен как «жёсткая площадка + мягкий откос»:
// внутри основной площадки земля лежит на отметке оси, за кромкой уходит
// откосом постоянного заложения до природной поверхности. Постройка повторяет
// эту форму для ПРЯМОУГОЛЬНИКА вместо коридора: внутри габарита земля лежит
// на отметке площадки, за кромкой — откос того же заложения до натуры.
//
// # Отметка площадки — природная в точке привязки, и это выбор модели
//
// У постройки в рецепте нет своей отметки (mapfmt.Building): земля назначает
// дому высоту, а не наоборот (§4.3 region-objects-design). Площадка поэтому
// встаёт на отметку природной поверхности в точке привязки (X, Y). Инвариант
// §3 держится по построению: эффект — чистая функция природной поверхности и
// собственного исходника, чужих результатов не читает, порядок построек на
// результат не влияет.
//
// # Жёсткий габарит и пост-инвариант
//
// Площадка — жёсткое ограничение (§2.2.2): поверхность обязана лежать ровно
// на ней. Планировка или путь, нарушающие габарит, — два несовместимых
// жёстких, отказ на компиляции (HeightCm), как у правки поверх основной
// площадки пути (TestGradingOverPathPlatformRefused).
package terrain

import (
	"math"

	"github.com/shady2k/ClearAhead/server/internal/mapfmt"
)

// buildingField — постройка, приготовленная к земляным работам: габарит в
// плане и отметка площадки.
type buildingField struct {
	cx, cy    float64 // центр пятна (метры региона)
	heading   float64 // поворот вокруг вертикали, радианы
	halfW     float64 // полуширина (поперёк)
	halfD     float64 // полуглубина (вдоль)
	platformZ float64 // отметка площадки: природная поверхность в точке привязки
}

// buildingEffect — эффект ОДНОЙ постройки: жёсткая площадка под габаритом и
// мягкий откос постоянного заложения до природной поверхности. Зеркало
// pathEffect: та же пара «площадка + откос», другая форма в плане.
//
// Внутри прямоугольника (повёрнутого на heading) земля лежит на отметке
// площадки. За кромкой — откос: перепад, который он успевает набрать на
// расстоянии d от кромки, равен d/SideSlope, и земля уходит к природе тем же
// max/min, что и у пути: насыпь не проваливается сквозь натуру, выемка не
// парит над ней.
func (f *Field) buildingEffect(natural, x, y float64, b buildingField) (worked float64, onPlatform bool, platformZ float64) {
	// Точка в локальных координатах пятна: перенос в центр и поворот на
	// -heading. Прямоугольник в локальных осях — axis-aligned, и проверка
	// габарита сводится к двум сравнениям модулей.
	cos, sin := math.Cos(b.heading), math.Sin(b.heading)
	dx, dy := x-b.cx, y-b.cy
	lx := cos*dx + sin*dy
	ly := -sin*dx + cos*dy
	if math.Abs(lx) <= b.halfW && math.Abs(ly) <= b.halfD {
		return b.platformZ, true, b.platformZ
	}
	// Расстояние до ПРЯМОУГОЛЬНИКА, а не до центра: откос растёт от КРОМКИ
	// площадки, и точка у длинной стены не обязана ждать, пока радиус дойдёт
	// до угла. Ноль внутри — уже возвращено выше.
	dxOut := math.Max(math.Abs(lx)-b.halfW, 0)
	dyOut := math.Max(math.Abs(ly)-b.halfD, 0)
	d := math.Hypot(dxOut, dyOut)
	drop := d / f.recipe.Earthworks.SideSlope
	if natural < b.platformZ {
		// Насыпь: спускаемся от площадки, но не ниже природной земли.
		return math.Max(natural, b.platformZ-drop), false, 0
	}
	// Выемка: поднимаемся от площадки, но не выше природной земли.
	return math.Min(natural, b.platformZ+drop), false, 0
}

// buildingsOf — постройки карты: исходник земляного эффекта.
func buildingsOf(m *mapfmt.Map) []mapfmt.Building {
	if m.Objects == nil {
		return nil
	}
	return m.Objects.Buildings
}

// BuildingEarthExtent — полный габарит земляного следа постройки в плане:
// пятно (повёрнутый прямоугольник) плюс откос до природной поверхности.
//
// Габарит нужен замыканию инвалидизации (project.SourceStructure): пересборка
// адресна по чанкам, и постройка шириной 16–30 м покрывает от 16 до 64 ячеек
// уровня 0 (region-objects-design §4.4) — её след обязан попасть в замыкание
// ВСЕХ задетых чанков, а не одного «домашнего» по точке привязки (sqym.15).
// Домашняя клетка — про РАЗМЕЩЕНИЕ объекта в ресурсе выдачи, а не про имя
// или инвалидизацию: тождество постройки — UUIDv7, и оно к габариту отношения
// не имеет.
//
// maxDropM — максимальный перепад площадки и природной поверхности, который
// откос успевает погасить. Площадка стоит на NaturalM(точки привязки), а
// натура живёт в [base−total, base+total] (total — сумма амплитуд октав),
// поэтому безопасная оценка — 2·total. Число передаётся вызывающим: terrain
// не знает, кто считает замыкание, а размах шума лежит в рецепте.
func BuildingEarthExtent(b mapfmt.Building, sideSlope, maxDropM float64) (minX, minZ, maxX, maxZ float64) {
	cos, sin := math.Cos(b.Heading), math.Sin(b.Heading)
	// Полуоси повёрнутого прямоугольника в осях региона: |w·cos|+|d·sin| и
	// |w·sin|+|d·cos| пополам — проекция габарита на ось при повороте.
	hw := (math.Abs(b.Width*cos) + math.Abs(b.Depth*sin)) * 0.5
	hd := (math.Abs(b.Width*sin) + math.Abs(b.Depth*cos)) * 0.5
	reach := maxDropM * sideSlope
	return b.X - hw - reach, b.Y - hd - reach, b.X + hw + reach, b.Y + hd + reach
}
