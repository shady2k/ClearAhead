// Прямой терраморфинг: правка высот как редактируемые ДАННЫЕ.
//
// В модели §1 контракта (спека sources-compilers-projections.md) правка высот —
// ИСХОДНИК, а чанк — ПРОЕКЦИЯ: правка живёт своей жизнью, чанк пересобирается
// из неё. Проекцию сносить можно всегда, исходник — нет; на этом держится
// выбор «правки переживают пересев» (бида ClearAhead-26g, W6-B): правки не
// ложатся в базу чанков, и -reseed, сносящий проекции, их не касается.
//
// # Клетка — единица данных и конфликта
//
// Правка задаёт АБСОЛЮТНУЮ отметку земли на клетке уровня 0 целиком
// (полуоткрытый прямоугольник [cx·256, (cx+1)·256) × [cz·256, (cz+1)·256)).
// Клетка — атом: частичную правку клетки модель не выражает, и это названо
// ценой, а не дырой — сплошные правки по образцам и частичные площадки
// приезжают вместе с формой эффекта (шаги 2–7 эпика). Уровень правки ровно
// ноль: клетки уровня 0 пространственно непересекающиеся, и только на них
// «наложение по клетке есть конфликт» (спека транзакций §5) получает один
// непротиворечивый смысл — две клетки разных уровней пересекались бы в плане,
// оставаясь разными ключами, и конфликт был бы пропущен.
//
// # Инвариант §3 контракта
//
// Эффект правки — чистая функция природной поверхности и собственного
// исходника: в покрытой клетке земля лежит РОВНО на отметке правки, не читая
// рабочую поверхность и чужие эффекты. Отсюда порядок применения правок не
// влияет на результат: клетка — независимый атом, и композиция — просто
// множество клеток. Правка «пишет прямо в чанк» — обратная дельта, которой в
// модели нет; хранится отметка, а не приращение.
//
// # Два жёстких габарита
//
// Основная площадка пути тоже жёсткий габарит (спека §4): правка, накрывшая
// площадку на ДРУГОЙ отметке, — два несовместимых жёстких, отказ, а не
// компромисс (валидатор отказывает, а не чинит). Отказ живёт в HeightCm:
// WorkedM ответа с ошибкой не несёт, а компилятор чанка читает HeightCm.
// Правка же поверх МЯГКОГО откоса пути законна: мягкое не вправе нарушить
// чужое жёсткое (§4.1), и площадка перерезает откос.
package terrain

import (
	"fmt"
	"math"

	"github.com/shady2k/ClearAhead/server/internal/chunk"
)

// GradeCell — одна клетка прямой правки высот.
//
// HeightCm — абсолютная отметка земли в целых сантиметрах ОТНОСИТЕЛЬНО base_z
// рецепта: та же единица, в которой отсчёты едут на провод, поэтому правка
// ложится в чанк без второго округления. Отметка абсолютная, а не дельта:
// дельты не аддитивны (спека §7 контракта: две насыпи удвоили бы подъём), и
// повторное применение правки обязано быть идемпотентным.
type GradeCell struct {
	Level    int
	CX, CZ   int
	HeightCm int16
}

// Bounds — ЗАМКНУТЫЙ прямоугольник клетки в плане (метры региона).
//
// Замыкание инвалидизации режет габарит по замкнутым клеткам (шовный
// инвариант): граница правки задевает соседа, и замыкание обязано включить
// обоих. Полуоткрытость самой правки (правый и верхний край клетки — уже не
// её) остаётся внутри terrain и наружу не светится.
func (c GradeCell) Bounds() (minX, minZ, maxX, maxZ float64) {
	side := chunk.SideM(c.Level)
	ox, oz := float64(c.CX)*side, float64(c.CZ)*side
	return ox, oz, ox + side, oz + side
}

// Grading — множество правок высот: исходник мира, а не проекция.
//
// Это ровно то, что edit коммитит и worldgen потребляет: список клеток с
// отметками. Порядок в списке значения не имеет — клетки независимы, и любой
// порядок даёт одно множество (инвариант §3).
type Grading struct {
	Cells []GradeCell
}

// Validate проверяет множество правок. Отказ, а не подстановка: клетка не
// уровня 0 — ошибка вызывающего, и молча округлять её до уровня 0 значило бы
// править чужую площадь.
func (g Grading) Validate() error {
	for _, c := range g.Cells {
		if c.Level != 0 {
			return fmt.Errorf("terrain: правка клетки (%d, %d, %d): уровень %d, разрешён только 0 — клетки уровня 0 пространственно непересекающиеся, и только на них конфликт «по клетке» однозначен", c.Level, c.CX, c.CZ, c.Level)
		}
	}
	return nil
}

// gradeKey — ключ клетки уровня 0 в индексе правок. Уровень в ключ не входит:
// Validate запретил ненулевые уровни, и два ключа одного плана не могут
// значить разное.
type gradeKey struct{ cx, cz int }

// addGrading кладёт правки в индекс поля.
//
// Две правки одной клетки с РАЗНЫМИ отметками — отказ: две отметки одного
// атома несовместимы (спека §5 «две площадки в общей области — одинаковая
// отметка в пределах допуска, иначе отказ»; допуск не объявлен — расхождение
// равно отказу, §8.5 контракта). Равные отметки схлопываются: множество, а не
// список, и повторное применение идемпотентно.
func (f *Field) addGrading(g Grading) error {
	if err := g.Validate(); err != nil {
		return err
	}
	if len(g.Cells) == 0 {
		return nil
	}
	f.grading = make(map[gradeKey]int16, len(g.Cells))
	for _, c := range g.Cells {
		k := gradeKey{cx: c.CX, cz: c.CZ}
		if h, ok := f.grading[k]; ok && h != c.HeightCm {
			return fmt.Errorf("terrain: клетка (%d, %d): две правки с отметками %d и %d см — несовместимые жёсткие габариты (спека §5); отказ",
				c.CX, c.CZ, h, c.HeightCm)
		}
		f.grading[k] = c.HeightCm
	}
	return nil
}

// gradingHeightM возвращает отметку правки в метрах, если точка покрыта.
//
// Покрытие — полуоткрытый прямоугольник клетки: отсчёт на границе двух клеток
// принадлежит ПРАВОЙ/ВЕРХНЕЙ, и обе соседние клетки согласованы (одна правку
// исключает, другая её не имеет) — шов не рвётся, ступень между правкой и
// натурой ложится ровно на границу, где её и ждёт игрок.
func (f *Field) gradingHeightM(x, y float64) (float64, bool) {
	if len(f.grading) == 0 {
		return 0, false
	}
	h, ok := f.grading[gradeKey{cx: int(math.Floor(x / chunk.SideM(0))), cz: int(math.Floor(y / chunk.SideM(0)))}]
	if !ok {
		return 0, false
	}
	return f.recipe.BaseZ + float64(h)/100, true
}

// gradingAt — отметка правки в сантиметрах, если точка покрыта (для сравнения
// с жёсткой площадкой пути без двойного перевода в метры).
func (f *Field) gradingAt(x, y float64) (int16, bool) {
	if len(f.grading) == 0 {
		return 0, false
	}
	h, ok := f.grading[gradeKey{cx: int(math.Floor(x / chunk.SideM(0))), cz: int(math.Floor(y / chunk.SideM(0)))}]
	return h, ok
}
